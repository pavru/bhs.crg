const { chromium } = require(process.cwd() + '/docs/tools/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const { readFileSync } = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {channel:'chrome'}),headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const url=pathToFileURL(process.cwd()+'/openspec/roadmap/dist/roadmap-3-4.html').href;
 await page.goto(url);
 const original=JSON.parse(readFileSync('openspec/roadmap/claude-marks.json','utf8')).marks;
 const payload=await page.locator('#data').textContent().then(JSON.parse);
 assert.deepEqual(payload.claudeMarks,original);
 const partCount=Object.values(payload.changes).reduce((n,c)=>n+(c.milestones||[]).length,0);
 assert.equal(await page.locator('[data-milestone]').count(),partCount);
 for(const c of Object.values(payload.changes)) for(const p of c.milestones||[]) assert.equal(await page.locator('[data-milestone="'+p.id+'"]').getAttribute('data-state'),p.state);
 assert.equal(await page.locator('time.who').count(),453);
 for(const key of Object.keys(original)) {
  assert(await page.locator('[data-key="'+key+'"]').count()>0,key+' missing');
 }
 const panel=page.locator('[data-milestone="work-18-crew#2"]');
 const server=page.locator('[data-milestone="work-18-crew#1"]');
 assert.equal(await server.getAttribute('data-state'),payload.changes['work-18-crew'].milestones[0].state);
 assert.equal(await panel.getAttribute('data-state'),payload.changes['work-18-crew'].milestones[1].state);
 const nextIds=await page.locator('#summary [data-goto]').evaluateAll(nodes=>nodes.map(n=>n.dataset.goto));
 const allParts=Object.values(payload.changes).flatMap(c=>c.milestones||[]);
 assert(nextIds.every(id=>['ready','partial'].includes(allParts.find(p=>p.id===id).state)));
 await page.locator('#q').fill('work-18-crew');
 assert.equal(await page.locator('#s-work-00-epic_4_3 [data-milestone]').count(),2);
 await page.locator('#s-work-00-epic_4_3').screenshot({path:'openspec/roadmap/dist/roadmap-a-work18.png'});
 const condition=panel.locator('.conditions li').filter({hasText:'work-21-review-ui / PR 2: задачи выполнены'});
 await condition.evaluate(el=>{for(let p=el.parentElement;p;p=p.parentElement) if(p.tagName==='DETAILS') p.open=true;});
 await condition.getByRole('button',{name:'Открыть условие',exact:true}).click();
 assert.equal(await page.locator('#q').inputValue(),'');
 assert.equal(await page.evaluate(()=>document.activeElement.id),'s-work-21-review-ui_2');
 await page.locator('#f-ready').click();
 const states=await page.locator('[data-milestone]').evaluateAll(nodes=>nodes.map(n=>n.dataset.state));
 assert(states.every(s=>s==='ready'||s==='partial'));
 await page.locator('#f-waiting').click();
 const waiting=await page.locator('[data-milestone]').evaluateAll(nodes=>nodes.map(n=>n.dataset.state));
 assert(waiting.every(s=>['waiting','unknown','partial'].includes(s)));
 await page.locator('#q').fill('work-18-crew');
 await page.locator('#f-all').click();
 await server.locator('.task-list > summary').click();
 assert.equal(await server.locator('.task-list').getAttribute('open'),'');
 await page.reload();
 // Search is temporary, disclosure preference persists across reload.
 assert.equal(await page.locator('[data-milestone="work-18-crew#1"] .task-list').getAttribute('open'),'');
 await page.locator('#collapse').click();
 assert.equal(await page.locator('details[open]').count(),0);
 await page.locator('#f-open').click();
 assert.equal(await page.locator('[data-milestone][data-state="done"]').count(),0);
 await page.locator('#q').fill('нет-такой-задачи-123');
 await page.getByText('Нет вех под условия отбора.',{exact:false}).waitFor();
 await page.locator('#q').fill('work-19-period-closure');
 await page.locator('#f-all').click();
 await page.screenshot({path:'openspec/roadmap/dist/roadmap-a-work19.png',fullPage:true});
 const light=await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--sheet').trim());
 await page.emulateMedia({colorScheme:'dark'});
 const dark=await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--sheet').trim());
 assert(dark && dark!==light);
 await page.screenshot({path:'openspec/roadmap/dist/roadmap-a-dark.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'page overflows mobile');
 await page.screenshot({path:'openspec/roadmap/dist/roadmap-a-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: PR milestones match OpenSpec; original dates preserved; readiness filters, dependency navigation, disclosure persistence, dark theme and mobile width');
})().catch(e=>{console.error(e);process.exit(1)});
