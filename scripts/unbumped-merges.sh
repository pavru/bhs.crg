#!/usr/bin/env bash
#
# Печатает слияния в текущую ветку, за которые версия ещё не поднята, — по строке на слияние:
#
#   after  <sha> <заголовок>   — слито ПОСЛЕ последнего изменения версии
#   before <sha> <заголовок>   — слито ДО ручной правки версии и ботом не учтено (см. ниже)
#
# Пустой вывод — «повышать нечего». Зовут его оба workflow: «Повышение версии» решает по этому
# списку, поднимать ли и на сколько, «Release» отказывает в выпуске, пока есть строки `after`
# (issue #1153). Скриптом, а не текстом в двух YAML — чтобы граница была одна и чтобы её гоняли
# проверки (bump-version.tests.sh).
#
# ГРАНИЦА — последний коммит ветки, изменивший саму строку версии. Им оказывается и прошлое
# повышение, и слияние, которое поменяло версию руками. Отсюда:
#   — цикла нет: коммит повышения сам становится границей, и запущенный им прогон видит пустоту;
#   — отменённый прогон ничего не теряет: уцелевший увидит всё, что слито с границы.
#
# `[skip bump]` в заголовке коммита — «это слияние версию не двигает». Так помечен коммит самого
# повышения; так же можно пометить слияние в окне «Squash and merge».
#
# ЗАЧЕМ `before`. Ручная правка версии — тоже граница, и всё слитое до неё считается учтённым. Для
# PATCH это верно: номер вырос. Но метка `version:minor` на PR, слитом ДО ручной правки и не
# дождавшемся повышения (прогон был красным, или правку слили следом), пропала бы без следа — если
# сама правка MINOR не подняла. Такие слияния отдаются видом `before`: метки на них стоит спросить,
# а повода для PATCH они не дают. Если ручная правка подняла MAJOR или MINOR, спрашивать не о чем.

set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FILE=$("$DIR/get-version.sh" --file)
name=$(basename "$FILE")
cd "$(dirname "$FILE")"

SKIP='[skip bump]'

# -G смотрит на добавленные и удалённые строки дифа: правка комментария в том же файле границей не
# становится. --first-parent: у слияния merge-коммитом версию «меняет» сам merge-коммит, а не
# коммит из ветки — иначе слияние, принёсшее правку версии, оказалось бы ПОСЛЕ границы.
version_change() { # version_change РЕВИЗИЯ → последний коммит не позже неё, менявший строку версии
    git log -1 --first-parent --format=%H -G'^[[:space:]]*<Version>[0-9]' "$1" -- "$name"
}

# `|| true`: grep, отсеявший всё, выходит с 1, а скрипт идёт под errexit.
merges() { # merges ВИД ДИАПАЗОН
    git log --first-parent --format='%H %s' "$2" | { grep -vF "$SKIP" || true; } | sed "s/^/$1 /"
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
minor_at() { # minor_at КОММИТ → «MAJOR.MINOR» версии в этом коммите; пусто, если не разобралась
    git show "$1:./$name" > "$tmp" 2>/dev/null || return 0
    VERSION_FILE="$tmp" "$DIR/get-version.sh" 2>/dev/null | cut -d. -f1,2 || true
}

base=$(version_change HEAD)
if [ -z "$base" ]; then
    echo "unbumped-merges: в истории не нашёлся коммит, менявший <Version> в $FILE" >&2
    exit 1
fi

# Граница — ручная правка (не коммит повышения): смотрим на шаг назад.
if ! git log -1 --format=%s "$base" | grep -qF "$SKIP" && git rev-parse -q --verify "$base^" > /dev/null; then
    prev=$(version_change "$base^")
    if [ -n "$prev" ]; then
        was=$(minor_at "$prev"); now=$(minor_at "$base")
        if [ -z "$was" ] || [ -z "$now" ]; then
            echo "unbumped-merges: версия в ${prev:0:8} или ${base:0:8} не разобралась — слияния до ручной правки не проверены" >&2
        elif [ "$was" = "$now" ]; then
            merges before "$prev..$base^"
        fi
    fi
fi

merges after "$base..HEAD"
