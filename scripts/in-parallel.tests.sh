#!/usr/bin/env bash
#
# Проверка in-parallel.sh — в песочнице, на командах оболочки: ни .NET, ни Node здесь не нужны.
#
# Зачем набор для скрипта в полсотни строк. Он сводит коды возврата нескольких сборок в один, и
# ошибка в этом сведении означает зелёный шаг при упавшей сборке: самая простая запись — `wait` без
# номеров — отвечает нулём всегда. Зелёный шаг никто не открывает, поэтому набор гоняется в CI на
# каждый PR (issue #1178).

set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUN="$HERE/in-parallel.sh"

SB="$(mktemp -d)"
trap 'cd /; rm -rf "$SB"' EXIT
cd "$SB" || exit 1

ok=0; bad=0
check() { # check «что проверяем» ожидание факт
    if [ "$2" = "$3" ]; then ok=$((ok + 1)); printf '  ok   %s\n' "$1"
    else bad=$((bad + 1)); printf '  ФЕЙЛ %s\n       ждали: %s\n       факт:  %s\n' "$1" "$2" "$3"; fi
}
has() { # has «что проверяем» образец текст — образец есть в тексте (строкой, не выражением)
    case "$3" in *"$2"*) ok=$((ok + 1)); printf '  ok   %s\n' "$1" ;;
    *) bad=$((bad + 1)); printf '  ФЕЙЛ %s\n       не нашлось: %s\n' "$1" "$2" ;; esac
}
hasnt() { # hasnt «что проверяем» образец текст — образца в тексте нет
    case "$3" in *"$2"*) bad=$((bad + 1)); printf '  ФЕЙЛ %s\n       нашлось лишнее: %s\n' "$1" "$2" ;;
    *) ok=$((ok + 1)); printf '  ok   %s\n' "$1" ;; esac
}

# ── Команды ветвей ────────────────────────────────────────────────────────────────────────────
# `meet ИМЯ` отмечается и ждёт, пока отметятся все трое. Это и есть проверка одновременности:
# запусти скрипт ветви по очереди, первая не дождалась бы остальных. Мерить вместо этого время
# значило бы завести проверку, которая краснеет на медленном раннере.
#
# `hang` называет свой номер и зависает. Он нарочно НЕ последний в команде ветви: последнюю
# команду оболочка запускает вместо себя, и погасить такую ветвь удалось бы и без групп процессов.
export M="$SB/marks"
mkdir -p "$SB/bin"
cat > "$SB/bin/meet" <<'EOF'
#!/usr/bin/env bash
: > "$M/$1"
for _ in $(seq 1 100); do
    [ -e "$M/a" ] && [ -e "$M/b" ] && [ -e "$M/c" ] && { echo "встретились-$1"; exit 0; }
    sleep 0.1
done
echo 'соседи не начались: ветви идут по очереди'; exit 9
EOF
cat > "$SB/bin/hang" <<'EOF'
#!/usr/bin/env bash
echo $$ > "$M/child"
exec sleep 60
EOF
chmod +x "$SB/bin/meet" "$SB/bin/hang"
export PATH="$SB/bin:$PATH"

scene() { rm -rf "$M"; mkdir -p "$M"; }
run() { out=$(bash "$RUN" "$@" 2>&1); rc=$?; }
verdict() { # verdict ИМЯ — итоговая строка ветви без времени: оно от прогона к прогону своё
    grep "^$1: " <<<"$out" | sed 's/: [0-9]*:[0-9]* — /: /'
}
line() { grep -n -m1 -- "$1" <<<"$out" | cut -d: -f1; } # номер строки с образцом
unset GITHUB_ACTIONS

echo
echo '── Все ветви прошли ──'
scene; run 'Сервер' 'echo вывод-сервера' 'Клиент и браузер' 'echo вывод-клиента'
check 'код возврата — 0'                        '0' "$rc"
has   'вывод первой ветви'                      'вывод-сервера' "$out"
has   'вывод второй ветви'                      'вывод-клиента' "$out"
check 'итог первой'                             'Сервер: готово' "$(verdict 'Сервер')"
check 'итог второй — имя с пробелами цело'      'Клиент и браузер: готово' "$(verdict 'Клиент и браузер')"
check 'время ветви — минуты и секунды'          '1' "$(grep -c '^Сервер: [0-9]*:[0-9][0-9] — ' <<<"$out")"
has   'время всех вместе'                       'Все вместе: ' "$out"
scene; run 'Одна' 'echo в-ошибки >&2'
has   'поток ошибок тоже собран'                'в-ошибки' "$out"
scene; run 'Одна' 'pwd'
has   'команда идёт из текущего каталога'       "$(pwd)" "$out"
scene; FROM_OUTSIDE=дошло run 'Одна' 'echo "окружение: $FROM_OUTSIDE"'
has   'окружение доходит до ветви'              'окружение: дошло' "$out"
# Ветвь, читающая ввод, получает его конец сразу — а не ждёт терминала, которого в фоне нет.
scene; out=$(echo из-ввода | bash "$RUN" 'Одна' 'cat; echo дочитала' 2>&1)
hasnt 'ввод скрипта до ветви не доходит'        'из-ввода' "$out"
has   'и ветвь на нём не виснет'                'дочитала' "$out"

echo
echo '── Ветви идут одновременно ──'
scene; run 'А' 'meet a' 'Б' 'meet b' 'В' 'meet c'
check 'код возврата — 0'                        '0' "$rc"
hasnt 'ни одна не ждала соседей зря'            'идут по очереди' "$out"
check 'вывод — по ветвям, в порядке вызова'     'встретились-a встретились-b встретились-c' \
    "$(grep -o 'встретились-.' <<<"$out" | tr '\n' ' ' | sed 's/ $//')"

echo
echo '── Отказ одной ветви красит всё — на каком бы месте она ни стояла ──'
for place in 1 2 3; do
    cmd=('echo прошла-1' 'echo прошла-2' 'echo прошла-3')
    cmd[place - 1]='echo причина-отказа; exit 3'
    scene; run 'Первая' "${cmd[0]}" 'Вторая' "${cmd[1]}" 'Третья' "${cmd[2]}"
    check "упала ветвь $place — код 1"          '1' "$rc"
    check "отказов в итоге — один"              '1' "$(grep -c ' — ОТКАЗ (код 3)$' <<<"$out")"
    check "остальные названы прошедшими"        '2' "$(grep -c ' — готово$' <<<"$out")"
    has   "причина видна"                       'причина-отказа' "$out"
done
check 'упавшая названа по имени'                'Третья: ОТКАЗ (код 3)' "$(verdict 'Третья')"
scene; run 'Первая' 'echo причина-отказа; exit 3' 'Вторая' 'echo прошла-2'
check 'вывод упавшей — после прошедших'         'да' "$([ "$(line 'причина-отказа')" -gt "$(line 'прошла-2')" ] && echo да || echo нет)"
scene; run 'Первая' 'exit 1' 'Вторая' 'exit 1'
check 'упали все — код 1'                       '1' "$rc"

echo
echo '── Отказ посреди ветви — отказ ветви ──'
scene; run 'Ветвь' 'false
echo дошли-до-конца'
check 'упала первая строка — код 1'             '1' "$rc"
hasnt 'и дальше ветвь не пошла'                 'дошли-до-конца' "$out"
scene; run 'Ветвь' 'false && echo дошли-до-конца'
check 'цепочка через && — код 1'                '1' "$rc"
scene; run 'Ветвь' 'false | cat'
check 'отказ в начале конвейера — код 1'        '1' "$rc"

echo
echo '── Остальных дожидаются и после отказа ──'
scene; run 'Быстрая' 'exit 1' 'Медленная' 'sleep 1; echo медленная-дошла'
check 'код возврата — 1'                        '1' "$rc"
has   'медленная доработала'                    'медленная-дошла' "$out"
check 'и названа прошедшей'                     'Медленная: готово' "$(verdict 'Медленная')"

echo
echo '── Позвали не так — отказ, и ничего не запущено ──'
scene; run
check 'без аргументов — код 2'                  '2' "$rc"
scene; run 'Имя без команды'
check 'имя без команды — код 2'                 '2' "$rc"
scene; run 'Первая' 'meet a' 'Вторая'
check 'нечётное число — код 2'                  '2' "$rc"
check 'первая ветвь не начиналась'              'нет' "$([ -e "$M/a" ] && echo да || echo нет)"
has   'сказано, как звать'                      'парами' "$out"

echo
echo '── Прервали посреди работы — вывод напечатан, ветви погашены ──'
# Вторая ветвь говорит и зависает; скрипту приходит TERM — так шаг отменяет Actions.
scene
bash "$RUN" 'Быстрая' 'echo быстрая-успела' 'Зависшая' 'echo зависшая-успела; hang; echo после' \
    > "$SB/abort.out" 2>&1 & runner=$!
for _ in $(seq 1 100); do [ -s "$M/child" ] && break; sleep 0.1; done
child=$(cat "$M/child" 2>/dev/null)
check 'вторая ветвь зависла'                    'да' "$([ -n "$child" ] && kill -0 "$child" 2>/dev/null && echo да || echo нет)"
kill -TERM "$runner"; wait "$runner"; rc=$?
out=$(cat "$SB/abort.out")
check 'код возврата — 143'                      '143' "$rc"
has   'вывод зависшей напечатан'                'зависшая-успела' "$out"
has   'и помечен как неоконченный'              'Зависшая — вывод до остановки' "$out"
has   'вывод закончившей — тоже'                'быстрая-успела' "$out"
hasnt 'итога при этом нет'                      'Все вместе' "$out"
# Погашенный и ещё не прибранный процесс на вид жив — даём ему время исчезнуть.
for _ in $(seq 1 50); do kill -0 "$child" 2>/dev/null || break; sleep 0.1; done
check 'зависшая команда погашена, а не только её оболочка' 'нет' "$(kill -0 "$child" 2>/dev/null && echo да || echo нет)"

echo
echo '── Вывод в Actions ──'
scene; GITHUB_ACTIONS=true run 'Первая' 'echo прошла-1' 'Вторая' 'exit 1' 'Третья' 'exit 1'
has   'прошедшая ветвь свёрнута'                '::group::Первая — вывод' "$out"
hasnt 'упавшая — развёрнута'                    '::group::Вторая' "$out"
has   'отказ помечен для сводки прогона'        '::error::Не прошло: Вторая, Третья' "$out"
scene; GITHUB_ACTIONS=true run 'Первая' 'echo прошла-1'
hasnt 'зелёный шаг отказом не помечен'          '::error::' "$out"
scene; run 'Первая' 'echo прошла-1'
hasnt 'вне Actions групп нет'                   '::group::' "$out"

echo
echo "Итог: $ok прошло, $bad упало"
[ "$bad" -eq 0 ]
