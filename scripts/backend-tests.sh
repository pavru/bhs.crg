#!/usr/bin/env bash
#
# Тесты backend двумя потоками — двумя процессами `dotnet test` одновременно, каждый на своей базе
# (issue #1164).
#
#   bash scripts/backend-tests.sh                        собрать и прогнать
#   bash scripts/backend-tests.sh --no-build -c Debug    прогнать собранное (так зовёт CI)
#   bash scripts/backend-tests.sh --filters              напечатать два фильтра и выйти
#
# Остальные аргументы уходят в `dotnet build` и в оба `dotnet test` как есть. `--filter` не
# принимается: фильтр у каждого потока свой.
#
# ЗАЧЕМ. Интеграционные тесты — одна коллекция xUnit без параллельности: база у них общая, и каждый
# тест начинает с её очистки. Это 130 классов из 298, но 235 секунд из 246: очередь в один поток,
# которой четыре ядра раннера не достаются вовсе. Делить коллекцию внутри процесса значило бы
# заводить вторую фикстуру и следить за общим статическим состоянием двух хостов; два ПРОЦЕССА
# развязаны целиком и тем, что уже есть: имя базы прогона берётся из BHS_TEST_DB (issue #618), и от
# него же выводятся базы хостов модулей (issue #1145). Так живут прогоны в соседних рабочих
# деревьях — здесь то же самое, только из одного каталога сборки.
#
# КАК ДЕЛИТСЯ. Второй поток — классы пространства имён BHS.CRG.Tests.Integration, чьё имя
# начинается с буквы из SECOND_STREAM. Первый — ВСЁ ОСТАЛЬНОЕ: его фильтр есть отрицание фильтра
# второго, и собраны оба из одного списка в одном цикле. Тест, не попавший во второй поток,
# оказывается в первом по построению — потерять тест правкой списка нельзя, можно только сделать
# потоки неравными. Новый класс попадает в поток сам, по своей первой букве.
#
# ⚠️ Деление по буквам — про ВРЕМЯ, а не про смысл: буквы подобраны так, чтобы потоки шли поровну
# (в первом ещё и все тесты без базы). Само оно не выравнивается: классы добавляются, и поток,
# которому достаются новые, растёт. Разъедутся больше чем на полминуты — скрипт скажет об этом
# предупреждением; тогда переложите букву. Цена ошибки — секунды, а не пропущенный тест.
#
# ⚠️ Поток, не выполнивший ни одного теста, — ОТКАЗ. `dotnet test` с фильтром, под который ничего
# не подошло, отвечает кодом 0. Переименуй кто-нибудь пространство имён — второй поток опустел бы,
# первый забрал бы всё, шаг остался бы зелёным, а время вернулось бы к одному потоку — молча.
#
# Базы потоков — <BHS_TEST_DB>_s1 и <BHS_TEST_DB>_s2 (по умолчанию bhs_crg_test_s1/_s2), рядом с
# каждой — базы хостов модулей с теми же суффиксами, что всегда. На машине разработчика они
# остаются лежать, как и база обычного прогона.
#
# ⚠️ Сколько дают два потока, решает сервер базы. В CI он работает без fsync, и там это половина
# времени; на стенде разработчика сервер бережёт данные, потоки ждут диска друг за другом, и
# выигрыш меньше. Замеры — docs/DEV_NOTES.md, «Тесты backend: два потока…».
#
# Обычный `dotnet test` этим скриптом НЕ заменён: один класс или один фильтр по-прежнему гоняют им.

set -uo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="$DIR/../src/server/BHS.CRG.Tests/BHS.CRG.Tests.csproj"

NAMESPACE='BHS.CRG.Tests.Integration.'
SECOND_STREAM='I M S'

# Оба фильтра — из одного списка: `~` «содержит», `!~` «не содержит»; второй поток — «любая из
# букв», первый — «ни одна из них». Разойтись они могут только вместе.
first=''; second=''
for letter in $SECOND_STREAM; do
    second="${second:+$second|}FullyQualifiedName~$NAMESPACE$letter"
    first="${first:+$first&}FullyQualifiedName!~$NAMESPACE$letter"
done

if [ "${1:-}" = '--filters' ]; then
    printf '%s\n%s\n' "$first" "$second"
    exit 0
fi

# ── Аргументы ─────────────────────────────────────────────────────────────────────────────────
# `--no-build` — наш, где бы ни стоял: уйди он дальше как есть, `dotnet build` отказал бы
# неизвестным ключом. `--filter` не принимаем вовсе: второй `--filter` в той же команде — либо
# отказ разбора, либо, хуже, молчаливая замена нашего, и тогда оба потока гоняют одно и то же.
build=1; args=()
for arg in "$@"; do
    case "$arg" in
        --no-build) build=0 ;;
        --filter|--filter=*|--filter:*)
            echo 'backend-tests.sh: --filter здесь не задаётся — потоки делит сам скрипт.' >&2
            echo 'Один класс или один фильтр гоняют обычным dotnet test … --filter ….' >&2
            exit 2 ;;
        *) args+=("$arg") ;;
    esac
done
# Команда с остальными аргументами в хвосте. Запись — из-за `set -u`: пустой массив в старом bash
# считается неустановленной переменной.
pass() { "$@" ${args[@]+"${args[@]}"}; }

# ── Имя базы ──────────────────────────────────────────────────────────────────────────────────
# Потоку дописывается «_s1»/«_s2», а тесты отводят имени базы прогона 39 байт
# (TestDatabases.MaxBaseBytes). Значит здесь BHS_TEST_DB вправе занять 36 — и отказать лучше сразу
# и своими словами: иначе отказ придёт из каждого класса хостов модулей, назовёт имя с суффиксом,
# которого никто не задавал, и предел, которого заданное значение не нарушало.
base="${BHS_TEST_DB:-bhs_crg_test}"
MAX_BASE_BYTES=36
if [ "$(printf %s "$base" | wc -c)" -gt "$MAX_BASE_BYTES" ]; then
    echo "backend-tests.sh: имя базы «$base» длиннее $MAX_BASE_BYTES байт." >&2
    echo 'Потоку дописывается «_s1»/«_s2», и вместе с ним имя не уместится в предел тестов. Укоротите BHS_TEST_DB.' >&2
    exit 2
fi

# Сборка — ОДИН раз и до потоков. Два `dotnet test` без --no-build собирали бы один проект
# одновременно и делили бы его obj: отказ пришёл бы не от тестов, а от занятого файла.
if [ "$build" -eq 1 ]; then
    pass dotnet build "$PROJECT" || exit 1
fi

logs="$(mktemp -d)"
reported=0

# Прервали посреди прогона — отмена шага, таймаут работы, Ctrl-C: гасим потоки и печатаем то, что
# они успели написать. Вывод копится в файлах, и без этого прерванный прогон не оставил бы в логе
# НИЧЕГО — ни упавшего теста, ни места, на котором он встал. А прерывают как раз зависшие.
finish() {
    local n
    if [ "$reported" -eq 0 ]; then
        # Сначала обёртки потоков, потом сами прогоны: обёртка, пережившая свой прогон, дописала бы
        # время в уже снесённый каталог.
        kill ${pid1:-} ${pid2:-} 2>/dev/null
        for n in 1 2; do
            [ -f "$logs/$n.pid" ] && kill "$(cat "$logs/$n.pid")" 2>/dev/null
        done
        for n in 1 2; do
            [ -s "$logs/$n.log" ] || continue
            echo "── Поток $n — вывод до остановки ──"
            cat "$logs/$n.log"
        done
    fi
    rm -rf "$logs"
}
# Одного EXIT хватает: bash зовёт его и тогда, когда оболочку гасят сигналом.
trap finish EXIT

stream() { # stream НОМЕР ФИЛЬТР — в фоне; вывод, время и pid складывает в $logs
    local n="$1" filter="$2" started=$SECONDS rc
    # Язык вывода называем сами: итог потока читается из строки «Total: N», а на машине с русской
    # локалью её бы не нашлось.
    #
    # ⚠️ minimal, а не normal: normal печатает строку на КАЖДЫЙ прошедший тест, и единственный
    # упавший тонет в тысячах строк — лог открывают ровно тогда, когда он красный. Про отказ
    # minimal не теряет ничего: имя теста, Error Message целиком, Stack Trace с файлом и строкой,
    # итоговая сводка. Проверено ломанием сторожа, а не догадкой.
    #
    # Команда — прямо здесь, а не через pass: у функции в фоне $! — это оболочка вокруг неё, и
    # погасить по такому номеру сам `dotnet test` не вышло бы.
    BHS_TEST_DB="${base}_s$n" DOTNET_CLI_UI_LANGUAGE=en \
        dotnet test "$PROJECT" --no-build --filter "$filter" \
        --logger 'console;verbosity=minimal' ${args[@]+"${args[@]}"} > "$logs/$n.log" 2>&1 &
    echo $! > "$logs/$n.pid"
    wait $!
    rc=$?
    echo $((SECONDS - started)) > "$logs/$n.time"
    return $rc
}

stream 1 "$first" & pid1=$!
stream 2 "$second" & pid2=$!
wait "$pid1"; rc1=$?
wait "$pid2"; rc2=$?

clock() { printf '%d:%02d' $(($1 / 60)) $(($1 % 60)); }

failed=0
report() { # report НОМЕР КОД — вывод потока и его итог
    local n="$1" rc="$2" total spent verdict
    # Число тестов — из итоговой строки `dotnet test`: «… Total:  3092, Duration: …».
    total=$(sed -n 's/.*Total: *\([0-9][0-9]*\).*/\1/p' "$logs/$n.log" | tail -1)
    spent=$(cat "$logs/$n.time" 2>/dev/null || echo 0)

    if [ "$rc" -ne 0 ]; then
        verdict='УПАЛ'
    elif [ "${total:-}" = 0 ] || grep -q 'No test matches the given testcase filter' "$logs/$n.log"; then
        verdict='ПУСТ — ни одного теста, деление по буквам устарело (SECOND_STREAM)'
    elif [ -z "$total" ]; then
        # Не «пуст»: тесты, судя по коду, прошли, но сколько их — не сказано. Причина не в делении,
        # а в виде вывода, и отправлять чинить буквы было бы неправдой.
        verdict='НЕ РАЗОБРАН — в выводе нет строки «Total: N»: у dotnet test сменился вид итога, правьте разбор в scripts/backend-tests.sh'
    else
        verdict='прошёл'
    fi

    # В Actions вывод прошедшего потока сворачиваем: тысячи строк про успех читать незачем. Упавший
    # оставляем развёрнутым — в свёрнутой группе отказ не видно, пока её не откроешь.
    if [ "$verdict" = 'прошёл' ] && [ "${GITHUB_ACTIONS:-}" = 'true' ]; then
        echo "::group::Поток $n — вывод"
        cat "$logs/$n.log"
        echo '::endgroup::'
    else
        echo "── Поток $n — вывод ──"
        cat "$logs/$n.log"
    fi

    summary="${summary}"$'\n'"Поток $n: ${total:-0} тестов за $(clock "$spent") — $verdict"
    [ "$verdict" = 'прошёл' ] || failed=1
    tests=$((tests + ${total:-0}))
    times="$times $spent"
}

summary=''; tests=0; times=''
report 1 "$rc1"
report 2 "$rc2"
reported=1

echo "$summary"
echo "Всего тестов: $tests"

if [ "$failed" -ne 0 ]; then
    [ "${GITHUB_ACTIONS:-}" = 'true' ] && echo '::error::Тесты backend не прошли — см. вывод потока, помеченного выше'
    exit 1
fi

# Потоки разъехались — говорим вслух: шаг при этом зелёный, а время потоков в логе зелёного шага
# никто не читает. Не отказ: цена перекоса — секунды, и красить из-за них обязательную проверку
# значило бы останавливать слияния ради замера.
# shellcheck disable=SC2086 — два числа через пробел, разбиение здесь и нужно
set -- $times
skew=$(( $1 > $2 ? $1 - $2 : $2 - $1 ))
if [ "$skew" -gt "${BACKEND_TESTS_MAX_SKEW:-30}" ]; then
    note="Потоки тестов backend разъехались на $skew с ($(clock "$1") и $(clock "$2")): переложите букву в SECOND_STREAM, scripts/backend-tests.sh"
    if [ "${GITHUB_ACTIONS:-}" = 'true' ]; then echo "::warning::$note"; else echo "⚠️ $note"; fi
fi
