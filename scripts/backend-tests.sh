#!/usr/bin/env bash
#
# Тесты backend несколькими потоками — процессами `dotnet test` одновременно, каждый на своей базе
# (issue #1164; четыре потока на двух раннерах — с 13.11.2026).
#
#   bash scripts/backend-tests.sh                        собрать и прогнать все доли по очереди,
#                                                        по два потока разом — как на раннере CI
#   bash scripts/backend-tests.sh --no-build -c Debug    прогнать собранное
#   bash scripts/backend-tests.sh --shard 1/2 --no-build -c Debug
#                                                        только потоки первой доли из двух (так
#                                                        зовёт CI: доля — своя работа, свой раннер)
#   bash scripts/backend-tests.sh --filters              напечатать фильтры потоков и выйти
#                                                        (с --shard — только потоков доли)
#
# Остальные аргументы уходят в `dotnet build` и во все `dotnet test` как есть. `--filter` не
# принимается: фильтр у каждого потока свой.
#
# ЗАЧЕМ. Интеграционные тесты — одна коллекция xUnit без параллельности: база у них общая, и каждый
# тест начинает с её очистки. Это 240 классов из 320, но 682 секунды из 891 (замер 13.11.2026):
# очередь в один поток, которой ядра не достаются вовсе. Делить коллекцию внутри процесса значило
# бы заводить вторую фикстуру и следить за общим статическим состоянием двух хостов; отдельные
# ПРОЦЕССЫ развязаны целиком и тем, что уже есть: имя базы прогона берётся из BHS_TEST_DB
# (issue #618), и от него же выводятся базы хостов модулей (issue #1145). Так живут прогоны в
# соседних рабочих деревьях — здесь то же самое, только из одного каталога сборки.
#
# КАК ДЕЛИТСЯ. Потоки 2…N — классы пространства имён BHS.CRG.Tests.Integration, чьё имя
# начинается с одного из префиксов своей строки STREAMS. Первый — ВСЁ ОСТАЛЬНОЕ: его фильтр есть
# отрицание всех прочих, и собраны они из одного списка в одном цикле. Тест, не попавший ни в один
# названный поток, оказывается в первом по построению — потерять тест правкой списка нельзя, можно
# только сделать потоки неравными. Новый класс попадает в поток сам, по началу своего имени.
#
# ⚠️ Префиксы не накрывают друг друга: «Invoice» рядом с «InvoiceP» отдал бы InvoicePaymentTests
# двум потокам сразу. Такой список — отказ до запуска, а не тесты дважды.
#
# ⚠️ Деление — про ВРЕМЯ, а не про смысл: префиксы подобраны так, чтобы потоки шли поровну (в
# первом ещё и все тесты без базы). Само оно не выравнивается: классы добавляются, и поток, которому
# достаются новые, растёт. Разъедутся потоки одной доли больше чем на полминуты — скрипт скажет об
# этом предупреждением; тогда переложите префикс. Цена ошибки — секунды, а не пропущенный тест.
#
# ⚠️ Поток, не выполнивший ни одного теста, — ОТКАЗ. `dotnet test` с фильтром, под который ничего
# не подошло, отвечает кодом 0. Переименуй кто-нибудь пространство имён — названные потоки
# опустели бы, первый забрал бы всё, шаг остался бы зелёным, а время вернулось бы к одному потоку —
# молча.
#
# ДОЛИ. `--shard K/N` гоняет K-ю из N равных частей списка потоков: число потоков обязано делиться
# на N. CI идёт двумя долями по два потока — на раннере четыре ядра, и двух процессов на них
# хватает (замер — docs/DEV_NOTES.md, «Тесты backend: два потока…»), а третий и четвёртый поток
# дал второй раннер. Число долей названо в матрице работы в ci.yml; что оно делит число потоков,
# сверяет backend-tests.tests.sh.
#
# Без `--shard` доли идут ПО ОЧЕРЕДИ, а не все потоки разом. Четыре процесса тестов на одном
# сервере базы исчерпали его соединения: на стенде разработчика `max_connections` — 100, и сервер
# общий с соседними прогонами, — и тесты падали отказом «too many clients already» (13.11.2026).
# Пока соединения хватало, четыре разом шли 7:40 против 12:11 по два; но прогон, который краснеет от
# соседа, хуже долгого. По два разом — ровно то, что проверено в CI.
#
# Базы потоков — <BHS_TEST_DB>_s1 … _sN (по умолчанию bhs_crg_test_s1 …), рядом с каждой — базы
# хостов модулей с теми же суффиксами, что всегда. На машине разработчика они остаются лежать, как
# и база обычного прогона.
#
# ⚠️ Сколько дают потоки, решает сервер базы. В CI он работает без fsync, и там это почти линейно;
# на стенде разработчика сервер бережёт данные, потоки ждут диска друг за другом, и выигрыш меньше.
#
# Обычный `dotnet test` этим скриптом НЕ заменён: один класс или один фильтр по-прежнему гоняют им.

set -uo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="$DIR/../src/server/BHS.CRG.Tests/BHS.CRG.Tests.csproj"

NAMESPACE='BHS.CRG.Tests.Integration.'
# Потоки 2, 3, 4 — по строке на поток; первый — всё, что здесь не названо (и все тесты без базы).
# Подобраны по трём прогонам CI 13.11.2026 (PR #1946): разница между ними дала цену переложенных
# групп в CI — G ≈ 55 с (Typst), N ≈ 66, P ≈ 21, H, U, Q и T — единицы. Четвёртый прогон: 177, 159,
# 151 и 121 с. Секундам машины разработчика здесь не верьте: G и N там стоили 11 и 12 с, в профиле
# одним потоком. Шум между прогонами — до полуминуты на поток.
STREAMS=(
    'InvoiceP InvoiceV M G'
    'InvoiceS InvoiceR InvoiceA R S E'
    'A B C D W InvoiceL N'
)
count=$((${#STREAMS[@]} + 1))

# Префиксы не накрывают друг друга — ни в одной строке, ни в разных. Повтор — тоже накрытие.
# ⚠️ Без учёта регистра: так сравнивает сам фильтр (`~` у dotnet test — OrdinalIgnoreCase), и
# «Invoices» рядом с «InvoiceS» отдал бы InvoiceSameFileTests двум потокам.
all_prefixes=()
for line in "${STREAMS[@]}"; do
    # Строка без префиксов — поток без фильтра: `--filter ''` прогнал бы весь набор, повторив все
    # прочие потоки, и отчитался бы зелёным.
    if [ -z "${line//[[:space:]]/}" ]; then
        echo 'backend-tests.sh: в STREAMS строка без префиксов — у потока не было бы фильтра. Уберите строку или впишите префиксы.' >&2
        exit 2
    fi
    # shellcheck disable=SC2206 # строка нарочно разбивается на префиксы
    all_prefixes+=($line)
done
for i in "${!all_prefixes[@]}"; do
    for j in "${!all_prefixes[@]}"; do
        [ "$i" -ne "$j" ] || continue
        p="${all_prefixes[$i]}"; q="${all_prefixes[$j]}"
        case "${q,,}" in "${p,,}"*)
            echo "backend-tests.sh: префикс «$p» накрывает «$q» — классы на «$q» шли бы в двух потоках. Поправьте STREAMS." >&2
            exit 2 ;;
        esac
    done
done

# Фильтры — из одного списка: `~` «содержит», `!~` «не содержит»; названный поток — «любой из его
# префиксов», первый — «ни один из всех». Разойтись они могут только вместе.
filters=('')
for line in "${STREAMS[@]}"; do
    f=''
    for prefix in $line; do
        f="${f:+$f|}FullyQualifiedName~$NAMESPACE$prefix"
        filters[0]="${filters[0]:+${filters[0]}&}FullyQualifiedName!~$NAMESPACE$prefix"
    done
    filters+=("$f")
done

# ── Аргументы ─────────────────────────────────────────────────────────────────────────────────
# `--no-build` и `--shard` — наши, где бы ни стояли: уйди они дальше как есть, `dotnet build`
# отказал бы неизвестным ключом. `--filter` не принимаем вовсе: второй `--filter` в той же команде —
# либо отказ разбора, либо, хуже, молчаливая замена нашего, и тогда все потоки гоняют одно и то же.
build=1; print_filters=0; shard=''; shard_given=0; args=()
take_shard() {
    # Второй ключ — отказ, а не «побеждает последний»: склеенная команда молча прогнала бы не ту долю.
    if [ "$shard_given" -eq 1 ]; then
        echo "backend-tests.sh: --shard назван дважды: «$shard» и «$1»." >&2
        exit 2
    fi
    shard="$1"; shard_given=1
}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --no-build) build=0 ;;
        --filters) print_filters=1 ;;
        --shard) take_shard "${2:-}"; shift ;;
        --shard=*) take_shard "${1#--shard=}" ;;
        --filter|--filter=*|--filter:*)
            echo 'backend-tests.sh: --filter здесь не задаётся — потоки делит сам скрипт.' >&2
            echo 'Один класс или один фильтр гоняют обычным dotnet test … --filter ….' >&2
            exit 2 ;;
        *) args+=("$1") ;;
    esac
    shift
done
# Команда с остальными аргументами в хвосте. Запись — из-за `set -u`: пустой массив в старом bash
# считается неустановленной переменной.
pass() { "$@" ${args[@]+"${args[@]}"}; }

# ── Доля ──────────────────────────────────────────────────────────────────────────────────────
# Битая доля — отказ: молча прогнать все потоки вместо доли значило бы гонять каждый тест дважды
# (по разу на раннер) и выдать это за успех.
selected=()
# Пустое значение — тоже битое: «--shard "$PART"» с забытой переменной гонял бы всё.
if [ "$shard_given" -eq 0 ]; then
    for ((n = 1; n <= count; n++)); do selected+=("$n"); done
else
    # Без ведущих нулей: «08» арифметика bash читает как восьмеричное, и вместо этого отказа вышла бы
    # ошибка оболочки, а «010» молча значило бы восемь.
    if ! [[ "$shard" =~ ^([1-9][0-9]*)/([1-9][0-9]*)$ ]] || [ "${BASH_REMATCH[1]}" -gt "${BASH_REMATCH[2]}" ]; then
        echo "backend-tests.sh: --shard ждёт «доля/всего», например 1/2, а получено «$shard»." >&2
        exit 2
    fi
    index="${BASH_REMATCH[1]}"; parts="${BASH_REMATCH[2]}"
    if [ $((count % parts)) -ne 0 ]; then
        echo "backend-tests.sh: потоков $count, на $parts долей поровну они не делятся. Поправьте STREAMS или число долей в ci.yml." >&2
        exit 2
    fi
    per=$((count / parts))
    for ((n = (index - 1) * per + 1; n <= index * per; n++)); do selected+=("$n"); done
fi

if [ "$print_filters" -eq 1 ]; then
    for n in "${selected[@]}"; do printf '%s\n' "${filters[$((n - 1))]}"; done
    exit 0
fi

# ── Имя базы ──────────────────────────────────────────────────────────────────────────────────
# Потоку дописывается «_s1»…«_s9», а тесты отводят имени базы прогона 39 байт
# (TestDatabases.MaxBaseBytes). Значит здесь BHS_TEST_DB вправе занять 36 — и отказать лучше сразу
# и своими словами: иначе отказ придёт из каждого класса хостов модулей, назовёт имя с суффиксом,
# которого никто не задавал, и предел, которого заданное значение не нарушало.
base="${BHS_TEST_DB:-bhs_crg_test}"
MAX_BASE_BYTES=36
if [ "$(printf %s "$base" | wc -c)" -gt "$MAX_BASE_BYTES" ]; then
    echo "backend-tests.sh: имя базы «$base» длиннее $MAX_BASE_BYTES байт." >&2
    echo 'Потоку дописывается «_sN», и вместе с ним имя не уместится в предел тестов. Укоротите BHS_TEST_DB.' >&2
    exit 2
fi

# Сборка — ОДИН раз и до потоков. Несколько `dotnet test` без --no-build собирали бы один проект
# одновременно и делили бы его obj: отказ пришёл бы не от тестов, а от занятого файла.
if [ "$build" -eq 1 ]; then
    pass dotnet build "$PROJECT" || exit 1
fi

# ── Без доли: доли по очереди ─────────────────────────────────────────────────────────────────
# Каждую долю гоняет этот же скрипт с `--shard`: потоки, итог и уборка — те же, что в CI. Красная
# доля не останавливает следующие — как и поток не останавливает соседа: сначала увидеть всё.
#
# Прерванный прогон гасит долю, которая идёт: без этого TERM убил бы только эту оболочку, а доля
# со своими `dotnet test` осталась бы работать без присмотра — и без вывода.
AT_ONCE=2
if [ "$shard_given" -eq 0 ]; then
    if [ $((count % AT_ONCE)) -ne 0 ]; then
        echo "backend-tests.sh: потоков $count, по $AT_ONCE разом поровну они не делятся. Поправьте STREAMS." >&2
        exit 2
    fi
    waves=$((count / AT_ONCE)); rc=0; child=''
    trap '[ -n "$child" ] && kill -TERM "$child" 2>/dev/null && wait "$child"; exit 143' TERM INT
    for ((k = 1; k <= waves; k++)); do
        bash "${BASH_SOURCE[0]}" --shard "$k/$waves" --no-build ${args[@]+"${args[@]}"} & child=$!
        wait "$child" || rc=1
        child=''
    done
    exit "$rc"
fi

echo "Доля $shard: потоки ${selected[*]} из $count"

logs="$(mktemp -d)"
reported=0
pids=()

# Прервали посреди прогона — отмена шага, таймаут работы, Ctrl-C: гасим потоки и печатаем то, что
# они успели написать. Вывод копится в файлах, и без этого прерванный прогон не оставил бы в логе
# НИЧЕГО — ни упавшего теста, ни места, на котором он встал. А прерывают как раз зависшие.
finish() {
    local n
    if [ "$reported" -eq 0 ]; then
        # Сначала обёртки потоков, потом сами прогоны: обёртка, пережившая свой прогон, дописала бы
        # время в уже снесённый каталог.
        kill ${pids[@]+"${pids[@]}"} 2>/dev/null
        for n in "${selected[@]}"; do
            [ -f "$logs/$n.pid" ] && kill "$(cat "$logs/$n.pid")" 2>/dev/null
        done
        for n in "${selected[@]}"; do
            [ -s "$logs/$n.log" ] || continue
            echo "── Поток $n — вывод до остановки ──"
            cat "$logs/$n.log"
        done
    fi
    rm -rf "$logs"
}
# Одного EXIT хватает: bash зовёт его и тогда, когда оболочку гасят сигналом.
trap finish EXIT

stream() { # stream НОМЕР ФИЛЬТР — в фоне; вывод, время и pid складывает в $logs
    local n="$1" filter="$2" started=$SECONDS rc
    # Язык вывода называем сами: итог потока читается из строки «Total: N», а на машине с русской
    # локалью её бы не нашлось.
    #
    # ⚠️ minimal, а не normal: normal печатает строку на КАЖДЫЙ прошедший тест, и единственный
    # упавший тонет в тысячах строк — лог открывают ровно тогда, когда он красный. Про отказ
    # minimal не теряет ничего: имя теста, Error Message целиком, Stack Trace с файлом и строкой,
    # итоговая сводка. Проверено ломанием сторожа, а не догадкой.
    #
    # Команда — прямо здесь, а не через pass: у функции в фоне $! — это оболочка вокруг неё, и
    # погасить по такому номеру сам `dotnet test` не вышло бы.
    BHS_TEST_DB="${base}_s$n" DOTNET_CLI_UI_LANGUAGE=en \
        dotnet test "$PROJECT" --no-build --filter "$filter" \
        --logger 'console;verbosity=minimal' ${args[@]+"${args[@]}"} > "$logs/$n.log" 2>&1 &
    echo $! > "$logs/$n.pid"
    wait $!
    rc=$?
    echo $((SECONDS - started)) > "$logs/$n.time"
    return $rc
}

for n in "${selected[@]}"; do
    stream "$n" "${filters[$((n - 1))]}" & pids+=($!)
done
codes=()
for pid in "${pids[@]}"; do
    wait "$pid"; codes+=($?)
done

clock() { printf '%d:%02d' $(($1 / 60)) $(($1 % 60)); }

failed=0
report() { # report НОМЕР КОД — вывод потока и его итог
    local n="$1" rc="$2" total spent verdict
    # Число тестов — из итоговой строки `dotnet test`: «… Total:  3092, Duration: …».
    total=$(sed -n 's/.*Total: *\([0-9][0-9]*\).*/\1/p' "$logs/$n.log" | tail -1)
    spent=$(cat "$logs/$n.time" 2>/dev/null || echo 0)

    if [ "$rc" -ne 0 ]; then
        verdict='УПАЛ'
    elif [ "${total:-}" = 0 ] || grep -q 'No test matches the given testcase filter' "$logs/$n.log"; then
        verdict='ПУСТ — ни одного теста, деление по префиксам устарело (STREAMS)'
    elif [ -z "$total" ]; then
        # Не «пуст»: тесты, судя по коду, прошли, но сколько их — не сказано. Причина не в делении,
        # а в виде вывода, и отправлять чинить префиксы было бы неправдой.
        verdict='НЕ РАЗОБРАН — в выводе нет строки «Total: N»: у dotnet test сменился вид итога, правьте разбор в scripts/backend-tests.sh'
    else
        verdict='прошёл'
    fi

    # В Actions вывод прошедшего потока сворачиваем: тысячи строк про успех читать незачем. Упавший
    # оставляем развёрнутым — в свёрнутой группе отказ не видно, пока её не откроешь.
    if [ "$verdict" = 'прошёл' ] && [ "${GITHUB_ACTIONS:-}" = 'true' ]; then
        echo "::group::Поток $n — вывод"
        cat "$logs/$n.log"
        echo '::endgroup::'
    else
        echo "── Поток $n — вывод ──"
        cat "$logs/$n.log"
    fi

    summary="${summary}"$'\n'"Поток $n: ${total:-0} тестов за $(clock "$spent") — $verdict"
    [ "$verdict" = 'прошёл' ] || failed=1
    tests=$((tests + ${total:-0}))
    times+=("$spent")
}

summary=''; tests=0; times=()
for i in "${!selected[@]}"; do
    report "${selected[$i]}" "${codes[$i]}"
done
reported=1

echo "$summary"
echo "Всего тестов: $tests"

if [ "$failed" -ne 0 ]; then
    [ "${GITHUB_ACTIONS:-}" = 'true' ] && echo '::error::Тесты backend не прошли — см. вывод потока, помеченного выше'
    exit 1
fi

# Потоки разъехались — говорим вслух: шаг при этом зелёный, а время потоков в логе зелёного шага
# никто не читает. Не отказ: цена перекоса — секунды, и красить из-за них обязательную проверку
# значило бы останавливать слияния ради замера. Сравниваются потоки, шедшие вместе, — то есть одной
# доли: время другой доли с её раннера сюда не доходит.
slowest=0; fastest=''
for t in "${times[@]}"; do
    [ "$t" -gt "$slowest" ] && slowest=$t
    { [ -z "$fastest" ] || [ "$t" -lt "$fastest" ]; } && fastest=$t
done
skew=$((slowest - fastest))
if [ "$skew" -gt "${BACKEND_TESTS_MAX_SKEW:-30}" ]; then
    note="Потоки тестов backend разъехались на $skew с ($(clock "$fastest") и $(clock "$slowest")): переложите префикс в STREAMS, scripts/backend-tests.sh"
    if [ "${GITHUB_ACTIONS:-}" = 'true' ]; then echo "::warning::$note"; else echo "⚠️ $note"; fi
fi
