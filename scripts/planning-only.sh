#!/usr/bin/env bash
#
# Отвечает, затрагивает ли изменение между двумя ревизиями ТОЛЬКО планирование — `docs/tz/**`
# (ТЗ будущих этапов) и `openspec/**` (спецификации и нарезки):
#
#   planning-only.sh БЫЛО СТАЛО
#     0 — только планирование: CI не нужен, версия не двигается
#     1 — есть хоть один файл вне этих двух каталогов (или изменение пустое) — обычное слияние
#     2 — ответить не удалось (ревизии нет и т.п.); причина — в stderr
#
# Такие PR идут сериями и кода не меняют, а прогон каждого — полный CI и лишний номер версии.
# Проверок содержимого этих каталогов нет НАРОЧНО: владелец от них отказался.
#
# Зовут его трое, и каждый обязан понимать «только планирование» одинаково — поэтому скрипт один:
#   — ci.yml решает, пропускать ли тяжёлые работы (на PR и на push в master);
#   — unbumped-merges.sh — значит и «Повышение версии», и шаг Release «Версия поднята за все
#     слияния» — не считает такое слияние поводом поднять номер.
# Разойдись они, Release отказывал бы на коммите, который бот законно не повысил, — или выпускал бы
# то, что CI не проверял.
#
# Ошибка обязана давать «обычное слияние», а не «только планирование»: лишний прогон CI дешевле
# пропущенного. Поэтому вызывающие считают «да» только код 0 — а код 2 отличают, чтобы отказ
# выглядел отказом, а не молчаливым «нет».

set -uo pipefail

if [ $# -ne 2 ]; then
    echo "planning-only: нужны две ревизии — БЫЛО СТАЛО" >&2
    exit 2
fi

# -z: имена без кавычек и восьмеричных escape — у ТЗ кириллические имена файлов, и с кавычками
# (core.quotepath по умолчанию) строка начиналась бы с `"`, а не с `docs/tz/`: файл ТЗ стал бы
# «чужим». --no-renames: перенос `src/x` в `openspec/y` иначе виден одним новым именем — и
# удаление кода из src прошло бы за правку планирования. --no-relative: unbumped-merges.sh зовёт нас
# из src/server, и при `diff.relative=true` в настройках git пути вне подкаталога из дифа исчезли бы
# — ответ зависел бы от машины, а не от изменения.
if ! files=$(git diff --no-renames --no-relative --name-only -z "$1" "$2" | tr '\0' '\n'); then
    echo "planning-only: git diff $1 $2 не удался" >&2
    exit 2
fi

# Пустое изменение — не «только планирование»: доказательства, что код не тронут, у него нет, а
# ошибаться мы договорились в сторону лишнего прогона.
[ -n "$files" ] || exit 1

while IFS= read -r f; do
    case "$f" in
        docs/tz/*|openspec/*) ;;
        *) exit 1 ;;
    esac
done <<<"$files"
exit 0
