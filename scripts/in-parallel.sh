#!/usr/bin/env bash
#
# Несколько команд одновременно — и один код возврата на всех (issue #1178).
#
#   bash scripts/in-parallel.sh 'Имя ветви' 'команда' ['Имя ветви' 'команда' …]
#
# Команда — строка для `bash -c`; идёт из текущего каталога с `-e` и `pipefail`: отказ на любом
# шаге ветви есть отказ ветви. Код возврата — 0, когда прошли ВСЕ, иначе 1; 2 — позвали не так.
#
# ЗАЧЕМ. Шаги работы в Actions идут строго по очереди, а подготовка живых прогонов состоит из
# частей, которым друг от друга ничего не нужно: сборка сервера, сборка клиента, браузер. По
# очереди это полторы минуты на раннере с четырьмя ядрами, из которых занято одно-два.
#
# Вывод ветвей копится в файлах и печатается после всех, по одной: вперемешку три сборки не
# прочесть. В Actions вывод прошедшей ветви свёрнут, упавшей — развёрнут и стоит последним, рядом
# с итогом. Итог называет каждую ветвь и её время, а каждая строка вывода несёт секунду от начала
# ветви: шаг в интерфейсе теперь один, и без этого было бы не узнать, какая из частей его держит.
#
# ⚠️ Ветви ждут ВСЕ, даже когда одна уже упала: гасить соседей ради полуминуты значило бы получать
# в красном прогоне вывод, оборванный на полуслове, и гадать, упали они сами или их погасили.
#
# ⚠️ Ветви обязаны не мешать друг другу сами: скрипт их не разводит. Две ветви, пишущие в один
# `node_modules` или собирающие один проект, дадут отказ от занятого файла — через раз.

set -uo pipefail

if [ $# -eq 0 ] || [ $(($# % 2)) -ne 0 ]; then
    echo "in-parallel.sh: аргументы идут парами — имя ветви и её команда." >&2
    echo "  bash scripts/in-parallel.sh 'Сервер' 'dotnet publish …' 'Клиент' 'npm ci && npm run build'" >&2
    exit 2
fi

names=(); commands=()
while [ $# -gt 0 ]; do names+=("$1"); commands+=("$2"); shift 2; done

logs="$(mktemp -d)"
pids=()
reported=0

# Каждой ветви — своя группа процессов: команда ветви есть цепочка (`npm ci && npm run build`), и
# погасить по номеру оболочки удалось бы только оболочку — сборка под ней осталась бы работать.
set -m

# Прервали посреди работы — отмена шага, таймаут работы, Ctrl-C: гасим ветви и печатаем то, что они
# успели написать. Вывод копится в файлах, и без этого прерванный шаг не оставил бы в логе НИЧЕГО —
# а прерывают как раз зависшие.
finish() {
    local i
    if [ "$reported" -eq 0 ]; then
        for i in "${!pids[@]}"; do
            kill -- "-${pids[$i]}" 2>/dev/null || kill "${pids[$i]}" 2>/dev/null
        done
        for i in "${!pids[@]}"; do
            [ -s "$logs/$i.log" ] || continue
            echo "── ${names[$i]} — вывод до остановки ──"
            cat "$logs/$i.log"
        done
    fi
    rm -rf "$logs"
}
# Одного EXIT хватает: bash зовёт его и тогда, когда оболочку гасят сигналом.
trap finish EXIT

branch() { # branch НОМЕР — в фоне; вывод и время складывает в $logs
    local i="$1" started=$SECONDS line rc
    # Ввод закрыт: ветвь в фоне, спросившая что-нибудь у терминала, ждала бы ответа вечно.
    #
    # Каждой строке вывода — секунда от начала ветви. Времени шагов в интерфейсе у ветвей нет, а
    # ветвь — цепочка команд: без отметок итог сказал бы «клиент — 0:51» и не сказал бы, что из
    # них держит остальных. Последняя строка без перевода строки не теряется.
    bash -eo pipefail -c "${commands[$i]}" < /dev/null 2>&1 |
        while IFS= read -r line || [ -n "$line" ]; do
            printf '%3d с  %s\n' $((SECONDS - started)) "$line"
        done > "$logs/$i.log"
    rc=${PIPESTATUS[0]}
    echo $((SECONDS - started)) > "$logs/$i.time"
    return $rc
}

started=$SECONDS
for i in "${!names[@]}"; do
    branch "$i" & pids+=($!)
done
# Ждём КАЖДУЮ по её номеру: `wait` без номеров дожидается всех и отвечает нулём, что бы ни вернули
# ветви, — шаг был бы зелёным при упавшей сборке.
codes=()
for i in "${!names[@]}"; do
    wait "${pids[$i]}"; codes+=($?)
done

clock() { printf '%d:%02d' $(($1 / 60)) $(($1 % 60)); }

print() { # print НОМЕР — вывод ветви: прошедшей в Actions — свёрнутым
    local i="$1"
    if [ "${codes[$i]}" -eq 0 ] && [ "${GITHUB_ACTIONS:-}" = 'true' ]; then
        echo "::group::${names[$i]} — вывод"
        cat "$logs/$i.log"
        echo '::endgroup::'
    else
        echo "── ${names[$i]} — вывод ──"
        cat "$logs/$i.log"
    fi
}

# Сначала прошедшие, потом упавшие: отказ должен стоять внизу, у итога, а не над сотнями строк
# чужого успеха.
for i in "${!names[@]}"; do [ "${codes[$i]}" -eq 0 ] && print "$i"; done
for i in "${!names[@]}"; do [ "${codes[$i]}" -ne 0 ] && print "$i"; done
reported=1

failed=''
for i in "${!names[@]}"; do
    spent=$(cat "$logs/$i.time" 2>/dev/null || echo 0)
    if [ "${codes[$i]}" -eq 0 ]; then
        echo "${names[$i]}: $(clock "$spent") — готово"
    else
        echo "${names[$i]}: $(clock "$spent") — ОТКАЗ (код ${codes[$i]})"
        failed="${failed:+$failed, }${names[$i]}"
    fi
done
echo "Все вместе: $(clock $((SECONDS - started)))"

if [ -n "$failed" ]; then
    [ "${GITHUB_ACTIONS:-}" = 'true' ] && echo "::error::Не прошло: $failed — вывод выше, под именем ветви"
    exit 1
fi
