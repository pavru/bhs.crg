#!/usr/bin/env bash
#
# Несколько команд одновременно — и один код возврата на всех (issue #1178).
#
#   bash scripts/in-parallel.sh 'Имя ветви' 'команда' ['Имя ветви' 'команда' …]
#
# Команда — строка для `bash -c`; идёт из текущего каталога с `-e` и `pipefail`: отказ на любом
# шаге ветви есть отказ ветви. Код возврата — 0, когда прошли ВСЕ, иначе 1; 2 — позвали не так.
#
# ЗАЧЕМ. Шаги работы в Actions идут строго по очереди, а подготовка живых прогонов состоит из
# частей, которым друг от друга ничего не нужно: сборка сервера, сборка клиента, браузер. По
# очереди это полторы минуты.
#
# ВЫВОД. Каждая строка ветви печатается СРАЗУ — с именем ветви и секундой от её начала: шаг в
# интерфейсе один, а ветвь — цепочка команд, и без отметок не узнать, что из них держит шаг. В
# Actions это поток вперемешку, свёрнутый в группу. Упавшая ветвь после всех печатается ещё раз,
# целиком и развёрнутой, — внизу, у итога, где её и ищут.
#
# ⚠️ Сразу, а не после всех — нарочно. Отменённый или упавший по таймауту шаг Actions добивает
# SIGKILL всему дереву процессов: никакая уборка в скрипте не успевает, и вывод, отложенный «на
# потом», пропал бы целиком — ровно у зависшей ветви, ради которой лог и открывают.
#
# ⚠️ Ветви ждут ВСЕ, даже когда одна уже упала: гасить соседей ради полуминуты значило бы получать
# в красном прогоне вывод, оборванный на полуслове, и гадать, упали они сами или их погасили.
#
# ⚠️ Ветви обязаны не мешать друг другу сами: скрипт их не разводит. Две ветви, пишущие в один
# `node_modules` или собирающие один проект, дадут отказ от занятого файла — через раз.

set -uo pipefail

if [ $# -eq 0 ] || [ $(($# % 2)) -ne 0 ]; then
    echo "in-parallel.sh: аргументы идут парами — имя ветви и её команда." >&2
    echo "  bash scripts/in-parallel.sh 'Сервер' 'dotnet publish …' 'Клиент' 'npm ci && npm run build'" >&2
    exit 2
fi

names=(); commands=()
while [ $# -gt 0 ]; do names+=("$1"); commands+=("$2"); shift 2; done

actions() { [ "${GITHUB_ACTIONS:-}" = 'true' ]; }

logs="$(mktemp -d)"
pids=()
waited=0

# Каждой ветви — своя группа процессов: команда ветви есть цепочка (`npm ci && npm run build`), и
# погасить по номеру оболочки удалось бы только оболочку — сборка под ней осталась бы работать.
set -m

# Прервали посреди работы — Ctrl-C, TERM от `timeout`: гасим ветви целиком. Вывод печатать не
# нужно, он уже напечатан. SIGKILL сюда не доходит, но он и приходит от Actions вместе с гашением
# всего дерева процессов.
finish() {
    local pid
    if [ "$waited" -eq 0 ]; then
        for pid in ${pids[@]+"${pids[@]}"}; do
            kill -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null
        done
        actions && echo '::endgroup::'
    fi
    rm -rf "$logs"
}
# Одного EXIT хватает: bash зовёт его и тогда, когда оболочку гасят сигналом.
trap finish EXIT

branch() { # branch НОМЕР — в фоне; вывод печатает сразу и копит в $logs, туда же — время
    local i="$1" started=$SECONDS line stamped rc
    # Ввод закрыт: ветвь в фоне, спросившая что-нибудь у терминала, ждала бы ответа вечно.
    # Последняя строка без перевода строки не теряется. Строка печатается ОДНОЙ записью, и
    # строки соседних ветвей не режут друг друга.
    bash -eo pipefail -c "${commands[$i]}" < /dev/null 2>&1 |
        while IFS= read -r line || [ -n "$line" ]; do
            printf -v stamped '%3d с  %s' $((SECONDS - started)) "$line"
            printf '%s\n' "$stamped" >&3
            printf '%s │ %s\n' "${names[$i]}" "$stamped"
        done 3> "$logs/$i.log"
    rc=${PIPESTATUS[0]}
    echo $((SECONDS - started)) > "$logs/$i.time"
    return $rc
}

started=$SECONDS
actions && echo '::group::Ход ветвей — вперемешку, по мере работы'
for i in "${!names[@]}"; do
    branch "$i" & pids+=($!)
done
# Ждём КАЖДУЮ по её номеру: `wait` без номеров дожидается всех и отвечает нулём, что бы ни вернули
# ветви, — шаг был бы зелёным при упавшей сборке.
codes=()
for i in "${!names[@]}"; do
    wait "${pids[$i]}"; codes+=($?)
done
waited=1
actions && echo '::endgroup::'

clock() { printf '%d:%02d' $(($1 / 60)) $(($1 % 60)); }

# Упавшие — ещё раз, целиком и подряд: вперемешку с соседями отказ не прочесть.
for i in "${!names[@]}"; do
    [ "${codes[$i]}" -eq 0 ] && continue
    echo "── ${names[$i]} — вывод ──"
    cat "$logs/$i.log"
done

failed=''
for i in "${!names[@]}"; do
    spent=$(cat "$logs/$i.time" 2>/dev/null || echo 0)
    if [ "${codes[$i]}" -eq 0 ]; then
        echo "${names[$i]}: $(clock "$spent") — готово"
    else
        echo "${names[$i]}: $(clock "$spent") — ОТКАЗ (код ${codes[$i]})"
        failed="${failed:+$failed, }${names[$i]}"
    fi
done
echo "Все вместе: $(clock $((SECONDS - started)))"

if [ -n "$failed" ]; then
    actions && echo "::error::Не прошло: $failed — вывод выше, под именем ветви"
    exit 1
fi
