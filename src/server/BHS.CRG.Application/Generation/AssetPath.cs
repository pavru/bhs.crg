namespace BHS.CRG.Application.Generation;

/// <summary>
/// Путь к материализованному ассету в том виде, в каком его получает шаблон через <c>data.json</c>
/// (issue #513).
///
/// Путь — ОТ КОРНЯ пакета файлов: ведущий «/» в Typst означает корень (компилятор зовётся с
/// <c>--root</c> на временную папку генерации). Это не косметика: <c>image()</c> резолвит путь
/// относительно ФАЙЛА, В КОТОРОМ НАПИСАН ВЫЗОВ, а не относительно того, кто его вызвал. Относительный
/// «assets/img_0.png» поэтому работал, только пока хелпер вроде <c>img()</c> лежал в корне; стоило
/// вынести его в дерево библиотеки — ровно то, ради чего дерево и заводилось (#473), — и картинки
/// пропадали во всех документах с «file not found».
///
/// Проверено на Typst 0.15.1: из вложенного файла дерева относительный путь не находится, а путь от
/// корня компилируется; отладочный бандл при этом не страдает — там <c>template.typ</c> лежит в
/// корне, а корень по умолчанию равен папке входного файла.
/// </summary>
public static class AssetPath
{
    /// <summary>Путь вида <c>/assets/img_0.png</c> — из имени подпапки и имени файла.</summary>
    public static string FromRoot(string assetsSubdir, string fileName) =>
        $"/{assetsSubdir.Trim('/')}/{fileName}";
}
