namespace BHS.CRG.Application.Generation;

/// <summary>
/// Откуда взялся развёрнутый объект (issues #594, #595).
///
/// Резолвер разворачивает ссылку в данные и идентификатор источника при этом теряется: карточка
/// организации в трёх местах документа выглядит как три одинаковых объекта, а не как одна
/// организация, упомянутая трижды. Для генерации PDF это безразлично — шаблону нужны значения, —
/// а внешнему читателю нет: без идентификатора ни свернуть повторы, ни проверить тождество.
///
/// Ключи проставляются ТОЛЬКО по явной просьбе (<c>keepRefProvenance</c>), поэтому в data.json
/// шаблона и в сохранённых данных их по-прежнему нет.
/// </summary>
public static class RefProvenance
{
    /// <summary>Идентификатор записи каталога, развёрнутой на этом месте.</summary>
    public const string EntryIdKey = "_entryId";

    /// <summary>Идентификатор документа, развёрнутого на этом месте.</summary>
    public const string InstanceIdKey = "_instanceId";
}

/// <summary>
/// Почему ссылка осталась неразвёрнутой (issue #723). Сканеру нельзя выдавать одну причину за
/// другую: «цель удалена» и «резолвер сам не пошёл дальше» требуют от человека противоположных
/// действий, а внешне сырой <c>$ref</c> в обоих случаях один и тот же.
///
/// Пометку ставит резолвер в момент отказа; отсутствие пометки означает «цель не нашлась».
/// </summary>
public static class RefUnresolved
{
    /// <summary>Ключ пометки на самом $ref-узле.</summary>
    public const string Key = "$unresolved";

    /// <summary>Резолвер упёрся в предел глубины и оставил ссылку как есть.</summary>
    public const string DepthLimit = "depth-limit";

    /// <summary>
    /// Цель — документ качества, живой, но вне области видимости документа-владельца (issue #733).
    /// Отдельная причина по той же логике, что и предел глубины: искать запись человеку незачем —
    /// она на месте, — и чинится это перемещением документа качества выше по оси, а не поиском.
    /// </summary>
    public const string QualityOutOfScope = "quality-out-of-scope";

    /// <summary>
    /// Документ-источник найден, но поля с таким ключом в его реквизитах нет (issue #762).
    ///
    /// Отдельная причина по той же логике, что предел глубины и документ качества вне области: искать
    /// человеку нечего — документ на месте, — и чинится это заполнением поля, а не поиском пропажи.
    /// Случай самый частый из всех: связать поле «как в АОСР» и заполнить АОСР потом — нормальный
    /// порядок работы, а не поломка.
    /// </summary>
    public const string SourceFieldEmpty = "source-field-empty";
}
