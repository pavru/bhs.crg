namespace BHS.CRG.Application.Generation;

/// <summary>
/// Откуда взялся развёрнутый объект (issues #594, #595).
///
/// Резолвер разворачивает ссылку в данные и идентификатор источника при этом теряется: карточка
/// организации в трёх местах документа выглядит как три одинаковых объекта, а не как одна
/// организация, упомянутая трижды. Для генерации PDF это безразлично — шаблону нужны значения, —
/// а внешнему читателю нет: без идентификатора ни свернуть повторы, ни проверить тождество.
///
/// Ключи проставляются ТОЛЬКО по явной просьбе (<c>keepRefProvenance</c>), поэтому в data.json
/// шаблона и в сохранённых данных их по-прежнему нет.
/// </summary>
public static class RefProvenance
{
    /// <summary>Идентификатор записи каталога, развёрнутой на этом месте.</summary>
    public const string EntryIdKey = "_entryId";

    /// <summary>Идентификатор документа, развёрнутого на этом месте.</summary>
    public const string InstanceIdKey = "_instanceId";
}
