using BHS.CRG.Application.Backup;

namespace BHS.CRG.Application.Settings;

/// <summary>
/// Может ли восстановление копии сменить настройку модуля, у которой есть обработчик смены (E2, issue #1100,
/// spec v3.3 п. 1.9). Смену с экрана обработчик проводит двумя фиксациями и пишет книгу запертым счетам;
/// восстановление идёт одной транзакцией ядра и так не умеет.
///
/// <para>Копия, несущая данные модуля, приносит настройку и записанное ею одним срезом — ей можно. Копия
/// без них сменила бы настройку над ЗДЕШНИМИ данными, то есть провела бы обычную смену без книги: такую
/// смену, если она что-то запишет, восстановление не проводит и называет причину.</para>
///
/// <para>Живёт в приложении: обработчики объявляют модули, а восстановлению (инфраструктура) их не видно.</para>
/// </summary>
public interface IModuleSettingRestoreGuard
{
    /// <param name="before">Значение здесь, в хранимом виде; <c>null</c> — не задано.</param>
    /// <param name="after">Значение из копии, в хранимом виде; <c>null</c> — не задано.</param>
    /// <param name="data">Данные модулей в копии, как их положит восстановление.</param>
    /// <returns>Почему не менять — словами модуля; <c>null</c> — менять можно.</returns>
    Task<string?> RestoreRefusalAsync(
        string key, string? before, string? after, IReadOnlyList<BackupModuleSchema> data, CancellationToken ct = default);
}
