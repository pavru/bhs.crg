namespace BHS.CRG.Application.Settings;

/// <summary>
/// Форма значений настроек «Избранные стройки» (issue #1217, #1218).
///
/// <para>Избранное — фильтр ЭКРАНОВ клиента, а не права (см. CLAUDE.md про <c>CatalogScope</c>):
/// сервер его хранит за человеком, но при выдаче данных не читает нигде. MCP, экспорт, генерация,
/// почта и фоновые задачи остаются без фильтра по построению — им просто неоткуда его взять.</para>
///
/// <para>Чего здесь НЕТ нарочно: проверки, что стройки существуют. Стройку удаляют, а избранное
/// лежит в настройках других людей — сверка при записи всё равно не удержала бы список живым. Живой
/// его делает клиент: избранное пересекается со справочником строек, и «пусто после пересечения»
/// значит «фильтра нет», а не «пустые экраны».</para>
/// </summary>
public static class FavoriteConstructionValues
{
    /// <summary>
    /// Предел избранного. Двадцать — решение владельца (#1217): больше — это уже не «избранное», а
    /// почти весь список, и фильтр перестаёт что-либо отбирать, продолжая выглядеть включённым.
    /// </summary>
    public const int MaxFavorites = 20;

    /// <summary>Длина значения при пределе: двадцать GUID по 36 знаков и девятнадцать запятых.</summary>
    public const int MaxLength = MaxFavorites * 36 + MaxFavorites - 1;

    /// <summary>
    /// Список избранного: GUID через запятую, без пробелов и повторов, от одного до двадцати.
    /// Пустой список не хранится — избранное снимают удалением ключа, как любую настройку: пустая
    /// строка рядом с отсутствием ключа дала бы два способа сказать одно и то же.
    /// </summary>
    public static bool IsList(string value)
    {
        var parts = value.Split(',');
        if (parts.Length > MaxFavorites) return false;

        var seen = new HashSet<Guid>();
        foreach (var part in parts)
            // Строгая форма «D» (36 знаков с дефисами): клиент пишет id ровно так, как получил их от
            // сервера, а вольная форма дала бы два написания одной стройки — и повтор прошёл бы мимо.
            // Длина — отдельно: разбор GUID молча отрезает пробелы по краям, и «a, b» прошло бы.
            if (part.Length != 36 || !Guid.TryParseExact(part, "D", out var id) || !seen.Add(id)) return false;

        return true;
    }
}
