namespace BHS.CRG.Application.Settings;

/// <summary>Что известно про конкретную модель движка.</summary>
public enum ModelState
{
    /// <summary>Проверить не удалось. НЕ «плохо» — просто нечего сказать.</summary>
    Unknown,
    /// <summary>Движок эту модель принимает.</summary>
    Ok,
    /// <summary>Движок отвечает «нет такой модели».</summary>
    Gone,
}

/// <param name="State">Что известно.</param>
/// <param name="Advice">Совет поставщика, если он его дал («перейдите на models/gemini-3.5-flash-lite»).</param>
public record ModelStatus(ModelState State, string? Advice = null)
{
    public static readonly ModelStatus Unknown = new(ModelState.Unknown);
    public static readonly ModelStatus Ok = new(ModelState.Ok);
}

/// <summary>
/// Насколько дорого разрешено отвечать на вопрос «принимает ли поставщик модель» (issue #921).
///
/// Устроено как <see cref="VisionProbe"/>, и по той же причине три значения, а не флаг: кроме «спроси,
/// если не знаешь» нужно «спроси заново». Без него вердикт «модель снята» не пересматривался бы, пока
/// не сменят модель или ключ, — а он не протухает сам (см. <see cref="IRecognitionModelCatalog.GetStatusAsync"/>).
///
/// Цена касается ОБЛАЧНОЙ пробы — она идёт попыткой генерации и оплачивается. Про Ollama каталог
/// отвечает по списку установленных моделей, это дёшево, и режим на неё не влияет.
///
/// Кто и как часто платит — решает вызывающий, а не каталог: каталог не знает ни про расписание
/// мониторинга, ни про экран настроек, и не должен подгонять под них свои сроки.
/// </summary>
public enum ModelProbe
{
    /// <summary>Только кэш. Нет вердикта — «не проверено».</summary>
    CacheOnly,
    /// <summary>Сходить к поставщику, если вердикта нет.</summary>
    IfUnknown,
    /// <summary>Сходить заново, что бы ни лежало в кэше.</summary>
    Refresh,
}

/// <summary>Что известно про ЗРЕНИЕ модели — принимает ли она изображения (issue #801).</summary>
public enum VisionState
{
    /// <summary>Проверить не удалось. НЕ «слепа» — просто нечего сказать.</summary>
    Unknown,
    /// <summary>Модель картинку получила и описала — распознавать ею можно.</summary>
    Sighted,
    /// <summary>Модель ответила, но изображения не увидела.</summary>
    Blind,
}

/// <summary>
/// Насколько дорого разрешено отвечать на вопрос о зрении (issue #801).
///
/// Три значения, а не флаг «можно сходить»: кроме «спроси, если не знаешь», нужен ещё и «спроси
/// заново». Человек, которому система сказала «обновите Ollama», обновляет её и жмёт «Проверить
/// зрение» — а модель, адрес и веса те же, то есть ключ кэша тот же. Двузначным флагом кнопка
/// вернула бы прежний приговор мгновенно и молча, и единственное средство перепроверки оказалось бы
/// пустышкой на всё время жизни записи.
/// </summary>
public enum VisionProbe
{
    /// <summary>Только кэш. Для мест, где ждать нельзя, — например при отрисовке страницы настроек.</summary>
    CacheOnly,
    /// <summary>Спросить движок, если ответа ещё нет. Обычный режим: прогон платит за пробу один раз.</summary>
    IfUnknown,
    /// <summary>Спросить движок заново, что бы ни лежало в кэше. Только по явному действию человека.</summary>
    Refresh,
}

/// <param name="State">Что известно.</param>
/// <param name="Detail">Чем именно ответила модель (для сообщения пользователю и лога).</param>
public record VisionStatus(VisionState State, string? Detail = null)
{
    public static readonly VisionStatus Unknown = new(VisionState.Unknown);
    public static readonly VisionStatus Sighted = new(VisionState.Sighted);
}

/// <summary>
/// Принимает ли движок распознавания ту модель, которая ему назначена (issue #799).
///
/// Нужен потому, что список моделей в настройках — курируемый, и он протухает молча: в живом случае
/// из четырёх предлагавшихся моделей Gemini три отвечали «нет такой модели», а работавшая в списке
/// отсутствовала вовсе. Со стороны пользователя это выглядело как «документ не распознаётся».
///
/// Спрашивать приходится ПОПЫТКОЙ ГЕНЕРАЦИИ, и это проверено, а не выбрано из удобства: перечисление
/// моделей Google (<c>/v1beta/models</c>) и метаданные конкретной модели отдают 200 и для тех
/// моделей, которые на generateContent отвечают 404 с советом перейти на новую. Каталог, построенный
/// на перечислении, объявил бы протухшие модели живыми — то есть промолчал бы ровно там, где от него
/// вся польза. Поэтому проба: один запрос на модель, с ограничением ответа в один токен.
///
/// Ключевое в контракте — <see cref="ModelState.Unknown" />. Это НЕ «плохо»: движок недоступен, ключ
/// не принят, деньги на счёте кончились. Приняв такое за «модели нет», интерфейс пошлёт пользователя
/// чинить не то, что сломано, — и именно так выглядела бы Ollama, которую просто не запустили.
/// </summary>
public interface IRecognitionModelCatalog
{
    /// <summary>
    /// Модели, установленные локально (Ollama); <c>null</c> — спросить не удалось, и это не «ноль
    /// моделей». Для облачных движков всегда <c>null</c>: их каталог не перечисляем (см. описание типа).
    /// </summary>
    Task<IReadOnlyList<string>?> GetInstalledAsync(string engine, IntegrationEngine cfg, CancellationToken ct = default);

    /// <summary>
    /// Принимает ли движок эту модель.
    ///
    /// Срок у вердикта свой, по его виду (issue #921). «Модель снята» НЕ протухает, пока не сменились
    /// движок, модель или ключ: вердикт «нет» из кэша не может превратиться в «не проверено», иначе
    /// проверка, молчащая на «не проверено», через срок кэша объявила бы снятую модель
    /// восстановленной. Пересматривается он только явным <see cref="ModelProbe.Refresh"/>.
    /// «Модель есть» живёт долго, «не проверено» — недолго: это не вердикт, а его отсутствие.
    /// </summary>
    /// <param name="probe">
    /// Насколько дорого разрешено отвечать. Проба стоит секунд и денег, и тратить её надо на ту модель,
    /// с которой работают: замер показал 28 секунд на тринадцать моделей, то есть на открытие страницы
    /// настроек с пометками у каждого пункта списка.
    /// </param>
    Task<ModelStatus> GetStatusAsync(string engine, IntegrationEngine cfg, string model,
        ModelProbe probe = ModelProbe.IfUnknown, CancellationToken ct = default);

    /// <summary>
    /// Распознавание получило от поставщика настоящий «нет такой модели» (issue #923) — записать
    /// вердикт «снята», как записала бы его проба. Наблюдать реальный отказ честнее и дешевле, чем
    /// зондировать: проба стоит денег и идёт раз в часы, а отказ уже случился и уже оплачен.
    ///
    /// Дополнение к плановой пробе, а не замена: простаивающая установка ничего не распознаёт.
    /// Вердикт живёт по тем же правилам, что и полученный пробой, — до смены модели или ключа либо
    /// до пересмотра <see cref="ModelProbe.Refresh"/>, который получит определённый ответ.
    /// </summary>
    void ObserveGone(string engine, IntegrationEngine cfg, string model, string? advice);

    /// <summary>
    /// Видит ли модель изображения — «канарейка зрения» (issue #801, выделено из #481).
    ///
    /// Вопрос отдельный от <see cref="GetStatusAsync" /> и осью отдельной намеренно. Слепая модель —
    /// это <see cref="ModelState.Ok" /> на вопрос «знает ли её поставщик» и «нет» на вопрос «увидит
    /// ли она лист»; слив их в один перечислимый тип, мы заставили бы значения конкурировать, а
    /// каждое место, сравнивающее с <see cref="ModelState.Gone" />, молча забывало бы про слепоту —
    /// то есть завело бы ровно тот молчаливый отказ, ради которого проверка и пишется.
    ///
    /// Проверка нужна потому, что слепота НЕ даёт отказа: gemma4 под ollama 0.32.3 не получала
    /// изображения ни одним из трёх способов, при этом <c>/api/show</c> заявляла
    /// <c>capabilities: ['vision']</c>, а прогон альбома из 16 листов завершался успехом с
    /// правдоподобной выдумкой в каждом поле — 0 совпадений из 106 с эталоном.
    ///
    /// Спрашивается ТОЛЬКО у Ollama; облачным движкам отвечаем <see cref="VisionState.Unknown" />,
    /// никуда не ходя, — как <see cref="GetInstalledAsync" /> отвечает им <c>null</c>. Причина не в
    /// экономии: у облачных модель выбирается из курируемого списка vision-моделей, а незнакомое имя
    /// поставщик отвергает вслух (404, см. #799) — класс отказа там громкий. Появится тихий —
    /// хватит снять это условие.
    /// </summary>
    /// <param name="probe">
    /// Насколько дорого разрешено отвечать. Проба стоит секунд (замер: 6 с у горячей локальной
    /// модели, до полутора минут у холодной), а распознавание вызывается ПОСТРАНИЧНО — на альбоме в
    /// двести листов её нельзя гнать двести раз, потому ответ и кэшируется.
    /// </param>
    Task<VisionStatus> GetVisionAsync(string engine, IntegrationEngine cfg, string model,
        VisionProbe probe = VisionProbe.IfUnknown, CancellationToken ct = default);
}
