namespace BHS.CRG.Application.Settings;

/// <summary>Что известно про конкретную модель движка.</summary>
public enum ModelState
{
    /// <summary>Проверить не удалось. НЕ «плохо» — просто нечего сказать.</summary>
    Unknown,
    /// <summary>Движок эту модель принимает.</summary>
    Ok,
    /// <summary>Движок отвечает «нет такой модели».</summary>
    Gone,
}

/// <param name="State">Что известно.</param>
/// <param name="Advice">Совет поставщика, если он его дал («перейдите на models/gemini-3.5-flash-lite»).</param>
public record ModelStatus(ModelState State, string? Advice = null)
{
    public static readonly ModelStatus Unknown = new(ModelState.Unknown);
    public static readonly ModelStatus Ok = new(ModelState.Ok);
}

/// <summary>
/// Принимает ли движок распознавания ту модель, которая ему назначена (issue #799).
///
/// Нужен потому, что список моделей в настройках — курируемый, и он протухает молча: в живом случае
/// из четырёх предлагавшихся моделей Gemini три отвечали «нет такой модели», а работавшая в списке
/// отсутствовала вовсе. Со стороны пользователя это выглядело как «документ не распознаётся».
///
/// Спрашивать приходится ПОПЫТКОЙ ГЕНЕРАЦИИ, и это проверено, а не выбрано из удобства: перечисление
/// моделей Google (<c>/v1beta/models</c>) и метаданные конкретной модели отдают 200 и для тех
/// моделей, которые на generateContent отвечают 404 с советом перейти на новую. Каталог, построенный
/// на перечислении, объявил бы протухшие модели живыми — то есть промолчал бы ровно там, где от него
/// вся польза. Поэтому проба: один запрос на модель, с ограничением ответа в один токен.
///
/// Ключевое в контракте — <see cref="ModelState.Unknown" />. Это НЕ «плохо»: движок недоступен, ключ
/// не принят, деньги на счёте кончились. Приняв такое за «модели нет», интерфейс пошлёт пользователя
/// чинить не то, что сломано, — и именно так выглядела бы Ollama, которую просто не запустили.
/// </summary>
public interface IRecognitionModelCatalog
{
    /// <summary>
    /// Модели, установленные локально (Ollama); <c>null</c> — спросить не удалось, и это не «ноль
    /// моделей». Для облачных движков всегда <c>null</c>: их каталог не перечисляем (см. описание типа).
    /// </summary>
    Task<IReadOnlyList<string>?> GetInstalledAsync(string engine, IntegrationEngine cfg, CancellationToken ct = default);

    /// <summary>
    /// Принимает ли движок эту модель. Ответ кэшируется на минуты: спрашивают на каждом открытии
    /// настроек, а меняется он раз в месяцы.
    /// </summary>
    /// <param name="probe">
    /// Можно ли ради ответа сходить к поставщику. <c>false</c> — отвечать только из кэша. Проба стоит
    /// секунд, и тратить её надо на ту модель, с которой работают: замер показал 28 секунд на
    /// тринадцать моделей, то есть на открытие страницы настроек с пометками у каждого пункта списка.
    /// </param>
    Task<ModelStatus> GetStatusAsync(string engine, IntegrationEngine cfg, string model,
        bool probe = true, CancellationToken ct = default);
}
