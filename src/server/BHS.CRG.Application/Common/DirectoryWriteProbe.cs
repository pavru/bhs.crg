namespace BHS.CRG.Application.Common;

/// <summary>
/// Проба записи в каталог: можно ли в нём создать файл и убрать его за собой (issue #1135).
///
/// <para>Приложение проверяет так на старте каталог резервных копий и каталог ключей Data Protection:
/// оба монтируются с хоста, и чужой владелец каталога — самый вероятный отказ обеих подсистем. Текст
/// отказа у каждого каталога свой (чем лечить — зависит от каталога), поэтому здесь его нет: проба
/// пропускает исключение ввода-вывода как есть, а называет беду вызывающий.</para>
///
/// <para><b>Имя файла — своё у каждой попытки.</b> С одним именем на всех два приложения, стартующие
/// в одном каталоге разом, пробовали один и тот же файл: второе получало «файл занят другим
/// процессом», и проба читала это как «каталог недоступен для записи» — с советом сменить владельца,
/// который к делу не относился. Так падал случайный интеграционный тест на Windows (два хоста в одном
/// процессе), и так же упал бы второй экземпляр приложения на общем каталоге ключей.</para>
/// </summary>
public static class DirectoryWriteProbe
{
    private const string Prefix = ".write-probe-";

    /// <summary>Создаёт в каталоге пустой файл и удаляет его. Каталог обязан существовать.</summary>
    public static void Run(string directory)
    {
        var probe = Path.Combine(directory, Prefix + Guid.NewGuid().ToString("N"));
        try
        {
            File.WriteAllText(probe, string.Empty);
        }
        finally
        {
            // Удаляем и при отказе записи: файл мог успеть появиться. Несуществующий файл Delete не
            // считает ошибкой, а отказ удалить созданный — такой же повод не стартовать, как отказ
            // создать: свои файлы в этом каталоге приложению потом придётся и убирать.
            File.Delete(probe);
        }
    }
}
