namespace BHS.CRG.Application.Activity;

/// <summary>
/// Вид журнала по коду — ядра и включённых модулей (ТЗ CORE-28.3).
///
/// <para>Службе журнала он нужен дважды: при записи — узнать группу свёртки ПРЕДЫДУЩЕЙ записи цели (в
/// ней лежит только код), при чтении — правило слияния ряда. Каталог модулей служба сама не знает: он
/// собирается в приложении из объявлений, а служба живёт ниже.</para>
/// </summary>
public interface IActivityActionLookup
{
    /// <summary>Вид с этим кодом; <c>null</c> — незнакомый код (переименованный или от выключенного модуля).</summary>
    ActivityAction? Find(string code);
}
