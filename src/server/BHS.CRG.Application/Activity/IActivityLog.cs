using BHS.CRG.Domain.Activity;

namespace BHS.CRG.Application.Activity;

/// <summary>
/// Журнал действий — ОДНА служба на весь продукт (ТЗ CORE-25, CORE-28, issue #950).
///
/// Одна, а не по журналу на подсистему: как только их становится два, они расходятся в главном —
/// в том, что считается автором и что считается временем. Сводить потом два журнала с разными
/// представлениями об авторе — работа, которой не бывает конца. Поэтому журналы изменений отчёта,
/// счёта и разноски, которые появятся в модулях, пишутся сюда же.
///
/// ⚠️ Прямой доступ к набору записей есть ТОЛЬКО у реализации, и это проверяется сторожем
/// (<c>ActivityLogInventoryTests</c>). Причина не в чистоте слоёв: запись мимо службы — это запись
/// без автора и без кода действия из каталога, то есть строка, которую на экране журнала не
/// отличить от испорченной.
///
/// ⚠️ Запись делается ПОСЛЕ того, как действие удалось. Своей транзакции у журнала нет: он
/// сохраняет через тот же контекст базы, и запись, сделанная заранее, осталась бы в журнале даже
/// если само действие потом отказало. Обратная плата названа вслух: падение между действием и
/// записью теряет запись. Из двух ошибок эта — тихая потеря следа — лучше, чем громкое
/// свидетельство о том, чего не было.
/// </summary>
public interface IActivityLog
{
    /// <summary>
    /// Записать действие. Автора и время служба берёт сама — у вызывающего их не спрашивают, иначе
    /// автор стал бы параметром, который можно передать чужой.
    /// </summary>
    Task RecordAsync(ActivityAction action, string? targetId = null, string? targetLabel = null,
        string? before = null, string? after = null, CancellationToken ct = default);

    /// <summary>Страница журнала, новые записи первыми. <paramref name="action" /> — фильтр по коду действия.</summary>
    Task<IReadOnlyList<ActivityRecord>> ReadAsync(int skip, int take, string? action = null,
        CancellationToken ct = default);

    /// <summary>Сколько записей отвечает фильтру: экран показывает «ещё N» и не врёт о конце списка.</summary>
    Task<int> CountAsync(string? action = null, CancellationToken ct = default);

    /// <summary>Последняя запись такого действия — по ней сверяют состояние (состав модулей при старте).</summary>
    Task<ActivityRecord?> LastAsync(ActivityAction action, CancellationToken ct = default);

    /// <summary>Весь журнал для резервной копии (ТЗ CORE-28: записи в копию попадают).</summary>
    Task<IReadOnlyList<ActivityRecord>> ExportAsync(CancellationToken ct = default);

    /// <summary>
    /// Принять записи из резервной копии — со своим временем, автором и идентификатором. Уже
    /// известные идентификаторы пропускаются: восстановление копии на работающий экземпляр не
    /// должно удваивать его собственную историю. Возвращает число добавленных.
    ///
    /// Единственный путь, где время и автор приходят снаружи, — и он отделён от
    /// <see cref="RecordAsync" /> нарочно: смешав их, мы дали бы любому издателю способ подписать
    /// запись чужим именем.
    /// </summary>
    Task<int> ImportAsync(IReadOnlyList<ActivityRecord> records, CancellationToken ct = default);
}
