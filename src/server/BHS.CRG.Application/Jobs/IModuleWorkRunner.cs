namespace BHS.CRG.Application.Jobs;

/// <summary>
/// Кто выполняет фоновую операцию МОДУЛЯ (<see cref="Domain.Jobs.JobKind.ModuleWork" />).
///
/// <para>Абстракция здесь нужна из-за направления ссылок, и по-другому не получается. Фоновый цикл
/// живёт в инфраструктуре, обработчик — в модуле, а сослаться на контракты модулей инфраструктура не
/// может: модулем считается любой проект, сославшийся на них, и ссылка сделала бы модулем весь слой
/// доступа к данным. Поэтому цикл знает только «есть кому выполнить работу модуля», а связывает
/// операцию с обработчиком корень композиции, где и без того перечислены модули.</para>
///
/// <para>⚠️ Служба может быть НЕ зарегистрирована: приложение, собранное без модулей, о работах
/// модулей не знает. Цикл обязан прочитать это как отказ с названной причиной, а не как «сделано»:
/// задача, снятая с очереди и никем не выполненная, выглядела бы успешной.</para>
/// </summary>
public interface IModuleWorkRunner
{
    /// <param name="payload">Аргументы задачи, как их сложила постановка: код операции и то, что
    /// передал модуль. Разбирает их реализация — формат её собственный, и цикл в него не смотрит.</param>
    /// <param name="report">Доклад о ходе: единица, сделано, всего. Тот же, что у операций ядра, —
    /// прореживание по времени уже внутри.</param>
    Task RunAsync(Guid jobId, Guid targetId, Guid userId, string? payload,
        Func<string, int, int, Task> report, CancellationToken ct);
}
