using BHS.CRG.Domain.Documents;
using BHS.CRG.Domain.Schema;

namespace BHS.CRG.Application.Documents;

/// <summary>
/// Типы, скелет которых объявляет САМО ЯДРО (issue #962) — тем же механизмом, что и модули
/// (<see cref="ModuleTypeProjection" />, ТЗ CORE-20.1, CORE-20.2).
///
/// <para><b>Почему скелет от кода, а не «заведёт администратор».</b> ТЗ CORE-19 задаёт
/// «Сотруднику» уровень «расширяемый», а уровень, по CORE-19.1, определяется ПРОИСХОЖДЕНИЕМ поля:
/// запертые поля бывают только у полей модуля или ядра. Тип, заведённый человеком, открыт по
/// определению — и тогда ключ «ТабельныйНомер» переименуем, а вместе с ним ломается выгрузка в
/// бухгалтерию, ради которой справочник и отделён от учётных записей (CORE-7).</para>
///
/// <para><b>Отличие от <see cref="CoreOwnedTypes" />.</b> Тот — список кодов, которые ОДИН раз
/// перешла миграция: типы, заведённые людьми до появления владельца. Здесь — объявление, которое
/// подтверждается КАЖДЫМ стартом и правит схему. Списки не пересекаются по смыслу: «кому
/// принадлежит уже существующее» против «что ядро заводит само».</para>
///
/// <para>⚠️ Состав скелета наращивает заказчик (CORE-7.1), и ядро ему не мешает: уровень
/// «расширяемый» разрешает добавлять свои поля и править их. Заперто ровно то, что читает код.</para>
/// </summary>
public static class CoreRecordTypes
{
    /// <summary>Код справочника сотрудников. По нему ядро находит тип — см. <see cref="Employee" />.</summary>
    public const string EmployeeCode = "Сотрудник";

    /// <summary>Код типа-родителя: лицо любой организации (ТЗ TYPE-7.1).</summary>
    public const string PersonCode = "Персона";

    /// <summary>Код классификатора видов работ. По нему его найдут ссылки — см. <see cref="WorkType" />.</summary>
    public const string WorkTypeCode = "ВидРаботы";

    /// <summary>
    /// Код единого справочника единиц измерения (ТЗ TYPE-7.1, TYPE-Q3).
    ///
    /// <para>Ядро его НЕ заводит: он существует у заказчика потому, что его когда-то завёл человек,
    /// и ТЗ велит «использовать как есть» — один справочник единиц на всю систему. Здесь только
    /// код, которым на него ссылаются.</para>
    /// </summary>
    public const string UnitCode = "ЕдиницаИзмерения";

    /// <summary>
    /// Справочник сотрудников (ТЗ CORE-7, TYPE-7.1, TYPE-9.1).
    ///
    /// <para><b>Производный от «Персоны», а не заведённый рядом.</b> TYPE-7.1 требует этого прямо:
    /// иначе у заказчика оказалось бы два справочника людей, и ФИО пришлось бы объявить второй раз
    /// — через релиз это два разных «ФИО» в одной системе.</para>
    ///
    /// <para><b>Чего здесь нет и почему.</b> «Должность» (перечисление) и «Допуски» (массив
    /// составного типа) из примера TYPE-9.1 объявить кодом НЕЛЬЗЯ: перечисление целится в другой
    /// справочник, а массив цель пока не принимает (<see cref="ModuleFieldSpec.Target" /> — только
    /// <c>complex</c>). Их заводит администратор и размечает тэгами — <c>employee.position</c> и
    /// <c>cert.validUntil</c> для этого и заведены. Самого типа «Допуск» в системе нет, и завести
    /// его кодом было бы нечестно: «обязательно отдельным составным типом» из CORE-7.2 — правило
    /// для человека, и проверкой кода оно не становится.</para>
    ///
    /// <para>⚠️ <b>«УчётнаяЗапись» сегодня некому заполнить, и это осознанно.</b> Связь
    /// необязательная (CORE-7), а действия «связать» в этапе 1 нет: ни эндпоинта, ни кнопки — их
    /// некому было бы проверить. Поле заведено запертым, чтобы ключ и тэг существовали с первого
    /// дня: схему заказчика позже переписывать дороже, чем добавить поведение. Что у поля сегодня
    /// РАБОТАЕТ и проверено — замок: подмена значения обычным сохранением карточки отвергается.</para>
    /// </summary>
    public static ModuleTypeSpec Employee { get; } = new(
        TypeOwner.Core,
        EmployeeCode,
        "Сотрудник",
        SchemaEditLevel.Extendable,
        [
            // Табельный номер заводит ядро, а заполняет ЧЕЛОВЕК — отсюда Locked: false. Запертым он
            // не заполнился бы никогда: кода, который его кладёт, нет и не будет.
            // «identity:1» — номер компонента составного ключа: табельный номер идёт первым, ФИО
            // от «Персоны» следом. Запись «код:параметр» разбирает TagCode; так её пишет и ТЗ.
            new("ТабельныйНомер", "Табельный номер", "string",
                [FunctionalTag.Identity + ":1", FunctionalTag.EmployeePersonnelNumber],
                Required: true, Locked: false),

            new("ПринятС", "Принят с", "date", [FunctionalTag.EmployeeEmployedFrom], Locked: false),
            new("УволенС", "Уволен с", "date", [FunctionalTag.EmployeeEmployedTo], Locked: false),

            new("УчётнаяЗапись", "Учётная запись", "string", [FunctionalTag.EmployeeAccount],
                Locked: true),
        ],
        Group: null,
        Kind: DocumentTypeKind.Composite,
        Parent: PersonCode,
        // На чистой установке «Персоны» нет: её заводил человек, а не код. Отказ старта там
        // означал бы, что новая установка не поднимается вовсе; справочник заведётся сам, как
        // только появится родитель. У уже заведённого «Сотрудника» родитель пропасть не вправе —
        // это по-прежнему отказ.
        SkipWhenBlocked: true);

    /// <summary>
    /// Классификатор видов работ (ТЗ CORE-8, TYPE-7.1, TYPE-9).
    ///
    /// <para><b>Скелет от кода, а не «заведёт администратор»</b> — по той же причине, что у
    /// сотрудника: уровень «расширяемый» из CORE-19 держится на происхождении поля, а тип,
    /// заведённый человеком, открыт по определению. Переименуй кто-нибудь ключ «ВходитВИД» — и
    /// работа перестала бы попадать в исполнительную документацию молча, без единого отказа.</para>
    ///
    /// <para><b>Ссылка на единицу измерения — КОДОМ цели</b> (<see cref="UnitCode" />). ТЗ CORE-8
    /// называет единицу частью классификатора и требует её обязательно, а второй справочник единиц
    /// заводить запрещено (TYPE-7.1): «использовать как есть». Поэтому ссылка идёт на существующий
    /// тип, а найти его в каждой установке можно только по коду — идентификатор везде свой.</para>
    ///
    /// <para><b>Чего здесь нет.</b> «Варианты» из примера TYPE-9 — массив типа «ВариантРаботы»,
    /// которого нет ни в системе, ни в ТЗ: ни схемы, ни читателя. Завести его кодом значило бы
    /// придумать схему за заказчика. Придёт с учётом работ в этапе 2, вместе с тем, кто варианты
    /// читает.</para>
    ///
    /// <para>⚠️ <b>Читающего кода у трёх признаков пока нет</b> — место, материалы и попадание в
    /// ИД спрашивает учёт работ, а он в этапе 2. Поля и тэги заводятся сейчас, чтобы позже не
    /// переписывать схемы у заказчиков; сказано это и в описаниях тэгов в реестре — обещать
    /// разметкой поведение нельзя.</para>
    /// </summary>
    public static ModuleTypeSpec WorkType { get; } = new(
        TypeOwner.Core,
        WorkTypeCode,
        "Вид работы",
        SchemaEditLevel.Extendable,
        [
            // Код и наименование — составной ключ классификатора: по ним позиция сметы и строка
            // отчёта находят вид работы, а не склеиваются по совпадению названия (ТЗ CORE-13 —
            // главная ошибка старой системы, только теперь она была бы в деньгах и сроках).
            new("Код", "Код", "string", [FunctionalTag.Identity + ":1"], Required: true, Locked: false),
            new("Наименование", "Наименование", "string", [FunctionalTag.Identity + ":2"],
                Required: true, Locked: false),

            new("ЕдиницаИзмерения", "Ед. изм.", "complex", Required: true, Locked: false,
                Target: UnitCode),

            new("ТребуетМесто", "Требует указания места", "boolean",
                [FunctionalTag.WorkRequiresLocation], Locked: false),
            new("ТребуетМатериалы", "Требует указания материалов", "boolean",
                [FunctionalTag.WorkRequiresMaterials], Locked: false),
            new("ВходитВИД", "Попадает в исполнительную документацию", "boolean",
                [FunctionalTag.WorkProducesId], Locked: false),
        ],
        Group: null,
        Kind: DocumentTypeKind.Composite,
        // Родителя нет — классификатор ни из чего не выводится.
        Parent: null,
        // На чистой установке справочника единиц ещё нет: его заводит человек. Отказ старта там
        // означал бы, что новая установка не поднимается вовсе; классификатор появится сам, как
        // только появятся единицы. У уже заведённого классификатора цель пропасть не вправе — это
        // по-прежнему отказ старта.
        SkipWhenBlocked: true);

    /// <summary>
    /// Всё, что ядро объявляет. Порядок значим: родитель обязан существовать к моменту проекции
    /// наследника, и типы ядра объявляются раньше типов модулей по той же причине.
    /// </summary>
    public static IReadOnlyList<ModuleTypeSpec> All { get; } = [Employee, WorkType];
}
