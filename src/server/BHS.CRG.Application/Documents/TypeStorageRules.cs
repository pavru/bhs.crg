using BHS.CRG.Application.Common;
using BHS.CRG.Domain.Documents;

namespace BHS.CRG.Application.Documents;

/// <summary>
/// Способ хранения (ТЗ CORE-16, CORE-18) — не пометка, а запрет: объект типа, который модуль
/// держит в СВОЕЙ таблице, общим путём не заводится.
///
/// Почему это запрет, а не соглашение. У записи модуля есть скелет-колонки — статус, период,
/// суммы, — которые общий путь не заполнит; а модуль-владелец о появлении такой записи не узнает,
/// потому что она пришла мимо него. Получилась бы запись, которая выглядит как настоящая и не
/// участвует ни в одной проверке владельца.
///
/// ⚠️ Запрет заведён вместе с признаком, а не после появления первого модуля с записями: иначе
/// первым его потребителем стал бы код, написанный в расчёте на то, что запрета нет. Первый такой
/// тип — счёт модуля затрат.
///
/// <para><b>Где запрет стоит</b> (issue #1215). На ЗАВЕДЕНИИ — в каждом месте, где общий путь
/// создаёт объект: запись справочника, документ комплекта, его копия, профиль уровня (перепись —
/// <c>ClosedTypeCreationInventoryTests</c>). На правке и удалении — у адресов записи справочника
/// (<c>ClosedTypeCommonPathTests</c>). Документные адреса правки и удаления его не спрашивают: это
/// названо в задаче, а не решено здесь.</para>
///
/// <para>Объект закрытого типа в общей таблице через приложение не появляется, но попасть туда
/// может: копией, собранной не этой системой, или прямой правкой базы. Правка и удаление такой
/// строки общим адресом выглядели бы как работа с записью модуля, а её не касались бы вовсе:
/// настоящая запись лежит у владельца.</para>
/// </summary>
public static class TypeStorageRules
{
    /// <summary>
    /// Объекты типа лежат в общей таблице. Один ответ на вопрос «чей носитель» — и для запрета
    /// ниже, и для порта модуля к его справочникам: два условия, написанные порознь («не таблица
    /// модуля» и «общая таблица»), разошлись бы на третьем значении носителя, и молча.
    /// </summary>
    public static bool KeptInCommonTable(DocumentType type) => type.Storage == TypeStorage.SharedObject;

    /// <summary>Бросает <see cref="ConflictException" /> (409), если объект типа общим путём не ведётся.</summary>
    public static void EnsureCommonPathAllowed(DocumentType type, CommonPathAction action = CommonPathAction.Create)
    {
        if (KeptInCommonTable(type)) return;
        // Причина у каждого действия своя: заведённую здесь запись не заполнить, а правка и
        // удаление лежащей здесь строки настоящей записи не касаются.
        var (verb, why) = action switch
        {
            CommonPathAction.Update => ("правится",
                "Правит запись сам модуль: настоящая запись лежит в его таблице, и эта правка её не коснулась бы."),
            CommonPathAction.Delete => ("удаляется",
                "Удаляет запись сам модуль: настоящая запись лежит в его таблице, и это удаление её не коснулось бы."),
            _ => ("заводится",
                "Заводит его сам модуль: у записи есть колонки, которые общий путь не заполнит, а " +
                "владелец о появлении записи не узнал бы."),
        };
        throw new ConflictException(
            $"Объекты типа «{type.Name}» хранит модуль «{type.Module}» в собственной таблице — " +
            $"общим путём такой объект не {verb}. {why}");
    }
}

/// <summary>Что общий адрес собирается сделать с объектом — от этого зависит причина отказа.</summary>
public enum CommonPathAction { Create, Update, Delete }
