using MediatR;

namespace BHS.CRG.Application.Documents;

/// <summary>
/// Запись общих данных ССЫЛКОЙ: то, чем её называют человеку, и ничего больше (issue #1078).
///
/// <para><b>Зачем отдельно от <see cref="ListCommonDataEntriesQuery" />.</b> Тот отдаёт записи
/// целиком, вместе с <c>Data</c>, — и это верно для редактора и для сопоставления по реквизитам. Но
/// выбору позиции из справочника нужны имя и идентификатор, а справочник номенклатуры — самый
/// большой в системе: в одной установке список общих данных весил 5,43 МБ, из них 99,6 % — картинки
/// в base64 (issue #1015). Выпадающий список, тянущий мегабайты картинок на каждый набранный
/// символ, работал бы — и был бы непригоден.</para>
/// </summary>
/// <param name="DisplayName">Название записи. Пустым не бывает у записей, заведённых экраном, но
/// в базе поле допускает <c>null</c> — и подставлять вместо него имя типа здесь нельзя: список
/// показал бы «Номенклатура» вместо «нет названия», то есть соврал бы о данных.</param>
/// <param name="MatchedAlias">Альтернативное имя, по которому запись НАЙДЕНА, — когда искали текст,
/// а в названии его нет (issue #1169). Без него найденное выглядит ошибкой поиска: набрали «ВВГ 3*2.5»,
/// а в списке стоит «Кабель ВВГнг(А)-LS 3х2,5». <c>null</c> — искали не текстом или нашли по
/// названию.</param>
/// <param name="Archived">Запись в архиве (issue #1185). Признак едет ВСЕГДА и стоит обязательным:
/// ссылку показывают человеку, и тот, кто её собирает, обязан решить, что сказать об архиве, — а не
/// получить «не в архиве» значением по умолчанию.</param>
public sealed record CommonDataRef(
    Guid Id, Guid CompositeTypeId, string? DisplayName, bool Archived, string? MatchedAlias = null);

/// <summary>
/// Зачем читают записи справочника: чтобы ВЫБРАТЬ новое значение или чтобы ПОКАЗАТЬ уже стоящее
/// (issue #1185, ТЗ CORE-34.4).
///
/// <para>Архивная запись «из выбора убрана, сохранённые ссылки целы» — то есть один и тот же список
/// обязан отвечать по-разному в зависимости от того, кто спрашивает. Поэтому назначение — обязательный
/// параметр без значения по умолчанию у каждого запроса, отдающего записи списком: умолчание
/// «показывать всё» вернуло бы архивные записи в выбор молча, умолчание «скрывать» — оставило бы
/// сохранённую ссылку без названия.</para>
///
/// <para><b>Почему назначение, а не «показывать / скрывать архив».</b> «Показывать» читается как
/// настройка вида, и следующий автор выберет её, «чтобы ничего не потерять». «Выбор» спрашивает то,
/// что он действительно знает о своём месте.</para>
/// </summary>
public enum RecordsFor
{
    /// <summary>Список, из которого человек или код ВЫБИРАЕТ новое значение. Архивных в нём нет.</summary>
    Choice,

    /// <summary>Показ того, что уже есть: страница справочника, название сохранённой ссылки, сверка.
    /// Архивные на месте, признак — в ответе.</summary>
    Display,
}

/// <summary>
/// Кандидаты на выбор — и сколько записей под тот же запрос лежит в архиве.
///
/// <para>Второе число нужно, чтобы пустой выбор не выглядел как «таких записей нет»: человек,
/// не нашедший поставщика, заведёт его заново — а он есть, в архиве. Отличить одно от другого по
/// пустому списку нельзя, поэтому ответ называет архив сам.</para>
/// </summary>
/// <param name="Items">Живые записи. Архивных здесь нет.</param>
/// <param name="InArchive">Сколько архивных записей подходит под тот же отбор.</param>
public sealed record ChoiceCandidates(IReadOnlyList<CommonDataRef> Items, int InArchive)
{
    public static ChoiceCandidates Empty { get; } = new([], 0);
}

/// <summary>
/// Кандидаты на ВЫБОР из справочника (ТЗ CORE-34): живые записи вида, по части названия.
///
/// <para><paramref name="TypeIds" /> — вид и его подтипы (их разворачивает тот, кто зовёт: вид —
/// свойство записи, а не запроса). <paramref name="Search" /> — часть названия или альтернативного
/// имени, без учёта регистра.</para>
///
/// <para><b>Почему выбор и названия по идентификаторам — два запроса, а не один с параметрами</b>
/// (issue #1185). Раньше это был один запрос: текст — для выбора, идентификаторы — для названий уже
/// стоящих позиций. С архивом они отвечают на разные вопросы: выбор архивную запись скрывает, а
/// название сохранённой ссылки обязано найтись всегда. Один запрос с флагом означал бы, что забытый
/// флаг либо возвращает архив в выбор, либо оставляет строку счёта без названия позиции.</para>
///
/// <para>⚠️ <paramref name="Limit" /> отсекает по названию, а порядок сортировки здесь — БАЗЫ, а не
/// культуры. Разница видна на «Ё» и на латинице, и для отсечения она безобидна, а для показа нет:
/// окончательный порядок задаёт тот, кто показывает список человеку. Без сортировки в базе отсечение
/// вернуло бы произвольные N записей — то есть «этой позиции в справочнике нет» означало бы
/// «не повезло».</para>
/// </summary>
public sealed record SearchCommonDataForChoiceQuery(
    IReadOnlyCollection<Guid> TypeIds,
    string? Search = null,
    int? Limit = null) : IRequest<ChoiceCandidates>;

/// <summary>
/// Названия записей по известным идентификаторам — для ПОКАЗА уже стоящих ссылок: строки счёта
/// ссылаются на номенклатуру, и имён у них нет. Архивные записи здесь на месте, с признаком:
/// сохранённая ссылка на архивную запись цела и обязана читаться.
/// </summary>
public sealed record CommonDataRefsByIdsQuery(
    IReadOnlyCollection<Guid> TypeIds,
    IReadOnlyCollection<Guid> Ids) : IRequest<IReadOnlyList<CommonDataRef>>;
