using BHS.CRG.Domain.Documents;

namespace BHS.CRG.Application.Documents;

/// <summary>
/// Типы, которые переходят ЯДРУ (ТЗ CORE-30). Всё остальное, что было в системе до появления
/// владельца, достаётся модулю исполнительной документации: справочники здесь заводил человек, и
/// принадлежность каждого определяется не кодом, а смыслом — поэтому список ЯВНЫЙ.
///
/// Список — по КОДАМ типов, а не по именам: имя администратор переименовывает («Персона» →
/// «Лицо» по TYPE-7.1), а код постоянен, потому что им адресуются печатные блоки (TYPE-6).
///
/// Как он составлен. Семена названы в ТЗ: организации, лица, стройки, единица измерения, профили
/// уровней. Дальше действует правило «опора ядра — ядро» (<see cref="TypeOwnershipRules" />), и
/// список замкнут по нему: у каждого типа отсюда родитель и вложенные типы тоже отсюда. Замыкание
/// считалось по рабочей базе, а не выдумывалось: догадкой в него не попали бы ни «Угол» (широта
/// координат адреса), ни «Наименование организации».
///
/// ⚠️ Список применяется ОДИН раз — миграцией. Дальше владельца двигает человек
/// (<c>PUT /api/document-types/{id}/module</c>), и переносить его обратно при старте нельзя:
/// это отменяло бы решение администратора молча и каждый раз.
/// </summary>
public static class CoreOwnedTypes
{
    /// <summary>
    /// Коды типов ядра. Порядок — смысловой: сначала семена ТЗ, под каждым его опоры.
    /// </summary>
    public static readonly IReadOnlyList<string> Codes =
    [
        // Организации (семя ТЗ) и то, из чего состоит организация.
        "Организация",
        "НаименованиеОрганизации",   // вложенное поле «Наименование»
        "Адрес",                     // юридический и почтовый адрес; он же адрес стройки
        "ГеографическиеКоординаты",  // вложен в адрес
        "Угол",                      // широта и долгота координат

        // Лица (семя ТЗ). «Персона» — родитель будущего «Сотрудника» (CORE-30).
        "Персона",
        "ФИО",
        "ДополнительнаяХарактеристикаПерсоны",

        // Стройки (семя ТЗ).
        "ОбъектСтроительства",

        // Единый справочник единиц на всю систему (TYPE-Q3, TYPE-7.1).
        "ЕдиницаИзмерения",

        // Профили уровней. Стройка и раздел переходят ядру (CORE-5), поэтому их профили — тоже.
        // ⚠️ Профиль КОМПЛЕКТА сюда не входит: комплект документов — понятие исполнительной
        // документации, и ядру он достался бы только потому, что механизм профилей общий.
        "ПрофильСтройки",
        "ПрофильРаздела",
    ];

    /// <summary>
    /// Владелец всего, что было в системе ДО появления признака и в список ядра не попало. Это
    /// исторический факт, а не умолчание: до первого модуля система целиком была исполнительной
    /// документацией. Новые типы этим значением не заполняются — владельца им называет тот, кто
    /// их заводит.
    /// </summary>
    public const string LegacyOwner = "id";

    /// <summary>Владелец типа по коду — правило миграции и восстановления из старой копии.</summary>
    public static string OwnerFor(string code)
        => Codes.Contains(code, StringComparer.Ordinal) ? TypeOwner.Core : LegacyOwner;
}
