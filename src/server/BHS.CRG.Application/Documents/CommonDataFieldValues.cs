using MediatR;

namespace BHS.CRG.Application.Documents;

/// <summary>
/// Значение ОДНОГО поля записи общих данных — с уже разрешённым наследованием (issue #1077).
///
/// <para><b>Зачем отдельно от списка записей.</b> Сопоставлению по реквизиту (поставщик по ИНН) нужно
/// одно поле у всех записей вида. Список записей целиком тянул бы ради него и логотипы (issue #1015),
/// а главное — отдавал бы собственные данные записи: у записи-роли, которая реквизиты наследует
/// (<c>_baseRef</c>), ИНН в них нет вовсе, и сопоставление отвечало бы «такой организации нет» про
/// организацию, которая в справочнике стоит дважды.</para>
/// </summary>
/// <param name="Value">Значение текстом: строка как есть, число — своей записью. <c>null</c> — поля у
/// записи нет ни своего, ни унаследованного, либо оно пустое.</param>
/// <param name="InheritedFrom">Запись, у которой значение взято, когда оно не своё.</param>
/// <param name="Unreadable">Значение узнать НЕ УДАЛОСЬ: основа удалена, лежит вне области наследника,
/// цепочка замкнулась или в поле лежит не скаляр. Это не «пусто»: по такой записи нельзя сказать ни
/// «совпало», ни «не совпало», и звавший обязан это различить.</param>
public sealed record CommonDataFieldValue(CommonDataRef Record, string? Value, Guid? InheritedFrom, bool Unreadable);

/// <summary>
/// Значения одного поля у записей общих данных названных типов. Назначение обязательно, как у любого
/// списка записей (issue #1185): выбор архивные записи скрывает, показ и сопоставление — отдаёт с
/// признаком.
///
/// <para>Наследование разрешается тем же правилом, что при генерации (<c>EntityResolver</c>): своё
/// поле перекрывает унаследованное, даже пустое; основа обязана лежать в области самого наследника
/// или на уровне системы. Разница одна и нарочная: генерация на негодную основу отвечает «значения
/// нет» — в документе это пустое место, которое человек видит. Здесь тот же ответ читался бы как
/// «не совпало», поэтому негодная основа названа (<see cref="CommonDataFieldValue.Unreadable" />).</para>
/// </summary>
public sealed record CommonDataFieldValuesQuery(
    IReadOnlyCollection<Guid> TypeIds,
    string FieldKey,
    RecordsFor For) : IRequest<IReadOnlyList<CommonDataFieldValue>>;
