namespace BHS.CRG.Application.DataSets;

/// <summary>
/// Откуда берётся параметр доступа (ТЗ CORE-24.1, issue #965).
///
/// <para>Абстракция нужна по той же причине, что <c>IUserPermissions</c> у ворот адресов и
/// <c>INotificationAudience</c> у уведомлений: права считаются через учётные записи, роли и состав
/// включённых модулей — через то, о чём Application не знает и знать не должен. Подставляет сюда
/// свой счётчик слой Api, где объявлены и права, и модули.</para>
///
/// <para><b>Пользователь, а не принципал.</b> На вход идёт идентификатор: параметр доступа нужен и
/// там, где запроса нет вовсе — в фоновой задаче, запущенной человеком. Задание несёт его
/// идентификатор с самого начала (<c>Job.UserId</c>), и именно этим путём пользователь доходит до
/// поставщика. Брать права из токена нельзя (ТЗ AUTH-6): к моменту, когда фоновая сборка доберётся
/// до строк, право может быть уже отозвано.</para>
/// </summary>
public interface IDataAccessResolver
{
    /// <summary>
    /// Параметр доступа человека. Пользователя не нашли — отказ, а не «система»: задание, потерявшее
    /// автора, должно остановиться, а не продолжиться с другими правами.
    /// </summary>
    Task<DataAccess> ForUserAsync(Guid userId, CancellationToken ct);
}
