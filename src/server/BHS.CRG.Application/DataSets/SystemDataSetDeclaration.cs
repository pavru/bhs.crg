namespace BHS.CRG.Application.DataSets;

/// <summary>
/// Насколько узко набор отбирает строки (ТЗ CORE-24.1).
///
/// <para><see cref="Unset" /> — значение по умолчанию, и оно НЕГОДНО: поставщик обязан выбрать, а не
/// промолчать. Без него забытое объявление совпало бы с <see cref="None" /> — «отдаёт всем
/// одинаково» — то есть самое широкое поведение достигалось бы молчанием. Сторож на такое не
/// срабатывает: он не отличает «решили» от «не подумали».</para>
/// </summary>
public enum SystemDataSetIsolation
{
    /// <summary>Не объявлено — отказ при старте.</summary>
    Unset = 0,

    /// <summary>
    /// Без построчной изоляции: у кого есть требуемый ключ, тот видит все строки. Такой набор можно
    /// привязывать к печатной форме и к определению сверки — он одинаков для всех, кто вправе его
    /// читать.
    /// </summary>
    None,

    /// <summary>
    /// Строки отбираются по правам спрашивающего: два человека получают разное. К шаблону печати и к
    /// определению сверки такой набор НЕ подключается (ТЗ CORE-24.1) — два инженера получили бы
    /// разные акты, две находки сверки — разные суммы, и расхождение вскрылось бы после подписи.
    /// </summary>
    PerUser,
}

/// <summary>
/// Объявление системного набора: модуль, требуемый ключ доступа, вид отбора и текст границы выдачи
/// (ТЗ CORE-24.1, CORE-24.3, issue #965).
///
/// <para>Набор без объявления не регистрируется — ядро отказывает при СТАРТЕ, а не отдаёт всё.
/// Проверяется один раз при запуске (<c>ValidateSystemDataSets</c>), потому что отказ на первом
/// чтении означал бы 500 в чужом экране вместо неподнявшегося приложения — уже наступали на этом с
/// реестром тэгов (ревью PR #1012).</para>
/// </summary>
/// <param name="Module">
/// Код модуля-поставщика: <c>core</c> у наборов ядра, <c>id</c> у исполнительной документации.
/// Нужен для отдельной причины «модуль не подключён» (ТЗ CORE-24.3): источник не исчезает, а
/// говорит, чего не хватает, и генерация останавливается с той же причиной.
/// </param>
/// <param name="Requires">
/// Ключ доступа: код права (<c>core.catalog.read</c>) либо код модуля (<c>id</c>), если своего права
/// у данных пока нет — как у библиотеки документов качества, чьи адреса закрыты воротами модуля
/// (ТЗ AUTH-12.2). Второго правила доступа к тем же данным не заводим.
/// </param>
/// <param name="Isolation">Вид отбора строк — обязан быть выбран, см. <see cref="SystemDataSetIsolation" />.</param>
/// <param name="Boundary">
/// Текст границы выдачи — по строке на каждый исход отбора (ТЗ CORE-24.3). Слова принадлежат словарю
/// модуля: «Отдаёт принятые объёмы всех строек — право „факты работ“». Ядро на его месте сочинило бы
/// безликое «показаны доступные вам строки», и человек не узнал бы, чего он не видит.
/// </param>
public sealed record SystemDataSetDeclaration(
    string Module,
    string Requires,
    SystemDataSetIsolation Isolation,
    IReadOnlyList<string> Boundary)
{
    /// <summary>Код ядра: наборы, которые публикует не модуль, а сама система.</summary>
    public const string CoreModule = "core";

    /// <summary>Что не так с объявлением; null — годно.</summary>
    public string? Validate()
    {
        if (string.IsNullOrWhiteSpace(Module)) return "не назван модуль";
        if (string.IsNullOrWhiteSpace(Requires)) return "не назван требуемый ключ доступа (право или модуль)";
        if (Isolation == SystemDataSetIsolation.Unset) return "не объявлен вид отбора строк";
        if (Boundary.Count == 0 || Boundary.Any(string.IsNullOrWhiteSpace))
            return "нет текста границы выдачи — ни одной строки о том, что именно набор отдаёт";
        return null;
    }
}

/// <summary>
/// Ворота опубликованного набора: пускать ли этого спрашивающего к строкам (ТЗ CORE-24.1).
///
/// <para>Проверка идёт при КАЖДОМ чтении строк, а не при создании источника, и заново на каждом
/// пути: предпросмотр, выгрузка, генерация, MCP, сверка. Право отзывают между этими двумя
/// моментами, и источник, проверенный однажды, остался бы открытым навсегда.</para>
///
/// <para>Отказ, а не пустая таблица. Пустая таблица в подписанном акте обнаружится у заказчика, и
/// отличить её от «данных действительно нет» будет нечем (ТЗ CORE-24.3).</para>
/// </summary>
public static class SystemDataSetGate
{
    /// <summary>Бросает отказ, если этому спрашивающему строк не положено.</summary>
    public static void Ensure(SystemDataSetDeclaration declaration, DataAccess access, string setName)
    {
        if (Refusal(declaration, access, setName) is { } refusal) throw refusal;
    }

    /// <summary>
    /// Открыт ли набор — без исключения.
    ///
    /// Нужно там, где набор не открывают, а ПРЕДЛАГАЮТ: список кандидатов в диалоге создания
    /// источника. Кандидат считает свои строки, чтобы показать их число, — то есть предложить набор
    /// значит уже его прочитать. Недоступный набор поэтому не предлагается вовсе: показать его и
    /// отказать на выборе было бы обещанием, а показать с числом строк — той самой утечкой, которую
    /// правило закрывает.
    /// </summary>
    public static bool Allows(SystemDataSetDeclaration declaration, DataAccess access) =>
        Refusal(declaration, access, "") is null;

    /// <summary>Причина отказа или null. Порядок причин — смысловой, см. тело.</summary>
    private static DomainException? Refusal(
        SystemDataSetDeclaration declaration, DataAccess access, string setName)
    {
        var name = string.IsNullOrWhiteSpace(setName) ? "системный набор" : $"Набор «{setName}»";

        // Система проверяется ПЕРВОЙ: у неё нет ни ключей, ни списка модулей, и любая другая проверка
        // ответила бы ей «модуль не подключён» — причиной, которая уведёт разбор в сторону включения
        // модулей вместо настоящего вопроса «зачем служебное задание читает опубликованный набор».
        if (access.IsSystem)
            return new ConflictException(
                $"{name} не читается служебным заданием ({access.SystemReason}): строки отбираются по " +
                "правам человека, а у системы их нет. Задание, запущенное человеком, несёт его до " +
                "поставщика; служебное — опубликованных наборов не читает (ТЗ CORE-24.1).");

        if (declaration.Module != SystemDataSetDeclaration.CoreModule
            && !access.EnabledModules.Contains(declaration.Module))
            return new ConflictException(
                $"{name} публикует модуль «{declaration.Module}», а он не подключён. Источник на нём " +
                "остаётся, но строк не отдаёт, и генерация документа на нём останавливается с этой же " +
                "причиной — пустая таблица в подписанном акте хуже отказа (ТЗ CORE-24.3).");

        if (!access.Allows(declaration.Requires))
            return new ForbiddenException(
                $"{name} отдаёт строки по ключу «{declaration.Requires}», а у «{access.Who}» его нет. " +
                "Это отказ, а не пустая таблица: пустую нельзя отличить от «данных нет».");

        return null;
    }
}
