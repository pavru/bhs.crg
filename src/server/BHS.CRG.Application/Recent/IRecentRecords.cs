namespace BHS.CRG.Application.Recent;

/// <summary>
/// Служба ядра «Недавние» (ТЗ CORE-25.3) — то, что о личных отметках открытия нужно коду вне адресов
/// <c>/api/account/recent</c>. Реализация — рядом с ними (<c>RecentRecords</c> в <c>BHS.CRG.Api</c>).
/// </summary>
public interface IRecentRecords
{
    /// <summary>
    /// Версия шаблона уходит (удаление версии, shell-09, Р-5): её отметки у всех пользователей переходят к
    /// текущей из ОСТАЛЬНЫХ версий того же шаблона (<c>TemplateCurrentVersion</c>), а у кого отмечены обе —
    /// остаётся одна, с поздним открытием. Других версий нет — шаблон уходит целиком, и отметки снимаются:
    /// иначе они занимали бы места предела «Недавних», ничего не показывая.
    ///
    /// <para>Зовётся ДО удаления и пишет в базу сразу, одной командой «вставить или поднять» — открытие той же
    /// версии в другой вкладке тем временем не упирается в ключ и не роняет удаление. Не дошедшее затем
    /// удаление вреда не несёт: отметки стоят на живой версии того же шаблона.</para>
    /// </summary>
    Task TemplateVersionLeavingAsync(Guid versionId, CancellationToken ct);
}

/// <summary>Коды типов записей модуля <c>id</c> — те же, что у его групп «Поиска записей».</summary>
public static class IdRecordTypes
{
    /// <summary>Комплект документов.</summary>
    public const string DocumentSet = "КомплектДокументов";

    /// <summary>Шаблон документа — все его версии одной записью (shell-09, Р-5).</summary>
    public const string Template = "ШаблонДокумента";
}
