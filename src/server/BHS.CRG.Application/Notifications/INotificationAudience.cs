namespace BHS.CRG.Application.Notifications;

/// <summary>
/// Кто получатель: аудитория уведомления считается по правам, а не по роли и не по списку
/// пользователей (ТЗ AUTH-13, CORE-27).
///
/// Отбор идёт ПРИ ЧТЕНИИ, а не при публикации, и это главное решение здесь. Раскладывать
/// уведомление по получателям в момент публикации (как сегодня делают сообщения об обновлении и об
/// ошибках — перебором администраторов) значит заморозить аудиторию: кому право выдали позже,
/// тот не увидит ничего, а у кого отозвали — увидит всё равно. При отборе на чтении список всегда
/// соответствует сегодняшним правам, а «прочитано/скрыто» у каждого своё и так (issue #821).
/// </summary>
public interface INotificationAudience
{
    /// <summary>
    /// Ключи, по которым пользователь считается получателем: его права плюс коды модулей, к которым
    /// у него есть доступ. Аудитория уведомления сверяется с этим набором простым вхождением —
    /// поэтому «право» и «модуль» не нужно различать при чтении и нельзя различить по-разному в
    /// двух местах.
    /// </summary>
    Task<IReadOnlyCollection<string>> KeysForAsync(Guid userId, CancellationToken ct);

    /// <summary>
    /// Объявлена ли такая аудитория: право есть в каталоге прав или это код включённого модуля.
    /// Бросает, если нет.
    ///
    /// Нужно потому, что опечатка в коде права адресует уведомление НИКОМУ, и выглядит это как
    /// успешная отправка: запись создана, в списке её ни у кого нет. Тот же довод, что у ворот на
    /// необъявленное право (AUTH-8.2).
    /// </summary>
    void EnsureDeclared(string audience);
}
