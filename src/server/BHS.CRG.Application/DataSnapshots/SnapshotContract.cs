namespace BHS.CRG.Application.DataSnapshots;

/// <summary>
/// Версия контракта выдач для внешнего агента (issue #590).
///
/// Понадобилась после того, как #577 перевёл часть списков на страницы, а часть оставил голыми
/// массивами: клиент, написанный под массив, получал объект и молча видел ноль записей. Отказ был
/// ТИХИМ — ни ошибки, ни признака, что форма другая, — и поймал его живьём внешний агент, а не тест.
///
/// Поэтому номер едет в каждой страничной выдаче: клиент сравнивает его с тем, под который написан,
/// и следующая смена формы становится заметной сразу, а не через неверный отчёт. Двадцать байт на
/// ответ (не на элемент) — цена, которую эта заметность стоит.
///
/// Номер один на ВЕСЬ контракт MCP, а не на конкретную выдачу: возить его в каждом ответе значило бы
/// платить за поле там, где смотрят одну сущность, а списки агент вызывает в любом сценарии — по
/// первому же из них видно, с какой формой он имеет дело.
///
/// Номер поднимается, когда меняется ФОРМА ответа так, что прежний клиент разберёт её неправильно:
/// переименовано или убрано поле, изменился смысл существующего. Добавление нового поля версию не
/// двигает — оно совместимо, читатель прежних полей его просто не заметит.
/// </summary>
public static class SnapshotContract
{
    /// <summary>
    /// 1 — единая оболочка списков: у всех <c>list_*</c> инструментов ответ вида
    /// <c>{items, offset, limit, total, truncated}</c>, у строк источника — <see cref="RowsPage"/>.
    ///
    /// 2 — у источника вместо одного <c>rowCount</c> два числа с разными именами: <c>rawRowCount</c>
    /// (до обработки) и <c>rowCount</c> (после фильтра, только в <c>get_source</c>) плюс
    /// <c>filtered</c> (#592). Прежнее имя сменило смысл — ровно тот случай, ради которого версия и
    /// заведена: клиент, читающий <c>rowCount</c> сводки источника, теперь не найдёт поля.
    ///
    /// 3 — <c>validate_document</c> отдаёт диагностики ГРУППАМИ (<c>code</c>, <c>message</c>,
    /// <c>count</c>, <c>paths</c>) вместо плоского списка (#597): у элемента <c>diagnostics</c>
    /// больше нет поля <c>path</c>.
    ///
    /// 4 — в развёрнутых реквизитах <c>get_document</c> записи каталога вынесены в словарь
    /// <c>entities</c>, по месту стоит <c>{"$entity":"…"}</c> (#594), а реквизиты других документов
    /// заменены ссылкой <c>{"$document":"…","displayName":"…"}</c> (#595). Клиент, читавший поля
    /// организации прямо в реквизитах, найдёт там ссылку.
    ///
    /// 5 — у наборов появилось <c>scopeName</c> (#593), у источника <c>rowsHash</c>, у строк
    /// <c>rowsHash</c> и <c>unchanged</c>, у документов качества и связей материалов —
    /// <c>updatedAt</c> (#598). Добавления совместимы, но номер поднят вместе с новыми параметрами
    /// <c>ifNoneMatch</c> и <c>changedSince</c>: по нему клиент понимает, что они уже доступны.
    /// </summary>
    public const int Version = 5;
}
