namespace BHS.CRG.Application.DataSnapshots;

/// <summary>
/// Страница списочной выдачи для внешнего агента (issue #576).
///
/// Появилась там, где список растёт вместе со стройкой, а не задан её структурой: документы качества,
/// записи каталога, карта материалов, находки сверки. Прежнее допущение «списки домена навигационные
/// и естественно ограничены» на них не распространяется — восемнадцать документов качества уже дали
/// ответ, который клиент отказался принимать целиком.
///
/// Форма повторяет <see cref="RowsPage"/> сознательно: агент уже умеет обходить строки источников
/// по <c>offset</c>/<c>truncated</c>, и второй способ листать означал бы второй способ ошибиться.
///
/// С #590 эту оболочку носят ВСЕ списочные выдачи, включая навигационные (стройки, наборы, сверки):
/// разделение «эти страничные, а те голым массивом» стоило клиенту тихого нуля записей, и экономия
/// на оболочке коротких списков того не стоит.
/// </summary>
/// <param name="Total">Сколько элементов всего — ДО нарезки. Без него агент не отличит конец списка
/// от конца страницы.</param>
/// <param name="Truncated">За этой страницей есть ещё. Тихое усечение здесь — худший вид отказа:
/// не полученные позиции выглядят как отсутствующие, и вывод получается уверенным и неверным.</param>
public record SnapshotPage<T>(
    IReadOnlyList<T> Items, int Offset, int Limit, int Total, bool Truncated)
{
    /// <inheritdoc cref="SnapshotContract.Version" />
    public int ContractVersion => SnapshotContract.Version;

    /// <summary>
    /// Нарезка УЖЕ упорядоченной последовательности: порядок задаёт вызывающий, потому что от него
    /// зависит устойчивость адреса «страница + позиция» между вызовами.
    ///
    /// Аргументы за границами не считаются ошибкой — агент листает вслепую, и отказ на последней
    /// странице заставлял бы его гадать, где кончился список.
    /// </summary>
    public static SnapshotPage<T> Of(IReadOnlyList<T> ordered, int offset, int limit, int maxLimit)
    {
        var from = Math.Clamp(offset, 0, ordered.Count);
        var take = Math.Clamp(limit, 1, maxLimit);
        var items = ordered.Skip(from).Take(take).ToArray();
        return new(items, from, take, ordered.Count, from + items.Length < ordered.Count);
    }
}
