using BHS.CRG.Domain.Templates;

namespace BHS.CRG.Application.Templates;

/// <summary>
/// Запись новых строк шаблонов — новой версии, нового шаблона, копии — в порядке, которого требует
/// база (id-template-version-integrity, D4), и с отказом гонки, понятным человеку (D5).
/// <para>
/// Частичный уникальный индекс «одна действующая версия» проверяется на каждом операторе, а не в
/// конце транзакции. Вставь новую действующую раньше, чем погашена прежняя, — и запрос упадёт без
/// всякой гонки. Порядок команд внутри одного <c>SaveChanges</c> для фильтрованного индекса EF не
/// гарантирует, а транзакции общий репозиторий не даёт — поэтому узкий метод инфраструктуры.
/// </para>
/// <para>
/// Отказ одного из двух индексов целостности переводится здесь, а не на адресе: так его получает
/// каждый путь записи — адрес, MCP, переход на Код.Имя, — и ни один не ответит на гонку пятисоткой.
/// </para>
/// </summary>
public interface ITemplateVersionWriter
{
    /// <summary>
    /// Сохраняет всё, что вызывающий уже отметил в единице работы (погашенные версии, пересаженные
    /// документы, копии ассетов), и только затем вставляет <paramref name="created" /> — двумя
    /// записями в одной транзакции. Отказ любой из них откатывает обе. Новые строки в единицу работы
    /// заранее не добавляются: их добавляет этот метод.
    /// </summary>
    /// <exception cref="Domain.Common.ConflictException">
    /// Запись проиграла гонку — индекс отверг вторую действующую версию или повторный номер. Текст —
    /// <paramref name="conflictMessage" />. Отвергнутые строки из единицы работы убраны: вызывающий
    /// вправе повторить запись с другими.
    /// </exception>
    Task SaveRetiredThenInsertAsync(
        IReadOnlyCollection<Template> created, string conflictMessage, CancellationToken ct = default);
}
