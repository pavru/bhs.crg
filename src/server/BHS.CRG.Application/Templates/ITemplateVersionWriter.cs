using BHS.CRG.Domain.Templates;

namespace BHS.CRG.Application.Templates;

/// <summary>
/// Запись новых версий шаблона в порядке, которого требует база (id-template-version-integrity, D4).
/// <para>
/// Частичный уникальный индекс «одна действующая версия» проверяется на каждом операторе, а не в
/// конце транзакции. Вставь новую действующую раньше, чем погашена прежняя, — и запрос упадёт без
/// всякой гонки. Порядок команд внутри одного <c>SaveChanges</c> для фильтрованного индекса EF не
/// гарантирует, а транзакции общий репозиторий не даёт — поэтому узкий метод инфраструктуры.
/// </para>
/// </summary>
public interface ITemplateVersionWriter
{
    /// <summary>
    /// Сохраняет всё, что вызывающий уже отметил в единице работы (погашенные версии, пересаженные
    /// документы), и только затем вставляет <paramref name="created"/> — двумя записями в одной
    /// транзакции. Отказ любой из них откатывает обе. Новые версии в единицу работы заранее не
    /// добавляются: их добавляет этот метод.
    /// </summary>
    Task SaveRetiredThenInsertAsync(IReadOnlyCollection<Template> created, CancellationToken ct = default);
}
