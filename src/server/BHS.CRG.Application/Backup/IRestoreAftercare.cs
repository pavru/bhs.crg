namespace BHS.CRG.Application.Backup;

/// <summary>
/// Шаги старта, которые восстановление копии обязано повторить само (issue #1400).
///
/// <para>Типы, объявленные модулями, заводит при старте проекция — и только она. Тип счёта на оплату
/// ссылается полем на справочник организаций, а роль справочника на новой установке назначает как раз
/// восстановление. Без этого шага тип появлялся лишь после перезапуска API: модуль счетов работал без
/// своего типа, и ничто об этом не говорило.</para>
///
/// <para>Порт, а не прямой вызов: проекция живёт в корне композиции — единственном слое, который
/// знает и ядро, и модули (см. <c>ModuleTypeProjector</c>), а восстановление — в инфраструктуре.</para>
/// </summary>
public interface IRestoreAftercare
{
    /// <summary>
    /// Выполнить шаги ПОСЛЕ фиксации восстановления.
    /// </summary>
    /// <param name="warnings">Отчёт восстановления. Сбой шага не отменяет восстановленного — оно уже
    /// зафиксировано, — а называется здесь, с выходом.</param>
    Task RunAsync(List<string> warnings, CancellationToken ct = default);
}
