using System.Data.Common;

namespace BHS.CRG.Application.Backup;

/// <summary>
/// Схемы модулей в резервной копии: чтение и восстановление (задача A2b этапа 2, issue #1073,
/// ТЗ CORE-4, CORE-29).
///
/// <para>Порт, а не класс, потому что данные модуля лежат за границей, которую ядру пересекать
/// нечем: таблицы объявляет контекст модуля, а контракты модулей (<c>BHS.CRG.Modules</c>) для
/// инфраструктуры недоступны — на неё же ссылается модуль, и обратная ссылка сделала бы
/// инфраструктуру модулем в смысле <c>ModuleBoundaryTests</c>. Реализация живёт в корне
/// композиции, рядом с <c>ModuleSchemaMigrator</c>, — единственном месте, где известны и ядро, и
/// модули.</para>
///
/// <para><b>⚠️ Названное исключение из правила «нет общей транзакции ядро↔модуль».</b> Копия обязана
/// быть СНИМКОМ: если схему ядра прочитать в одной транзакции, а схему модуля — в другой, между ними
/// уместится чужая запись, и в копии окажется счёт, ссылающийся на объект, которого в той же копии
/// нет. Поэтому и чтение, и восстановление получают ГОТОВУЮ транзакцию ядра и ходят к таблицам
/// модуля командами на её соединении. Контекст модуля при этом не трогается — от него нужна только
/// модель (issue #1158). Исключение ровно на две операции: во всём остальном правило в силе — см.
/// <c>ModuleDbContext</c>.</para>
///
/// <para>Восстановление в той же транзакции значит и то, что отказ на данных модуля откатывает
/// восстановление ЦЕЛИКОМ. Иначе у заказчика оставалась бы система, где ядро уже новое, а счета —
/// прежние, и отличить это от исправного восстановления нечем.</para>
/// </summary>
public interface IModuleSchemaBackup
{
    /// <summary>
    /// Снять данные схем включённых модулей в рамках уже открытой транзакции ядра.
    /// </summary>
    /// <param name="transaction">Транзакция ядра, в которой читается манифест. Таблицы модуля
    /// читаются ЕЁ соединением — иначе снимок не один.</param>
    /// <param name="warnings">Предупреждения паспорта копии — пополняется на месте. Сюда попадает
    /// выключенный модуль, в схеме которого есть данные: в копию они не входят (issue #1158).</param>
    /// <returns>По записи на модуль, у которого объявлена схема. Пустой массив — модулей со схемой
    /// нет; это не то же, что <c>null</c> в манифесте (там <c>null</c> означает «копия снята
    /// версией, которая схем модулей не знала»).</returns>
    Task<BackupModuleSchema[]> ReadAsync(
        DbTransaction transaction, List<string> warnings, CancellationToken ct);

    /// <summary>
    /// Восстановить данные схем модулей в транзакции ядра — ПОСЛЕ таблиц ядра: строка модуля
    /// адресует объект ядра идентификатором, и до него ссылаться ей не на что.
    /// </summary>
    /// <param name="data">Секции из манифеста. Модуль, которого на этом экземпляре нет или который
    /// выключен, пропускается с предупреждением: данные в копии есть, приложить их некуда. И
    /// обратное: включённый здесь модуль, секции которого в копии нет, тоже назван — если у него есть
    /// данные (issue #1158).</param>
    /// <param name="warnings">Предупреждения отчёта о восстановлении — пополняется на месте.</param>
    /// <returns>Что восстановлено, секциями отчёта: по одной на таблицу модуля.</returns>
    Task<IReadOnlyList<RestoreSectionStat>> RestoreAsync(
        BackupModuleSchema[] data, DbTransaction transaction, List<string> warnings,
        CancellationToken ct);
}
