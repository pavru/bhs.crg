namespace BHS.CRG.Application.QualityDocs;

/// <summary>
/// Составной ключ идентичности объекта (issue #582): склейка ВСЕХ полей с тэгом «Идентификатор»
/// в порядке, заданном параметром тэга.
///
/// До этого ключ создавался по первому непустому полю идентичности, а сопоставлялся по любому из
/// них. Асимметрия допускала две связки на один материал с разными сертификатами и молча выбирала
/// победителя по порядку полей: на живых данных из 151 строки реестра у 49 нашлась связка и по
/// артикулу, и по наименованию, и во всех 49 сертификаты были РАЗНЫЕ — побеждала именная, потому
/// что «Наименование» стоит в схеме раньше «Артикула».
///
/// Составной ключ делает такой конфликт невозможным по построению: у объекта ровно один ключ,
/// выбирать победителя не из чего. Платой становится строгость — позиция, записанная в разных
/// таблицах по-разному, даёт разные ключи. Это осознанное решение: качество данных на стороне
/// пользователя, и он решает — исправить материал или завести две связки.
/// </summary>
public static class IdentityKey
{
    /// <summary>
    /// Разделитель компонентов. Значения приходят уже нормализованными (пробелы схлопнуты), поэтому
    /// последовательность «пробел-черта-пробел» внутри значения практически не встречается, а сам
    /// ключ остаётся читаемым — его видит человек в связках, в бэкапе и в выдаче MCP.
    /// </summary>
    public const string Separator = " | ";

    /// <summary>
    /// Ключ из значений полей идентичности, взятых В ПОРЯДКЕ <paramref name="values" />.
    ///
    /// Пустое поле даёт пустой слот, а не пропускается: позиция компонента в ключе обязана быть
    /// постоянной, иначе материал без артикула и материал без наименования дали бы неразличимые
    /// ключи из одного значения. Пустой слот вдобавок видно глазами — «трубка тут нг 20/10 | »
    /// сразу объясняет, чего в данных не хватает.
    /// </summary>
    public static string From(IEnumerable<string?> values)
        => string.Join(Separator, values.Select(MatchKeyNormalizer.Normalize));

    /// <summary>Ключ из объекта-строки: значения берутся по ключам полей в заданном порядке.</summary>
    public static string From(IReadOnlyList<string> fieldKeys, Func<string, string?> valueOf)
        => From(fieldKeys.Select(valueOf));

    /// <summary>Пуст ли ключ по существу: одни разделители и пробелы — сопоставлять нечего.</summary>
    public static bool IsEmpty(string? key)
        => string.IsNullOrWhiteSpace(key) || key.Replace(Separator, "").Trim().Length == 0;
}
