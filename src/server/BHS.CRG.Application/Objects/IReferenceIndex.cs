namespace BHS.CRG.Application.Objects;

/// <summary>
/// Быстрое сужение: у кого в данных вообще УПОМИНАЮТСЯ эти идентификаторы (issue #745).
///
/// <para><b>Сужение, а не решение.</b> Здесь нет и не должно быть ответа на вопрос «ссылается ли».
/// Ссылок несколько видов, и различия между ними тонкие: <c>_baseRef</c> бывает объектом и голой
/// строкой, у <c>$ref</c> идентификатор лежит то в <c>entryId</c>, то в <c>instanceId</c>, а
/// <c>$ref:"instance"</c> внутри реквизитов документа качества ссылкой НЕ считается вовсе —
/// резолвер её там не разворачивает (issue #735). Уедь хоть одно из этих правил в SQL, и оно
/// разойдётся с тем, которым пользуется генерация: guard начнёт держать лишнее или, что хуже,
/// молча пропускать. Поэтому запрос отбирает строки, где идентификатор встречается ХОТЬ ГДЕ, а
/// решает по-прежнему <see cref="DomainObjectReferences" /> — тот же код, что и раньше, на тех же
/// тестах.</para>
///
/// <para>Отсюда требование к реализации: результат обязан быть НАДМНОЖЕСТВОМ настоящих
/// держателей. Лишняя строка стоит одного разбора JSON в памяти, пропущенная — оборванной ссылки.</para>
///
/// <para>Зачем вообще: до этого обе таблицы-держателя читались целиком и разбирались в памяти на
/// каждую проверку — а проверка стоит перед каждым удалением. Пока данных мало, это меньше
/// мегабайта, но растёт оно вместе с общими данными, и первым почувствует не редкая уборка, а
/// обычное удаление документа.</para>
/// </summary>
public interface IReferenceIndex
{
    /// <summary>Идентификаторы записей <c>domain_objects</c>, в чьих данных встречается любой из <paramref name="ids" />.</summary>
    Task<IReadOnlyList<Guid>> ObjectsMentioningAsync(IReadOnlyCollection<Guid> ids, CancellationToken ct = default);

    /// <summary>То же для реквизитов документов качества.</summary>
    Task<IReadOnlyList<Guid>> QualityDocumentsMentioningAsync(IReadOnlyCollection<Guid> ids, CancellationToken ct = default);
}
