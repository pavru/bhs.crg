namespace BHS.CRG.Application.Objects;

/// <summary>
/// Единственное место, которое меняет признак архива записи справочника (issue #1185, ТЗ CORE-34.4).
///
/// <para><b>Почему служба, а не метод сущности.</b> Запись общих данных сохраняется целиком и без
/// версии, поэтому колонку архива обычное сохранение не пишет вовсе (см. конфигурацию
/// <c>DomainObject</c>). Меняется она отдельным условным обновлением — здесь. Второй писатель
/// колонки вернул бы гонку «правка сняла архив», ради которой всё это и устроено.</para>
///
/// <para>Правил «кому можно» здесь нет: профиль уровня, запись типа, которым владеет модуль, право
/// пользователя — дело того, кто службу зовёт. Одно правило служба держит сама, потому что оно
/// проверяется тем же обновлением: документ в архив не уходит.</para>
/// </summary>
public interface IRecordArchive
{
    /// <summary>
    /// Отправить запись в архив или вернуть из него.
    /// </summary>
    /// <returns>
    /// <c>true</c> — состояние изменилось. <c>false</c> — менять было нечего: запись уже в нужном
    /// состоянии, её нет или это документ. Повтор действия ничего не трогает — дата первого
    /// архивирования остаётся прежней.
    /// </returns>
    Task<bool> SetAsync(Guid id, bool archived, CancellationToken ct = default);

    /// <summary>
    /// Поставить признак как в резервной копии — точными значениями, включая «не в архиве».
    ///
    /// <para>Зовётся только восстановлением и только для копии, которая о признаке ЗНАЕТ: у копии,
    /// снятой прежней версией, «не в архиве» и «поля не было» неразличимы, и применить её значило бы
    /// снять архив со всех записей.</para>
    /// </summary>
    Task RestoreAsync(IReadOnlyDictionary<Guid, DateTimeOffset?> states, CancellationToken ct = default);
}
