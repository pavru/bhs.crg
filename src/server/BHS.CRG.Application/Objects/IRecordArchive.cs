namespace BHS.CRG.Application.Objects;

/// <summary>Чем кончилась попытка отправить запись в архив или вернуть из него.</summary>
public enum ArchiveOutcome
{
    /// <summary>Состояние изменилось.</summary>
    Changed,
    /// <summary>Запись уже в нужном состоянии. Повтор ничего не трогает — дата первого архива прежняя.</summary>
    Unchanged,
    /// <summary>Такой записи нет.</summary>
    NotFound,
    /// <summary>Это документ: архив — для записей справочника.</summary>
    Document,
    /// <summary>Это профиль уровня: на него указывает стройка, раздел или комплект.</summary>
    LevelProfile,
}

/// <summary>
/// Единственное место, которое меняет признак архива записи справочника (issue #1185, ТЗ CORE-34.4).
///
/// <para><b>Почему служба, а не метод сущности.</b> Запись общих данных сохраняется целиком и без
/// версии, поэтому колонку архива обычное сохранение не пишет вовсе (см. конфигурацию
/// <c>DomainObject</c>). Меняется она отдельным условным обновлением — здесь. Второй писатель
/// колонки вернул бы гонку «правка сняла архив», ради которой всё это и устроено.</para>
///
/// <para><b>Два запрета служба держит сама</b>, потому что они проверяются тем же обновлением, что и
/// запись, и обойти их нельзя ни одним путём, включая восстановление копии: документ в архив не
/// уходит, профиль уровня — тоже. Остальное «кому можно» — право пользователя, запись типа, которым
/// владеет модуль, — дело того, кто службу зовёт: у модуля к своим записям путь собственный.</para>
/// </summary>
public interface IRecordArchive
{
    /// <summary>
    /// Отправить запись в архив или вернуть из него. Исход назван явно: адресу действия нужно
    /// отличить «нет такой записи» и «нельзя» от безобидного повтора, не читая запись заранее —
    /// чтение перед обновлением вернуло бы гонку «проверил — изменил».
    /// </summary>
    Task<ArchiveOutcome> SetAsync(Guid id, bool archived, CancellationToken ct = default);

    /// <summary>
    /// Примет ли служба эту запись в архив прямо сейчас: она есть, не документ, не профиль уровня и
    /// ещё не в архиве. Ответ — подсказка экрану («предложить архив вместо удаления»), а не
    /// разрешение: решает по-прежнему <see cref="SetAsync" />, и устаревшая подсказка кончится его
    /// отказом, а не неверной записью.
    /// </summary>
    Task<bool> AllowsAsync(Guid id, CancellationToken ct = default);

    /// <summary>
    /// Поставить признак как в резервной копии — точными значениями, включая «не в архиве».
    ///
    /// <para>Зовётся только восстановлением и только для копии, которая о признаке ЗНАЕТ: у копии,
    /// снятой прежней версией, «не в архиве» и «поля не было» неразличимы, и применить её значило бы
    /// снять архив со всех записей.</para>
    /// </summary>
    /// <returns>
    /// Записи, которые копия называет архивными, а здесь они — профили уровня. Им признак не
    /// поставлен; восстановление обязано об этом сказать, а не промолчать.
    /// </returns>
    Task<IReadOnlyList<Guid>> RestoreAsync(
        IReadOnlyDictionary<Guid, DateTimeOffset?> states, CancellationToken ct = default);

    /// <summary>
    /// Снять признак с объектов, ставших документами. Зовётся восстановлением после документов: копия
    /// может принести документ под идентификатором, под которым здесь лежит архивная запись, — фасета
    /// добавится, а колонку архива сохранение не пишет. Документ в архиве не бывает; побеждает то,
    /// чем объект стал.
    /// </summary>
    /// <returns>Сколько объектов затронуто.</returns>
    Task<int> ClearOnDocumentsAsync(CancellationToken ct = default);
}
