namespace BHS.CRG.Domain.Common;

/// <summary>
/// Ключи совещательных замков PostgreSQL — общий реестр (issue #1081).
///
/// <para>Пространство ключей на базе ОДНО, и делят его все, кто к ней подключён: ядро, модули (их
/// схемы живут в той же базе) и прогон тестов. Два замка с одним ключом — не ошибка, а взаимное
/// ожидание двух несвязанных вещей, и найти его можно только в <c>pg_locks</c>. Поэтому ключи
/// записаны в одном месте, а сторож <c>PeriodClosureInventoryTests</c> сверяет, что они различны.</para>
///
/// <para>⚠️ Занято вне этого файла: <c>1142_2026</c> — замок прогона тестов (<c>TestRunDatabase</c>).
/// Контракты модулей повторяют <see cref="PeriodWrite" /> своей константой
/// (<c>OpenPeriodWrite.LockKey</c>): сослаться сюда им нельзя — ссылок на наши проекты у контрактов
/// нет вовсе. Сверяет их тот же сторож.</para>
/// </summary>
public static class AdvisoryLockKeys
{
    /// <summary>
    /// «Запись в учёт против закрытия периода» (ТЗ CORE-35). Модуль, пишущий запись с учётной
    /// датой, держит замок РАЗДЕЛЯЕМЫМ до конца своей транзакции; закрытие периода берёт его
    /// ИСКЛЮЧИТЕЛЬНЫМ. Так закрытие не проходит между «проверил, что период открыт» и «записал».
    /// </summary>
    public const long PeriodWrite = 1081_2026;

    /// <summary>
    /// «Заведение записи справочника портом модулей» (issue #1077): проверка «записи с таким
    /// значением ещё нет» и создание идут под этим замком, исключительным, до конца транзакции.
    /// Один ключ на все типы: операция редкая.
    /// </summary>
    public const long CatalogIntake = 1077_2026;
}
