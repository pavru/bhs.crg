namespace BHS.CRG.Domain.Common;

/// <summary>
/// Отказ, сформулированный НАМИ: текст написан для пользователя и доходит до него дословно.
///
/// Отдельный тип заведён не ради стройности, а потому что отличить свой отказ от чужого иначе
/// нельзя. Раньше отказы бросались framework-типами (<c>ArgumentException</c>,
/// <c>KeyNotFoundException</c>, <c>InvalidOperationException</c>), а обработчик отдавал их текст
/// клиенту дословно — так и задумано для наших сообщений. Но ровно эти же типы бросают Npgsql, SDK
/// хранилища, Jint и разбор CIDR, и их сообщения называют хост, базу, бакет и имя параметра.
/// Различить их по типу невозможно: тип один и тот же.
///
/// Правило теперь обратное прежнему: наружу дословно уходит ТОЛЬКО потомок этого класса, всё
/// остальное — обобщённый ответ с идентификатором запроса, а подробности в лог. Значит, забыть
/// пометить свой отказ этим типом безопасно (пользователь увидит обобщённый текст), а вот
/// обратная ошибка — пометить им чужое сообщение — требует осознанного действия.
///
/// Код ответа выбирает слой API: здесь называется РОД отказа, а не HTTP-статус — Domain про HTTP
/// не знает и знать не должен.
/// </summary>
public abstract class DomainException(string message) : Exception(message);

/// <summary>Данные запроса недопустимы — исправить может тот, кто их прислал.</summary>
public sealed class InvalidRequestException(string message) : DomainException(message);

/// <summary>
/// Запрошенного объекта нет.
///
/// Сообщение по умолчанию есть, потому что «не найдено» чаще всего бросается без слов: ответ 404
/// говорит сам за себя, и половина мест в коде так и написана — <c>?? throw new NotFoundException()</c>.
/// Раньше в этом случае наружу уходил английский текст фреймворка про отсутствующий ключ словаря.
/// </summary>
public sealed class NotFoundException(string message = "Запрошенный объект не найден.")
    : DomainException(message);

/// <summary>
/// Состояние не допускает операцию: объект занят, имя занято, порядок действий нарушен.
/// Отличается от <see cref="InvalidRequestException" /> тем, что запрос сам по себе правильный —
/// не пускает текущее положение дел.
/// </summary>
public sealed class ConflictException(string message) : DomainException(message);

/// <summary>Действие запрещено этому пользователю.</summary>
public sealed class ForbiddenException(string message) : DomainException(message);
