namespace BHS.CRG.Domain.Common;

/// <summary>
/// Запись ядра, которая только ДОПИСЫВАЕТСЯ: правку и удаление её строк отвергает
/// <c>AppDbContext.SaveChanges</c>. Так живут журнал действий (ТЗ CORE-28) и закрытия учётного
/// периода (ТЗ CORE-35) — всё, что отвечает на вопрос «как было и кто это решил».
///
/// <para>Пометкой на сущности, а не списком в контексте: список пришлось бы вспомнить, заводя
/// таблицу, а пометка стоит там же, где её причина. До закрытий периода защита знала журнал по
/// имени — и вторая дописываемая таблица осталась бы без неё молча (issue #1081).</para>
///
/// <para>⚠️ У модулей пометка СВОЯ — <c>IAppendOnly</c> в контрактах: ядро на контракты модулей не
/// ссылается и ссылаться не может. Два имени одного правила — цена этого направления ссылок.</para>
///
/// <para>⚠️ Чего пометка не закрывает: <c>ExecuteUpdate</c>, <c>ExecuteDelete</c> и голый SQL идут
/// мимо отслеживания изменений. Их ловит перепись обращений к набору по исходникам
/// (<c>ActivityLogInventoryTests</c>, <c>PeriodClosureInventoryTests</c>).</para>
/// </summary>
public interface IAppendOnlyRecord
{
    /// <summary>Как назвать строку в отказе: по ней ищут, какой код её тронул.</summary>
    string AppendOnlyLabel { get; }
}
