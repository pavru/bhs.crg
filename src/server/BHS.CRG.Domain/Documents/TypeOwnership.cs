namespace BHS.CRG.Domain.Documents;

/// <summary>
/// Владелец типа — код модуля, кроме одного значения: <see cref="Core" />.
///
/// Ядро модулем не является и в <c>Modules__Enabled</c> не перечисляется — выключить его нельзя.
/// Отдельный код нужен потому, что владелец обязателен: «пусто» пришлось бы читать как «ядро», а
/// пустое значение появляется и от недозаполненной строки.
/// </summary>
public static class TypeOwner
{
    public const string Core = "core";

    public static bool IsCore(string module) => string.Equals(module, Core, StringComparison.OrdinalIgnoreCase);
}

/// <summary>
/// Где лежат объекты типа (ТЗ CORE-16, CORE-18).
///
/// Признак нужен потому, что механизм типов «описывает форму данных и производит печатные формы»,
/// а носителем хранения становится не всегда (CORE-14): модуль может держать свои записи в
/// собственных таблицах, а тип заводить ради схемы, проверок и печати.
/// </summary>
public enum TypeStorage
{
    /// <summary>Объект общей таблицы (<c>domain_objects</c>) — как хранится всё, что есть сегодня.</summary>
    SharedObject,

    /// <summary>
    /// Запись в таблице модуля. Общим путём такой объект не заводится: у него есть скелет-колонки,
    /// которые общий путь не заполнит, и владелец, который о появлении записи не узнает.
    /// </summary>
    ModuleTable,
}

/// <summary>
/// Видно ли объекты типа за пределами модуля-владельца (ТЗ CORE-18, TYPE-5).
///
/// ⚠️ **Признак управляет порядком, а не тайной.** Того, что показывать нельзя, в общей таблице не
/// держат вовсе: её читают полтора десятка мест, и шесть — прямым запросом мимо слоя доступа.
/// </summary>
public enum TypeVisibility
{
    /// <summary>
    /// Дело модуля-владельца: в общих списках других модулей объекты не показываются. Умолчание
    /// для типа, который объявил модуль, — чтобы чужие типы не засоряли списки.
    /// </summary>
    Closed,

    /// <summary>
    /// Общий тип: объекты видны всем каналам чтения. Так записано состояние дел у всех типов,
    /// которые были в системе до появления признака, — и это не умолчание, а факт: сегодня их
    /// читают все каналы, и запиши мы им «закрыто», признак лгал бы до самого дня, когда начнёт
    /// действовать, а в тот день половина системы погасла бы разом.
    /// </summary>
    Shared,
}
