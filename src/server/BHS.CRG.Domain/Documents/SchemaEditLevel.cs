namespace BHS.CRG.Domain.Documents;

/// <summary>
/// Кто и насколько правит схему типа (ТЗ CORE-19). Уровень — свойство ТИПА, а не класса.
///
/// Смысл среднего уровня — то же правило, что у полевого API: допустимы только добавления. Иначе
/// переименование поля в редакторе типов молча ломает офлайн-клиентов, а чинится это выпуском
/// приложения, а не откатом правки.
///
/// ⚠️ Уровень объявляет МОДУЛЬ для своих типов, а не администратор: иначе замок открывался бы тем
/// же ключом, которым заперт. Поэтому адреса «сменить уровень» нет и не будет — есть только
/// значение, с которым тип заводят. Тип, заведённый человеком в редакторе, всегда
/// <see cref="Open" />: его поля — поля заказчика, запирать в них нечего.
/// </summary>
public enum SchemaEditLevel
{
    /// <summary>Администратор меняет схему как хочет. Так живут все типы, заведённые человеком.</summary>
    Open,

    /// <summary>
    /// Можно добавлять только НЕОБЯЗАТЕЛЬНЫЕ поля и править свои; поля модуля заперты.
    /// </summary>
    Extendable,

    /// <summary>Схему задаёт модуль. Администратору остаётся подпись поля — и печатная форма.</summary>
    Closed,
}
