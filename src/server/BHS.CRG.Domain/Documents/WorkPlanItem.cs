using BHS.CRG.Domain.Common;

namespace BHS.CRG.Domain.Documents;

/// <summary>
/// Позиция перечня работ стройки — якорь, общая точка всех модулей (ТЗ CORE-10, issue #964).
///
/// <para><b>Позиция — это ключ и ничего больше</b>: вид работы, стройка, раздел, единица измерения.
/// Ни объёма, ни цены, ни сроков, ни факта, ни статуса. Объём плана держит смета, даты — график,
/// факт — учёт работ, акт — исполнительная документация; каждый модуль ссылается на позицию и
/// хранит своё мнение о ней у себя.</para>
///
/// <para><b>Почему у неё нет ни одного изменяемого свойства.</b> Все четыре составляющие — это сам
/// ключ: смени любую, и речь пойдёт о другой позиции, а ссылки модулей остались бы висеть на
/// прежней. Поэтому правки нет вовсе — только «найди или создай» и удаление. Сеттеров нет не для
/// строгости, а чтобы такую правку нельзя было написать по невнимательности.</para>
///
/// <para><b>Три правила CORE-11</b>, чтобы позиция не стала свалкой: модули не добавляют в неё своих
/// полей (здесь нет ни схемы, ни JSONB — положить поле физически некуда, и это стережёт
/// <c>WorkPlanItemTests.В_позиции_ничего_кроме_ключа</c>); у позиции нет статуса; удаляется она только когда на неё никто не
/// ссылается (<c>IRecordHolders</c>).</para>
///
/// <para>⚠️ <b>Позиции ПЛОСКИЕ</b> — решение по ТЗ CORE-Q2 (вариант Г, 18.09.2026). Смета на стройку
/// целиком и отчёты по разделам дают РАЗНЫЕ позиции, и они не знают друг о друге: складывает их свод
/// в отчёте, а распределение плана по разделам — мнение сметы (PLAN-5.1), не поле позиции. Дерева
/// здесь нет и заводить его не нужно: складывать в позиции нечего, объёмов она не хранит.</para>
///
/// <para>⚠️ <b>Заводит позицию СЕРВЕР</b> по правилу «найди или создай» из ключа (CORE-12) — и этого
/// правила здесь пока НЕТ: первый вызывающий приходит с импортом сметы в этапе 3, а идемпотентность
/// без вызывающего проверять не на чем (нарезка 20.09.2026). Поэтому в этапе 1 таблица заводится
/// пустой, и ни один путь её не наполняет: телефон и интерфейс позиций не создают — иначе справочник
/// разошёлся бы на шести телефонах в шести написаниях.</para>
/// </summary>
public class WorkPlanItem : Entity
{
    /// <summary>
    /// Запись классификатора видов работ (объект типа <c>ВидРаботы</c>, ТЗ CORE-8).
    ///
    /// <para>Ссылка на запись КЛАССИФИКАТОРА, а не название работы — ТЗ CORE-13. Склейка по
    /// совпадению названия была главной ошибкой старой системы, только теперь она была бы в деньгах
    /// и сроках.</para>
    /// </summary>
    public Guid WorkTypeId { get; private set; }

    /// <summary>Стройка, к перечню которой относится позиция.</summary>
    public Guid ConstructionId { get; private set; }

    /// <summary>
    /// Раздел стройки — или <c>null</c>: «стройка в целом».
    ///
    /// <para>Пусто здесь — не «неизвестно», а полноправное значение: сметы у заказчика бывают на
    /// стройку целиком (CORE-Q2), и запрещать позицию без раздела значило бы делить такие сметы
    /// руками. Поэтому и уникальность ключа считает пустой раздел ЗНАЧЕНИЕМ — см. конфигурацию.</para>
    /// </summary>
    public Guid? SectionId { get; private set; }

    /// <summary>
    /// Единица измерения позиции (объект типа <c>ЕдиницаИзмерения</c>, ТЗ TYPE-7.1 «использовать как
    /// есть»). Часть ключа: «прокладка кабеля, м» и «прокладка кабеля, шт» — разные позиции, и
    /// сложить их в одну означало бы сложить метры со штуками.
    /// </summary>
    public Guid UnitId { get; private set; }

    private WorkPlanItem() { }

    /// <summary>
    /// Позиция по её ключу. Создание — единственный способ задать любую из четырёх составляющих.
    /// </summary>
    public static WorkPlanItem Create(Guid workTypeId, Guid constructionId, Guid? sectionId, Guid unitId)
        => new()
        {
            WorkTypeId = workTypeId,
            ConstructionId = constructionId,
            SectionId = sectionId,
            UnitId = unitId,
        };

    /// <summary>
    /// Позиция из резервной копии — со своим идентификатором и временами. Только для восстановления:
    /// в пустую систему оно обязано вернуть ТЕ ЖЕ идентификаторы, иначе ссылки модулей на позиции
    /// после восстановления указывали бы в пустоту.
    ///
    /// <para>⚠️ При СЛИЯНИИ с непустой системой идентификатор из копии отбрасывается — побеждает
    /// тот, что уже лежит под этим ключом. Так и правильно: таблиц модулей в копии нет, и ссылки на
    /// позицию держат ЖИВЫЕ строки живой системы. Принеси восстановление свой идентификатор — оно
    /// оборвало бы их, починив ссылки, которых в копии не было (разобрано в ревью PR #1056).</para>
    /// </summary>
    public static WorkPlanItem Restore(
        Guid id, Guid workTypeId, Guid constructionId, Guid? sectionId, Guid unitId,
        DateTimeOffset createdAt, DateTimeOffset updatedAt)
        => new()
        {
            Id = id,
            WorkTypeId = workTypeId,
            ConstructionId = constructionId,
            SectionId = sectionId,
            UnitId = unitId,
            CreatedAt = createdAt,
            UpdatedAt = updatedAt,
        };
}
