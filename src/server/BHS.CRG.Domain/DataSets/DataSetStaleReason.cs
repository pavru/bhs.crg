namespace BHS.CRG.Domain.DataSets;

/// <summary>
/// Почему данные источника перестали соответствовать своему происхождению (issue #815).
///
/// Заменяет прежний <c>bool RecognitionStale</c>: носитель у всех причин один — источник, на него
/// смотрит и привязка, и клиент, и действие «Перераспознать», — а вот сказать человеку нужно разное.
/// Причина хранится, а не выводится из данных: устаревание — это СОБЫТИЕ (файл заменили, границы
/// сдвинули, профиль сменили), а не свойство текущего состояния, вычислить его задним числом нельзя.
///
/// Прежде часть причин жила не здесь: <c>DataSetFile.RecognitionStale</c> (колонка без единого
/// писателя в проде) и <c>GostGroupingGroup.TableStale</c>, который снимок читал напрямую, а UI не
/// видел вовсе. Оба обхода сняты — новая причина заводится ЗДЕСЬ и доезжает до обоих потребителей.
/// </summary>
public enum DataSetStaleReason
{
    /// <summary>Файл набора заменён после распознавания — данные относятся к прежнему содержимому.</summary>
    FileReplaced = 1,

    /// <summary>Источник не разобрался против нового файла (лист/путь исчез или сменился формат).
    /// Единственная причина, не связанная с распознаванием: касается парсерных источников.</summary>
    NotParsedAgainstNewFile = 2,

    /// <summary>Состав страниц документа изменился после распознавания таблицы — строки относятся
    /// к прежним границам.</summary>
    TableBoundariesChanged = 3,

    /// <summary>Сменён профиль распознавания — данные получены прежними параметрами чтения.
    /// Распознавание при этом НЕ перезапускается: вызов дорогой, решает пользователь.</summary>
    ProfileChanged = 4,
}
