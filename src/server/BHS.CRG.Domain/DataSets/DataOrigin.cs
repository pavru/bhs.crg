namespace BHS.CRG.Domain.DataSets;

/// <summary>
/// Откуда взялись строки источника. Ключевое различие для доменного правила пользователя «истина в
/// xml, а docx/pdf генерируются»: без него агент примет распознанную vision-моделью таблицу за
/// первоисточник и построит сверку на менее достоверных данных, а человек не узнает, что значение в
/// реквизите документа прочитала модель.
///
/// Живёт в Domain, а не рядом с первым спросившим (снимок для внешней сверки): происхождение — это
/// свойство САМОГО источника, и спрашивают его теперь и снимок, и привязки, и интерфейс.
/// </summary>
public enum DataOrigin
{
    /// <summary>Детерминированный парсинг структурированного файла (XML/CSV/XLSX/JSON).</summary>
    Parsed = 1,

    /// <summary>Извлечено распознаванием (vision-LLM) — данные вероятностные.</summary>
    Recognized = 2,

    /// <summary>Консолидация данных самой системы (документы комплекта и т.п.) — строки собраны
    /// запросом к БД на момент чтения, поэтому детерминированы и никогда не устаревают.</summary>
    System = 3,
}
