namespace BHS.CRG.Domain.Catalog;

/// <summary>
/// Уровень расположения объекта на единой оси (issue #84). Значение enum = приоритет при
/// разрешении иерархии: Set=1 (высший), Section=2, Construction=3, System=5 (низший).
/// </summary>
/// <remarks>
/// <para>
/// <b>Это механизм организации данных и приоритета их разрешения, а НЕ граница безопасности.</b>
/// Уровни выглядят как области видимости, и на них легко сослаться как на разграничение доступа —
/// такого разграничения здесь нет и никогда не было. Привязки данных к пользователю в системе нет
/// вообще: любой вошедший видит и правит объекты всех уровней и всех строек. Так задумано —
/// пользователи системы суть сотрудники одной компании с равным допуском (issue #675, решение
/// от 2026-08-05).
/// </para>
/// <para>
/// <b>Когда это перестанет быть верным.</b> В тот день, когда учётную запись получает кто-то вне
/// компании — заказчик, технадзор, субподрядчик, — изоляция данных становится обязательной и
/// делается ДО всего остального. Это не «добавить колонку»: наследование по поддереву, базовый
/// экземпляр из родительской области, провайдеры системных наборов, библиотека документов
/// качества и инструменты MCP (они действуют правами пользователя) построены на общем
/// пространстве данных, и каждое из этих мест придётся пересматривать.
/// </para>
/// <para>
/// Пока этого не произошло — не выдавайте проверку уровня за проверку прав и не полагайтесь на
/// неё в коде, который решает, что человеку показать.
/// </para>
/// </remarks>
public enum CatalogScope { Set = 1, Section = 2, Construction = 3, System = 5 }
