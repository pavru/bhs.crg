using BHS.CRG.Domain.Common;

namespace BHS.CRG.Domain.Recognition;

/// <summary>
/// Чем кончилось распознавание, которое не дало результата (issue #1077). Вид причины нужен тому,
/// кто показывает отказ человеку: чинятся они по-разному, и общий совет «проверьте настройки»
/// во втором и третьем случае отправлял бы искать то, что и так на месте.
/// </summary>
public enum RecognitionRefusal
{
    /// <summary>Распознавать некому: нет включённого и настроенного движка либо все они слепы.
    /// Чинит администратор в настройках; повтор без этого даст то же самое.</summary>
    NotConfigured,

    /// <summary>Движки есть, но ни один не справился: недоступен, исчерпал лимит, не уложился в
    /// срок. Повтор позже имеет смысл.</summary>
    Unavailable,

    /// <summary>Движок ответил, а ответа в ответе не было: пусто, проза вместо данных, ни одного
    /// значения. Файл, скорее всего, не тот документ или нечитаем.</summary>
    NoAnswer,
}

/// <summary>
/// Распознавание не дало результата — и говорит об этом отказом, а не пустыми полями.
///
/// <para>Пустой результат и отказ различает ТИП, а не содержимое: словарь с ключами и пустыми
/// значениями неотличим от «модель прочитала и ничего не нашла», и получатель разложил бы его по
/// полям записи как распознанное. Отказ, переодетый в результат, интерфейс показать не может.</para>
///
/// <para>Доменный — текст наш и адресован человеку: его показывают и ответ на запрос, и запись
/// фоновой задачи.</para>
/// </summary>
public sealed class RecognitionRefusedException(RecognitionRefusal reason, string message, Exception? inner = null)
    : InvalidRequestException(message, inner)
{
    public RecognitionRefusal Reason { get; } = reason;

    /// <summary>Через сколько секунд движок советует повторить (исчерпан лимит); иначе <c>null</c>.</summary>
    public int? RetryAfterSeconds { get; init; }
}
