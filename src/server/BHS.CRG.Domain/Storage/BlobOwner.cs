namespace BHS.CRG.Domain.Storage;

/// <summary>
/// Чей файл хранилища (ТЗ CORE-37.2): ядра или модуля. Владелец модуля — его код
/// (<c>costs</c>, <c>work</c>), отдельной константы ему не нужно.
///
/// <para>Строка, а не перечисление: модули объявляет поставка, и ядро их кодов не знает. Код модуля
/// «core» невозможен — им названы права ядра (<c>core.*</c>), и порт файлов отказывает такому модулю на
/// старте.</para>
/// </summary>
public static class BlobOwner
{
    /// <summary>Файл ядра: вложение, ассет шаблона, сформированный PDF, файл набора данных.</summary>
    public const string Core = "core";

    /// <summary>
    /// «Любой владелец» — НЕ значение записи, а вопрос резервной копии: она переносит файлы всех
    /// владельцев и потому читает мимо проверки. Перепись читателей хранилища
    /// (<c>BlobReaderInventoryTests</c>) пускает этот маркер только в файлы копии.
    /// </summary>
    public const string Any = "*";

    /// <summary>Предел длины кода в реестре: код модуля короче, предел — с запасом.</summary>
    public const int MaxLength = 64;
}
