using System.ComponentModel;
using BHS.CRG.Application.DataSnapshots;
using ModelContextProtocol;
using ModelContextProtocol.Server;

namespace BHS.CRG.Api.Mcp;

/// <summary>
/// Промпты сверки (issue #429) — NL-фасад над рабочим сценарием пользователя: подготовил комплект,
/// попросил агента проверить на непротиворечивость, получил отчёт.
///
/// Принцип тот же, что принят для распознавания (#405): <b>промпты пишем мы, пользователь задаёт
/// параметр</b>. Здесь параметр ровно один — комплект.
///
/// Содержимое — накопленное доменное знание о том, что в исполнительной документации значит
/// «непротиворечивость», и правила, без которых отчёт становится вредным: неполная выборка даёт ложные
/// находки, распознанные данные нельзя судить как разобранные, находка без адреса непроверяема.
/// </summary>
[McpServerPromptType]
public class ReconciliationPrompts(IDomainSnapshotService domain)
{
    /// <summary>
    /// Правила, общие для обоих промптов. Вынесены, потому что расхождение между ними означало бы, что
    /// один отчёт аккуратен, а другой выдумывает — при внешне одинаковой постановке задачи.
    /// </summary>
    private const string CommonRules = """
        Обязательные правила работы с данными:

        1. Полнота. У строк источников выборка страничная. Всегда сверяйте totalRows с числом
           полученных строк и продолжайте, пока truncated = true. Анализ по неполной выборке даёт
           ЛОЖНЫЕ находки: недополученные позиции выглядят как отсутствующие.

        2. Происхождение. Поле origin различает Parsed и Recognized. Parsed — детерминированный разбор
           XML/CSV/XLSX, расхождение здесь означает расхождение в самих данных. Recognized — извлечено
           зрительной моделью из PDF, и расхождение прежде всего кандидат в ошибку распознавания, а не
           в ошибку документа. Формулируйте такие находки соответственно.

        3. Свежесть. Поле stale означает, что данные могли устареть относительно текущего содержимого
           файла; staleReason говорит почему. Упоминайте это, а не выдавайте устаревшее за текущее.

        4. Адресация. Каждая находка должна быть проверяема глазами:
           - для документа — его идентификатор, наименование и путь поля;
           - для строки — идентификатор источника, смещение строки и имя колонки;
           - для табличных источников из PDF — якорь sheet (шифр и номера страниц исходного листа).

        5. Не выдумывайте. Чего в полученных данных нет — того нет. Отсутствие данных сообщайте как
           отсутствие данных, а не как нарушение. Если для вывода не хватает сведений, скажите, каких
           именно, и каким инструментом их можно получить.

        6. Ссылки в реквизитах. get_document по умолчанию разворачивает ссылки на каталог. Если нужно
           сравнить тождество (та же организация или разные), запросите resolveRefs=false и
           сопоставляйте entryId — это надёжнее, чем сравнение строк с именами.
        """;

    /// <summary>Контекст комплекта в текст промпта: без имён стройки и раздела агент начинает
    /// с уточняющих вопросов вместо работы.</summary>
    private async Task<DocumentSetDetail> SetOrThrowAsync(Guid setId, CancellationToken ct)
        => await domain.GetDocumentSetAsync(setId, ct)
           ?? throw new McpException($"Комплект не найден: {setId}");

    [McpServerPrompt(Name = "reconcile_document_set", Title = "Сверка комплекта на непротиворечивость")]
    [Description("Проверить документы комплекта и связанные данные на внутренние расхождения и составить отчёт.")]
    public async Task<string> ReconcileDocumentSetAsync(
        [Description("Идентификатор комплекта документов.")] Guid setId, CancellationToken ct)
    {
        var set = await SetOrThrowAsync(setId, ct);
        return $"""
            Проверь на внутреннюю непротиворечивость комплект исполнительной документации
            «{set.Name}» (раздел {set.SectionName}, стройка {set.ConstructionName}).
            Идентификатор комплекта: {setId}. Документов в комплекте: {set.Documents.Count}.

            Начни с get_document_set, дальше разбирайся сам, какие данные нужны.

            Что сопоставлять:

            - Организации и лица. Одна и та же организация под разными названиями в разных документах.
              Представитель, подписывающий от организации, которой в этом акте нет. Лицо, фигурирующее
              в документе, но отсутствующее в каталоге.

            - Номера и даты. Номер документа в реестре против номера самого документа. Дата акта
              раньше даты начала работ. Пропуски и дубли в нумерации документов комплекта.

            - Материалы и документы качества. Позиция кабельного журнала, отсутствующая в ведомости
              материалов, и наоборот. Сертификат, указанный в реестре документов качества, но не
              привязанный в системе — это прямое сопоставление list_material_quality_links (что
              подставит система) с get_rows соответствующего источника (что написано в файлах).

            - Реестры. Реестр исполнительной документации перечисляет документы, которых в комплекте
              нет, — или комплект содержит документы, в реестре не перечисленные.

            {CommonRules}

            Отчёт: сгруппируй находки по видам выше, каждую с адресом и с указанием, насколько она
            достоверна (расхождение в разобранных данных против кандидата в ошибку распознавания).
            Отдельно перечисли, что проверить не удалось и почему.
            """;
    }

    [McpServerPrompt(Name = "check_set_readiness", Title = "Готовность комплекта к выпуску")]
    [Description("Проверить каждый документ комплекта средствами системы и сказать, что мешает выпуску.")]
    public async Task<string> CheckSetReadinessAsync(
        [Description("Идентификатор комплекта документов.")] Guid setId, CancellationToken ct)
    {
        var set = await SetOrThrowAsync(setId, ct);
        return $"""
            Проверь готовность к выпуску комплекта «{set.Name}»
            (раздел {set.SectionName}, стройка {set.ConstructionName}). Идентификатор: {setId}.

            Обойди документы комплекта через get_document_set и проверь КАЖДЫЙ через validate_document.
            Это проверка самой системы — цитируй её, а не рассуждай самостоятельно о том, что с
            документом не так.

            Сводка по каждому документу: наименование, тип, статус, число ошибок и предупреждений.
            Ошибка блокирует выпуск, предупреждение нет. Для каждой ошибки укажи код и путь поля;
            однотипные проблемы уже сгруппированы — приводи count, а не перечень одинаковых строк.

            Затем скажи одной строкой: сколько документов готовы к выпуску, сколько заблокировано, и
            перечисли самые частые причины блокировки — по ним обычно чинится сразу несколько
            документов.

            Ничего не выпускай. generate_document вызывай только если тебя об этом попросят отдельно.

            {CommonRules}
            """;
    }
}
