using System.Reflection;
using BHS.CRG.Application.DataSnapshots;

namespace BHS.CRG.Api.Mcp;

/// <summary>
/// Что сервер объявляет о себе при подключении (issue #600).
///
/// За одну живую сессию внешнего агента набор инструментов вырос 10 → 15 → 17 → 21 → 22, и вдобавок
/// сменилась форма списочных ответов. Каждое такое изменение инвалидирует кэш модели ЦЕЛИКОМ: по
/// разбору расхода около 35 % контекста сессии ушло на перечитывание инструкций и списка
/// инструментов, а не на работу с данными.
///
/// Отсюда два правила. Техническое: набор инструментов объявлен статически и закреплён тестом —
/// добавление обязано быть видно в дифе, а не появляться на ходу. Организационное: пока агент
/// работает в живой сессии, сервер с изменённым контрактом не выкатывают; если выкатили — версия
/// контракта в ответе (<see cref="SnapshotContract.Version"/>) даёт клиенту это заметить.
/// </summary>
public static class McpContract
{
    /// <summary>
    /// Версия сборки в <c>serverInfo</c>: клиент видит, с какой именно сборкой говорит. Раньше здесь
    /// стояла константа «1.0.0», и по ответу нельзя было отличить вчерашний сервер от сегодняшнего —
    /// а разбор жалоб на MCP всегда начинается с этого вопроса.
    /// </summary>
    public static readonly string ServerVersion =
        typeof(McpContract).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()
            ?.InformationalVersion
        ?? typeof(McpContract).Assembly.GetName().Version?.ToString()
        ?? "0.0.0";

    /// <summary>
    /// Инструкции, уходящие клиенту при инициализации. Здесь только то, что относится ко ВСЕМ
    /// инструментам сразу: описания отдельных инструментов живут при них и повторять их тут значит
    /// платить за один и тот же текст дважды.
    /// </summary>
    public static readonly string Instructions = $"""
        Данные системы исполнительной документации: наборы данных («что лежит в файлах») и домен
        («что об этом знает сама система»). Версия контракта выдач: {SnapshotContract.Version}.

        Четыре правила, без которых анализ получится уверенным и неверным:

        1. Списки страничные. Пока truncated=true, данные получены НЕ полностью — листайте по
           offset. Недочитанные позиции неотличимы от отсутствующих, и вывод «такой позиции нет»
           будет означать лишь «не дочитано».
        2. origin=Recognized означает, что строки извлечены распознаванием и вероятностны;
           origin=Parsed — детерминированный разбор файла. Если по правилам проекта первоисточник
           XML, а PDF производный, это различие меняет вывод.
        3. stale=true означает, что данные могли устареть относительно текущего содержимого файла.
        4. warning у источника — оговорка К ДАННЫМ: строки получены и верны, но часть данных внутри
           них неизвестна («не собрано документов: 9 из 12 — количество листов известно только у
           собранных»). Пустая ячейка при такой оговорке означает «неизвестно», а НЕ «нуль». Это не
           отказ чтения: отказ приходит отдельно, в rowsError, и тогда строк нет вовсе.

        Проверки системы (validate_document) цитируйте как есть — это детерминированный результат, а
        не мнение. Собственные наблюдения записывайте через report_observation: они попадают в журнал
        как утверждения, требующие подтверждения человеком.
        """;
}
