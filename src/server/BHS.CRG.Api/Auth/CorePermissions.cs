            ["core.nomenclature.edit"]),

        new("core.nomenclature.edit",
            "вести справочник номенклатуры материалов",
            "номенклатуру и сопоставление наименований поставщиков",
            []),

        new("core.employees.read",
            "видеть список сотрудников",
            "ФИО, должности и табельные номера сотрудников — без кадровых сведений и без часов",
