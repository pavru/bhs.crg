    public const string ConstructionsEdit = "core.constructions.edit";

    /// <summary>Разбор чужих сообщений об ошибках.</summary>
    public const string SupportReview = "core.support.review";

    /// <summary>
    /// Чтение журнала действий (ТЗ CORE-28).
    ///
    /// ⚠️ Код исторически называет журнал «audit», а служба и таблица — «activity». Расхождение
    /// намеренное: словом «аудит» в этой системе уже названы проверки данных против схемы
    /// (<c>QualityAuditRun</c>, аудит типа), и служба с таким же именем перестала бы находиться
    /// поиском. Код права менять нельзя — он объявлен в справочнике и уже назван соседями в
    /// «обычно выдаётся вместе».
    /// </summary>
    public const string AuditRead = "core.audit.read";

    /// <summary>Управление аудиторией уведомлений: кто на что подписан.</summary>
    public const string NotifyManage = "core.notify.manage";

    /// <summary>Делать представления таблиц общими (ТЗ CORE-33). Своей двери пока не носит.</summary>
    public const string ViewsShare = "core.views.share";

    /// <summary>Настройка движков и профилей распознавания (ТЗ CORE-37).</summary>
    public const string RecognitionSettings = "core.recognition.settings";

    /// <summary>
    /// Сверка на непротиворечивость целиком (ТЗ CORE-37, CORE-32.1). Под этим правом ДВЕ группы
    /// адресов, а не одна: <c>/api/reconciliations</c> — определения (создание, правка, удаление),
    /// прогоны, находки, решения, алиасы позиций и выгрузка отчёта по любому комплекту; и
    /// <c>/api/observations</c> — замечания внешнего анализа, включая их удаление.
    ///
    /// Одно право на всё — решение владельца 21.09.2026 (issue #992). Границу между «прогнать» и
    /// «править определение» рассматривали и отклонили: сверки ведут те же люди, что их
    /// настраивают, и второе право пришлось бы всегда выдавать парой с первым.
    ///
    /// ⚠️ Цена решения названа в объяснении права вслух: кто может завести определение, тот
    /// сравнивает любые наборы данных и читает их значения в находках. Ворота модулей ЭТОГО НЕ
    /// ОСТАНАВЛИВАЮТ: правило прогоняется <c>ReconciliationRunner</c>, а тот берёт источник по
    /// идентификатору и грузит строки загрузчиком, не зная, кто заказал прогон. Право даёт чтение
    /// ПОВЕРХ прав на модули, а не в их пределах, — не выдавайте его как «посмотреть расхождения».
    /// </summary>
    public const string ReconciliationRun = "core.reconciliation.run";

