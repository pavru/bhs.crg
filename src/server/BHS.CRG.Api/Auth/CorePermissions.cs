using BHS.CRG.Modules;

namespace BHS.CRG.Api.Auth;

/// <summary>
/// Права самого ядра (ТЗ CORE-37).
///
/// Объявлены рядом с правами модулей и теми же средствами: ядро не освобождено от требования
/// объяснять свои права — в редакторе ролей их больше всего, и именно они раздаются чаще прочих.
///
/// ⚠️ Список объявляет права, но ещё не ставит их на адреса: проверка появится вместе с политиками.
/// Порядок именно такой, потому что редактор ролей нельзя строить на пустом справочнике, а
/// поставить право на адрес, которого нет в справочнике, — значит выдать его некому.
/// </summary>
public static class CorePermissions
{
    /// <summary>
    /// Управление пользователями и ролями. Единственный код, названный здесь константой: он стоит
    /// в воротах адреса, в составе роли «Администратор» и в защите от её самоограничения — три
    /// места, между которыми строка обязана совпадать буква в букву, иначе дверь не откроется
    /// никому и выглядеть это будет как «мне не дали прав».
    /// </summary>
    public const string UsersManage = "core.users.manage";

    /// <summary>Обслуживание экземпляра: копии, обновление, почта, внешние службы (ТЗ CORE-37.1).</summary>
    public const string SystemManage = "core.system.manage";

    /// <summary>
    /// Работа с файлами хранилища (ТЗ CORE-37.2).
    ///
    /// ⚠️ Это право отвечает на вопрос «кому вообще можно работать с файлами», и выдано оно будет
    /// почти каждой роли. Подбор пути к чужому файлу оно НЕ закрывает: выдача идёт по пути и не
    /// сверяет владельца. Настоящее лекарство — владелец у вложения; пока его нет, не выдавайте эти
    /// ворота за защиту содержимого хранилища.
    /// </summary>
    public const string FilesUse = "core.files.use";

