namespace BHS.CRG.Api.Endpoints.DataSets;

/// <summary>
/// Версия источника в запросе (issue #1141, поле <c>ifMatch</c>) — общее правило входа HTTP для правок,
/// собранных по копии источника на странице: обработка, извлечение, материализация, «Сохранить как
/// шаблон».
///
/// <para><b>Вход HTTP версию требует всегда.</b> За ним — страница, и правку она собирает по своей
/// копии. Запрос без версии — отказ, а не «сверять не с чем»: иначе вкладка с прежней сборкой клиента,
/// которая версию не шлёт, так и затирала бы чужие правки молча — а это как раз страница, открытая
/// дольше всех. Отказ она показывает в своём диалоге, и путь из него один — обновить страницу.
/// Служба, в отличие от входа, сверяет версию, только когда она названа: вызову из кода, задающему
/// настройку заново, сверять нечего.</para>
/// </summary>
public static class SourceIfMatch
{
    public const string Key = "ifMatch";

    /// <summary>Названа ли версия: null, пустая строка и пробелы значат одно — страница версии не знает.</summary>
    public static bool Has(string? ifMatch) => !string.IsNullOrWhiteSpace(ifMatch);

    /// <summary>Отказ запросу без версии. <paramref name="notDone" /> — что именно не сделано.</summary>
    public static string Missing(string notDone) =>
        $"{notDone}: запрос не называет версию источника («{Key}»), которую показывала страница, — без неё "
        + "не проверить, не изменил ли источник тем временем кто-то ещё. Так бывает, когда страница "
        + "открыта в прежней версии приложения: обновите страницу и повторите.";

    /// <summary>Ответ 400 запросу без версии; <c>null</c> — версия названа, можно работать.</summary>
    public static IResult? Refuse(string? ifMatch, string notDone) =>
        Has(ifMatch) ? null : Results.BadRequest(new { error = Missing(notDone) });
}
