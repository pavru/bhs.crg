namespace BHS.CRG.Api.Endpoints.Common;

/// <summary>
/// Пределы размера загружаемых файлов — одной точкой (issue #482).
///
/// До этого числа были разбросаны по эндпоинтам (50/50/20/нет/нет), а главное — **заявленные пределы
/// были недостижимы**: Kestrel по умолчанию режет тело запроса на 30 000 000 байт, то есть проверка
/// «файл превышает 50 МБ» не срабатывала никогда, а пользователь вместо неё получал 500 с
/// английским текстом фреймворка «Request body too large».
///
/// Правило, из которого всё остальное следует: **заявленное значение обязано быть достижимым на всём
/// пути запроса**. Путь такой:
/// <code>
/// nginx (client_max_body_size)  →  Kestrel (MaxRequestBodySize)  →  разбор формы  →  наша проверка
/// </code>
/// Порог на любом из звеньев ниже нашего превращает проверку в украшение, а отказ — в чужое
/// сообщение не на том языке. <see cref="MaxAnywhere"/> держит эти звенья синхронными; в
/// <c>deploy/nginx.conf</c> стоит соответствующий комментарий.
/// </summary>
public static class UploadLimits
{
    private const long Mb = 1024 * 1024;

    /// <summary>Вложение документа.</summary>
    public const long Attachment = 50 * Mb;

    /// <summary>Скан печатной формы.</summary>
    public const long PrintForm = 50 * Mb;

    /// <summary>Графика и шрифты шаблонов (#62) — заметно меньше: это элементы вёрстки, не сканы.</summary>
    public const long TemplateAsset = 20 * Mb;

    /// <summary>Файл набора данных: PDF-альбомы, XLSX, ZIP выгрузки.</summary>
    public const long DataSetFile = 50 * Mb;

    /// <summary>
    /// Архив восстановления. Заметно больше прочих: бэкап несёт блобы и растёт вместе с ними, а
    /// упереться в потолок он должен не молча и не на середине.
    ///
    /// С решения по issue #687 копия несёт ещё и сканы библиотеки качества — а это не элементы
    /// вёрстки, а сканы целиком, десятки мегабайт на сотню сертификатов. Предел выбран с запасом
    /// на годы наполнения; когда до него дойдёт, поднимать надо не только его: экспорт собирает
    /// архив в памяти.
    /// </summary>
    public const long BackupArchive = 500 * Mb;

    /// <summary>
    /// Запас на служебную обвязку multipart (границы частей, заголовки) — тело запроса всегда больше
    /// самого файла.
    ///
    /// Без запаса проверка на эндпоинте становится НЕДОСТИЖИМОЙ: файл ровно в предел даёт тело чуть
    /// больше и режется транспортом раньше, а файл меньше предела проходит проверку всегда. То есть
    /// ровно тот же дефект, ради которого issue и заведён, только этажом ниже.
    /// </summary>
    public const long MultipartOverhead = 8 * Mb;

    /// <summary>
    /// Наибольший ОБЫЧНЫЙ предел (без восстановления бэкапа) — им ограничивается тело запроса
    /// глобально.
    ///
    /// Глобальный потолок в 500 МБ был бы дырой: <c>file.Length</c> известен только ПОСЛЕ того, как
    /// форма прочитана и часть выгружена во временный файл, поэтому обычный пользователь, отправив
    /// 400 МБ на вложения, заставил бы сервер выписать их на диск и лишь затем получил бы отказ.
    /// Восстановление бэкапа поднимает предел себе само — это действие администратора и оно одно.
    /// </summary>
    public const long OrdinaryRequest = Attachment + MultipartOverhead;

    /// <summary>Предел тела запроса для восстановления бэкапа.</summary>
    public const long BackupRequest = BackupArchive + MultipartOverhead;

    /// <summary>
    /// Наибольшее тело, которое вообще может понадобиться. Этим значением настраивается разбор
    /// multipart и с ним обязан быть согласован <c>client_max_body_size</c> в nginx.
    /// </summary>
    public const long MaxAnywhere = BackupRequest;

    /// <summary>Человеческий отказ, если файл больше предела; иначе null.</summary>
    public static IResult? Exceeded(IFormFile? file, long limit) =>
        file is not null && file.Length > limit ? TooLarge(limit) : null;

    /// <summary>
    /// 413, а не 400: размер — это про транспорт, и код должен отличать «файл не такой» от «файл
    /// слишком большой», иначе клиенту нечем выбрать между «поправьте формат» и «разбейте файл».
    /// </summary>
    public static IResult TooLarge(long limit) =>
        Results.Json(new { error = $"Файл превышает {limit / Mb} МБ" }, statusCode: StatusCodes.Status413PayloadTooLarge);
}
