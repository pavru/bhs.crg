using BHS.CRG.Domain.Schema;
using BHS.CRG.Modules.Recognition;

namespace BHS.CRG.Api.Modules;

/// <summary>
/// Заводские профили распознавания модуля исполнительной документации (ТЗ ID-2, CORE-Q6; задача B1a,
/// issue #1075): что читать в альбоме рабочей документации по ГОСТ Р 21.101-2020.
///
/// <para>До этой задачи перечни лежали в ядре, в общем списке встроенных профилей, и ядро знало графы
/// штампа и колонки кабельного журнала. Теперь содержимое объявляет модуль, а в ядре осталось только
/// служебное — то, на чём держится сам разбор ответа: ключи классификаторов страницы и ключ массива
/// строк (<c>GostTitleBlockFields</c>, <c>GostTableFields</c>).</para>
///
/// <para>⚠️ Конвейер разбиения альбома (группировка листов, выбор региона штампа, авто-тэг таблицы)
/// по-прежнему лежит в ядре: модуль исполнительной документации — обёртка, а не отдельная сборка, и
/// увести конвейер некуда. Долг записан 07.10.2026. Ядро при этом модуль не называет: оно спрашивает
/// профиль у поставщика, и отказ даёт владелец профиля.</para>
///
/// <para>⚠️ Содержимое прибито хешами (<c>BuiltInProfileHashPinTests</c>): правка описания поля
/// зажигает «заводской профиль обновился» у каждого, кто профиль менял.</para>
/// </summary>
public static class IdRecognitionProfiles
{
    // Стабильные коды — ключи строк в базе, не переименовываются.
    public const string TitleBlockCode = "titleblock";
    public const string CoverTitleCode = "cover-title";
    public const string SpecificationTableCode = "spec-table";
    public const string CableJournalCode = "cable-journal";

    /// <summary>
    /// Графы основной надписи (форма 3 — чертежи, форма 5 — текстовые документы). Только
    /// подтверждённые стандартом графы, нужные для машиночитаемого реестра листов; графы 10–13
    /// (должности, фамилии, подписи разработчиков) не включены — реестру они не нужны.
    /// </summary>
    public static readonly IReadOnlyList<ModuleRecognitionField> TitleBlockFields =
    [
        new("Шифр", "Обозначение документа (шифр)"),
        new("ОбъектСтроительства", "Наименование объекта строительства"),
        new("ЗданиеСооружение", "Наименование здания (сооружения) или вид работ"),
        new("НаименованиеДокумента", "Наименование документа/листа из графы наименования ШТАМПА (напр. «Общие данные», название схемы, «Спецификация...»)"),
        new("ВидДокументации", "Вид документации", Options: ["П", "Р", "И"]),
        new("НомерЛиста", "Номер листа"),
        new("ВсегоЛистов", "Всего листов"),
        new("Организация", "Организация-разработчик"),
        new("Масштаб", "Масштаб"),
    ];

    /// <summary>
    /// Поля ЗАГЛАВНОГО листа комплекта (обложка, титульный лист). В отличие от граф основной надписи,
    /// которые лежат в угловом штампе, эти реквизиты размещены по всему листу крупным титульным
    /// блоком, а штампа с шифром на обложке и титуле нет. Поэтому такие листы читаются ОТДЕЛЬНЫМ
    /// проходом этим набором — иначе колонки штампа оказываются пустыми: читать их неоткуда.
    /// </summary>
    public static readonly IReadOnlyList<ModuleRecognitionField> CoverTitleFields =
    [
        new("ОбъектСтроительства", "Наименование объекта строительства (полное, как на титуле)"),
        new("НаименованиеКомплекта", "Наименование комплекта/раздела документации (напр. «Электроосвещение и силовое электрооборудование»)"),
        new("Шифр", "Шифр (обозначение) комплекта документации"),
        new("Организация", "Организация-разработчик (генпроектировщик)"),
        new("Стадия", "Стадия документации: П (проектная) или Р (рабочая)", Options: ["П", "Р"]),
        new("Город", "Город (место разработки/строительства)"),
        new("Год", "Год разработки"),
        new("ГИП", "ГИП/ГАП — главный инженер (архитектор) проекта, ФИО"),
    ];

    /// <summary>Спецификация и ведомость оборудования и материалов (ГОСТ 21.110-2013, приближённо).
    /// Колонки фиксированы под тип: так надёжнее распознавание и чище выгрузка.</summary>
    public static readonly IReadOnlyList<ModuleRecognitionField> SpecificationColumns =
    [
        new("Позиция", "Позиция"),
        new("Обозначение", "Обозначение (документа/типового проекта)"),
        new("Наименование", "Наименование и техническая характеристика"),
        new("ТипМарка", "Тип, марка, обозначение"),
        new("Код", "Код оборудования/изделия/материала"),
        new("Изготовитель", "Завод-изготовитель / поставщик"),
        new("Единица", "Единица измерения"),
        new("Количество", "Количество"),
        new("Масса", "Масса единицы, кг"),
        new("Примечание", "Примечание"),
    ];

    /// <summary>
    /// Кабельный журнал — колонки-надмножество (issue #389): покрывают формы четырёх стандартов
    /// (21.613 силовое, 21.608 внутреннее освещение, 21.607 наружное освещение, Р 70444) как
    /// подмножества. Ключевое — ДВОЙНАЯ форма «по проекту / проложено»: у каждой секции своя марка,
    /// сечение и длина (пары <c>…Проект</c> / <c>…Факт</c>). Простые одиночные формы заполняют только
    /// <c>…Проект</c>. Все значения — строки: форматирует шаблон (issue #60).
    /// </summary>
    public static readonly IReadOnlyList<ModuleRecognitionField> CableJournalColumns =
    [
        new("НомерКабеля", "Номер (обозначение) кабеля/провода/линии"),
        new("Начало", "Начало линии (откуда): пункт/щит/опора"),
        new("Конец", "Конец линии (куда): пункт/щит/опора"),
        new("Участок", "Участок / № группы (освещение) / пролёт опор (наружное); для силового обычно пусто"),
        new("МаркаПроект", "Марка кабеля/провода ПО ПРОЕКТУ"),
        new("СечениеПроект", "Число и сечение жил (напряжение) по проекту"),
        new("ДлинаПроект", "Длина по проекту, м"),
        new("МаркаФакт", "Марка проложенного ФАКТИЧЕСКИ"),
        new("СечениеФакт", "Число и сечение жил фактически"),
        new("ДлинаФакт", "Длина фактически, м"),
        new("СпособПрокладки", "Способ прокладки / характеристика трассы"),
        new("Примечание", "Примечание"),
    ];

