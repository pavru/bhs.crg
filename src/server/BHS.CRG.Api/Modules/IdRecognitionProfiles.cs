            RowColumns: SpecificationColumns, Shape: new ModuleRecognitionShape(),
            DocumentTag: FunctionalTag.GostDocSpecification),

        new(CableJournalCode, "Кабельный журнал", "CableJournal",
            RowColumns: CableJournalColumns, Shape: new ModuleRecognitionShape(),
            DocumentTag: FunctionalTag.GostDocCableJournal),
    ];
}
