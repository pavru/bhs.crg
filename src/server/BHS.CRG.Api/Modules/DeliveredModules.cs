using BHS.CRG.Modules;
using BHS.CRG.Modules.Costs;

namespace BHS.CRG.Api.Modules;

/// <summary>
/// Состав поставки: модули, которые ЕСТЬ в сборке. Единственное место, где ядро знает их по именам, —
/// и это намеренно корень композиции, а не сканер сборок рядом с приложением: набор модулей на
/// экземпляре обязан быть решением поставки (<c>Modules__Enabled</c>, AUTH-17), а не следствием того,
/// какие DLL кто-то скопировал.
///
/// <para>Отдельным файлом (issue #1104) по двум причинам. Перепись «ядро не называет модуль» выдаёт
/// исключение ровно ему, а не файлу регистрации служб, где рядом живёт что угодно. И сторожа, которым
/// нужен состав поставки, берут его здесь же: список, набранный в тесте второй раз, отстал бы на первом
/// новом модуле — и молчал бы про него.</para>
///
/// <para>⚠️ Порядок перечисления порядка ВКЛЮЧЕНИЯ не задаёт: его задаёт <c>Modules__Enabled</c>.
/// <c>costs</c> на экземпляре выключен, пока его не назвали, и отвечает отказом с названной причиной
/// (задача A1, issue #1068).</para>
/// </summary>
public static class DeliveredModules
{
    /// <summary>Новые экземпляры на каждый вызов: модуль — объявление без состояния.</summary>
    public static IAppModule[] All() => [new IdModule(), new CostsModule()];
}
