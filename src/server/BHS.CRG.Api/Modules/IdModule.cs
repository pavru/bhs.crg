using BHS.CRG.Api.Endpoints.Documents;
using BHS.CRG.Api.Endpoints.QualityDocs;
using BHS.CRG.Modules;

namespace BHS.CRG.Api.Modules;

/// <summary>
/// Модуль исполнительной документации — с него система начиналась, и пока он единственный.
///
/// ⚠️ Это ОБЁРТКА, а не переезд (issue #942). Код исполнительной документации остаётся там, где
/// лежал: в общих слоях приложения вперемешку с кодом ядра. Обёртка объявляет модуль и забирает
/// себе те группы адресов, принадлежность которых не вызывает вопросов, — остальные остаются в
/// корне композиции до разбора по воротам, где каждой группе всё равно придётся назначить право.
///
/// Почему не забрано больше. Адреса комплектов документов лежат в одном файле с адресами строек и
/// разделов, а стройки по ТЗ переходят ЯДРУ (CORE-5): заберись обёртка за весь файл — и при
/// выключенном модуле пропали бы стройки, то есть общий справочник. Резать файл здесь незачем: он
/// всё равно режется переносом строек в ядро.
///
/// Почему не забрано меньше. Механизм, который ничего не регистрирует, не проверен ничем: «работает»
/// и «вызывается» — разные утверждения, и разница вскрывается не сразу.
/// </summary>
public sealed class IdModule : IAppModule
{
    public string Code => "id";

    public string Title => "Исполнительная документация";

    /// <summary>
    /// Пусто до появления прав в базе: список объявляется здесь же, но вместе с объяснением
    /// каждого права, а объяснению пока негде храниться. Пустой список честнее выдуманного.
    /// </summary>
    public IReadOnlyList<string> Permissions => [];

    /// <summary>
    /// Своих служб у обёртки нет: всё, чем пользуется исполнительная документация, регистрируется
    /// общим кодом запуска. Появятся при переезде кода в собственный проект модуля.
    /// </summary>
    public void RegisterServices(IServiceCollection services, IConfiguration configuration) { }

    /// <summary>
    /// Пути модуля. <c>/api/document-sets</c> делится с ядром — там же стоят общие адреса
    /// комплектов; это безопасно, потому что отказ выключенного модуля уступает адресам ядра:
    /// глубже префикса — по точности образца, на самом префиксе — по явно заданному порядку
    /// (<c>AppModuleExtensions.MapRefusal</c>). Плата за общий префикс — при выключенном модуле
    /// опечатка в пути комплектов получит отказ «модуль не подключён» вместо пустого 404; из двух
    /// неточностей эта безвреднее.
    /// </summary>
    public IReadOnlyList<string> RoutePrefixes =>
        ["/api/quality-docs", "/api/plans", "/api/document-sets"];

    public void MapEndpoints(IEndpointRouteBuilder endpoints)
    {
        endpoints.MapQualityDocEndpoints();
        endpoints.MapPrintFormEndpoints();
        endpoints.MapPlanEndpoints();
    }

    /// <summary>
    /// Инициализировать нечего: типы и справочники исполнительной документации заводит
    /// администратор, а не код. Появится вместе с владельцем-модулем у типа.
    /// </summary>
    public Task InitializeAsync(IServiceProvider services, CancellationToken ct) => Task.CompletedTask;
}
