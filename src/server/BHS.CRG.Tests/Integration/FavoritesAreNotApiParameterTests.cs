namespace BHS.CRG.Tests.Integration;

/// <summary>
/// Избранные стройки — фильтр ЭКРАНОВ клиента, а не права и не отбор сервера (issue #1217, #1218).
/// Сервер слова «избранное» не знает нигде, кроме двух ключей настроек, и при выдаче данных
/// настройку не читает: MCP, экспорт, генерация, почта и фоновые задачи остаются без фильтра по
/// построению.
///
/// <para>Проверяемо это так же, как у рабочих пространств: ни один адрес не ПРИНИМАЕТ избранное.
/// Появится параметр <c>favorites=true</c> — сервер начнёт сам читать настройку человека, и отбор,
/// который тот не видит, станет возможен там, где экрана нет вовсе: в выгрузке, в письме, у агента
/// MCP. Пустой результат такого отбора неотличим от «данных нет».</para>
///
/// <para>Страничный список, которому отбор нужен на сервере (накладные, #1222), принимает ЯВНЫЙ
/// перечень строек — <c>sites</c>. Перечень присылает клиент, и сервер не знает, откуда тот взялся:
/// это обычный видимый отбор, а не «избранное».</para>
///
/// Чего разбор адресов не видит — в <see cref="ApiParameterNames" />.
/// </summary>
[Collection("Integration")]
public class FavoritesAreNotApiParameterTests(IntegrationTestFixture fixture)
{
    /// <summary>Слова, которыми избранное назвали бы, — по-английски в обоих написаниях и по-русски.</summary>
    private static readonly string[] Banned = ["favorite", "favourite", "избранн"];

    [Fact]
    public void Ни_один_адрес_не_принимает_избранное()
    {
        var named = ApiParameterNames.Collect(fixture);

        ApiParameterNames.AssertParsed(named);

        var found = ApiParameterNames.Matching(named, Banned);

        Assert.True(found.Count == 0,
            "Адрес принимает избранные стройки. Избранное — фильтр экранов клиента (#1217): сервер его "
            + "хранит, но не читает. Страничному списку нужен явный перечень строек (sites), а не "
            + "«избранное»:\n  " + string.Join("\n  ", found));
    }
}
