namespace BHS.CRG.Modules;

/// <summary>
/// Пометка на адресе-ОТКАЗЕ выключенного модуля (<c>AppModuleExtensions.MapRefusal</c>).
///
/// За таким адресом нет ни данных, ни служб: он отвечает 501 «модуль не подключён» и анонимен
/// намеренно — требовать вход, чтобы сообщить состав поставки, значит прятать то, что и так видно в
/// интерфейсе.
///
/// Пометка нужна инвентаризации адресов (ТЗ AUTH-9): без неё каждый выключенный модуль приносил бы
/// в приложение два незакрытых пути, и записывать их пришлось бы поимённо — списком, который
/// расходится дважды. Сначала при появлении модуля (запись забудут), потом при его включении
/// (запись останется и станет ложной: у включённого модуля этих адресов нет вовсе). Признак
/// «это отказ», проверяемый по существу, от состава поставки не зависит.
/// </summary>
/// <param name="Code">Код выключенного модуля.</param>
public sealed record DisabledModuleEndpoint(string Code);
