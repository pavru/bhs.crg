namespace BHS.CRG.Modules;

/// <summary>
/// Право с объяснением: <c>модуль.объект.действие</c> плюс человеческие слова о том, что оно даёт
/// (ТЗ AUTH-1, AUTH-5).
///
/// Объяснение — не документация, а условие, без которого редактор ролей небезопасен. Администратор
/// раздаёт права галками, и галка с подписью <c>costs.invoice.approve</c> не даёт ему ни одного
/// основания решить, ставить её или нет. Поэтому объяснение объявляется ВМЕСТЕ с правом и в том же
/// месте: приписать его потом отдельным файлом означает, что у половины прав его не будет.
/// </summary>
/// <param name="Code">Код вида <c>модуль.объект.действие</c>: <c>work.report.review</c>.</param>
/// <param name="Gives">Что право даёт: «приёмка и возврат отчётов своих строек».</param>
/// <param name="Opens">
/// К каким данным открывает доступ: «отчёты монтажников по стройкам, на которые назначен».
/// Это отдельный вопрос от «что даёт»: право на действие почти всегда шире, чем кажется по
/// названию, и администратор обязан видеть, что именно станет видно.
/// </param>
/// <param name="UsuallyWith">
/// С какими правами обычно выдаётся вместе. Подсказка, а не зависимость: система ничего не
/// досоздаёт сама — иначе выданной окажется не та галка, которую поставили.
/// </param>
public sealed record AppPermission(
    string Code,
    string Gives,
    string Opens,
    IReadOnlyList<string>? UsuallyWith = null)
{
    public IReadOnlyList<string> UsuallyWith { get; init; } = UsuallyWith ?? [];

    /// <summary>
    /// Проверяет объявление. Возвращает причину отказа или <c>null</c>, если всё на месте.
    ///
    /// Отдельным методом, а не проверкой в конструкторе: отказ собирается по ВСЕМ правам сразу, и
    /// человек чинит объявления за один заход, а не по одному на каждый перезапуск.
    /// </summary>
    public string? Validate()
    {
        if (string.IsNullOrWhiteSpace(Code)) return "код пуст";

        var parts = Code.Split('.');
        if (parts.Length != 3 || parts.Any(string.IsNullOrWhiteSpace))
            return $"«{Code}» — код обязан быть вида «модуль.объект.действие»";

        if (string.IsNullOrWhiteSpace(Gives))
            return $"«{Code}» — не сказано, что право даёт";

        if (string.IsNullOrWhiteSpace(Opens))
            return $"«{Code}» — не сказано, к каким данным оно открывает доступ";

        return null;
    }
}
