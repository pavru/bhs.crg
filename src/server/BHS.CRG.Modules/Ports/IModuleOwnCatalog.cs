namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Записи СВОИХ справочников модуля в общей таблице ядра — ЗАПИСЬ (задача F3 этапа 2, issue #1087, ТЗ
/// COST-10.1, CORE-16): модуль «Счета и накладные» ведёт справочник статей вне строек («Склад», «Общие
/// расходы») под своим правом <c>costs.articles.edit</c>.
///
/// <para><b>Почему не <see cref="IModuleCatalog" />.</b> Тот — только чтение, и нарочно: чужие справочники
/// (организации, номенклатуру) ведёт человек в разделе каталога, а модуль, заводящий их молча, стал бы
/// вторым источником одних и тех же записей. Здесь другой случай — справочник, который объявил САМ модуль
/// (класс A, тип в общей таблице): дублировать в нём нечего, а вести его обязан тот, у кого есть право
/// модуля, — бухгалтеру не выдают <c>core.catalog.edit</c> ради двух статей. Поэтому запись — отдельным
/// портом, и только для таких типов.</para>
///
/// <para>⚠️ <b>Чей тип — проверяет ядро.</b> Порт принимает код типа, и тип обязан принадлежать модулю (а
/// не ядру) и лежать в общей таблице; иначе — отказ. Кто из модулей зовёт, порт не знает — как не знают
/// этого и остальные порты: модули поставляются вместе с ядром, и граница здесь — «ядро или модуль», а не
/// «модуль против модуля».</para>
///
/// <para>⚠️ Дверь «Общих данных» этими записями тоже правит — под <c>core.catalog.edit</c>, как любым
/// справочником класса A. Это не обход права модуля: <c>core.catalog.edit</c> и так означает «править
/// любую запись справочников», а узкое право открывает ровно один справочник.</para>
/// </summary>
public interface IModuleOwnCatalog
{
    /// <summary>
    /// Завести запись с этим названием (уровень — вся система). <c>null</c> — типа нет: проекция при старте
    /// его пропустила. Отказ с объяснением говорит модуль — слой ядра доменных отказов не бросает.
    /// </summary>
    Task<ModuleCatalogRef?> CreateAsync(string typeCode, string displayName, CancellationToken ct = default);

    /// <summary>Переименовать; <c>null</c> — такой записи этого типа нет (или нет самого типа).</summary>
    Task<ModuleCatalogRef?> RenameAsync(string typeCode, Guid id, string displayName, CancellationToken ct = default);

    /// <summary>
    /// Удалить; <c>false</c> — такой записи этого типа нет. Ссылки из данных ядра (<c>$ref</c> в документах)
    /// удаление останавливают тем же отказом, что и в разделе каталога; свои ссылки модуль проверяет сам.
    /// </summary>
    Task<bool> DeleteAsync(string typeCode, Guid id, CancellationToken ct = default);
}
