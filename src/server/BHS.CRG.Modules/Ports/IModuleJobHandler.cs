namespace BHS.CRG.Modules.Ports;

/// <summary>Что досталось обработчику фоновой задачи модуля.</summary>
/// <param name="JobId">Задача — по нему её состояние спрашивают снаружи.</param>
/// <param name="TargetId">Цель операции, как её назвал модуль при постановке.</param>
/// <param name="UserId">Кто поставил; <see cref="Guid.Empty" /> — поставил не человек
/// (расписание, старт). Обработчик обязан пережить оба случая.</param>
/// <param name="Payload">Аргументы операции, как их передали при постановке.</param>
/// <param name="Report">
/// Доложить ход: единица измерения, сделано, всего («строк», 12, 57). Зовите свободно — ядро само
/// прореживает доклады по времени, чтобы не писать в базу на каждой строке.
/// </param>
public sealed record ModuleJobRun(
    Guid JobId, Guid TargetId, Guid UserId, string? Payload, Func<string, int, int, Task> Report);

/// <summary>
/// Обработчик фоновой операции модуля. Модуль регистрирует его в <c>RegisterServices</c> — как
/// обычную службу, по этому интерфейсу.
///
/// <para>⚠️ Операция выполняется ВНЕ запроса, в своей области служб: <c>HttpContext</c> там нет, и
/// «кто действует» у порта пользователя ответит «система». Всё, что зависит от того, кто нажал,
/// обработчик берёт из <see cref="ModuleJobRun.UserId" />.</para>
///
/// <para>⚠️ Отказ — исключением. Ядро запишет его в задачу и покажет человеку текст: НАШ текст,
/// если исключение наше (доменные отказы), и общие слова про журнал сервера, если чужое. Значит,
/// отказ обработчика стоит бросать своим типом с текстом, годным для человека.</para>
///
/// <para>⚠️ Один обработчик — одна операция, и <see cref="Operation" /> у двух обработчиков совпасть
/// не может: постановка искала бы исполнителя по коду и нашла двух. Это отказ при постановке, а не
/// выбор первого.</para>
/// </summary>
public interface IModuleJobHandler
{
    /// <summary>Код операции — тот же, что модуль назовёт в <see cref="IModuleJobs.EnqueueAsync" />.</summary>
    string Operation { get; }

    Task RunAsync(ModuleJobRun run, CancellationToken ct);
}
