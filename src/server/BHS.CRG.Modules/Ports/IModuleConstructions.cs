namespace BHS.CRG.Modules.Ports;

/// <summary>Раздел стройки: «4 эт.», «ливнёвка».</summary>
public sealed record ModuleSection(Guid Id, string Name);

/// <summary>Стройка ядра вместе с её разделами.</summary>
public sealed record ModuleConstruction(Guid Id, string Name, IReadOnlyList<ModuleSection> Sections);

/// <summary>
/// Стройки и разделы ядра — ЧТЕНИЕ (ТЗ COST-10, CORE-34): цель части разноски счёта (задача F1,
/// issue #1085).
///
/// <para><b>Отдельным портом, а не видом в <see cref="IModuleCatalog" />.</b> Стройка и раздел — не
/// записи общих данных, а свои таблицы ядра с деревом «стройка → разделы»: спросить их у справочника
/// значило бы получить пустоту на любом экземпляре, и выглядело бы это как «строек ещё не завели».</para>
///
/// <para><b>Одним списком, без поиска и без выборки по идентификаторам.</b> Строек на экземпляре —
/// десятки, а не тысячи, как у номенклатуры: весь список дешевле, чем второй способ его читать. Им же
/// модуль проверяет, что выбранный раздел принадлежит выбранной стройке, и узнаёт, что стройку
/// удалили.</para>
///
/// <para>⚠️ «Стройки нет» здесь не отказ, а потеря: стройку удаляет человек в ядре, и о разноске
/// модуля ядро не знает (запрет удалять занятое — задача G2, issue #1094). Разбираться, чего не
/// хватает, обязан звавший — сравнением того, что хранит, с тем, что пришло.</para>
///
/// <para>⚠️ Правами не отбирается, как и <see cref="IModuleCatalog" />: привязки строек к пользователю
/// в системе нет (решение от 05.08.2026, issue #675).</para>
/// </summary>
public interface IModuleConstructions
{
    /// <summary>Все стройки с разделами, по названию (сравнение культурное — список читает человек).</summary>
    Task<IReadOnlyList<ModuleConstruction>> ListAsync(CancellationToken ct = default);
}
