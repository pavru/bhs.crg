namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Действие модуля для журнала: код и название для человека (ТЗ CORE-25, CORE-28).
///
/// <para>Типом, а не строкой, по той же причине, что и у ядра (<c>ActivityActions</c>): опечатка в
/// коде записалась бы молча и всплыла бы на экране журнала строкой без названия — то есть тогда,
/// когда запись уже сделана и переписать её нельзя. Каталог ядра закрыт (поля-константы), и модулю
/// туда не дописать: его действия объявляются у него, а формат кода проверяется
/// <see cref="Validate" /> — ровно как у прав модуля (<see cref="AppPermission" />).</para>
/// </summary>
/// <param name="Code">Код вида <c>модуль.объект.действие</c>: <c>costs.invoice.paid</c>.</param>
/// <param name="Title">Название на экране журнала: «Счёт отмечен оплаченным». ⚠️ На экран попадает
/// название ИЗ ОБЪЯВЛЕНИЯ (<see cref="IModuleActivityActions" />), а не из вызова записи: в самой
/// записи лежит только код — чтобы правка названия доезжала и до старых записей. Поэтому действие
/// объявляют и пишут ОДНИМ И ТЕМ ЖЕ объектом, обычно полем-константой, как это сделано у ядра;
/// расхождение названий отказывает при записи.</param>
public sealed record ModuleActivityAction(string Code, string Title)
{
    /// <summary>
    /// Что не так с объявлением; <c>null</c> — годное. Проверяется при записи, а не только при
    /// старте: действие объявляют рядом с кодом, который его пишет, и до первой записи объявление
    /// никто не читает.
    ///
    /// ⚠️ Префикс обязан быть кодом модуля, и это проверяет уже приложение (порту не с чем сверить
    /// состав поставки). Здесь — форма: три части и непустое название. Одно без другого не работает:
    /// форма без префикса пропустила бы <c>core.user.deleted</c>, написанный модулем, а префикс без
    /// формы — двухчастный код, по которому на экране журнала не понять, что вообще произошло.
    /// </summary>
    public string? Validate()
    {
        if (string.IsNullOrWhiteSpace(Code)) return "Код действия пуст.";

        var parts = Code.Split('.');
        if (parts.Length != 3 || parts.Any(string.IsNullOrWhiteSpace))
            return $"Код действия «{Code}» обязан быть из трёх частей: модуль.объект.действие.";

        if (string.IsNullOrWhiteSpace(Title))
            return $"У действия «{Code}» нет названия: на экране журнала осталась бы одна строка кода.";

        return null;
    }
}

/// <summary>
/// Журнал действий для модуля (ТЗ CORE-25, CORE-28) — тот же, что у ядра, а не свой.
///
/// <para>Журнал в продукте ОДИН нарочно: как только их становится два, они расходятся в главном —
/// в том, что считается автором и что считается временем, — и сводить потом два журнала с разными
/// представлениями об авторе некому. Поэтому журналы изменений счёта, накладной и разноски пишутся
/// сюда же, и экран журнала показывает их вперемешку с действиями ядра.</para>
///
/// <para>⚠️ Автора и время служба берёт САМА. У вызывающего их не спрашивают — иначе автор стал бы
/// параметром, который можно передать чужой. Вне запроса (старт, фоновая задача) автором становится
/// сам экземпляр, а не «неизвестно».</para>
///
/// <para>⚠️ Запись делается ПОСЛЕ того, как действие удалось, и своей транзакции у журнала нет.
/// Контекст при этом ЧУЖОЙ: журнал — таблица ядра, запись модуля — таблица его схемы, и общей
/// транзакции у двух контекстов не бывает (задача A2a этапа 2, issue #1072, см.
/// <see cref="Data.ModuleDbContext" />). Поэтому порядок обязателен: сначала сохранить своё, потом
/// записать в журнал. Наоборот — и в журнале останется свидетельство о действии, которого не
/// произошло; сохранить своё и не успеть записать — потеря следа, то есть меньшая из двух бед.</para>
///
/// <para>⚠️ Пишется только ОБЪЯВЛЕННОЕ действие (<see cref="IModuleActivityActions" />). Иначе строка
/// журнала читалась бы кодом, а в отборе по действию её не было бы вовсе — название, переданное при
/// записи, до человека не доезжает.</para>
///
/// <para>Чтения здесь нет, и это не забывчивость: журнал читает экран ядра — целиком, с фильтром по
/// коду действия. История ОДНОЙ записи модулю понадобится вместе с версиями записей (задача E2
/// этапа 2, issue #1100), и тогда сюда приедет чтение по цели. Метод, добавленный раньше
/// потребителя, был бы непроверенным.</para>
/// </summary>
public interface IModuleActivityLog
{
    /// <summary>
    /// Записать действие модуля.
    ///
    /// ⚠️ Негодное объявление — ОТКАЗ, а не тихая запись: см. <see cref="ModuleActivityAction.Validate" />.
    /// Код с чужим префиксом (<c>core.*</c> или код другого модуля) тоже отказ — иначе в журнале
    /// появились бы действия от имени того, кто их не делал.
    /// </summary>
    /// <param name="targetId">Над чем действие: идентификатор записи модуля. Строкой — у модуля
    /// бывают составные ключи, а журнал по цели не соединяет, он её показывает.</param>
    /// <param name="targetLabel">Как цель называлась в момент действия: «Счёт № 14 от 03.09.2026».
    /// Имя запоминается, а не резолвится при чтении: удалённая запись иначе стала бы безымянной
    /// ровно в тех строках, ради которых журнал и смотрят.</param>
    /// <param name="before">Прежнее значение, если действие его меняло.</param>
    /// <param name="after">Новое значение.</param>
    Task RecordAsync(ModuleActivityAction action, string? targetId = null, string? targetLabel = null,
        string? before = null, string? after = null, CancellationToken ct = default);
}
