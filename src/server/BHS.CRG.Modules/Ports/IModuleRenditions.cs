namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Читаемый вид файла модуля — ответ на вопрос «как это показать и распознать» (issue #1269).
///
/// <para>Ответов три, и пустого образа среди них нет: файл читается сам, образ построен, образа не
/// будет. Получателю не нужно знать виды файлов: что с этим файлом делать, сказано ответом.</para>
/// </summary>
public abstract record ModuleRendition
{
    private ModuleRendition() { }

    /// <summary>Файл читается сам — PDF или изображение.</summary>
    /// <param name="Path">Путь самого файла: его и показывать, и распознавать.</param>
    /// <param name="Mime">Вид содержимого, определённый по содержимому.</param>
    public sealed record AsIs(string Path, string Mime) : ModuleRendition;

    /// <summary>Образ построен: PDF с текстовым слоем.</summary>
    /// <param name="Path">Путь образа — открывается через <see cref="IModuleBlobs.OpenAsync" />.
    /// ⚠️ Это не оригинал: скачивать человеку дают оригинал, образ — только смотреть и распознавать.</param>
    /// <param name="Pages">Сколько в образе страниц.</param>
    /// <param name="Notes">Что человеку стоит знать об образе: «страниц: 2, из них без текста: 1».
    /// Показываются рядом с образом — образ с пометкой, показанный без неё, выглядит точной копией
    /// файла.</param>
    /// <param name="Converter">Чем построен: «gotenberg 8.37.0»; <c>null</c> — неизвестно.</param>
    /// <param name="BuiltAt">Когда построен.</param>
    /// <param name="Layout">Как образ разложен на бумагу (issue #1454) — готовым состоянием: модуль
    /// параметры профиля не толкует, он показывает строку. <c>null</c> — ядро не сказало.</param>
    public sealed record Built(
        string Path, int Pages, IReadOnlyList<string> Notes, string? Converter, DateTimeOffset BuiltAt,
        ModuleRenditionLayout? Layout = null)
        : ModuleRendition;

    /// <summary>Образа нет.</summary>
    /// <param name="Reason">Причина словами, для человека.</param>
    /// <param name="RetryHelps">Отказ временный — сервис занят или молчит; тот же файл позже может
    /// получить образ. Иначе повтор ничего не изменит.</param>
    /// <param name="OtherKind">Файл не того вида: образ ему не положен вовсе — это не Excel и не
    /// Word. Отличать нужно: про такой файл экран говорит «показать нечем», а не «образ не
    /// построен», и причину отказа не выдаёт за поломку.</param>
    /// <param name="AboutFile">Отказ — свойство самого файла (пароль, пуст, повреждён, велик,
    /// конвертер не открыл), и ядро его запомнило: тот же файл сам собой не построится, только
    /// явным «построить заново». Иначе дело в сервисе или в установке (конвертер занят, молчит, не
    /// настроен) — и говорить человеку «файл такой» нельзя.</param>
    public sealed record Refused(string Reason, bool RetryHelps, bool OtherKind = false, bool AboutFile = false)
        : ModuleRendition;
}

/// <summary>Чем кончилась раскладка книги по профилю печати (issue #1454).</summary>
public enum ModuleLayoutOutcome
{
    /// <summary>Файл не книга <c>.xlsx</c> — профили к нему не применяются.</summary>
    NotBook,

    /// <summary>
    /// Образ построен до профилей печати: без исхода раскладки (до #1453) или вписан константой #1453.
    /// ⚠️ Вида файла запись без исхода не помнит: книга это или Word, знает модуль, и строку
    /// «перестроение применит профиль» он показывает только книге.
    /// </summary>
    BeforeProfiles,

    /// <summary>Книга задала раскладку сама — профиль не применялся и не записан.</summary>
    BookOwn,

    /// <summary>Раскладка профиля подставлена.</summary>
    Applied,

    /// <summary>Подставить раскладку не удалось — образ построен по файлу как есть; профиль не записан.</summary>
    Skipped,
}

/// <summary>Профиль, по которому строился образ, — сейчас.</summary>
public enum ModuleLayoutProfileState
{
    /// <summary>Профиль есть, и его параметры те же, что при построении.</summary>
    Current,

    /// <summary>Профиль с тех пор правили: перестроение даст другой вид.</summary>
    Changed,

    /// <summary>Профиль удалили: перестроение без выбора возьмёт системный.</summary>
    Deleted,
}

/// <summary>Раскладка образа для показа рядом с ним (issue #1454).</summary>
/// <param name="ProfileId">Профиль, раскладка которого подставлена; <c>null</c> — не записан: профиль
/// записывается только у <see cref="ModuleLayoutOutcome.Applied" />.</param>
/// <param name="ProfileName">Его имя сейчас; <c>null</c> — профиля нет или он не записан.</param>
/// <param name="ProfileState"><c>null</c> — профиль не записан.</param>
public sealed record ModuleRenditionLayout(
    ModuleLayoutOutcome Outcome, Guid? ProfileId, string? ProfileName, ModuleLayoutProfileState? ProfileState);

/// <summary>
/// Читаемые образы файлов для модуля (issue #1269): счёт в Excel или Word показывают и распознают
/// не сам, а его образ — PDF, который строит ядро.
///
/// <para><b>Образом владеет ядро, оригиналом — модуль.</b> Модуль хранит у своей записи только путь
/// оригинала (<see cref="IModuleBlobs.PutAsync" />) и спрашивает образ по нему. Хранить у себя путь
/// образа, его пометки или отметку конвертера не нужно: у ядра это одна запись на файл, и она не
/// меняет строку модуля — а значит, и её версию.</para>
///
/// <para>⚠️ Если модуль путь образа всё же запомнил (счета помнят, по какому образу прочитан счёт),
/// колонку он обязан объявить производной — <c>ModuleFile.Derived</c> в <c>IAppModule.Files</c>
/// (issue #1261). Иначе резервная копия примет образ за файл модуля и увезёт его, хотя образы в копию
/// не кладутся: после восстановления их строит ядро.</para>
///
/// <para><b>Образ живёт, пока жив оригинал.</b> Удаление оригинала
/// (<see cref="IModuleBlobs.DeleteAsync" />) убирает и образ; отдельно удалять его не надо и нечем.</para>
///
/// <para>⚠️ <b>Образ не перестраивается сам</b> — ни после обновления конвертера, ни со временем.
/// Пока его не перестроили руками, то, что видел человек, и то, что читала модель, — один и тот же
/// PDF. Перестроить — <see cref="RebuildAsync" />, по явному действию.</para>
/// </summary>
public interface IModuleRenditions
{
    /// <summary>
    /// Образ этого файла: записанный, а если его ещё не строили — построенный сейчас.
    ///
    /// <para>Зовут после загрузки файла и первым шагом распознавания. Вызов синхронный и короткий —
    /// около секунды на счёт; файл, на который секунд не хватило, получает отказ, а не уходит в фон.</para>
    ///
    /// <para>Отказ о файле (под паролем, пуст, слишком велик) запоминается: следующий вызов вернёт
    /// его же, не строя. Временный отказ (<see cref="ModuleRendition.Refused.RetryHelps" />) и отказ
    /// «конвертера нет» не запоминаются — следующий вызов попробует снова.</para>
    ///
    /// <para>⚠️ Отказ приведения — не отказ загрузки: файл под паролем приложен и скачивается, у
    /// него лишь нет читаемого вида. Оригинала по пути нет — исключение «файл не найден».</para>
    /// </summary>
    Task<ModuleRendition> EnsureAsync(string originalPath, CancellationToken ct = default);

    /// <summary>
    /// Что известно об образе, не строя ничего; <c>null</c> — образ не строили. Для показа: чтение
    /// страницы не должно запускать конвертер.
    /// </summary>
    Task<ModuleRendition?> FindAsync(string originalPath, CancellationToken ct = default);

    /// <summary>
    /// Построить образ заново — по явному действию человека. Новый образ ложится под новым путём;
    /// после этого вызова пара «что видел человек — что читала модель» больше не обещана, и
    /// распознавание стоит повторить.
    ///
    /// <para><paramref name="layoutProfileId" /> — профиль печати, выбранный человеком (issue #1454). Не
    /// назван — тот, по которому строился прежний образ, пока он есть, иначе системный. Назван
    /// несуществующий — исключение «не найдено» (404), а не молча системный.</para>
    /// </summary>
    Task<ModuleRendition> RebuildAsync(string originalPath, Guid? layoutProfileId = null, CancellationToken ct = default);
}
