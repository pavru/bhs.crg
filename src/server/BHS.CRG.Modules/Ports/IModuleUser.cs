namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Кто сейчас действует и что ему можно (ТЗ AUTH-6, CORE-24.1).
///
/// <para>Ворота на адресах модуля уже стоят — группа требует доступ к модулю
/// (<see cref="AppPolicies.Module" />), а отдельные адреса модуль закрывает правами
/// (<see cref="AppPolicies.Permission" />). Этот порт нужен для второго случая: когда право решает
/// не «пустить ли», а ЧТО ПОКАЗАТЬ — реестр счетов с суммами или без них, кнопка оплаты видна или
/// нет. Такую разницу воротами не выразить: адрес один.</para>
///
/// <para>⚠️ Права берутся ИЗ БАЗЫ, а не из токена: права в токене устаревают ровно тогда, когда это
/// опаснее всего — при отзыве доступа. Ответы кэшируются ядром на запрос, поэтому спрашивать можно
/// столько раз, сколько нужно.</para>
///
/// <para>⚠️ Вне запроса (фоновая задача, старт, расписание) <see cref="Id" /> равен <c>null</c>, а
/// <see cref="HasAsync" /> отвечает <c>false</c> — «прав нет», а не «можно всё». Фоновой операции,
/// которой нужны права поставившего, они достаются из <see cref="ModuleJobRun.UserId" />, а не
/// отсюда.</para>
/// </summary>
public interface IModuleUser
{
    /// <summary>Учётная запись; <c>null</c> — действует сам экземпляр, а не человек.</summary>
    Guid? Id { get; }

    /// <summary>
    /// Имя на момент действия — то же, что попадёт в журнал. У экземпляра — «Система»: пустая строка
    /// читалась бы как «не смогли определить», а это другое утверждение.
    /// </summary>
    string Name { get; }

    /// <summary>Есть ли право. Незнакомый код — <c>false</c>, а не отказ: спрашивают его на каждом
    /// показе, и падение здесь означало бы пустой экран вместо урезанного.</summary>
    Task<bool> HasAsync(string permission, CancellationToken ct = default);

    /// <summary>
    /// Все действующие права — когда решений по правам на экране несколько и спрашивать по одному
    /// значит спрашивать одно и то же. Пустой набор — нормальный ответ.
    /// </summary>
    Task<IReadOnlyCollection<string>> PermissionsAsync(CancellationToken ct = default);
}
