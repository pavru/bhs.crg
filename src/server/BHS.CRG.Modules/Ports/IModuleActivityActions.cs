namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Действия журнала, которые пишет модуль, — ОБЪЯВЛЕНИЕМ, а не только вызовом (ТЗ CORE-28).
///
/// <para>Модуль регистрирует это в <c>RegisterServices</c>, как и обработчики фоновых операций. Не в
/// <see cref="IAppModule" />, потому что объявление нужно ровно тому, кто действия пишет: у модуля без
/// журнала не появляется пустого свойства, которое надо чем-то заполнять.</para>
///
/// <para><b>Зачем объявление вообще.</b> На экране журнала стоит НАЗВАНИЕ действия, а в записи лежит
/// только код: названия берутся из каталога при чтении, чтобы переименование названия доезжало и до
/// старых записей. Значит, название, переданное при записи, до экрана не доедет никак — доедет то,
/// что лежит в каталоге. Без объявления строка журнала читалась бы кодом
/// (<c>costs.invoice.paid</c>), а в отборе по действию модульных действий не было бы вовсе: отбор
/// строится из каталога, а не из того, что уже записано.</para>
///
/// <para>⚠️ Объявление проверяется ПРИ СТАРТЕ: негодный код, чужой префикс или два одинаковых кода —
/// отказ старта, а не тихая запись без названия. Причина та же, что у прав модуля: заметить такое на
/// экране журнала можно только после того, как запись уже сделана, а переписывать прошлое журнал не
/// умеет.</para>
/// </summary>
public interface IModuleActivityActions
{
    /// <summary>
    /// Все действия, которые модуль пишет. Записать действие, которого здесь нет, нельзя — порт
    /// журнала отказывает.
    /// </summary>
    IReadOnlyList<ModuleActivityAction> Actions { get; }
}
