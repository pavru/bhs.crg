using BHS.CRG.Modules.Settings;

namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Значения настроек модуля (задача M1, issue #1070).
///
/// <para>⚠️ Принимает ОБЪЯВЛЕНИЕ, а не строку ключа. Прочитать настройку, которой нет, так нельзя
/// вовсе: ключ с опечаткой не найдёт поля и не скомпилируется, а поле, не вписанное в
/// <c>IAppModule.Settings</c>, порт отвергнет при первом чтении — иначе оно читалось бы умолчанием
/// вечно, без экрана и без способа это заметить.</para>
///
/// <para>Значение читается из базы один раз на запрос: модуль вправе спрашивать его в цикле.
/// Между запросами не кешируется — смена настройки действует со следующего же запроса.</para>
/// </summary>
public interface IModuleSettings
{
    /// <summary>Действующее значение: сохранённое, а если его нет или оно не годится — умолчание.</summary>
    Task<T> GetAsync<T>(ModuleSetting<T> setting, CancellationToken ct = default);
}
