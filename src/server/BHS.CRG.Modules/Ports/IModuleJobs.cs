namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Состояние фоновой задачи.
///
/// ⚠️ Зеркало доменного <c>JobStatus</c>; сверяется сторожем по именам (<c>ModulePortMirrorTests</c>).
/// </summary>
public enum ModuleJobStatus
{
    Queued,
    Running,
    Succeeded,
    Failed,
    /// <summary>Отменена ДО старта: выполняемая задача добегает до конца.</summary>
    Cancelled,
}

/// <summary>
/// Чем занята или чем кончилась задача модуля.
///
/// ⚠️ Кода операции здесь нет, и это решение: операция лежит в аргументах задачи, а аргументы ядро
/// наружу не выдаёт — в них попадают и то, чего показывать не следует. Какую операцию он поставил,
/// модуль знает сам: идентификатор задачи он хранит у своей записи, иначе спрашивать было бы не о чем.
/// </summary>
/// <param name="Progress">Честный текстовый ход («12 из 57 строк»), без выдуманных процентов.
/// <c>null</c> — ещё не докладывали.</param>
/// <param name="Error">Текст отказа у неудавшейся задачи. У остальных <c>null</c>.</param>
public sealed record ModuleJobState(
    Guid Id, string Title, ModuleJobStatus Status, string? Progress, string? Error);

/// <summary>
/// Долгие операции модуля — в фон (ТЗ CORE-3): разбор выгрузки 1С, пересчёт разноски, выгрузка
/// большого реестра.
///
/// <para>Очередь и индикатор активных задач у продукта одни. Свой фоновый цикл в модуле означал бы
/// вторую очередь, которой нет ни в индикаторе у колокольчика, ни в ожидании тестового хоста, ни в
/// остановке при выключении приложения, — то есть задачи, о которых система не знает.</para>
///
/// <para>⚠️ Операцию выполняет <see cref="IModuleJobHandler" />, который модуль регистрирует в
/// <c>RegisterServices</c>. Постановка операции, у которой обработчика нет, — ОТКАЗ СРАЗУ, при
/// вызове. Иначе задача встала бы в очередь и осталась в ней навсегда: на экране «идёт», в базе
/// <c>Queued</c>, и ни отказа, ни результата — отказ, переодетый в работу.</para>
///
/// <para>⚠️ Владельца задачи модуль не называет: его берут из запроса, как автора записи журнала.
/// Вне запроса (расписание, старт) у задачи владельца нет — её отказ уходит общесистемным
/// уведомлением, а не в чей-то личный колокольчик.</para>
///
/// <para>⚠️ Одновременно по одной цели идёт ОДНА задача модуля — так устроена защита от дубля в
/// ядре (уникальный индекс по цели и семейству операции). Две разные операции над одной записью
/// подряд получат отказ «уже выполняется»; понадобится иначе — семейство в индексе расширяется кодом
/// операции, и это правка миграции, а не этого порта.</para>
/// </summary>
public interface IModuleJobs
{
    /// <param name="operation">Код операции модуля — по нему находится обработчик.</param>
    /// <param name="targetId">Над чем операция: запись модуля. Она же ключ защиты от дубля.</param>
    /// <param name="title">Заголовок для индикатора: «Разбор выгрузки 1С».</param>
    /// <param name="payload">Аргументы операции — строкой (обычно JSON). Хранятся с задачей и
    /// достаются обработчику как есть.</param>
    Task<Guid> EnqueueAsync(string operation, Guid targetId, string title, string? payload = null,
        CancellationToken ct = default);

    /// <summary>
    /// Состояние задачи В ЛЮБОМ статусе, включая завершившуюся; <c>null</c> — такой задачи нет.
    ///
    /// Завершённые не удаляются, поэтому спросить можно и спустя сутки. Без этого метода успех
    /// неотличим от отказа для того, кто не видит колокольчика.
    /// </summary>
    Task<ModuleJobState?> GetAsync(Guid jobId, CancellationToken ct = default);
}
