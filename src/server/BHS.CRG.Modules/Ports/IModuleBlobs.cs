namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Хранилище файлов для модуля (ТЗ CORE-34): сканы счётов и накладных, выгрузки 1С, выгруженные
/// XLSX.
///
/// <para>Порт, а не прямой доступ к S3: хранилище на экземпляре настраивает поставка (Garage,
/// ключи, имя корзины), и модуль, знающий об этом, стал бы вторым местом, где настройку читают, —
/// то есть местом, которое разойдётся с первым. Плюс обёртка ядра ведёт реестр блобов, по которому
/// считается вес резервной копии и находятся осиротевшие файлы; модуль, сложивший файл мимо
/// реестра, получил бы файл, который копия не заметит.</para>
///
/// <para>⚠️ Путь, который вернул <see cref="PutAsync" />, модуль обязан СОХРАНИТЬ у своей записи.
/// Восстановить его по имени файла нельзя: имя внутри пути дополняется, чтобы два скана с именем
/// «Счёт.pdf» не затирали друг друга.</para>
///
/// <para>Чего здесь нет: восстановления файла на точный путь (<c>PutAsync</c> ядра с готовым путём)
/// — это дело резервной копии, и модулю оно не нужно; копия проходит по реестру блобов и трогает
/// файлы модуля так же, как свои, не спрашивая модуль.</para>
/// </summary>
public interface IModuleBlobs
{
    /// <summary>Положить файл; возвращает путь, по которому его потом искать.</summary>
    Task<string> PutAsync(string fileName, Stream content, string contentType, CancellationToken ct = default);

    /// <summary>Открыть файл на чтение. Нет файла — отказ, а не пустой поток.</summary>
    Task<Stream> OpenAsync(string path, CancellationToken ct = default);

    /// <summary>Удалить файл. Удаление отсутствующего — не отказ: повтор обязан быть безобидным.</summary>
    Task DeleteAsync(string path, CancellationToken ct = default);

    /// <summary>
    /// Размер в байтах; <c>null</c> — файла нет или он недоступен.
    ///
    /// Отсутствие здесь не отказ намеренно: размер спрашивают, чтобы показать его человеку и чтобы
    /// оценить вес копии, и оба места обязаны пережить пропавший файл, а не упасть на нём.
    /// </summary>
    Task<long?> SizeAsync(string path, CancellationToken ct = default);
}
