namespace BHS.CRG.Modules.Ports;

/// <summary>Запись справочника ядра.</summary>
/// <param name="EntityType">Вид — это КОД ТИПА записи, тот же, что в списке типов: «Организация»,
/// «ОбъектСтроительства». У записи ПОДТИПА здесь стоит код подтипа («ОрганизацияСРО»), а не того
/// вида, которым её спрашивали: вид — свойство записи, а не запроса.
///
/// ⚠️ Дважды сверено с живой базой, и первый раз — неверно (issue #1076). Сначала здесь стояли
/// английские имена (<c>Organization</c>, <c>Person</c>) — по ним список приходил бы ПУСТЫМ. Я
/// заменил их русскими кодами, сверив с таблицей <c>catalog_entities</c>, и на этом остановился. А
/// организации, которые заводит ЭКРАН, лежат не там: общие данные — это <c>domain_objects</c>, и
/// ссылка <c>{"$ref":"catalog","entryId":…}</c> разрешается тоже по ним (<c>EntityResolver</c>,
/// <c>CommonDataBindingCheck</c>). <c>catalog_entities</c> — остаток прежней модели: ни один экран
/// в неё не пишет и ни один адрес клиента её не читает. То есть код вида я проверил у той таблицы,
/// у которой не надо было, и «сверено с живой базой» в этом комментарии было НЕВЕРНО.</param>
/// <param name="DisplayName">Название, которым запись показывают человеку.</param>
/// <param name="DataJson">Данные записи — СТРОКОЙ с JSON, как их хранит ядро. Разбирает их модуль
/// сам: состав полей у каждого вида свой и меняется настройкой, а не кодом, поэтому типа, который
/// здесь можно было бы объявить, не существует.</param>
/// <param name="Archived">Запись в архиве (ТЗ CORE-34.4, issue #1185): из выбора нового значения
/// убрана, сохранённые ссылки на неё целы. Признак обязательный и едет всегда — кто показывает
/// запись, обязан решить, что сказать об архиве.</param>
public sealed record ModuleCatalogEntry(Guid Id, string EntityType, string DisplayName, string DataJson, bool Archived);

/// <summary>
/// Зачем модуль читает справочник: чтобы человек ВЫБРАЛ новое значение или чтобы ПОКАЗАТЬ уже
/// стоящее (ТЗ CORE-34.4, issue #1185).
///
/// <para>Архивная запись из выбора убрана, а сохранённые ссылки на неё целы — поэтому один список
/// обязан отвечать по-разному. Назначение называет тот, кто зовёт, и умолчания у него нет: забытое
/// «показать всё» вернуло бы архивного поставщика в выбор, забытое «скрыть» — оставило бы счёт
/// закрытого периода без названия поставщика.</para>
/// </summary>
public enum RecordsFor
{
    /// <summary>Список, из которого выбирают новое значение. Архивных в нём нет.</summary>
    Choice,

    /// <summary>Показ, сверка, сопоставление того, что уже стоит. Архивные на месте, с признаком.</summary>
    Display,
}

/// <summary>
/// Запись справочника ССЫЛКОЙ: чем её называют и какого она вида — без данных (issue #1078).
///
/// <para><b>Зачем отдельно от <see cref="ModuleCatalogEntry" />.</b> Выбору позиции нужны имя и
/// идентификатор, а справочник номенклатуры — самый большой в системе: в одной установке общие данные
/// весили 5,43 МБ, из них 99,6 % — картинки в base64 (issue #1015). Отдавая строке счёта запись
/// целиком, выпадающий список тянул бы эти картинки на каждый набранный символ. Ровно этот случай
/// назван в <see cref="ModuleCatalogEntry.DataJson" /> как повод сузить, и это он.</para>
///
/// <para>⚠️ Данных здесь нет НАРОЧНО, и подмешивать их сюда нельзя: сопоставление поставщика по ИНН
/// (C3) читает реквизиты и обязано спрашивать <see cref="IModuleCatalog.ListAsync" />. Ссылка,
/// у которой однажды появится <c>DataJson</c>, немедленно станет вторым способом читать справочник —
/// и выбирать между ними будет тот, кто напишет следующую строку кода.</para>
/// </summary>
/// <param name="MatchedAlias">Альтернативное имя, по которому запись найдена поиском, — когда
/// набранного нет в её названии (issue #1169); иначе <c>null</c>. Кто показывает список, обязан
/// показать и его: запись, в названии которой набранного нет, без пояснения выглядит ошибкой поиска.</param>
/// <param name="Archived">Запись в архиве — см. <see cref="ModuleCatalogEntry" />.</param>
public sealed record ModuleCatalogRef(
    Guid Id, string EntityType, string? DisplayName, bool Archived, string? MatchedAlias = null);

/// <summary>
/// Ответ поиска на выбор: живые записи — и сколько под тот же запрос лежит в архиве.
///
/// <para>Число нужно затем, что пустой выбор и «таких записей нет» — разные вещи: не найдя позицию,
/// человек заведёт её заново, а она есть, в архиве. Кто показывает список, обязан это сказать.</para>
/// </summary>
/// <param name="Items">Живые записи; архивных здесь нет.</param>
/// <param name="InArchive">Сколько архивных записей подходит под тот же запрос.</param>
public sealed record ModuleCatalogChoice(IReadOnlyList<ModuleCatalogRef> Items, int InArchive);

/// <summary>
/// Справочники ядра для модуля — ЧТЕНИЕ (ТЗ CORE-34): поставщик у счёта, стройка у разноски, лицо в
/// подписи.
///
/// <para>Порт нужен потому, что ссылаться модуль обязан на СУЩЕСТВУЮЩУЮ запись ядра, а не заводить
/// свою копию организации. Копия разошлась бы с оригиналом на первой же правке реквизитов, и
/// сверить их было бы нечем — в документах печаталось бы одно, в счетах другое.</para>
///
/// <para><b>Записи берутся из общих данных</b> (<c>domain_objects</c>) — оттуда, куда пишет раздел
/// «Общие данные» и куда ведёт ссылка на запись справочника. Другого хранилища у справочников нет:
/// выбери порт второе, модуль ссылался бы на записи, которых не существует для остальной системы, и
/// выглядело бы это как «поставщик есть, а названия у него нет».</para>
///
/// <para><b>Подтипы входят в вид.</b> Спросив «Организация», модуль получает и «ОрганизацияСРО», и
/// «ПроектнаяОрганизация»: подтип организации — организация, и поставщик заказчика может быть любым
/// из них. Так же считает и ядро, когда проверяет, годится ли запись полю (<c>isSubtypeOf</c>).</para>
///
/// <para>⚠️ Записи здесь НЕ фильтруются по правам, и это не упущение: привязки данных к пользователю
/// в системе нет вовсе — уровни справочника (<c>CatalogScope</c>) организуют данные, а не
/// разграничивают доступ (решение от 05.08.2026, issue #675). Появится учётная запись вне компании —
/// изоляция делается в ядре, и этот порт получит её вместе со всеми.</para>
///
/// <para>⚠️ Записи модуль не создаёт и не правит. Справочник ведёт человек в разделе каталога, и
/// модуль, заводящий организации молча, — это второй источник записей, между которыми потом придётся
/// выбирать. Появится настоящий случай (распознали поставщика, которого в справочнике нет) — он
/// придёт задачей с решением, что делать с дублями, а не методом здесь.</para>
/// </summary>
public interface IModuleCatalog
{
    /// <summary>
    /// Все записи вида и его подтипов, по названию (сравнение культурное — список читает человек).
    ///
    /// <para>⚠️ Три ответа, а не два. <b>Список</b> — записи есть. <b>Пустой список</b> — вид есть,
    /// записей нет. <b>Ноль</b> — вида нет вовсе: типа с таким кодом в системе не заведено. Сведи мы
    /// последние два, опечатка в коде вида и «организаций ещё не завели» выглядели бы одинаково —
    /// пустым выпадающим списком, и выбирать между объяснениями пришлось бы человеку.</para>
    ///
    /// <para>Отказом на «нет вида» порт не отвечает НАРОЧНО: тип-справочник заводит человек, и его
    /// отсутствие — состояние установки, а не промах модуля. Что с этим делать, решает модуль: форме
    /// счёта нужен отказ с объяснением, а реестру — пустота, потому что счетов без типа тоже нет.</para>
    ///
    /// <para><paramref name="purpose" /> обязателен: выбор архивные записи скрывает, показ — отдаёт с
    /// признаком (<see cref="RecordsFor" />).</para>
    /// </summary>
    Task<IReadOnlyList<ModuleCatalogEntry>?> ListAsync(
        string entityType, RecordsFor purpose, CancellationToken ct = default);

    /// <summary>Запись по идентификатору; <c>null</c> — нет такой (например, её удалили). Архивная
    /// запись находится, признак — в ответе: по идентификатору спрашивают то, что уже стоит.</summary>
    Task<ModuleCatalogEntry?> GetAsync(Guid id, CancellationToken ct = default);

    /// <summary>
    /// Поиск записей вида по части названия — для ВЫБОРА позиции из большого справочника
    /// (issue #1078): номенклатура в счёте, где записей тысячи.
    ///
    /// <para>Ответы те же три, что у <see cref="ListAsync" />: список, пустой список, <c>null</c> —
    /// вида нет вовсе.</para>
    ///
    /// <para>Это ВСЕГДА выбор: архивных записей в списке нет, а сколько их под тот же запрос —
    /// названо в <see cref="ModuleCatalogChoice.InArchive" /> (issue #1185).</para>
    ///
    /// <para>Ищет и по альтернативным именам записи; найденное по ним называет
    /// <see cref="ModuleCatalogRef.MatchedAlias" />.</para>
    ///
    /// <para>⚠️ <paramref name="limit" /> отсекает список ПОСЛЕ сортировки по названию, но остаётся
    /// отсечением: «в справочнике нет» по неполному списку утверждать нельзя. Кто показывает список,
    /// тот и говорит человеку, что он неполон, — иначе ненайденная позиция читается как
    /// отсутствующая, и человек заведёт вторую такую же.</para>
    /// </summary>
    Task<ModuleCatalogChoice?> SearchAsync(
        string entityType, string? query, int limit, CancellationToken ct = default);

    /// <summary>
    /// Названия УЖЕ ВЫБРАННЫХ записей вида — одним обращением на все идентификаторы (issue #1078).
    ///
    /// <para>Нужен затем, что ссылку хранит модуль, а имя живёт в ядре: строка счёта помнит
    /// идентификатор позиции, и показать её без этого запроса можно только идентификатором. Запрос на
    /// строку означал бы сотню обращений на открытие счёта с сотней строк.</para>
    ///
    /// <para>⚠️ Ненайденный идентификатор в ответ НЕ попадает, и это главное, что здесь есть:
    /// «ссылка есть, записи нет» — потеря данных, и молчать о ней нельзя. Разбираться, чего не
    /// хватает, обязан звавший — сравнением того, что просил, с тем, что пришло.</para>
    ///
    /// <para>Архивная запись — НЕ потеря: она в ответе, с признаком (issue #1185).</para>
    /// </summary>
    Task<IReadOnlyList<ModuleCatalogRef>?> RefsAsync(
        string entityType, IReadOnlyCollection<Guid> ids, CancellationToken ct = default);
}
