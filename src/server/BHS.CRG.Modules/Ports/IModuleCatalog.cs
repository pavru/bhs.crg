namespace BHS.CRG.Modules.Ports;

/// <summary>Запись справочника ядра.</summary>
/// <param name="EntityType">Вид — это КОД ТИПА записи, тот же, что в списке типов: «Организация»,
/// «ОбъектСтроительства». У записи ПОДТИПА здесь стоит код подтипа («ОрганизацияСРО»), а не того
/// вида, которым её спрашивали: вид — свойство записи, а не запроса.
///
/// ⚠️ Дважды сверено с живой базой, и первый раз — неверно (issue #1076). Сначала здесь стояли
/// английские имена (<c>Organization</c>, <c>Person</c>) — по ним список приходил бы ПУСТЫМ. Я
/// заменил их русскими кодами, сверив с таблицей <c>catalog_entities</c>, и на этом остановился. А
/// организации, которые заводит ЭКРАН, лежат не там: общие данные — это <c>domain_objects</c>, и
/// ссылка <c>{"$ref":"catalog","entryId":…}</c> разрешается тоже по ним (<c>EntityResolver</c>,
/// <c>CommonDataBindingCheck</c>). <c>catalog_entities</c> — остаток прежней модели: ни один экран
/// в неё не пишет и ни один адрес клиента её не читает. То есть код вида я проверил у той таблицы,
/// у которой не надо было, и «сверено с живой базой» в этом комментарии было НЕВЕРНО.</param>
/// <param name="DisplayName">Название, которым запись показывают человеку.</param>
/// <param name="DataJson">Данные записи — СТРОКОЙ с JSON, как их хранит ядро. Разбирает их модуль
/// сам: состав полей у каждого вида свой и меняется настройкой, а не кодом, поэтому типа, который
/// здесь можно было бы объявить, не существует.</param>
public sealed record ModuleCatalogEntry(Guid Id, string EntityType, string DisplayName, string DataJson);

/// <summary>
/// Справочники ядра для модуля — ЧТЕНИЕ (ТЗ CORE-34): поставщик у счёта, стройка у разноски, лицо в
/// подписи.
///
/// <para>Порт нужен потому, что ссылаться модуль обязан на СУЩЕСТВУЮЩУЮ запись ядра, а не заводить
/// свою копию организации. Копия разошлась бы с оригиналом на первой же правке реквизитов, и
/// сверить их было бы нечем — в документах печаталось бы одно, в счетах другое.</para>
///
/// <para><b>Записи берутся из общих данных</b> (<c>domain_objects</c>) — оттуда, куда пишет раздел
/// «Общие данные» и куда ведёт ссылка на запись справочника. Другого хранилища у справочников нет:
/// выбери порт второе, модуль ссылался бы на записи, которых не существует для остальной системы, и
/// выглядело бы это как «поставщик есть, а названия у него нет».</para>
///
/// <para><b>Подтипы входят в вид.</b> Спросив «Организация», модуль получает и «ОрганизацияСРО», и
/// «ПроектнаяОрганизация»: подтип организации — организация, и поставщик заказчика может быть любым
/// из них. Так же считает и ядро, когда проверяет, годится ли запись полю (<c>isSubtypeOf</c>).</para>
///
/// <para>⚠️ Записи здесь НЕ фильтруются по правам, и это не упущение: привязки данных к пользователю
/// в системе нет вовсе — уровни справочника (<c>CatalogScope</c>) организуют данные, а не
/// разграничивают доступ (решение от 05.08.2026, issue #675). Появится учётная запись вне компании —
/// изоляция делается в ядре, и этот порт получит её вместе со всеми.</para>
///
/// <para>⚠️ Записи модуль не создаёт и не правит. Справочник ведёт человек в разделе каталога, и
/// модуль, заводящий организации молча, — это второй источник записей, между которыми потом придётся
/// выбирать. Появится настоящий случай (распознали поставщика, которого в справочнике нет) — он
/// придёт задачей с решением, что делать с дублями, а не методом здесь.</para>
/// </summary>
public interface IModuleCatalog
{
    /// <summary>
    /// Все записи вида и его подтипов, по названию (сравнение культурное — список читает человек).
    ///
    /// <para>⚠️ Три ответа, а не два. <b>Список</b> — записи есть. <b>Пустой список</b> — вид есть,
    /// записей нет. <b>Ноль</b> — вида нет вовсе: типа с таким кодом в системе не заведено. Сведи мы
    /// последние два, опечатка в коде вида и «организаций ещё не завели» выглядели бы одинаково —
    /// пустым выпадающим списком, и выбирать между объяснениями пришлось бы человеку.</para>
    ///
    /// <para>Отказом на «нет вида» порт не отвечает НАРОЧНО: тип-справочник заводит человек, и его
    /// отсутствие — состояние установки, а не промах модуля. Что с этим делать, решает модуль: форме
    /// счёта нужен отказ с объяснением, а реестру — пустота, потому что счетов без типа тоже нет.</para>
    /// </summary>
    Task<IReadOnlyList<ModuleCatalogEntry>?> ListAsync(string entityType, CancellationToken ct = default);

    /// <summary>Запись по идентификатору; <c>null</c> — нет такой (например, её удалили).</summary>
    Task<ModuleCatalogEntry?> GetAsync(Guid id, CancellationToken ct = default);
}
