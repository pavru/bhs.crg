namespace BHS.CRG.Modules.Ports;

/// <summary>Чем охрана запретила запись.</summary>
/// <param name="Code">Код отказа: <c>locked-field</c> — тронуто запертое поле модуля.</param>
/// <param name="Path">Адрес значения в данных (<c>Работы[3].Количество</c>); <c>null</c> — отказ не
/// про конкретное поле. Адрес нужен, чтобы форма подсветила поле, а не показала баннер, по которому
/// нарушение внутри строки таблицы не найти.</param>
public sealed record ModuleWriteRefusal(string Code, string? Path, string Message);

/// <summary>
/// Охрана записи для модуля (ТЗ CORE-20, issue #957): проверить вид значения и запертые поля ПЕРЕД
/// сохранением.
///
/// <para>Зачем модулю спрашивать то, что ядро проверяет само. Ядро проверяет пути, которые ведёт
/// оно: реквизиты документа, запись общих данных, документ качества, печатную форму. Запись, которую
/// модуль хранит в своей таблице, ядро не сохраняет и проверить не может — а правила у неё те же:
/// системное поле модуля заперто и для человека за формой, и для чужого кода.</para>
///
/// <para>⚠️ Отказы ВОЗВРАЩАЮТСЯ, а не бросаются. Отказ ядра модуль поймать не может (класс живёт в
/// слое, на который модуль не ссылается), поэтому решение — его: обычно отказать запросу доменным
/// отказом (<c>InvalidRequestException</c>), который приложение само превратит в 400 с перечислением
/// полей. Пустой список — запись разрешена.</para>
///
/// <para>⚠️ Проверяется только то, что запись ВНОСИТ, а не документ целиком. Кривые значения в базе
/// уже есть, и охрана «целиком» сделала бы такую запись нередактируемой: открыл, нажал «Сохранить»
/// без правок, получил отказ, и починить из того же экрана нечем.</para>
///
/// <para>⚠️ Здесь же — правило архива (ТЗ CORE-34.4): НОВАЯ ссылка <c>{"$ref":"catalog","entryId"}</c>
/// на запись в архиве даёт находку с кодом <c>archived-ref</c>. «Новая» — та, которой нет в
/// <c>storedJson</c>; у создания (<c>null</c>) новой считается КАЖДАЯ. Это верно, когда ссылки
/// выбирает человек. Машинный путь, который переносит стоявшие ссылки — копия записи, импорт,
/// черновик из распознавания, — обязан либо передать источник как <c>storedJson</c>, либо не
/// считать находку <c>archived-ref</c> отказом: иначе запись со ссылкой на архивную организацию
/// нельзя будет ни скопировать, ни завести заново. У путей ядра это стережёт перечень
/// <c>RecordWriteGuardCoverageTests</c>; модуль отвечает за свои сам.</para>
/// </summary>
public interface IModuleWriteGuard
{
    /// <param name="typeId">Тип записи — его схема и задаёт замки.</param>
    /// <param name="storedJson">Данные, КАК ОНИ ЛЕЖАТ сейчас; <c>null</c> — запись создаётся.</param>
    /// <param name="incomingJson">Данные, которые просят сохранить.</param>
    Task<IReadOnlyList<ModuleWriteRefusal>> RefusalsAsync(
        Guid typeId, string? storedJson, string incomingJson, CancellationToken ct = default);
}
