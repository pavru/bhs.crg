namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Важность уведомления модуля.
///
/// ⚠️ Это ЗЕРКАЛО доменного <c>NotificationSeverity</c>, как <see cref="ModuleSchemaLevel" /> —
/// зеркало уровня правки схемы: ссылок на наши проекты в контрактах нет вовсе. Что зеркало не
/// разошлось с оригиналом, сверяет сторож (<c>ModulePortMirrorTests</c>) — по именам значений.
/// </summary>
public enum ModuleNotificationLevel
{
    Info,
    Warning,
    Error,
}

/// <summary>
/// Уведомления (колокольчик) для модуля (ТЗ AUTH-13, CORE-27).
///
/// <para>⚠️ Аудитория общесистемного уведомления — КОД ПРАВА или КОД МОДУЛЯ, а не роль и не список
/// пользователей. Считается она при чтении, поэтому право, выданное завтра, откроет и вчерашние
/// уведомления, а отозванное — закроет. Необъявленная аудитория (опечатка в коде права) — ОТКАЗ:
/// иначе уведомление ушло бы никому, выглядя отправленным.</para>
///
/// <para>Кому — задаётся ровно одним способом: либо <paramref name="audience" />, либо
/// <paramref name="userId" />. Оба сразу — отказ: это разные способы назвать адресата, и молчаливый
/// выбор одного из них означал бы «отправлено» в ответ на неверно составленный вызов.</para>
///
/// <para>Чтения и отметок «прочитано» здесь нет: список показывает колокольчик ядра, один на весь
/// продукт. Модулю принадлежит только публикация.</para>
/// </summary>
public interface IModuleNotifications
{
    /// <param name="audience">Код права или код модуля — кому это общесистемное уведомление.</param>
    /// <param name="userId">Личное уведомление конкретному пользователю.</param>
    /// <param name="linkUrl">Куда ведёт уведомление: адрес экрана модуля.</param>
    /// <param name="linkLabel">Подпись ссылки — без неё ссылка в колокольчике безымянна.</param>
    /// <returns>Идентификатор записи: по нему издатель может сразу скрыть её у того, кому она не
    /// нужна (у автора собственного действия), не заводя для этого поля в самой записи.</returns>
    Task<Guid> PublishAsync(ModuleNotificationLevel level, string title, string message,
        string? audience = null, Guid? userId = null, string? linkUrl = null, string? linkLabel = null,
        CancellationToken ct = default);
}
