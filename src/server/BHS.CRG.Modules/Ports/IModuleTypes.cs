namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Типы ядра для модуля — ЧТЕНИЕ по коду (задача C1 этапа 2, issue #1076, ТЗ CORE-20.1).
///
/// <para><b>Зачем.</b> Запись модуля обязана помнить свой тип: по нему её рисует общая форма, печатает
/// общий механизм и находит реестр тэгов. Объявляет тип сам модуль, но заводит его ЯДРО — проекцией
/// при старте, — и идентификатор у типа в каждой установке свой. Значит модулю нужен способ спросить
/// «какой идентификатор у типа с моим кодом», и другого способа, кроме порта, у него нет: ссылки на
/// слой доступа к данным ему закрыты (<c>ModuleBoundaryTests</c>).</para>
///
/// <para>⚠️ <b>Только чтение и только по коду.</b> Ни схемы, ни списка типов, ни правки: схему
/// заводит объявление модуля, а править типы — дело администратора в редакторе. Порт, отдающий схему,
/// пригласил бы модуль читать её самому — и тогда у поля появился бы второй читатель мимо реестра
/// тэгов, то есть мимо единственного санкционированного моста между конфигурацией и кодом.</para>
///
/// <para>⚠️ <c>null</c> — <b>штатный ответ</b>, а не ошибка порта: тип модуля может быть не заведён.
/// Так бывает, когда код типа занял чужой тип или занято его имя — проекция тогда пропускает
/// объявление и называет причину в журнале запуска. Модуль обязан ответить на это отказом, который
/// отправляет читать журнал, а не пустым списком счетов.</para>
/// </summary>
public interface IModuleTypes
{
    /// <summary>Идентификатор типа с этим кодом; <c>null</c> — типа нет.</summary>
    Task<Guid?> FindAsync(string code, CancellationToken ct = default);
}
