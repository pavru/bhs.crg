namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Учётный период: до какой даты учёт закрыт (ТЗ COST-Q8).
///
/// <para>Служба ядра, а не модуля: закрытый период запирает записи ВСЕХ модулей сразу — иначе
/// «закрыто» у счетов и у выработки означало бы разное, и сводить их было бы нечем.</para>
///
/// <para>⚠️ Сегодня на любом экземпляре закрытых периодов НЕТ, и это правда, а не заглушка: закрывать
/// период пока нечем — служба закрытия приезжает задачей E1a этапа 2 (issue #1081). Тогда здешние
/// ответы начнут меняться, а сигнатуры останутся: модуль, написанный против этого порта, переживёт
/// появление службы без правок. Порт заведён раньше службы нарочно — иначе первый же модуль, которому
/// понадобился период, спросил бы базу напрямую и получил своё представление о закрытии.</para>
///
/// <para>⚠️ Отказывать на записи в закрытый период — дело модуля: только он знает, какая дата у его
/// записи считается учётной (дата счёта, дата оплаты, дата разноски). Порт отвечает на вопрос, а
/// решение принимает вызывающий.</para>
/// </summary>
public interface IModulePeriods
{
    /// <summary>
    /// Последний закрытый день: всё по эту дату включительно закрыто. <c>null</c> — не закрыто
    /// ничего.
    /// </summary>
    Task<DateOnly?> ClosedThroughAsync(CancellationToken ct = default);

    /// <summary>Закрыт ли день. Вопрос отдельным методом, чтобы сравнение дат жило в одном месте:
    /// «по эту дату включительно» — ровно то условие, которое каждый второй напишет со сдвигом.</summary>
    Task<bool> IsClosedAsync(DateOnly date, CancellationToken ct = default);
}
