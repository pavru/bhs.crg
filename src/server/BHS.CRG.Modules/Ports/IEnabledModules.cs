namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Состав поставки: какие модули включены на этом экземпляре (ТЗ AUTH-17, AUTH-19).
///
/// <para>Спрашивают его, чтобы не обещать того, чего на экземпляре нет: счёт ссылается на стройку
/// исполнительной документации, только если модуль <c>id</c> включён, а иначе показывает свои статьи
/// затрат — без ссылки, которую некому открыть.</para>
///
/// <para>⚠️ Узкий порт, а не сам реестр (<see cref="ModuleRegistry" />), хотя реестр и лежит в
/// контейнере рядом. Реестр отдаёт ОБЪЕКТЫ модулей, то есть их права, адреса и регистрацию служб:
/// модуль, получивший его, может позвать чужой <c>MapEndpoints</c> или прочитать чужое объявление
/// прав — и сведёт два модуля в один тем же способом, который запрещает <c>ModuleBoundaryTests</c>
/// на уровне ссылок. Здесь же только коды: вопрос «включён ли» на них отвечается целиком.</para>
/// </summary>
public interface IEnabledModules
{
    /// <summary>Включён ли модуль с таким кодом. Регистр не важен.</summary>
    bool IsEnabled(string code);

    /// <summary>Коды включённых модулей в том порядке, в каком их перечислила поставка.</summary>
    IReadOnlyList<string> Codes { get; }
}
