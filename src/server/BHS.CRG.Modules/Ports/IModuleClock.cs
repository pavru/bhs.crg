namespace BHS.CRG.Modules.Ports;

/// <summary>
/// Какой сегодня день — в поясе компании (ТЗ CORE-5, CORE-33; задача G1c, issue #1090).
///
/// <para>Нужен всему, что считается «от сегодня» и НЕ хранится: «осталось дней» и «просрочен» у счёта
/// (ТЗ COST-9.1). Такое значение верно ровно до полуночи, поэтому его считают на чтении — и граница
/// суток обязана быть одной на всю систему.</para>
///
/// <para><b>Почему порт, а не часы сервера.</b> Сервер стоит в одном поясе, компания работает в другом:
/// «сегодня» по часам сервера сдвинуло бы полночь на эту разницу, и счёт становился бы просроченным
/// на несколько часов раньше или позже, чем его срок истёк у людей. Пояс компании — настройка ядра, а
/// настроек ядра модуль не видит.</para>
///
/// <para>⚠️ <see cref="TodayAsync" /> — пояс компании, а не стройки: счёт к одной стройке не привязан.
/// «Сегодня на стройке» — другой вопрос и другой метод (<see cref="TodayOnSiteAsync" />), а не
/// параметр по умолчанию у этого: назначения и отчёты считают сутки стройки (ТЗ WORK-8), и полночь
/// во Владивостоке наступает на семь часов раньше московской.</para>
/// </summary>
public interface IModuleClock
{
    /// <summary>Сегодняшняя дата в поясе компании.</summary>
    Task<DateOnly> TodayAsync(CancellationToken ct = default);

    /// <summary>
    /// Сегодняшняя дата на стройке — по её действующему поясу (<see cref="ModuleConstruction.TimeZoneId" />,
    /// change <c>work-11-assignments</c>). <c>null</c> — стройки нет: дата по поясу компании выдала бы
    /// потерю стройки за обычный ответ.
    /// </summary>
    Task<DateOnly?> TodayOnSiteAsync(Guid constructionId, CancellationToken ct = default);

    /// <summary>
    /// Дата стройки для мгновения: смена, начатая в 23:30 по стройке, относится к этой дате, а не к
    /// дате сервера или компании (ТЗ WORK-8). Правило суток живёт здесь одно — и для «сегодня», и для
    /// отметки времени (подача отчёта, <c>work-15</c>). <c>null</c> — стройки нет.
    /// </summary>
    Task<DateOnly?> SiteDateOfAsync(Guid constructionId, DateTimeOffset instant, CancellationToken ct = default);
}
