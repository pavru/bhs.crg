namespace BHS.CRG.Modules;

/// <summary>
/// Поле справочника, которое модуль читает ПО ТЭГУ (ТЗ TYPE-23, issue #1101).
/// </summary>
/// <param name="Tag">Код тэга поля. Обязан относиться к роли своей потребности — иначе отказ старта.</param>
/// <param name="Required">Без поля не работает заявленное в <paramref name="WithoutIt" />. Необязательное
/// поле в счёт незакрытого не идёт: без него модуль работает, только беднее.</param>
/// <param name="WithoutIt">Что не работает без поля — словами того, кто работает с модулем, и что он
/// теперь делает руками: «поставщик по ИНН из файла счёта не находится — организацию в каждом счёте
/// выбирают вручную». Пусто быть не может: строка «не назначено» без следствия не говорит, срочно ли это.</param>
public sealed record ModuleFieldNeed(string Tag, bool Required, string WithoutIt);

/// <summary>
/// Справочник ядра, без которого модуль не работает, — названный РОЛЬЮ, а не кодом типа
/// (ТЗ TYPE-23, CORE-20.4, issue #1101).
///
/// <para><b>Почему роль.</b> Справочник заводит и называет человек: на новой установке типа
/// «Организация» нет вовсе, а на действующей он может зваться иначе. Модуль, знающий его по имени,
/// работает ровно до первого переименования — и отказывает словами «тип не заведён» про тип,
/// который стоит на месте.</para>
///
/// <para><b>Почему потребность объявляет модуль, а не роль.</b> У двух читателей одного справочника
/// требования разные: счетам ИНН нужен для сопоставления поставщика, а другому читателю организаций
/// он может быть не нужен вовсе. Обязательность на самой роли заставила бы врать одному из них.</para>
///
/// <para>⚠️ Объявление — не памятка, а граница: порт к справочнику отвечает только на роли и тэги,
/// объявленные здесь. Поэтому экран сопоставления не может показать меньше, чем код читает.</para>
/// </summary>
/// <param name="Role">Код тэга-роли типа: <c>role.organization</c>.</param>
/// <param name="Purpose">Зачем модулю справочник: «поставщик и плательщик счёта».</param>
/// <param name="WithoutIt">Что не работает, пока роль не назначена ни одному типу.</param>
/// <param name="Fields">Поля справочника, которые модуль читает по тэгам. Пусто — ему хватает самих
/// записей: названия и ссылки.</param>
public sealed record ModuleRoleNeed(
    string Role, string Purpose, string WithoutIt, IReadOnlyList<ModuleFieldNeed>? Fields = null)
{
    public IReadOnlyList<ModuleFieldNeed> Fields { get; init; } = Fields ?? [];
}
