namespace BHS.CRG.Modules.Tables;

/// <summary>
/// Готовый отбор таблицы — условие, которое модуль ПРЕДЛАГАЕТ поставить одним нажатием, и число строк
/// под ним (issue #1186): «Ссылки на удалённые записи · 3» над реестром счетов.
///
/// <para><b>Понятие таблицы, а не представления.</b> Представление условий не несёт
/// (<see cref="ModuleTableView" />: «настройка, а не отбор») — зашитое в него условие было бы отбором,
/// который человек не ставил и снять не может. Готовый отбор ничего не зашивает: экран по нажатию
/// кладёт его в ОБЫЧНЫЙ отбор, и дальше это условие как любое другое — видно чипом, снимается
/// крестиком, сочетается с остальными, едет в ссылке.</para>
///
/// <para><b>Число считает та же служба строк под тем же условием</b> — ядро спрашивает у неё страницу
/// нулевой длины и берёт число строк отбора. Отдельной арифметики у счётчика нет нарочно: посчитай
/// модуль число своим запросом, оно однажды разошлось бы с числом строк, которые человек увидит,
/// нажав на него.</para>
///
/// <para><b>Условие — одно: «колонка-выбор равна значению».</b> Не дерево. У закрытого перечня есть
/// обещание, которого нет у остальных видов: значение вне перечня — отказ, а не «ничего не нашлось»,
/// и объявление проверяется при старте целиком. Понадобится условие сложнее — модуль заводит колонку,
/// которая его называет словом: так человек видит в чипе то же, что написано на кнопке.</para>
/// </summary>
/// <param name="Code">Код отбора внутри таблицы: <c>lost</c>.</param>
/// <param name="Title">Подпись для человека: «Ссылки на удалённые записи».</param>
/// <param name="Column">Ключ колонки-выбора, по которой стоит условие.</param>
/// <param name="Value">Значение из её перечня (<see cref="ModuleTableColumn.Options" />).</param>
/// <param name="Hint">Что это за строки и что с ними делать — подсказкой к подписи.</param>
/// <param name="Requires">Ключ доступа, без которого отбор НЕ ПРЕДЛАГАЕТСЯ вовсе, — право или код
/// модуля. Нужен отбору, который зовёт к действию: тому, кто исправить не может, число было бы
/// упрёком без выхода. Саму колонку это не закрывает — условие по ней человек поставит и руками.
/// null — отбор предлагается каждому, кому открыта таблица.</param>
/// <param name="Quiet">Отбор не зовёт к срочному действию: строки под ним верны, их стоит заметить, а
/// не чинить («Записи в архиве»). Экран показывает такой отбор тише соседнего.</param>
public sealed record ModuleTableShortcut(
    string Code,
    string Title,
    string Column,
    string Value,
    string? Hint = null,
    string? Requires = null,
    bool Quiet = false)
{
    /// <summary>Оператор условия. Один на все готовые отборы — и экрану, и ядру.</summary>
    public const string Op = "eq";

    /// <summary>Что не так с объявлением; пусто — годно. Собирает ВСЁ, а не первое.</summary>
    /// <param name="declared">Объявленные колонки таблицы. Поля схемы типа сюда не входят: их состав
    /// меняет заказчик, и отбор модуля, опирающийся на них, ломался бы правкой типа.</param>
    public IReadOnlyList<string> Problems(IReadOnlyList<ModuleTableColumn> declared)
    {
        var problems = new List<string>();
        var name = string.IsNullOrWhiteSpace(Code) ? "без кода" : $"«{Code}»";
        void Add(string problem) => problems.Add($"готовый отбор {name}: {problem}");

        if (string.IsNullOrWhiteSpace(Code)) Add("не назван код");
        if (string.IsNullOrWhiteSpace(Title)) Add("нет подписи для человека");
        if (string.IsNullOrWhiteSpace(Column)) { Add("не названа колонка"); return problems; }

        var column = (declared ?? []).FirstOrDefault(c => c?.Key == Column);
        if (column is null) { Add($"колонки «{Column}» в таблице нет"); return problems; }

        if (column.DependsOnFilter) Add($"условие стоит на колонке «{Column}», а по ней не отбирают");

        // Колонка, закрытая правом, отказывает в отборе тому, у кого права нет: число у такого человека
        // не посчиталось бы вовсе, и адрес готовых отборов отвечал бы ему отказом вместо списка.
        if (!string.IsNullOrWhiteSpace(column.Requires))
            Add($"условие стоит на колонке «{Column}», а она закрыта правом «{column.Requires}»");

        if (column.Kind != ModuleTableColumnKind.Choice)
            Add($"условие стоит на колонке «{Column}», а она не выбор из закрытого перечня");
        else if (!(column.Options ?? []).Contains(Value, StringComparer.Ordinal))
            Add($"значения «{Value}» нет в перечне колонки «{Column}»");

        return problems;
    }
}
