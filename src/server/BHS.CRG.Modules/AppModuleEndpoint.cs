namespace BHS.CRG.Modules;

/// <summary>
/// Пометка на адресах включённого модуля: чей это адрес.
///
/// Нужна не для работы приложения, а чтобы правило можно было проверить: по ней тест находит все
/// адреса модуля и сверяет их с объявленными префиксами (<see cref="IAppModule.RoutePrefixes" />).
/// Без пометки расхождение — «модуль зарегистрировал адрес вне своих префиксов» — всплыло бы только
/// при выключении модуля, то есть у заказчика: адрес молча отвечал бы пустым 404 вместо отказа.
/// </summary>
/// <param name="Code">Код модуля.</param>
public sealed record AppModuleEndpoint(string Code);
