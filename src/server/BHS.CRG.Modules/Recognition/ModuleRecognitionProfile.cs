namespace BHS.CRG.Modules.Recognition;

/// <summary>
/// Поле или колонка заводского профиля распознавания: что вернуть и что это значит.
/// </summary>
/// <param name="Name">Ключ в ответе распознавателя, он же имя колонки источника. Без пробелов.</param>
/// <param name="Description">
/// Подсказка модели. Это единственный канал смысла в запрос: строка «ключ — описание — тип»
/// печатается из него, отдельного «названия» у поля нет.
/// </param>
/// <param name="Type">Вид значения: <c>string</c>, <c>number</c>, <c>date</c>.</param>
/// <param name="Options">Закрытый перечень допустимых значений; пусто — любое.</param>
public sealed record ModuleRecognitionField(
    string Name,
    string Description,
    string Type = "string",
    IReadOnlyList<string>? Options = null);

/// <summary>
/// Подсказки о ФОРМЕ таблицы — то, чего перечнем колонок не выразить. Зеркало записи ядра: у этой
/// сборки ноль ссылок на проекты (ТЗ CORE-2), и тип ядра сюда не дотянуть.
/// </summary>
public sealed record ModuleRecognitionShape(
    bool TwoTierHeader = false,
    bool PairedSections = false,
    bool SkipTotals = true);

/// <summary>
/// Заводской профиль распознавания, который вносит МОДУЛЬ (ТЗ CORE-Q6, задача B1a, issue #1075).
///
/// <para>Распознавание — служба ядра: движки, очередь, хранение профилей и сами запросы к модели
/// живут там. Модуль объявляет, ЧТО читать в его документах: перечень полей и колонок. Запрос к
/// модели он не пишет — выбирает один из известных ядру видов (<paramref name="Kind" />) и даёт к нему
/// параметры. Это тот же мост «конфигурация выбирает известную коду стратегию», что у функциональных
/// тэгов.</para>
///
/// <para>Объявляется в коде и читается у ВСЕХ модулей сборки, включая выключенные, — по той же
/// причине, что настройки и таблицы: строка профиля выключенного модуля лежит в базе и приезжает в
/// резервной копии, и узнать её владельца больше некому. Профиль выключенного модуля не предлагается
/// и не удаляется; обращение к нему — отказ, который называет модуль.</para>
///
/// <para>⚠️ Содержимое заводского профиля — часть поставки: администратор вправе его править, и по
/// хешу содержимого ядро решает, ушёл ли заводской вариант вперёд. Правка описания поля здесь зажжёт
/// «заводской профиль обновился» у каждого, кто профиль менял, — это и есть её смысл, но случайной
/// она быть не должна.</para>
/// </summary>
/// <param name="Code">
/// Стабильный код — ключ строки в базе, не переименовывается. Уникален во всей сборке: два владельца
/// одного кода — отказ при старте.
/// </param>
/// <param name="Name">Название для человека.</param>
/// <param name="Kind">
/// Вид профиля — имя стратегии ядра (<c>TitleBlock</c>, <c>Invoice</c>, <c>Table</c>, …). Строкой, а
/// не перечислением, по той же причине, что зеркало формы выше. Неизвестный вид — отказ при старте.
///
/// ⚠️ На один вид — один заводской профиль во всей сборке: им читают, когда к файлу не привязан
/// другой. Второй заводской профиль того же вида сделал бы это умолчание выбором наугад.
/// </param>
/// <param name="Fields">Скалярные поля. Пусто — у вида их нет (чистая таблица).</param>
/// <param name="RowColumns">Колонки табличной части. Пусто — таблицы у вида нет.</param>
/// <param name="Shape">Подсказки о форме таблицы; только для табличных видов.</param>
/// <param name="DocumentTag">
/// Функциональный тэг документа, по которому этот профиль выбирается сам: лист с таким тэгом читается
/// как таблица этими колонками. Тэг объявляет тот же модуль (<see cref="IAppModule.Tags" />).
/// </param>
public sealed record ModuleRecognitionProfile(
    string Code,
    string Name,
    string Kind,
    IReadOnlyList<ModuleRecognitionField>? Fields = null,
    IReadOnlyList<ModuleRecognitionField>? RowColumns = null,
    ModuleRecognitionShape? Shape = null,
    string? DocumentTag = null)
{
    public IReadOnlyList<ModuleRecognitionField> Fields { get; init; } = Fields ?? [];

    public IReadOnlyList<ModuleRecognitionField> RowColumns { get; init; } = RowColumns ?? [];
}
