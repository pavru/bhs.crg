namespace BHS.CRG.Modules.Data;

/// <summary>
/// Запись модуля, видимая не всем: монтажнику — свои отчёты, менеджеру — отчёты его строек (ТЗ WORK-39,
/// CORE-3; work-07). Такая запись читается ТОЛЬКО методом, принимающим параметр доступа
/// (<see cref="Access.ModuleReader" />): охват вычисляет этот метод (<see cref="Access.ModuleReach" />), и
/// стоит он в одном файле чтения на запись.
///
/// <para><b>Пометкой и переписью, а не запретом в контексте.</b> <see cref="ModuleDbContext" /> не
/// запрещает <c>Set&lt;T&gt;()</c>: запрет кодом обходится — вторым контекстом, сырым SQL, приведением
/// типа. Перепись (<c>IsolatedReadInventoryTests</c>) обхода не пропускает: у изолированной записи нет
/// <c>DbSet&lt;T&gt;</c>, а <c>Set&lt;T&gt;()</c> и сырой SQL по её таблице стоят только в файле чтения из
/// перечня — с причиной.</para>
///
/// <para><b>Почему не <c>HasQueryFilter</c> по текущему пользователю.</b> Фильтр модели не знает, кто
/// спросил, — его пришлось бы брать из окружения запроса. Фоновое задание окружения не имеет и прочитало
/// бы ноль строк: отказ, переодетый в пустоту. А чтение мимо фильтра (<c>IgnoreQueryFilters</c>, сырой
/// SQL) выглядит в коде как любое другое, и перепись не отличила бы его от законного.</para>
///
/// <para>Модуль, объявивший таблицу с отбором по правам (<c>ModuleTableIsolation.PerUser</c>), обязан
/// пометить хотя бы одну запись: иначе отбор держится одной службой строк таблицы, а прочие пути чтения
/// той же записи — экспорт, порты, MCP — его не знают.</para>
/// </summary>
public interface IIsolatedRecord;
