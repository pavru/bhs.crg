namespace BHS.CRG.Modules.Data;

/// <summary>
/// Набор, который только ДОПИСЫВАЕТСЯ: правка и удаление его строк отвергаются на сохранении
/// (<see cref="ModuleDbContext" />). Так живут журнал действий и история версий записи — всё, что
/// отвечает на вопрос «как было раньше».
///
/// <para>Пометкой на сущности, а не списком в контексте: список пришлось бы вспомнить при заведении
/// таблицы, а пометка стоит там же, где её причина. Забытая пометка — молчаливая потеря защиты, и
/// поймать её списком в другом файле не удалось бы ничем.</para>
///
/// <para>⚠️ Ядро защищает свой журнал ТЕМ ЖЕ приёмом, но своей пометкой: <c>AppDbContext</c> живёт в
/// инфраструктуре, а она на контракты модулей не ссылается и ссылаться не может — модулем считается
/// любой проект, сославшийся на них (ТЗ CORE-2). Две реализации одного правила — цена этого
/// направления ссылок, и названа она вслух: сторож требует, чтобы ОБА контекста отказывали, и падает,
/// если защиту сняли в одном из них.</para>
///
/// <para>⚠️ Чего пометка не закрывает — того же, чего не закрывает ядро: <c>ExecuteUpdate</c>,
/// <c>ExecuteDelete</c> и голый SQL идут мимо отслеживания изменений. Их ловит перепись обращений к
/// набору по исходникам (приём <c>ActivityLogInventoryTests</c>), а не эта пометка.</para>
/// </summary>
public interface IAppendOnly;
