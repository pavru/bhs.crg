using Microsoft.EntityFrameworkCore;

namespace BHS.CRG.Modules.Data;

/// <summary>
/// Контекст базы МОДУЛЯ: своя схема, свой набор миграций, своя история (ТЗ CORE-4, задача A2a этапа 2,
/// issue #1072).
///
/// <para>Модуль работает со своими таблицами сам — через этот контекст. Общего хранилища
/// (<c>Repository&lt;T&gt;</c>, <c>IRepository&lt;T&gt;</c>) ему НЕ достаётся, и это не упущение:
/// оно живёт в инфраструктуре ядра, а ссылка туда открыла бы модулю слой доступа к данным целиком —
/// вместе с таблицами ядра. Всё, что модулю нужно ОТ ЯДРА, приходит портами
/// (<c>BHS.CRG.Modules.Ports</c>); всё, что принадлежит ему самому, он держит здесь.</para>
///
/// <para><b>⚠️ Общей транзакции ядро↔модуль НЕТ.</b> Два контекста — два соединения, и сохранение в
/// схеме модуля не откатывается вместе с сохранением в схеме ядра. Последствие видно уже на первом
/// сценарии: скан счёта кладётся в блоб, реестр блобов (<c>blob_registry</c>) — таблица ЯДРА, а сам
/// счёт — таблица модуля, то есть запись идёт в две схемы двумя транзакциями. Отсюда правило:
/// <list type="number">
///   <item>сначала своё, потом чужое — модуль сохраняет свою запись, и только после успеха просит
///   ядро (журнал, уведомление, задача). Обратный порядок оставил бы в журнале ядра запись о
///   действии, которого не произошло;</item>
///   <item>у ядра не просят того, что придётся откатывать. Порт, у которого нет обратного действия,
///   вызывается последним;</item>
///   <item>ссылок внешним ключом СКВОЗЬ схемы не бывает: строка модуля ссылается на объект ядра
///   идентификатором, а целость проверяется кодом. Внешний ключ через границу связал бы два набора
///   миграций и две резервные копии в одну — и восстановление по частям стало бы невозможным.</item>
/// </list>
/// Это цена отдельной схемы, принятая вслух решением владельца 28.09.2026. Без неё пришлось бы
/// отдать модулю контекст ядра, то есть отменить границу целиком.</para>
///
/// <para>⚠️ Схема НЕ берётся из объявления модуля (<see cref="ModuleSchema" />) автоматически: её
/// называет сам контекст, а ядро сверяет два объявления и останавливает старт при расхождении.
/// Одно объявление на два места выглядело бы надёжнее, но контекст создаётся и вне приложения — из
/// <c>dotnet ef</c>, — и там реестра модулей нет вовсе: миграции сгенерировались бы в схему по
/// умолчанию, то есть в схему ядра, и заметили бы это по таблице в чужой схеме.</para>
/// </summary>
public abstract class ModuleDbContext(DbContextOptions options) : DbContext(options)
{
    /// <summary>Имя схемы модуля — то же, что объявлено в <see cref="ModuleSchema.Name" />.</summary>
    protected abstract string Schema { get; }

    /// <summary>
    /// Схема по умолчанию — схема модуля, то есть таблица без явного указания схемы попадает СЮДА, а
    /// не в схему ядра. Наследник, переопределяющий этот метод, обязан позвать базовый: без него
    /// первая же таблица модуля появится в <c>public</c> рядом с таблицами ядра.
    /// </summary>
    protected override void OnModelCreating(ModelBuilder builder)
    {
        builder.HasDefaultSchema(Schema);
        base.OnModelCreating(builder);
    }

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        RefuseAppendOnlyEdits();
        return base.SaveChanges(acceptAllChangesOnSuccess);
    }

    public override Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken ct = default)
    {
        RefuseAppendOnlyEdits();
        return base.SaveChangesAsync(acceptAllChangesOnSuccess, ct);
    }

    /// <summary>
    /// Дописываемый набор (<see cref="IAppendOnly" />) правке и удалению не подлежит — отказ здесь, в
    /// единственной точке сохранения контекста.
    ///
    /// <para>Приватных сеттеров для этого мало: состояние <c>Modified</c> ставится и прямым
    /// <c>Entry(...).State</c>, и правкой через рефлексию, — строка ушла бы в базу без единого
    /// признака. Отказ громкий и без обработки: историю правит только код, а код чинят, а не
    /// уговаривают.</para>
    /// </summary>
    private void RefuseAppendOnlyEdits()
    {
        var touched = ChangeTracker.Entries()
            .Where(e => e.Entity is IAppendOnly && e.State is EntityState.Modified or EntityState.Deleted)
            .Select(e => $"{e.Entity.GetType().Name} ({e.State})")
            .ToList();

        if (touched.Count == 0) return;

        throw new InvalidOperationException(
            $"Схема «{Schema}»: строки дописываемого набора изменению и удалению не подлежат, а " +
            "изменены: " + string.Join("; ", touched) +
            ". Новое событие записывается новой строкой — история отвечает на вопрос «как было " +
            "раньше», и правленая история отвечает на него неправдой.");
    }
}
