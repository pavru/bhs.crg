namespace BHS.CRG.Modules.Data;

/// <summary>
/// Объявление модуля о колонке, в которой лежит путь файла в хранилище (ТЗ CORE-34, CORE-29,
/// issue #1261).
///
/// <para><b>Объявление — не способ обнаружения</b>, как и у <see cref="ModuleReference" />. Файлы
/// модуля резервная копия находит САМА: проходит по строкам его схемы, которые уже сняла, и берёт
/// всё, что выглядит путём файла. Объявление даёт то, чего обход дать не может, — слова («сканы
/// счетов: 3 файлов нет») — и единственное, чем модуль может колонку ОСВОБОДИТЬ: сказать, что файл
/// в ней производный и в копию не едет.</para>
///
/// <para>Так сделано ради направления отказа. Будь объявление источником, забытая колонка означала
/// бы файл, не попавший в копию, — потерю, которую обнаруживают после аварии. Здесь забытая колонка
/// означает, что файл взят, а копия назвала колонку адресом вместо слов.</para>
/// </summary>
/// <param name="Table">Таблица в схеме модуля.</param>
/// <param name="Column">Колонка с путём: текст, массив или JSON.</param>
/// <param name="Carried">Едет ли файл в резервную копию.</param>
/// <param name="What">Что это за файлы, словами и во множественном числе: «сканы счетов». У колонки,
/// файл которой в копию не едет, — ПРИЧИНА.</param>
public sealed record ModuleFile(string Table, string Column, bool Carried, string What)
{
    /// <summary>
    /// Колонка держит файл: он уезжает в копию и возвращается из неё вместе со строкой. Две колонки с
    /// одним и тем же <paramref name="what" /> считаются одним перечнем — файл, названный в обеих,
    /// в отчёте не удваивается.
    /// </summary>
    public static ModuleFile Holding(string table, string column, string what) =>
        new(table, column, Carried: true, what);

    /// <summary>
    /// Файл производный: его можно построить заново, и в копию он не едет. Причина обязательна —
    /// «не едет» без объяснения неотличимо от забытого файла.
    /// </summary>
    public static ModuleFile Derived(string table, string column, string reason) =>
        new(table, column, Carried: false, reason);
}
