namespace BHS.CRG.Modules.Data;

/// <summary>
/// Таблица модуля, строки которой — документы с суммами в валюте учёта (issue #1248).
///
/// <para>Нужна одному правилу: валюту учёта меняют, пока таких документов нет. Суммы при смене не
/// пересчитываются, и документ, заведённый в рублях, после неё показывал бы те же числа с другим
/// знаком.</para>
///
/// <para>⚠️ <b>Объявление, а не порт.</b> Строки считает ядро — сырым запросом к схеме модуля, без
/// его служб: спрашивают и про ВЫКЛЮЧЕННЫЙ модуль, у которого в контейнере нет ни служб, ни
/// контекста, а счета в базе лежат. Порт, реализуемый модулем, ответил бы за него тишиной.</para>
///
/// <para>Называют таблицу документа, а не всё, где есть число: строки и разноска без счёта не
/// живут. Служебные таблицы (распознавание, сопоставления) не называют — они валюту не держат.</para>
/// </summary>
/// <param name="Table">Имя таблицы в схеме модуля, как в базе.</param>
/// <param name="Noun">Чем считать — родительный падеж множественного числа, со строчной: «счетов»,
/// «накладных». Встаёт в причину запрета — «счетов: 12».</param>
public sealed record ModuleAccountingDocument(string Table, string Noun)
{
    /// <summary>Что не так с объявлением; <c>null</c> — годное.</summary>
    public string? Validate()
    {
        // Имя уходит в текст запроса: параметром имя таблицы не передать. Поэтому только то, что
        // живёт в базе без кавычек, — как у имени схемы.
        if (string.IsNullOrWhiteSpace(Table)
            || Table.Any(c => !(char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c == '_')))
            return $"имя учётной таблицы «{Table}» обязано быть из строчных латинских букв, цифр и подчёркиваний";

        return string.IsNullOrWhiteSpace(Noun) ? $"у учётной таблицы «{Table}» не сказано, чем считать документы" : null;
    }
}
