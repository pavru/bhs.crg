namespace BHS.CRG.Modules.Data;

/// <summary>
/// Своя схема базы у модуля и контекст, который ею владеет (ТЗ CORE-4, задача A2a этапа 2,
/// issue #1072).
///
/// <para>Зачем модулю отдельная схема, а не таблицы с префиксом в общей. Схема — единственная
/// граница, которую видно И в базе, И в правах Postgres, и по которой копию можно снять и вернуть по
/// частям: «чьи это таблицы» отвечается одним взглядом, а не знанием соглашения об именах. Префикс же
/// читается только тем, кто о нём слышал, — и первая таблица, названная без него, ничем не
/// выделяется.</para>
///
/// <para>⚠️ В резервную копию таблицы модуля СЕГОДНЯ НЕ ВХОДЯТ: копия сущностная и построена на
/// контексте ядра. Это задача A2b (issue #1073), и до неё у контекста модуля не должно быть ни одной
/// таблицы — иначе первая же оказалась бы вне любой копии при зелёном CI (найдено ревью PR #1107).
/// Стережёт это <c>ModuleSchemaTests</c>.</para>
///
/// <para>⚠️ Объявление — это ещё не схема: ядро сверяет его с самим контекстом (схема по умолчанию у
/// модели обязана совпасть с названной здесь) и мигрирует ТОЛЬКО схемы включённых модулей. Выключенный
/// модуль своих таблиц не создаёт и своих данных не теряет: миграция его схемы не запускается вовсе.
/// </para>
/// </summary>
/// <param name="Name">Имя схемы в Postgres: <c>costs</c>. Обязано начинаться с кода модуля — см.
/// <see cref="Validate" />.</param>
/// <param name="ContextType">Тип контекста, наследника <see cref="ModuleDbContext" />. Типом, а не
/// самим контекстом: объявление читается на сборке приложения, когда контейнера ещё нет, а сам
/// контекст живёт областью запроса.</param>
public sealed record ModuleSchema(string Name, Type ContextType)
{
    /// <summary>Схема ядра. Модулю в неё нельзя — ни таблицей, ни историей миграций.</summary>
    public const string CoreSchema = "public";

    /// <summary>
    /// Что не так с объявлением; <c>null</c> — годное. Проверяется при старте: расхождение обязано
    /// останавливать запуск, а не обнаруживаться первой миграцией у заказчика.
    ///
    /// <para>Правила три, и каждое закрывает свой тихий отказ:</para>
    /// <list type="bullet">
    ///   <item><b>Имя начинается с кода модуля.</b> Иначе два модуля объявят одну схему и будут
    ///   мигрировать её по очереди, каждый своим набором миграций — то есть второй увидит в истории
    ///   чужие записи и начнёт с того, что не создавал. Разбираться в этом пришлось бы обоим.</item>
    ///   <item><b>Имя не <c>public</c>.</b> Схема ядра мигрируется своим контекстом; модуль, попавший
    ///   в неё, дописал бы в общую историю миграций свои строки — и обновление ядра остановилось бы
    ///   на миграции, которой в его сборке нет.</item>
    ///   <item><b>Имя без кавычек и регистра.</b> Postgres свернёт <c>Costs</c> в <c>costs</c> сам, а
    ///   в кавычках — нет: имя, набранное в двух регистрах, дало бы ДВЕ схемы, и запрос в одну
    ///   возвращал бы пустоту при полной другой.</item>
    /// </list>
    /// </summary>
    /// <param name="moduleCode">Код модуля, объявившего схему.</param>
    public string? Validate(string moduleCode)
    {
        if (string.IsNullOrWhiteSpace(Name)) return "Имя схемы модуля пусто.";

        if (string.Equals(Name, CoreSchema, StringComparison.OrdinalIgnoreCase))
            return $"Модуль «{moduleCode}» объявил схему «{CoreSchema}» — это схема ядра: " +
                   "его таблицы и его история миграций лежат там, и вписываться в них модулю нельзя.";

        if (Name.Any(c => !(char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c == '_')))
            return $"Имя схемы «{Name}» обязано быть из строчных латинских букв, цифр и подчёркиваний: " +
                   "иначе оно живёт в базе только в кавычках, и запрос без них уходит в другую схему.";

        if (!Name.Equals(moduleCode, StringComparison.Ordinal)
            && !Name.StartsWith(moduleCode + "_", StringComparison.Ordinal))
            return $"Схема «{Name}» названа не кодом модуля «{moduleCode}»: имя обязано быть либо самим " +
                   "кодом, либо начинаться с него и подчёркивания. Иначе по имени схемы в базе не " +
                   "ответить, чья она, и два модуля могут объявить одну.";

        if (ContextType is null) return $"У схемы «{Name}» не назван контекст.";

        if (!typeof(ModuleDbContext).IsAssignableFrom(ContextType))
            return $"Контекст «{ContextType.FullName}» схемы «{Name}» не наследует " +
                   $"{nameof(ModuleDbContext)}: без него у модуля нет ни схемы по умолчанию, ни " +
                   "защиты дописываемых наборов от правки.";

        return null;
    }
}
