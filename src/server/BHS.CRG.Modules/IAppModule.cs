using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace BHS.CRG.Modules;

/// <summary>
/// Модуль объявляет себя одним интерфейсом (ТЗ CORE-1). Добавление модуля не требует правок в общем
/// коде запуска: его перечисляют один раз в корне композиции, а дальше он сам говорит, что ему нужно.
///
/// Направление ссылок одностороннее: модуль знает ядро, ядро о модуле не знает (CORE-2). Поэтому
/// здесь нет ни одного нашего типа — только абстракции платформы. Всё, что модулю нужно от ядра, он
/// получает через <see cref="IServiceProvider" /> в момент, когда ядро уже собрано.
/// </summary>
public interface IAppModule
{
    /// <summary>
    /// Код модуля: <c>id</c>, <c>work</c>, <c>plan</c>, <c>costs</c>, <c>ozhr</c>. Им модуль назван в
    /// настройке включения, в правах (<c>модуль.объект.действие</c>) и в воротах адресов.
    /// Пользователю код не виден — для него есть <see cref="Title" />.
    /// </summary>
    string Code { get; }

    /// <summary>Название модуля для человека: «Исполнительная документация», «Учёт работ».</summary>
    string Title { get; }

    /// <summary>
    /// Права модуля — с объяснением каждого (<see cref="AppPermission" />). Список объявляется
    /// здесь, в коде модуля, а не в базе: при старте он сверяется с базой — новые права
    /// появляются, исчезнувшие помечаются устаревшими и не выдаются (AUTH-1).
    ///
    /// Объявление в коде, а не в миграции, потому что право — это часть поведения модуля:
    /// добавили проверку в обработчике, тут же добавили право. Миграция отстала бы от кода ровно
    /// на то время, пока о ней не вспомнят.
    /// </summary>
    IReadOnlyList<AppPermission> Permissions { get; }

    /// <summary>
    /// Регистрация служб модуля. Вызывается при сборке приложения и только для включённого модуля:
    /// выключенный не регистрирует ничего, поэтому его службы не висят в контейнере и не попадают в
    /// фоновые задания.
    /// </summary>
    void RegisterServices(IServiceCollection services, IConfiguration configuration);

    /// <summary>
    /// Под какими путями живут адреса модуля: <c>/api/quality-docs</c>, <c>/api/plans</c>.
    ///
    /// Нужны для ВЫКЛЮЧЕННОГО модуля. Его адреса не строятся вовсе — ни делегатов, ни привязки
    /// параметров, ни разрешения служб, которых он не регистрировал, — поэтому спросить у него
    /// маршруты нельзя, а отвечать на них отказом надо. Ядро вешает под каждым префиксом перехват
    /// «всё остальное» (<c>{**rest}</c>), и он по правилам сопоставления ПРОИГРЫВАЕТ любому
    /// конкретному маршруту ядра под тем же путём — поэтому общий префикс с ядром
    /// (<c>/api/document-sets</c>) объявлять безопасно.
    ///
    /// Что префиксы не разошлись с настоящими адресами, стережёт тест: каждый адрес включённого
    /// модуля обязан лежать под одним из них.
    /// </summary>
    IReadOnlyList<string> RoutePrefixes { get; }

    /// <summary>
    /// Регистрация адресов модуля. На вход приходит ГРУППА модуля, а не корень приложения: ворота
    /// ставятся на группу целиком, и новый адрес модуля закрыт самим фактом регистрации здесь
    /// (CORE-1, AUTH-10). Ставить свою авторизацию на отдельные адреса модулю не нужно.
    ///
    /// Вызывается только у ВКЛЮЧЁННОГО модуля: у выключенного службы не зарегистрированы, и
    /// построение адреса со служебным параметром уронило бы старт приложения.
    /// </summary>
    void MapEndpoints(IEndpointRouteBuilder endpoints);

    /// <summary>
    /// Типы, которые заводит модуль, — со своим скелетом системных полей (ТЗ CORE-20.1, CORE-20.2).
    ///
    /// Объявляются здесь, в коде, по той же причине, что и <see cref="Permissions" />: скелет — часть
    /// поведения модуля. Ядро при каждом старте идемпотентно проецирует объявление в схему типа;
    /// расхождение объявления с тем, что лежит в базе как поле ЗАКАЗЧИКА, останавливает старт —
    /// тихо это значило бы, что печать однажды напечатает пустоту.
    ///
    /// Умолчание — пустой список: модуль, не заводящий типов, об этом ничего не пишет.
    /// </summary>
    IReadOnlyList<ModuleRecordType> RecordTypes => [];

    /// <summary>
    /// Функциональные тэги, которые вносит модуль (ТЗ TYPE-21/TYPE-22, issue #959).
    ///
    /// Реестр тэгов — точка расширения ядра: ядро объявляет свои, модуль — свои, и собирается
    /// реестр из включённых. Тэги выключенного модуля не предлагаются в редакторе схем — читать их
    /// на этом экземпляре некому, а предложенная метка обещает поведение.
    ///
    /// ⚠️ Уже проставленные тэги выключенного модуля в схемах ОСТАЮТСЯ и при сохранении не
    /// теряются: выключение модуля — не повод переписывать конфигурацию заказчика, а включив его
    /// обратно, он обязан найти свои поля там же, где оставил.
    ///
    /// Умолчание — пустой список: модуль, ничего не читающий по тэгам, об этом не пишет.
    /// </summary>
    IReadOnlyList<ModuleTag> Tags => [];

    /// <summary>
    /// Своя схема базы и контекст, который ею владеет (ТЗ CORE-4, задача A2a этапа 2, issue #1072).
    /// <c>null</c> — модуль своих таблиц не держит.
    ///
    /// <para>Ядро мигрирует схему ВКЛЮЧЁННОГО модуля при старте, сразу после своей: модуль вправе
    /// рассчитывать, что схема ядра на месте, обратной зависимости не бывает (CORE-2). Схема
    /// выключенного модуля не мигрируется и не удаляется — его данные переживают выключение
    /// нетронутыми, и включить его обратно можно, не восстанавливая ничего.</para>
    ///
    /// <para>⚠️ Контекст модуля обязан быть зарегистрирован самим модулем в
    /// <see cref="RegisterServices" />: строку подключения он читает из настроек, которые ему туда и
    /// передают. Объявленная схема без зарегистрированного контекста — ОТКАЗ ПРИ СТАРТЕ: тихий
    /// пропуск означал бы модуль, работающий без своих таблиц, то есть отказ на первом же запросе
    /// пользователя.</para>
    ///
    /// <para>Умолчание — <c>null</c>: модуль-обёртка (<c>id</c>) живёт на таблицах ядра и своей схемы
    /// не имеет.</para>
    /// </summary>
    Data.ModuleSchema? Schema => null;

    /// <summary>
    /// Колонки модуля, в которых лежат идентификаторы записей ядра (ТЗ CORE-34.1, issue #1094): что
    /// каждая держит — словами — или почему не держит.
    ///
    /// <para>⚠️ Держателей записи ядро находит САМО, сканом схемы: необъявленная колонка тоже не даст
    /// удалить запись, только отказ назовёт её адресом таблицы вместо слов. Объявления читаются у всех
    /// модулей сборки, включая выключенные, — их данные на месте и держат так же.</para>
    ///
    /// <para>Умолчание — пустой список: модуль без своей схемы на записи ядра не ссылается.</para>
    /// </summary>
    IReadOnlyList<Data.ModuleReference> References => [];

    /// <summary>
    /// Табличные источники модуля (ТЗ CORE-33, CORE-24; задача G1b, issue #1089): зерно, колонки и
    /// обязательный параметр доступа — одно объявление на два потребителя, экран и набор данных.
    ///
    /// <para>Объявляются в коде по той же причине, что <see cref="Permissions" />, и читаются у ВСЕХ
    /// модулей сборки, включая выключенные: таблица выключенного модуля отвечает «модуль выключен», а
    /// не пропадает. Таблица без параметра доступа — отказ при старте с её названием.</para>
    ///
    /// <para>Умолчание — пустой список: модуль, не публикующий таблиц, об этом не пишет.</para>
    /// </summary>
    IReadOnlyList<Tables.ModuleTable> Tables => [];

    /// <summary>
    /// Настройки модуля (задача M1, issue #1070): что администратор может поменять на этом экземпляре.
    ///
    /// <para>Объявляются в коде и читаются у ВСЕХ модулей сборки, включая выключенные, — по той же
    /// причине, что <see cref="Tables" />: настройка выключенного модуля лежит в базе и приезжает в
    /// резервной копии, и узнать её ключ больше некому. Негодное объявление — отказ при старте.</para>
    ///
    /// <para>⚠️ Объявляют то, у чего есть потребитель: настройка, которую никто не читает,
    /// сохраняется и не действует. Значение модуль читает портом <c>IModuleSettings</c> — тем же
    /// объектом, который здесь перечислен.</para>
    ///
    /// <para>Умолчание — пустой список: модуль без настроек об этом не пишет.</para>
    /// </summary>
    IReadOnlyList<Settings.ModuleSetting> Settings => [];

    /// <summary>
    /// Заводские профили распознавания модуля (ТЗ CORE-Q6, задача B1a, issue #1075): что читать в его
    /// документах. Распознаёт ядро — модуль даёт параметры к известному ядру виду.
    ///
    /// <para>Читаются у ВСЕХ модулей сборки: профиль выключенного модуля остаётся в базе, не
    /// предлагается, а обращение к нему отвечает отказом с названием модуля. Негодное объявление —
    /// неизвестный вид, повтор кода, второй заводской профиль того же вида — отказ при старте.</para>
    ///
    /// <para>Умолчание — пустой список: модуль, ничего не распознающий, об этом не пишет.</para>
    /// </summary>
    IReadOnlyList<Recognition.ModuleRecognitionProfile> RecognitionProfiles => [];

    /// <summary>
    /// Первичная инициализация: справочники, системные роли, типы модуля. Обязана быть
    /// идемпотентной — вызывается при каждом старте, и повторный запуск не создаёт дубликатов и не
    /// затирает изменения администратора (AUTH-20).
    /// </summary>
    Task InitializeAsync(IServiceProvider services, CancellationToken ct);
}
