using System.Security.Claims;

namespace BHS.CRG.Modules;

/// <summary>
/// Откуда ворота узнают права владельца токена (ТЗ AUTH-6).
///
/// Абстракция нужна потому, что права считаются из базы — через учётные записи, роли и их состав,
/// то есть через то, о чём проект контрактов не знает и знать не должен. Приложение подставляет
/// сюда свой счётчик прав с кэшем, а ворота остаются частью механизма модулей.
///
/// ⚠️ Права берутся ИЗ БАЗЫ, а не из токена. Токен несёт только «кто это»: права в токене
/// устаревают ровно тогда, когда это опаснее всего — при отзыве доступа.
/// </summary>
public interface IUserPermissions
{
    /// <summary>
    /// Действующие права пользователя. Пустой набор — «никаких прав», это нормальный ответ, а не
    /// признак ошибки: у роли может не быть ни одного права.
    /// </summary>
    Task<IReadOnlyCollection<string>> ForAsync(ClaimsPrincipal principal, CancellationToken ct);
}
