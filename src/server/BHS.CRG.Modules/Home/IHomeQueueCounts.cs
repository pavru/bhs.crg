using BHS.CRG.Modules.Access;
using BHS.CRG.Modules.Exchange;

namespace BHS.CRG.Modules.Home;

/// <summary>
/// Числа очередей Главной (shell-08, ТЗ UI-34): контракт со многими поставщиками — реализацию даёт
/// каждый включённый модуль, объявивший <see cref="IAppModule.HomeQueues" />. Реализация в модуле —
/// <c>&lt;Module&gt;HomeQueueCounts</c>.
///
/// <para><b>Тот же счётчик, что у экрана очереди.</b> Реализация зовёт ту же службу, что отвечает
/// адресам очередей модуля, а не считает второй раз: число Главной, разошедшееся с чипом экрана, было
/// бы хуже, чем никакого (сторож — тест на одном посеве).</para>
///
/// <para><b>⚠️ Названное исключение из правила «право — у поставщика»:</b> ответа «скрыто правами»
/// (<see cref="ContractAnswer{T}.Hidden" />) здесь нет. Право известно ДО вызова — оно объявлено
/// (<see cref="ModuleHomeQueue.Requires" />), и проверяет его ядро: поставщику приходят только коды,
/// открытые спрашивающему. Правило одно на все контракты «со многими»: право известно до вызова —
/// его объявляют, и проверяет ядро; право зависит от данных поставщика — поставщик отвечает
/// «скрыто» (так устроен поиск записей, <c>shell-05</c>).</para>
///
/// <para>Ядро зовёт поставщика в своей области и с пределом времени; исключение или таймаут —
/// «не посчитано» всем его очередям, а соседние модули приходят. Отказ части чисел (у модуля сломался
/// один источник) — <see cref="HomeQueueCount.Refused" /> у этих кодов.</para>
/// </summary>
[ModuleContract("Очереди Главной", Many = true)]
public interface IHomeQueueCounts
{
    /// <param name="reader">От чьего имени спрашивают — для изоляции строк, когда она придёт (work-07).</param>
    /// <param name="codes">Коды очередей этого модуля, открытые спрашивающему. Не пусты.</param>
    /// <returns>По числу на каждый код из <paramref name="codes" />; кода, которого не спрашивали, нет.</returns>
    Task<IReadOnlyList<HomeQueueCount>> CountAsync(
        ModuleReader reader, IReadOnlyList<string> codes, CancellationToken ct);
}
