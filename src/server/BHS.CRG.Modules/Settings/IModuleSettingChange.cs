using BHS.CRG.Modules.Ports;

namespace BHS.CRG.Modules.Settings;

/// <summary>Смена настройки, как её видит обработчик модуля: значения и границы периода на момент смены.</summary>
/// <param name="Before">Хранимое значение до смены; <c>null</c> — действовало умолчание.</param>
/// <param name="After">Хранимое значение после смены; <c>null</c> — вернётся умолчание.</param>
/// <param name="Boundaries">Границы закрытия, прочитанные ядром ПОД его замком записи в учёт: до конца
/// смены они не сдвинутся — закрытие ждёт.</param>
public sealed record ModuleSettingChange(string? Before, string? After, PeriodBoundaries Boundaries);

/// <summary>Что сделает смена с уже записанными данными — для предупреждения перед сохранением.</summary>
/// <param name="Changed">Сколько документов изменится.</param>
/// <param name="Recorded">Сколько из них получат запись о смене (книгу исправлений у счетов).</param>
/// <param name="Text">То же словами — его и показывает экран: склонять «счёт» ядро не умеет и не обязано.</param>
public sealed record ModuleSettingImpact(int Changed, int Recorded, string Text);

/// <summary>
/// Обработчик смены настройки модуля (E2, issue #1100, spec v3.3 п. 1.9): смена, действующая на уже
/// записанные данные, обязана оставить в них след, а не только переписать число. Так допуск расхождения
/// у счетов пишет книгу исправлений запертым счетам: иначе закрытый месяц «на момент закрытия» сдвинулся
/// бы вместе с допуском.
///
/// <para><b>Две фиксации, модуль первым.</b> Общей транзакции у ядра и модуля нет (решение 28.09.2026),
/// поэтому смена идёт так: ядро открывает транзакцию, берёт замок по ключу настройки и РАЗДЕЛЯЕМЫЙ замок
/// записи в учёт (закрытие периода ждёт всю смену), читает «было» и зовёт <see cref="ApplyAsync" /> —
/// модуль пишет и фиксирует сам; потом ядро пишет значение и журнал и фиксирует. После этого — всегда, и
/// при отказе тоже — ядро зовёт <see cref="AlignAsync" /> с действующим значением.</para>
///
/// <para>Обратный порядок недопустим: сбой после фиксации ядра оставил бы запертый счёт без книги при
/// новом допуске — его закрытый месяц сдвинулся бы молча. При этом порядке сбой оставляет модуль ВПЕРЕДИ
/// настройки: закрытые дни целы, а <see cref="AlignAsync" /> возвращает его к действующему значению.</para>
///
/// <para>⚠️ <b>Замка записи в учёт не брать</b> (<see cref="Data.OpenPeriodWrite" />): его держит ядро на
/// своём соединении. Взятый модулем на своём, он встал бы в очередь за ждущим закрытием, а закрытие ждёт
/// ядро, — взаимная блокировка двух соединений одного запроса, которую PostgreSQL не видит.</para>
///
/// <para>⚠️ <b>Настройку через порт не читать</b> (<see cref="Ports.IModuleSettings" />): значения переданы.
/// Порт держит прочитанное до конца запроса, а записано новое значение будет только после
/// <see cref="ApplyAsync" />.</para>
///
/// <para>Регистрирует модуль в <c>RegisterServices</c> обычной службой, по этому интерфейсу. При старте ядро
/// сверяет: настройка объявлена этим же модулем, обработчик у неё один.</para>
/// </summary>
public interface IModuleSettingChange
{
    /// <summary>Настройка, смену которой стережёт обработчик, — тот же объект, что в <c>Settings</c> модуля.</summary>
    ModuleSetting Setting { get; }

    /// <summary>Что сделает смена — без записи. Ни замков, ни транзакции: это показ.</summary>
    Task<ModuleSettingImpact> PreviewAsync(string? before, string? after, CancellationToken ct = default);

    /// <summary>
    /// Записать следы смены и ЗАФИКСИРОВАТЬ их своей транзакцией. Отказ — исключением: ядро не запишет
    /// значение, и смена не состоится целиком.
    /// </summary>
    Task ApplyAsync(ModuleSettingChange change, CancellationToken ct = default);

    /// <summary>
    /// Привести записанное к действующему значению — идемпотентно. Ядро зовёт после каждой смены (её
    /// закончили или она сорвалась после фиксации модуля) и при каждом старте: так чинится сбой между
    /// двумя фиксациями. Свои замки — как у любой записи модуля; ядро в это время замков не держит.
    /// </summary>
    /// <param name="current">Действующее хранимое значение; <c>null</c> — действует умолчание.</param>
    Task AlignAsync(string? current, CancellationToken ct = default);
}
