namespace BHS.CRG.Modules;

/// <summary>
/// Уровень, на котором живёт тэг. Зеркало доменного <c>TagScope</c>, и зеркало оно по той же
/// причине, что <c>ModuleSchemaLevel</c>: у этой сборки НОЛЬ ссылок на проекты (ТЗ CORE-2) —
/// модуль знает ядро, ядро о модуле не знает, — поэтому доменный перечень сюда не дотянуть.
///
/// ⚠️ Состав обязан совпадать с доменным. Сверяет сторож в тестах: разойдись перечни, модуль
/// объявил бы тэг уровня, которого в ядре нет, и узналось бы это при первом обращении к реестру,
/// а не при сборке.
/// </summary>
public enum ModuleTagScope
{
    /// <summary>Тэг поля схемы (<c>fields[].tags</c>).</summary>
    Field,

    /// <summary>Тэг типа (<c>tags</c> в схеме).</summary>
    Type,

    /// <summary>Тэг набора данных.</summary>
    Dataset,

    /// <summary>Тэг документа, распознанного в ГОСТ-профиле.</summary>
    GostDocument,
}

/// <summary>
/// Функциональный тэг, который вносит МОДУЛЬ (ТЗ TYPE-21, TYPE-22, issue #959).
///
/// <para>Тэг — единственный санкционированный мост между конфигурацией заказчика и кодом: код
/// находит поле по тэгу, а не по имени. Поэтому у каждого тэга есть владелец, и объявляет он себя
/// там же, где живёт читающий его код, — в модуле. Выключен модуль — тэг не предлагается в
/// редакторе схем (TYPE-22): предлагать метку, которую никто не прочитает, значит обещать
/// поведение, которого на этом экземпляре нет.</para>
///
/// <para>Объявление в КОДЕ, а не в базе, по той же причине, что у прав и типов модуля: тэг — часть
/// поведения. Добавили чтение по тэгу — тут же добавили тэг; запись в базе отстала бы ровно на то
/// время, пока о ней не вспомнят.</para>
/// </summary>
/// <param name="Code">
/// Код тэга — то, что лежит в схеме (<c>line.quantity</c>). Уникален во всей системе: два владельца
/// на один код — отказ при старте, а не молчаливый победитель.
/// </param>
/// <param name="Label">Короткая подпись для редактора схем.</param>
/// <param name="Description">Что тэг означает и кто его читает — подсказка администратору.</param>
/// <param name="Scope">Уровень: поле, тип, набор данных, документ ГОСТ-профиля.</param>
/// <param name="AppliesTo">
/// Где тэг предлагается: для <see cref="ModuleTagScope.Field" /> — допустимые виды поля
/// (<c>string</c>, <c>number</c>, …), для <see cref="ModuleTagScope.Type" /> — вид типа
/// (<c>Document</c> / <c>Composite</c>). Пусто — где угодно.
/// </param>
/// <param name="Multiple">
/// Сколько полей ОДНОГО типа могут нести тэг: <c>false</c> — одно, <c>true</c> — сколько угодно
/// (столбец «Сколько» в ТЗ TYPE-21). Проверяется сервером при сохранении схемы.
///
/// ⚠️ Умолчание <c>false</c> выбрано нарочно: почти у всех тэгов кратность единичная, а тэг,
/// поставленный дважды по недосмотру, читается кодом как «возьми первое попавшееся» — то есть
/// молча выбирает одно из двух полей.
/// </param>
/// <param name="Group">
/// Группа для редактора схем («Строка документа», «Организация»). Тэгов к концу ТЗ около
/// пятидесяти, и одной строкой значков они уже не читаются. Пусто — тэг идёт под названием модуля.
/// </param>
public sealed record ModuleTag(
    string Code,
    string Label,
    string Description,
    ModuleTagScope Scope,
    IReadOnlyList<string>? AppliesTo = null,
    bool Multiple = false,
    string? Group = null)
{
    public IReadOnlyList<string> AppliesTo { get; init; } = AppliesTo ?? [];
}
