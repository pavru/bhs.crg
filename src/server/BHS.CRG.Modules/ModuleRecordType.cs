namespace BHS.CRG.Modules;

/// <summary>
/// Насколько администратор правит схему типа, заведённого модулем (ТЗ CORE-19.1).
///
/// ⚠️ Это ЗЕРКАЛО доменного <c>SchemaEditLevel</c>, и по-другому нельзя: в этом проекте нет ссылок
/// на наши проекты вовсе — на том и держится правило «модуль знает ядро, ядро о модуле не знает».
/// Чтобы зеркало не разошлось с оригиналом, стоит сторож (<c>ModuleRecordTypeTests</c>): состав
/// значений сверяется по именам.
/// </summary>
public enum ModuleSchemaLevel
{
    /// <summary>Администратор меняет схему как хочет — так живут типы, заведённые человеком.</summary>
    Open,

    /// <summary>Можно добавлять только необязательные поля и править свои; поля модуля заперты.</summary>
    Extendable,

    /// <summary>Схему задаёт модуль. Администратору остаётся подпись поля — и печатная форма.</summary>
    Closed,
}

/// <summary>
/// Системное поле типа модуля (ТЗ CORE-20.2): его значение кладёт КОД модуля, а не человек за
/// формой. В редакторе типа такое поле видно с замком, а охрана записи требует оставить его
/// бит-в-бит таким, как лежит.
/// </summary>
/// <param name="Key">Ключ поля в данных — по нему модуль читает значение.</param>
/// <param name="Title">Подпись для человека. Администратор её правит — это единственное, что ему
/// оставлено даже в закрытом типе; его правка переживает перезапуск, а смена подписи в НОВОЙ версии
/// модуля доезжает до тех полей, которых администратор не трогал.</param>
/// <param name="Type">Вид значения. Виды, которым не нужна ссылка на другой тип — <c>string</c>,
/// <c>text</c>, <c>number</c>, <c>date</c>, <c>boolean</c>, <c>image</c>, <c>file</c>, — объявляются
/// одним именем. Составному (<c>complex</c>) нужна цель, и называется она в <see cref="Target" />.
/// ⚠️ Остальные (<c>enum</c>, <c>array</c>, <c>primitive</c>, <c>doc-ref</c>, <c>doc-array</c>)
/// по-прежнему объявить нельзя: они адресуют цель по <c>Guid</c>, а он в каждой установке свой.
/// Отказ старта, а не тихий пропуск: поле без цели не нарисуется и не заполнится, и разбираться в
/// этом пришлось бы у заказчика.</param>
/// <param name="Tags">Функциональные тэги поля. Ими код находит поле — по тэгу, а не по имени
/// (единственный санкционированный мост между схемой и функционалом). Неизвестный тэг — отказ
/// старта: тихо он означал бы, что печать однажды не найдёт поле.</param>
/// <param name="Required">Обязательность. Проверяется на переходе и при выпуске, не при сохранении.</param>
/// <param name="Locked">Кто кладёт значение. <c>true</c> (по умолчанию) — код модуля, и охрана
/// записи не даёт тронуть поле руками. <c>false</c> — поле ЗАВОДИТ модуль, а заполняет человек:
/// так живёт «Табельный номер» из примера к <c>SchemaFieldLock</c>. Разница обязана быть явной:
/// запертое <c>Required</c>-поле, которое модуль не заполняет, не заполнит уже никто, а форма будет
/// молча требовать невозможного.</param>
/// <param name="Target">КОД типа-цели для составного поля (ТЗ CORE-30) — только для
/// <c>complex</c>; остальным видам цель не нужна, и указанная цель у них — отказ старта.
///
/// <para>Почему по коду, а не по <c>Guid</c>: идентификатор типа в каждой установке свой, и
/// объявить его в коде модуля нельзя в принципе. Ядро разрешает код в идентификатор при проекции,
/// а нет типа с таким кодом — тип модуля не заводится вовсе, и причина называется в журнале: поле
/// без цели не нарисуется и не заполнится.</para>
///
/// <para>⚠️ Появилось в C1 (issue #1076), и это ровно тот «настоящий случай», который здесь был
/// обещан: у счёта поставщик и плательщик — организации из справочника ЯДРА, а не строки. Объявить
/// их строками значило бы завести вторую, свою запись об организации — и сопоставление
/// распознанного поставщика с записью справочника (ТЗ COST-7.1) не имело бы к чему
/// сопоставлять.</para>
///
/// <para>Опираться можно на типы ядра и на свои: сторож этого правила — на стороне ядра, в проекции
/// (там же, где разрешается код), потому что здесь, в контрактах, чужих кодов не видно вовсе.</para></param>
public sealed record ModuleSystemField(
    string Key,
    string Title,
    string Type,
    IReadOnlyList<string>? Tags = null,
    bool Required = false,
    bool Locked = true,
    string? Target = null)
{
    public IReadOnlyList<string> Tags { get; init; } = Tags ?? [];
}

/// <summary>
/// Где лежат данные записей типа (ТЗ CORE-16, CORE-20.1).
///
/// ⚠️ Это ЗЕРКАЛО доменного <c>TypeStorage</c> — по той же причине и с тем же сторожем, что
/// <see cref="ModuleSchemaLevel" />: ссылок на наши проекты в этом проекте нет вовсе.
/// </summary>
public enum ModuleStorage
{
    /// <summary>Объект общей таблицы — так хранятся справочники и всё, что было до модулей с таблицами.</summary>
    SharedObject,

    /// <summary>
    /// Запись в таблице модуля: колонки-скелет плюс остальное по схеме типа. Общим путём такой
    /// объект не заводится — заводит его сам модуль.
    /// </summary>
    ModuleTable,
}

/// <summary>
/// Тип, который заводит МОДУЛЬ, — со своим скелетом системных полей (ТЗ CORE-20.1, CORE-20.2).
///
/// <para>Объявляется В КОДЕ, а не миграцией, по той же причине, что и права модуля: скелет — часть
/// поведения модуля, и миграция отстала бы от кода ровно на то время, пока о ней не вспомнят. Ядро
/// при каждом старте идемпотентно проецирует объявление в схему типа обычными полями с метками
/// «поле модуля» и «заперто».</para>
///
/// <para>⚠️ Почему проекция В СХЕМУ, а не ветка в расчёте эффективных полей: схему читают напрямую
/// девять мест на сервере, мимо резолвера, — и среди них реестр тэгов, на котором стоят печать,
/// метаданные генерации и ключ идентичности. Подмешивай мы системные поля веткой, тэг на системном
/// поле не нашёлся бы, и «печать теряет поле» случилось бы по нашей собственной вине.</para>
///
/// <para><b>Носитель</b> (<see cref="Storage" />) появился в C1 (issue #1076) — там, где обещано:
/// счёт стал первой таблицей модуля, и <c>TypeStorage.ModuleTable</c> впервые кем-то прочитался.
/// До него у перечисления был один работающий вариант, и выбор из одного был бы обещанием, которое
/// некому исполнить.</para>
/// </summary>
/// <param name="Code">Код типа — по нему модуль его и находит. Уникален в системе.</param>
/// <param name="Name">Название для человека.</param>
/// <param name="Level">Уровень правки схемы: что достанется администратору.</param>
/// <param name="Fields">Скелет: поля, которые ведёт модуль. Порядок сохраняется — в редакторе они
/// идут первыми.</param>
/// <param name="Group">Группа в списке типов, необязательно.</param>
/// <param name="SkipWhenBlocked">Что делать, если типа-цели у составного поля в системе нет:
/// <c>false</c> (умолчание) — отказ при старте, <c>true</c> — тип не заводится, а причина уходит в
/// журнал запуска.
///
/// <para>⚠️ <c>true</c> обязателен там, где цель — тип, который ЗАВОДИТ ЧЕЛОВЕК, а не ядро. «Организация»
/// существует у заказчика потому, что её когда-то завёл он; на чистой установке её нет, и отказ старта
/// означал бы, что установка с включённым модулем не поднимается вовсе. Выбраться из такого отказа
/// нечем: «заведите тип» делается в приложении, которое не запускается (тот же замкнутый круг, что
/// нашло ревью PR #1055).</para>
///
/// <para>⚠️ Цена названа: опечатку в коде цели это превращает из отказа в пропуск. Поэтому пропуск
/// молчаливым НЕ бывает — ядро называет причину в журнале запуска, а модуль обязан ответить отказом
/// на попытку завести запись типа, которого нет (см. адреса счёта).</para></param>
/// <param name="Storage">Где лежат записи. Умолчание — общая таблица: модуль, у которого своих
/// таблиц нет, об этом не пишет. <see cref="ModuleStorage.ModuleTable" /> означает, что записи
/// заводит и читает сам модуль, а общий путь их заводить откажется (<c>TypeStorageRules</c>).
///
/// <para>⚠️ Носитель объявляется, но НЕ переносится: смена носителя у типа, который уже завёлся,
/// останавливает старт. Перенос данных из общей таблицы в таблицу модуля — миграция, а не
/// свойство, которое подтверждают каждым запуском; молча он означал бы, что прежние объекты
/// остались лежать там, где их больше никто не читает.</para></param>
public sealed record ModuleRecordType(
    string Code,
    string Name,
    ModuleSchemaLevel Level,
    IReadOnlyList<ModuleSystemField> Fields,
    string? Group = null,
    ModuleStorage Storage = ModuleStorage.SharedObject,
    bool SkipWhenBlocked = false);
