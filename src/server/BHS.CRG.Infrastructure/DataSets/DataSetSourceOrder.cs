using BHS.CRG.Domain.DataSets;

namespace BHS.CRG.Infrastructure.DataSets;

/// <summary>
/// Порядок источников набора в выдачах (issue #1149): по времени создания, при равенстве — по
/// идентификатору.
///
/// <para><b>Зачем.</b> Без упорядочивания источники приходят в порядке строк в куче PostgreSQL, а
/// он меняется любой правкой: UPDATE кладёт новую версию строки в другое место, и следующая выборка
/// отдаёт источник уже после соседа. Сохранил обработку первого источника — на странице «Наборы
/// данных» он уехал вниз. Интерфейс рисует источники в порядке ответа, то есть переставлял их сам
/// сервер.</para>
///
/// <para><b>Почему время создания, а не имя.</b> Источники человек заводит по одному и в своём
/// порядке (листы книги, обложка — титул — документы альбома): новый встаёт в конец, а
/// переименованный остаётся на месте. По имени переименование перебрасывало бы строку под рукой.</para>
///
/// <para><b>Почему в памяти, а не запросом.</b> Источников у набора единицы, и читаются они все.
/// Зато правило одно на оба пути — через набор (<see cref="DataSetDtoMapper.MapFile" />) и через
/// список источников файла: два места с собственным <c>ORDER BY</c> однажды разошлись бы, и один и
/// тот же набор показывал бы разный порядок в зависимости от того, каким запросом его прочли.</para>
///
/// <para>Идентификатор — не «порядок», а развязка: источники, созданные одним действием, могут
/// совпасть по времени (в базе оно хранится до микросекунды), и без второго ключа между ними снова
/// решала бы куча.</para>
/// </summary>
internal static class DataSetSourceOrder
{
    public static IOrderedEnumerable<DataSetSource> InListOrder(this IEnumerable<DataSetSource> sources) =>
        sources.OrderBy(s => s.CreatedAt).ThenBy(s => s.Id);
}
