using BHS.CRG.Application.QualityDocs;

namespace BHS.CRG.Infrastructure.Recognition;

/// <summary>
/// Служебное основной надписи по ГОСТ Р 21.101-2020 — то, на чём держится сам разбор альбома:
/// классификаторы страницы. Перечень граф штампа здесь больше не лежит (issue #1075): его объявляет
/// модуль-владелец профиля, а ядру нужны только ключи, по которым оно маршрутизирует листы.
/// </summary>
public static class GostTitleBlockFields
{
    /// <summary>JSON-ключ классификатора страницы — обложка/титульный лист/обычный документ.
    /// Используется только для маршрутизации строки в нужный источник (обложка/титульный
    /// лист/документы), в кэш итоговых источников не попадает.</summary>
    public const string PageTypePath = "ТипСтраницы";

    public static readonly RecognitionField PageTypeField = new(
        PageTypePath,
        "Тип страницы: Обложка / ТитульныйЛист / Документ (обычный лист со штампом)",
        "string", ["Обложка", "ТитульныйЛист", "Документ"]);

    /// <summary>JSON-ключ классификатора ФОРМЫ основной надписи по ГОСТ Р 21.101-2020, приложение Ж.
    /// Используется для двух целей: (1) выбор размера региона обрезки штампа под второй проход
    /// распознавания — форма 6 заметно меньше физически, чем 3/4/5 (см. GostTitleBlockRegion);
    /// (2) решение о границе документа при группировке — форма 6 ВСЕГДА продолжает текущий документ,
    /// независимо от того, что распознано в Шифре/Наименовании на этом листе (см. GostPageGrouper) —
    /// это защищает от шума распознавания именно на продолжениях, где Шифр/имя часто не читаются
    /// стабильно. В итоговый кэш источника не попадает — служебное поле, как ТипСтраницы.</summary>
    public const string StampFormPath = "Форма";

    public static readonly RecognitionField StampFormField = new(
        StampFormPath,
        "Форма основной надписи по ГОСТ Р 21.101-2020: Форма3 (чертежи/схемы, первый лист основного " +
        "комплекта рабочих чертежей) / Форма4 (первый лист чертежа строительного изделия) / " +
        "Форма5 (первый/заглавный лист текстового документа) / Форма6 (ЛЮБОЙ последующий, не первый, " +
        "лист — чертежа, изделия или текстового документа; табличка заметно меньше)",
        "string", ["Форма3", "Форма4", "Форма5", "Форма6"]);

    /// <summary>Подмешивает классификаторы страницы к полям ПРОФИЛЯ штампа (issue #406).
    /// Классификаторы намеренно не входят в профиль: это не параметры пользователя, а внутренняя
    /// маршрутизация (выбор источника обложка/титул/документы и определение границы документа).</summary>
    public static IReadOnlyList<RecognitionField> WithClassifiers(IReadOnlyList<RecognitionField> stampFields)
        => [.. stampFields, PageTypeField, StampFormField];
}
