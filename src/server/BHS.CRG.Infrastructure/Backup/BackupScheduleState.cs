namespace BHS.CRG.Infrastructure.Backup;

/// <summary>
/// След планировщика копий — то, что записала служба, а не человек (issue #832).
///
/// Граница та же, что у проверки обновлений (#813): «в три часа ночи, хранить семь» задал человек —
/// это настройка; «последний раз ставили копию тогда-то» и «эти файлы сняло расписание» записала
/// служба — это состояние, и живёт оно в <c>service_state</c>, отдельно от настроек.
/// </summary>
public class BackupScheduleState
{
    /// <summary>
    /// Когда планировщик последний раз ПОСТАВИЛ копию в очередь — не когда она удалась.
    ///
    /// Именно попытка, а не успех: иначе неудачная ночь означала бы повтор через минуту, потом ещё
    /// через минуту, и к утру администратор получил бы полтысячи одинаковых уведомлений об одной и
    /// той же беде. Одна попытка в сутки — и одно сообщение.
    /// </summary>
    public DateTimeOffset? LastRunAt { get; set; }

    /// <summary>Чем кончилась последняя плановая попытка; <c>null</c> — удалась.</summary>
    public string? LastError { get; set; }

    public DateTimeOffset? LastErrorAt { get; set; }

    /// <summary>Имя последней удавшейся плановой копии — для строки «последняя плановая» в списке.</summary>
    public string? LastFileName { get; set; }

    public DateTimeOffset? LastSuccessAt { get; set; }

    /// <summary>
    /// Копии, снятые расписанием <b>на этой установке</b>. Уборка трогает ТОЛЬКО их.
    ///
    /// <para>Почему список, а не признак в имени файла или в паспорте копии. Любой признак внутри
    /// копии путешествует вместе с ней: администратор приносит копию с другого сервера — она
    /// оказывается «плановой» и здесь, попадает под уборку и однажды исчезает ночью. Признак же,
    /// который знает только эта установка, о принесённой копии не знает ничего — и не тронет её
    /// никогда, как не тронет и снятую вручную.</para>
    ///
    /// <para>Цена решения названа честно: если базу восстановят целиком из дампа другой установки,
    /// список разойдётся с каталогом и старые плановые копии перестанут убираться. Это заметно и
    /// поправимо — каталог заполнится, и система откажется делать новую копию, назвав причину.
    /// Обратная ошибка — удалить копию, которую принесли ради восстановления, — тиха и
    /// необратима.</para>
    /// </summary>
    public List<string> Managed { get; set; } = [];
}

public static class BackupScheduleStateKeys
{
    public const string Schedule = "backup-schedule";
}
