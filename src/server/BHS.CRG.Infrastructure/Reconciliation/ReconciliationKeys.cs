using System.Text;
using System.Text.RegularExpressions;

namespace BHS.CRG.Infrastructure.Reconciliation;

/// <summary>
/// Доменный ключ находки — высший продуктовый риск подсистемы (P2 в issue #414).
///
/// Ключ обязан строиться из СОДЕРЖАНИЯ строки (марка, сечение, наименование), а не из её порядкового
/// номера: перенумерация 1..N в этих документах происходит регулярно, и ключ на номере обнулял бы всю
/// накопленную память о принятых решениях при первой же вставке строки. Именно это делает журнал
/// сверки ценным артефактом, а не разовым отчётом.
/// </summary>
public static class ReconciliationKeys
{
    private static readonly Regex Spaces = new(@"\s+", RegexOptions.Compiled);

    /// <summary>Тире всех видов: в этих документах их пишут как попало.</summary>
    private const string Dashes = "‐‑‒–—−";

    /// <summary>
    /// Латинские буквы, неотличимые на вид от кириллических. В рабочих данных «ВВГнг(A)-LS» с
    /// латинской A и «ВВГнг(А)-LS» с кириллической встречаются в СОСЕДНИХ строках одного журнала:
    /// набирают вручную, раскладка скачет. Без сведения к одному виду одна марка кабеля дала бы две
    /// находки-сироты — тот же ущерб, что от ключа на порядковом номере.
    ///
    /// Сводим к кириллице: домен русский, и буква, попавшая в латиницу, здесь всегда опечатка.
    ///
    /// Таблица задана ОБОИМИ регистрами и применяется ДО приведения регистра: часть пар похожа только
    /// в верхнем (латинская B и кириллическая В — да, b и в — нет), и свернув сначала регистр, мы
    /// потеряли бы именно их.
    /// </summary>
    private static readonly Dictionary<char, char> Homoglyphs = new()
    {
        ['A'] = 'А', ['B'] = 'В', ['C'] = 'С', ['E'] = 'Е', ['H'] = 'Н', ['K'] = 'К',
        ['M'] = 'М', ['O'] = 'О', ['P'] = 'Р', ['T'] = 'Т', ['X'] = 'Х', ['Y'] = 'У',
        ['a'] = 'а', ['c'] = 'с', ['e'] = 'е', ['k'] = 'к', ['m'] = 'м',
        ['o'] = 'о', ['p'] = 'р', ['x'] = 'х', ['y'] = 'у',
    };

    /// <summary>
    /// Нормализация одного значения ключа: схлопнуть пробелы, унифицировать тире, десятичный
    /// разделитель, раскладку и регистр. Всё это — варианты записи ОДНОГО и того же, различающиеся
    /// между документами: «ВВГнг(А)-LS 3х2,5» и «ВВГнг(А)–LS 3Х2.5» обязаны дать один ключ, иначе одна
    /// позиция превратится в две находки-сироты.
    /// </summary>
    public static string NormalizePart(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return "";

        var sb = new StringBuilder(raw.Length);
        foreach (var c in raw.Trim())
        {
            var unified = Dashes.Contains(c) ? '-' : c == ',' ? '.' : c;
            sb.Append(Homoglyphs.GetValueOrDefault(unified, unified));
        }

        return Spaces.Replace(sb.ToString(), " ").ToLowerInvariant();
    }

    /// <summary>Составной ключ из нескольких колонок. Разделитель непечатный, чтобы значение с ним
    /// внутри не склеило два разных ключа в один.</summary>
    public static string Build(IEnumerable<string?> parts)
        => string.Join('', parts.Select(NormalizePart));

    /// <summary>Пустой ключ (все составляющие пусты) — строка не участвует в сверке: сопоставлять
    /// нечего, и такая «находка» была бы шумом, а не расхождением.</summary>
    public static bool IsEmpty(string key) => key.Replace('', ' ').Trim().Length == 0;
}
