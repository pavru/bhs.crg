using BHS.CRG.Modules.Costs.Data;
using BHS.CRG.Modules.Recognition;

namespace BHS.CRG.Modules.Costs;

/// <summary>
/// Заводские профили распознавания модуля счетов (ТЗ CORE-Q6, issue #1077).
///
/// <para>«Счёт на оплату» до этой задачи объявляло ЯДРО — отступление от ТЗ, принятое, пока у модуля
/// не было потребителя. Теперь потребитель есть: путь «скан → черновик счёта». Решение владельца
/// продукта 08.10.2026 — профиль живёт здесь, как в ТЗ.</para>
///
/// <para>⚠️ Следствие, о котором знали заранее: на установке без модуля счетов профиль не
/// предлагается и в наборах данных — PDF-источник «Счёт на оплату» читает тем же видом, а вид
/// доступен, пока включён его владелец. Заведённые наборы-счета остаются на месте; перераспознать их
/// можно, включив модуль.</para>
///
/// <para>⚠️ Ключи и подсказки перенесены ДОСЛОВНО: запрос к модели печатается из них, а по хешу
/// содержимого ядро решает, ушёл ли заводской вариант вперёд. Изменись здесь буква — у каждого, кто
/// профиль правил, зажглось бы «заводской профиль обновился», хотя переезд содержимого не менял.</para>
///
/// <para>Один профиль — ОДИН вызов распознавания: шапка и товары лежат в одном профиле (поля и
/// колонки), потому что запрос к модели единый. Поле-массив, которым модель возвращает таблицу, в
/// профиль не входит: это форма ответа, её подмешивает ядро.</para>
/// </summary>
public static class CostsRecognitionProfiles
{
    /// <summary>Стабильный код — ключ строки в базе, не переименовывается.</summary>
    public const string InvoiceCode = "invoice";

    // Ключи полей — константами: по ним обработчик раскладывает ответ в реквизиты счёта. Профиль
    // правит администратор, и ключа в ответе может не оказаться — это «не спрашивали», а не «пусто».
    public const string Number = "НомерСчёта";
    public const string Date = "ДатаСчёта";
    public const string Supplier = "Поставщик";
    public const string SupplierTaxId = "ИННПоставщика";
    public const string Payer = "Плательщик";
    public const string PayerTaxId = "ИННПлательщика";
    public const string Basis = "Основание";
    public const string Total = "СуммаКОплате";
    public const string VatTotal = "ВТомЧислеНДС";
    // Режим НДС со скана (issue #1501; разбор Архитектора, §5.3). Реквизитами счёта они не становятся: это
    // доводы распознавания. «Итого без НДС» помогает понять, что суммы строк без НДС, когда они не сходятся
    // ни так, ни так; ставка документа («НДС 22 %» в итогах) ложится строкам «сверху», у которых своей
    // ставки нет, — только прочитанная. Ключ ставки — не «СтавкаНДС»: так называется колонка строк.
    public const string Subtotal = "ИтогоБезНДС";
    public const string DocumentVatRate = "СтавкаНДСДокумента";

    public const string LineName = "Наименование";
    public const string LineUnit = "ЕдиницаИзмерения";
    public const string LineQuantity = "Количество";
    public const string LinePrice = "Цена";
    public const string LineAmount = "Сумма";
    // НДС строки (issue #1410). Колонок может не быть вовсе — НДС только в итогах бумаги, — и тогда
    // строки ложатся без НДС, а отчёты берут его из шапки.
    public const string LineVatRate = "СтавкаНДС";
    public const string LineVatAmount = "СуммаНДС";
    // Артикул (issue #1480). В заводском профиле его НЕТ, и это нарочно: колонка в нём сменила бы хеш, и
    // у каждого, кто профиль правил, зажглось бы «заводской профиль обновился». Колонку с этим ключом
    // добавляет администратор — и она ложится в строку счёта, как любая объявленная
    // (InvoiceScanLines.Targets).
    public const string LineCode = "Артикул";

    // «Сумма к оплате» и НДС описаны с issue #1481 (эпик #1496): прежнее «(итого)» на счёте с НДС
    // сверху вело модель к «Итого» БЕЗ НДС — сверка с такими же строками «сходилась», и счёт уходил
    // разобранным с суммой к оплате на НДС меньше. Подписи в форме и реестре — свои, их это не трогает.
    public static readonly IReadOnlyList<ModuleRecognitionField> InvoiceHeader =
    [
        new(Number, "Номер счёта"),
        new(Date, "Дата счёта"),
        new(Supplier, "Поставщик (исполнитель)"),
        new(SupplierTaxId, "ИНН поставщика"),
        new(Payer, "Плательщик (заказчик)"),
        new(PayerTaxId, "ИНН плательщика"),
        new(Basis, "Основание (договор/назначение платежа)"),
        new(Total, "Всего к оплате, с НДС (последняя сумма в итогах)"),
        new(VatTotal, "Сумма НДС (в том числе или сверху)"),
        new(Subtotal, "Итого без НДС — сумма до НДС из итогов, если она стоит отдельной строкой; нет такой строки — пусто"),
        new(DocumentVatRate, "Ставка НДС из итогов счёта (например «НДС 22 %» — 22); нет ставки в итогах — пусто"),
    ];

    // Описания колонок строк модель получает с issue #1481 (до того — одни ключи). Пересмотрены тогда же
    // — осознанно, со сменой хеша, как в #1410: у правленых копий зажжётся «Заводской профиль
    // обновился». Главное в них — какую из похожих граф брать: в счетах цена и сумма бывают и с НДС, и
    // без, а строка счёта считает НДС «в том числе» (InvoiceLineValues.Completed) — сумма нужна С НДС,
    // и цена тоже: без суммы на бумаге Completed досчитает её из цены. Одна сумма без НДС с НДС сверху
    // итогом документа описанием не лечится — это режим счёта, эпик #1496.
    public static readonly IReadOnlyList<ModuleRecognitionField> InvoiceLines =
    [
        new(LineName, "Наименование товара/услуги, как в строке счёта, без номера строки"),
        new(LineUnit, "Единица измерения, как в счёте (шт, м, кг, усл.)"),
        new(LineQuantity, "Количество из графы количества; не склей его с ценой: количество × цена даёт сумму строки (без НДС или с ним)"),
        new(LinePrice, "Цена за единицу, как напечатана в счёте; если цен две, без НДС и с НДС, бери цену с НДС; не пересчитывай"),
        new(LineAmount, "Сумма по строке (итог строки); если сумм две, без НДС и с НДС, бери сумму с НДС"),
        new(LineVatRate, "Ставка НДС по строке (например 22 %, 10 %, «Без НДС»)"),
        new(LineVatAmount, "Сумма НДС по строке из графы суммы НДС; нет такой графы — пусто"),
    ];

    /// <summary>
    /// Куда ложится шапка счёта (issue #1483): ключ поля профиля = ключ поля счёта. Поля, которые заказчик
    /// допишет в тип «Счёт на оплату», ядро добавит само — здесь только поля модуля.
    ///
    /// <para>Прежние ключи — закрытый список совместимости, а не синонимы (разбор Архитектора, §3):
    /// заводской профиль не переименовывается — его читают и наборы данных, где ключ — имя колонки, а
    /// правленые копии на установках держат старые ключи. Новым целям прежние ключи не положены — перечень
    /// закреплён снимком в тесте.</para>
    ///
    /// <para>«Основание» ложится в «Основание», а не в «Назначение», как было с #1255 (решение владельца
    /// 18.10.2026): «Назначение» — подпись человека, на бумаге его нет. Кому нужно заполнять его со скана —
    /// колонка профиля с ключом «Назначение».</para>
    ///
    /// <para>Каждое поле типа счёта решено здесь — поле, вход или недоступное с причиной: новое поле типа
    /// без решения краснеет в стороже, а не начинает молча заполняться общим разбором.</para>
    /// </summary>
    public static readonly ModuleRecognitionTargets InvoiceTargets = new(CostsRecordTypes.InvoiceCode,
    [
        new(InvoiceRequisites.NumberKey, LegacyKeys: [Number]),
        new(InvoiceRequisites.DateKey, LegacyKeys: [Date]),
        new(InvoiceRequisites.BasisKey),
        new(InvoiceRequisites.PurposeKey),
        new(InvoiceRequisites.TotalKey, LegacyKeys: [Total]),
        new(InvoiceRequisites.VatTotalKey),
        new(InvoiceRequisites.ShippedOnKey),

        // Стороны — через справочник организаций (InvoiceParties): в поле ложится найденная запись, а не текст.
        new(Supplier, ModuleTargetUse.Input, "организация ищется в справочнике по названию и ИНН"),
        new(Payer, ModuleTargetUse.Input, "организация ищется в справочнике по названию и ИНН"),
        new(SupplierTaxId, ModuleTargetUse.Input, "ИНН — ключ поиска поставщика в справочнике"),
        new(PayerTaxId, ModuleTargetUse.Input, "ИНН — ключ поиска плательщика в справочнике"),
        // Доводы режима НДС (issue #1501): реквизитами счёта они не становятся.
        new(Subtotal, ModuleTargetUse.Input, "по нему понимается, что цены в строках без НДС"),
        new(DocumentVatRate, ModuleTargetUse.Input, "ложится ставкой строкам с НДС сверху"),

        new(InvoiceRequisites.DeferralKey, ModuleTargetUse.Unavailable, "отсрочку подставляют условия поставщика"),
        new(InvoiceRequisites.DueDateKey, ModuleTargetUse.Unavailable,
            "срок считает правило из настроек по дате отгрузки и отсрочке"),
        new(InvoiceRequisites.StateKey, ModuleTargetUse.Unavailable, "состояние счёта двигают действия с ним"),
        new(InvoiceRequisites.PaymentKey, ModuleTargetUse.Unavailable, "состояние оплаты ставит отметка платежа"),
        new(InvoiceRequisites.ScanKey, ModuleTargetUse.Unavailable, "файл счёта прикладывают, а не распознают"),
    ]);

    public static IReadOnlyList<ModuleRecognitionProfile> All =>
    [
        new(InvoiceCode, "Счёт на оплату", "Invoice", InvoiceHeader, InvoiceLines, Targets: InvoiceTargets),
    ];
}
