using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace BHS.CRG.Modules.Costs;

/// <summary>
/// Модуль «Счета и накладные» (ТЗ COST-Q1) — учёт счетов на оплату, расходных накладных, разноски
/// затрат по стройкам и отчётов по затратам.
///
/// ⚠️ Это КАРКАС: объявление, права, пути за воротами. Ни одного экрана, ни одной таблицы данных,
/// ни одной своей службы. Так нарочно (задача A1 нарезки этапа 2, issue #1068): у переноса
/// распознавания в ядро — первого пункта этапа по ТЗ — признак готовности «установка ТОЛЬКО счета
/// распознаёт без модуля ИД», и показать его нечем, пока модуля `costs` нет вовсе. Выключить
/// единственный модуль нельзя: пустая настройка означает умолчание, а названный несуществующий код
/// останавливает старт. Поэтому сначала каркас, и уже на нём проверяется остальное. Правка порядка
/// ТЗ (`STG-5`) принята владельцем продукта 28.09.2026.
///
/// <para>В отличие от <c>id</c>, который живёт ОБЁРТКОЙ внутри хоста (его код остался в общих
/// слоях), это отдельный проект — ради чего и делался этап 1. Цена принята вслух: модулю доступны
/// только контракты ядра и домен, поэтому всё, что ему нужно от ядра, обязано прийти портами в
/// проекте контрактов (M2, issue #1069). Первая же попытка «взять нужный тип из Application»
/// роняет <c>ModuleBoundaryTests</c> — и это не препятствие, а смысл правила.</para>
/// </summary>
public sealed class CostsModule : IAppModule
{
    public string Code => "costs";

    public string Title => "Счета и накладные";

    /// <summary>
    /// Права модуля (ТЗ COST-28) — каждое с объяснением, потому что галку в редакторе ролей ставит
    /// человек, а код <c>costs.invoice.pay</c> сам по себе не даёт ему оснований решить.
    ///
    /// <para>⚠️ Здесь их восемь, а перечень ТЗ называет одиннадцать. Три выписаны с причиной, а не
    /// забыты:</para>
    /// <list type="bullet">
    ///   <item><c>costs.invoice.approve</c> — согласование счёта вынесено из этапа (задача C6,
    ///   решение владельца 28.09.2026): оно выключено по умолчанию, то есть его можно не делать
    ///   вовсе до первого спроса. Право без поведения в редакторе ролей обещает шаг, которого
    ///   нет.</item>
    ///   <item><c>costs.request.*</c> — заявки на закупку живут этапом 3 (нужен <c>plan</c>).</item>
    ///   <item><c>costs.materials.read</c> — оно открывает КОНТРАКТ «Материалы на объекте» для
    ///   других модулей (`CORE-34`, задача G6), а контракт вынесен до первого настоящего
    ///   потребителя. Внутренняя модель «отпущено на стройку» остаётся внутри модуля, и читает её
    ///   тот, у кого есть <c>costs.waybill.read</c>; наружу она не выходит, значит открывать её
    ///   отдельным правом сегодня нечем.</item>
    /// </list>
    ///
    /// <para>Все три уже перечислены в составах системных ролей (<c>SystemRoles</c>), и это не
    /// ошибка: неизвестные коды при наполнении роли пропускаются и придут вместе со своим модулем.
    /// Иначе состав роли пришлось бы дописывать в двух местах, и одно из них забылось бы.</para>
    ///
    /// <para>⚠️ Два кода названы НЕ так, как в таблице ТЗ (`COST-28`): там стоят <c>costs.allocate</c>
    /// и <c>costs.report</c> — из двух частей, тогда как `AUTH-1` требует <c>модуль.объект.действие</c>,
    /// и требование это не на словах: <c>AppPermission.Validate</c> останавливает старт на любом другом
    /// виде кода. Обе записи ТЗ противоречат его же модели, и обнаружилось это здесь — при первой
    /// попытке их объявить (сторож сработал). Взята форма из модели: <c>costs.allocation.edit</c> и
    /// <c>costs.report.read</c>; таблица ТЗ поправлена тем же решением. Состав системных ролей в ядре
    /// ссылался на прежние коды — они молча пропускались, потому что объявить их было нельзя.</para>
    ///
    /// <para>⚠️ «Право чтения» из кода всё равно НЕ выводится: <c>costs.allocation.edit</c> — запись,
    /// <c>costs.invoice.pay</c> — тоже, а <c>costs.report.read</c> даёт чтение сумм по всем стройкам.
    /// Поэтому раскрытие составного <c>*.read.all</c> объявляется явной пометкой у каждого права
    /// (задача A3, issue #1074), а не угадывается по суффиксу кода.</para>
    /// </summary>
    public IReadOnlyList<AppPermission> Permissions =>
    [
        new("costs.invoice.read",
            "видеть счета на оплату: реестр, строки, разноску, состояние и срок оплаты",
            "все счета экземпляра вместе с суммами — кто поставщик, за что и сколько; построчной " +
            "изоляции по стройкам в первой версии нет (COST-30)",
            ["core.constructions.read", "core.catalog.read"]),

        new("costs.invoice.edit",
            "заводить и править счета, их строки и сопоставление наименований поставщиков с номенклатурой",
            "то же, что чтение, плюс изменение — включая исправление счёта закрытого периода новой " +
            "версией с причиной",
            ["costs.invoice.read", "costs.allocation.edit", "core.nomenclature.edit"]),

        // Оплата — своё право, а не часть правки счёта (ТЗ COST-28, COST-9). Отметка оплаты меняет
        // цифры отчётов и учётный период, то есть закрытые данные бухгалтерии; сложи мы её в
        // costs.invoice.edit — оплату проставлял бы всякий, кто вводит счета, и снять это можно было
        // бы только вместе с вводом.
        new("costs.invoice.pay",
            "отмечать оплату — полную и частичную — и отменять ошибочную отметку",
            "суммы и сроки всех счетов; отметка задаёт и учётный период, в который попадёт платёж",
            ["costs.invoice.read"]),

        new("costs.waybill.read",
            "видеть расходные накладные: склад, получателя, дату отпуска и строки",
            "движение материалов по стройкам. Денег счетов НЕ открывает: право на накладные — не " +
            "право на счета (COST-29)",
            ["core.catalog.read"]),

        new("costs.waybill.edit",
            "вводить и проводить накладные, загружать машиночитаемую выгрузку 1С",
            "то же, что чтение, плюс изменение: проведённая накладная попадает в перечень материалов, " +
            "отпущенных на стройку",
            ["costs.waybill.read"]),

        new("costs.allocation.edit",
            "разносить счета и строки по стройкам, разделам и статьям вне строек",
            "суммы счетов: часть разноски считается от цены строки, и остаток «не разнесено» виден " +
            "по каждому документу",
            ["costs.invoice.read"]),

        new("costs.report.read",
            "отчёты по затратам и реестр счетов, включая выгрузку в XLSX",
            "суммы по стройкам, контрагентам, разделам и периодам — по всем стройкам экземпляра, " +
            "вместе с тем, что в них не сопоставлено",
            ["costs.invoice.read"]),

        new("costs.articles.edit",
            "вести справочник статей вне строек: «Склад», «Общие расходы»",
            "состав статей, на которые разносятся затраты. Самих затрат не открывает — но статья, " +
            "убранная из справочника, меняет то, куда попадут новые",
            ["costs.report.read"]),
    ];

    /// <summary>
    /// Своих служб у каркаса нет, и пустое тело здесь — утверждение, а не заглушка: A1 не заводит ни
    /// одной таблицы и ни одного экрана. Первые появятся в A2a (issue #1072) — отдельный контекст EF
    /// и своя схема базы.
    /// </summary>
    public void RegisterServices(IServiceCollection services, IConfiguration configuration) { }

    /// <summary>
    /// Путь модуля. Объявлен ДО первого адреса нарочно: по нему ядро вешает отказ «модуль не
    /// подключён» на выключенный модуль, и сегодня — когда `costs` выключен на каждом экземпляре —
    /// это единственное, чем модуль отвечает. Без объявления обращение к <c>/api/costs/...</c>
    /// давало бы пустой 404, неотличимый от опечатки в ссылке (ТЗ OVW-10, AUTH-15, AUTH-19).
    /// </summary>
    public IReadOnlyList<string> RoutePrefixes => ["/api/costs"];

    /// <summary>
    /// Группа модуля заводится пустой. Это не забытая строка: ворота (<c>module:costs</c>) стоят на
    /// группе целиком, поэтому первый же адрес, добавленный здесь в C1 (issue #1076), закрыт самим
    /// фактом регистрации — своей авторизации ему ставить не нужно.
    ///
    /// ⚠️ Пустая группа НЕ доказывает, что ворота работают: доказывает это первый адрес под ними,
    /// и проверяется это там же, где адрес появляется. Сторож A1 — другой и про другое: живой хост с
    /// <c>Modules__Enabled=costs</c> БЕЗ <c>id</c> (<c>CostsOnlyHostTests</c>). До сих пор настоящее
    /// приложение без модуля исполнительной документации не поднимал никто, а
    /// <c>DisabledModuleTests</c> проверяет механизм на поддельных модулях в slim-хосте.
    /// </summary>
    public void MapEndpoints(IEndpointRouteBuilder endpoints) { }

    /// <summary>
    /// Инициализировать нечего: своих справочников у каркаса нет, системные роли «Снабженец» и
    /// «Бухгалтер» заводит ядро (<c>SystemRoles</c>) — их состав назван там целиком, включая права
    /// этого модуля, и наполняется он ими сразу, как только права объявлены здесь.
    /// </summary>
    public Task InitializeAsync(IServiceProvider services, CancellationToken ct) => Task.CompletedTask;
}
