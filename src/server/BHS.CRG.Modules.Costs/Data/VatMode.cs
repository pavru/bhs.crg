namespace BHS.CRG.Modules.Costs.Data;

/// <summary>
/// Как бумага счёта считает НДС (эпик #1496, issue #1497; решение владельца, Архитектора и Дизайнера
/// 18.10.2026).
///
/// <para><b>Признак счёта, а не строки и не реквизит.</b> Бумага одна, и смешанных режимов в одном
/// документе не бывает: признак строки допускал бы состояние, которого на бумаге нет. Реквизитом схемы
/// он быть не может по правилу CORE-15 — на него опирается арифметика строк, и правка схемы
/// администратором меняла бы её молча.</para>
///
/// <para>⚠️ <b>Ниже записи строк режима не знает никто.</b> <see cref="InvoiceLine.Amount" /> — сумма
/// С НДС в обоих режимах: режим приводится к ней один раз, в <see cref="InvoiceLineValues.Completed" />.
/// Разноска, книга, оплата, отчёты и реестр читают <c>amount</c>, а сумма строк складывается и в SQL
/// (<c>InvoiceBook.BehindAsync</c>, <c>Moves</c>) — туда «функция с режимом» не дотянулась бы. Кто начнёт
/// учить режим сам, того назовёт перепись <c>VatModeInventoryTests</c>.</para>
/// </summary>
public enum VatMode
{
    /// <summary>Суммы строк в бумаге — с НДС, НДС «в том числе». Так жили все счета до #1497.</summary>
    Included,

    /// <summary>
    /// Цены и суммы строк в бумаге — без НДС, ниже «НДС» и «Всего к оплате» (НДС сверху). Сумма строки
    /// из бумаги лежит в <see cref="InvoiceLine.NetAmount" />, сумма с НДС досчитывается построчно.
    /// </summary>
    OnTop,
}

/// <summary>Режим НДС словами — для журнала и отказов.</summary>
public static class VatModes
{
    public static string Shown(VatMode mode) => mode == VatMode.OnTop ? "сверху" : "в том числе";
}
