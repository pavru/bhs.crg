using BHS.CRG.Domain.Schema;

namespace BHS.CRG.Modules.Costs;

/// <summary>
/// Справочники ядра, которые читает модуль «Счета и накладные», — названные РОЛЯМИ, и их поля,
/// названные тэгами (ТЗ TYPE-23, CORE-20.4, issue #1101).
///
/// <para><b>Почему не код типа.</b> Справочники заводит и называет человек. Раньше модуль знал их по
/// именам — тип «Организация», поля «ИНН» и «Наименование», тип «Номенклатура» — и на новой
/// установке эти имена надо было угадать буква в букву, а переименование поля на действующей
/// останавливало сопоставление поставщика. Теперь справочник находится по тэгу типа, поле — по тэгу
/// поля, и имена остаются делом администратора.</para>
///
/// <para>⚠️ Литералов-адресов («Организация», «ИНН») в модуле быть не должно вовсе — стережёт
/// <c>CostsDirectoryAddressTests</c>. Свои типы модуля (счёт, статья вне строек) адресуются кодом
/// по-прежнему: их заводит он сам, и сопоставлять их не с чем.</para>
/// </summary>
public static class CostsDirectories
{
    /// <summary>Справочник организаций: поставщик и плательщик счёта.</summary>
    public const string Organization = FunctionalTag.RoleOrganization;

    /// <summary>Справочник номенклатуры: позиция в строке счёта и накладной.</summary>
    public const string Nomenclature = FunctionalTag.RoleNomenclature;

    /// <summary>ИНН организации — по нему сопоставляется сторона, прочитанная в файле счёта.</summary>
    public const string TaxId = FunctionalTag.OrgTaxId;

    /// <summary>Название организации — в него ложится название при заведении организации из файла.</summary>
    public const string OrganizationName = FunctionalTag.OrgName;

    /// <summary>
    /// Что модулю нужно от ядра и что не работает без каждого. Тексты читает администратор на экране
    /// сопоставления и тот, кто вводит счета, — в отказе; поэтому они говорят о действии человека, а
    /// не об устройстве системы.
    /// </summary>
    public static readonly IReadOnlyList<ModuleRoleNeed> Needs =
    [
        new(Organization,
            "Поставщик и плательщик счёта",
            "Счёт не завести: поставщика и плательщика выбрать не из чего.",
            [
                new(TaxId, Required: true,
                    "Не работает поиск поставщика и плательщика по ИНН из файла счёта и заведение организации " +
                    "из файла. Организацию в каждом счёте выбирают вручную."),
                new(OrganizationName, Required: true,
                    "Не работает заведение организации из файла счёта. Нового поставщика заводят в справочнике " +
                    "вручную."),
            ]),
        new(Nomenclature,
            "Позиция в строке счёта и накладной",
            "Не работает выбор позиции в строках счёта и накладной и запоминание соответствий поставщика. " +
            "Счёт с позициями нельзя перевести в «разобран»."),
    ];

    /// <summary>
    /// Куда идти, чтобы назначить справочник или его поле. Одно место — путь изменится один раз.
    /// Путь назван словами, а не ссылкой: отказ читает и тот, у кого права на типы нет, — ему
    /// сказано, к кому идти и что тот откроет.
    /// </summary>
    public const string WhoAssigns =
        "Назначает администратор: «Настройка системы» → «Сопоставление полей».";

    /// <summary>Справочник организаций не назначен — и что из-за этого не получилось.</summary>
    public static string NoOrganizations(string consequence) =>
        $"Справочник организаций не назначен, поэтому {consequence}. Ни один тип не несёт тэг типа " +
        $"«Справочник организаций» (либо несут несколько). {WhoAssigns}";

    /// <summary>Справочник номенклатуры не назначен — и что из-за этого не получилось.</summary>
    public static string NoNomenclature(string consequence) =>
        $"Справочник номенклатуры не назначен, поэтому {consequence}. Ни один тип не несёт тэг типа " +
        $"«Справочник номенклатуры» (либо несут несколько). {WhoAssigns}";

    /// <summary>
    /// В справочнике организаций не сопоставлено поле ИНН. Причину называет ЯДРО
    /// (<c>ModuleCatalogFieldValues.Reason</c>): их четыре, и одна из них — тэг, поставленный иначе у
    /// подтипа, — без имени подтипа отправляла человека проверять корневой тип, где всё верно.
    /// </summary>
    public static string TaxIdNotMapped(string? reason) =>
        "Сопоставить организацию по ИНН не получилось: " +
        (reason ?? "в справочнике не назначено поле «ИНН организации»") + ". " + WhoAssigns +
        " Пока организацию выберите из справочника.";
}
