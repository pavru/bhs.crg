namespace BHS.CRG.Modules.Costs;

/// <summary>
/// Типы и тэги, которые заводит модуль «Счета и накладные» (задача C1 этапа 2, issue #1076,
/// ТЗ TYPE-14, COST-6, COST-6.1, CORE-15, CORE-20.1, CORE-20.2).
///
/// <para><b>Почему тип объявлен в коде, а не заведён администратором.</b> Счёт распознаётся живым
/// профилем и печатается тем же механизмом, что остальные документы, — значит у него обязаны быть
/// тэги, по которым код находит поля (номер, дата, контрагент, итог). Тип, собранный руками,
/// разошёлся бы с кодом молча: поле есть, тэга нет, и «печать теряет поле» случилось бы у
/// заказчика.</para>
///
/// <para><b>Состав полей сверен с тем, что уже распознаёт профиль «Счёт на оплату»</b> (ТЗ COST-6,
/// TYPE-14): номер и дата, поставщик и плательщик, основание, сумма к оплате, в том числе НДС. ИНН
/// отдельными полями НЕ входят — они реквизит организации и служат ключом сопоставления
/// распознанного поставщика с записью справочника.</para>
///
/// <para>⚠️ <b>Строк счёта здесь нет.</b> Они приезжают задачей C2 (issue #1078) и приезжают СВОЕЙ
/// таблицей, а не полем-массивом: строка — отдельный класс хранения («колонки-скелет плюс остальное
/// по схеме», ТЗ CORE-16), и на неё опирается код — отбор «без номенклатуры», сверка суммы,
/// разноска. Объяви мы их массивом в схеме, каждая из этих опор читала бы JSON.
/// </para>
/// </summary>
public static class CostsRecordTypes
{
    /// <summary>Код типа счёта. Постоянен: им адресуются печатные блоки (ТЗ TYPE-6).</summary>
    public const string InvoiceCode = "СчётНаОплату";

    /// <summary>Код типа организации в ядре — цель полей «Поставщик» и «Плательщик» (ТЗ CORE-30).</summary>
    public const string OrganizationCode = "Организация";

    /// <summary>
    /// Код типа номенклатуры в ядре — на него ссылается строка счёта (ТЗ COST-7, C2, issue #1078).
    ///
    /// <para>⚠️ Полем СЧЁТА этот тип не назван, и потому его отсутствие проекцию типа счёта не
    /// останавливает: ссылается на номенклатуру строка, а у строки схемы нет вовсе. Если типа в системе
    /// нет (его завело ядро миграцией «Номенклатура над материалом», issue #963, — но только там, где
    /// был «Материал»), выбор позиции отказывает с названной причиной, а счета и их строки продолжают
    /// жить: строка без позиции — штатное состояние.</para>
    /// </summary>
    public const string NomenclatureCode = "Номенклатура";

    // Тэги счёта. Владелец — модуль (ТЗ TYPE-21, таблица тэгов: столбец «модуль» = costs), потому
    // что читает их его код: сверку суммы разносок с итогом документа делает он.
    public const string CounterpartyTag = "doc.counterparty";
    public const string PayerTag = "doc.payer";
    public const string TotalTag = "doc.total";
    public const string VatTotalTag = "doc.vatTotal";

    // Тэги ЯДРА, которые модуль только использует. Объявлять их здесь не надо и нельзя: владелец у
    // кода один, а два владельца на один код — отказ при старте.
    private const string NumberTag = "doc.number";
    private const string DateTag = "doc.date";

    /// <summary>
    /// Тэги, которые вносит модуль (ТЗ TYPE-21, TYPE-22).
    ///
    /// <para>⚠️ <c>org.inn</c> из таблицы ТЗ здесь НЕТ, и это не пропуск: он стоит на поле
    /// ОРГАНИЗАЦИИ и нужен сопоставлению распознанного поставщика с записью справочника — а
    /// сопоставление приезжает задачей C3 (issue #1079). Тэг, объявленный раньше читающего его
    /// кода, предлагается администратору в редакторе схем и обещает поведение, которого нет.</para>
    /// </summary>
    public static readonly IReadOnlyList<ModuleTag> Tags =
    [
        new(CounterpartyTag, "Контрагент документа",
            "От кого документ: поставщик в счёте. По нему считаются затраты по контрагенту и " +
            "ищется дубликат счёта (поставщик + номер + дата).",
            ModuleTagScope.Field, ["complex"], Group: "Счета и накладные"),

        new(PayerTag, "Плательщик",
            "Своя организация, от которой идёт оплата: у компании их несколько, и реестр счетов " +
            "отбирается по ней.",
            ModuleTagScope.Field, ["complex"], Group: "Счета и накладные"),

        new(TotalTag, "Итоговая сумма документа",
            "Сумма к оплате — та, что стоит в бумаге поставщика. Код сверяет её с суммой строк и с " +
            "суммой разносок по стройкам; расхождение показывается числом и ничего не запрещает.",
            ModuleTagScope.Field, ["number"], Group: "Счета и накладные"),

        new(VatTotalTag, "В том числе НДС",
            "Сумма НДС по документу целиком — для отчётов и сверки с итогом по строкам.",
            ModuleTagScope.Field, ["number"], Group: "Счета и накладные"),
    ];

    /// <summary>
    /// Счёт на оплату — запись модуля (ТЗ CORE-20.1): суммы лежат в таблице модуля, а не в общей, и
    /// потому не видны ни «Общим данным», ни MCP, ни поиску сопоставления (ТЗ COST-29, COST-30).
    ///
    /// <para><b>Уровень «расширяемый», а не «закрытый».</b> Поля модуля заперты, но заказчик вправе
    /// дописать свои необязательные: в действующем реестре счетов у него есть колонки, которых в ТЗ
    /// нет вовсе, и запрет означал бы, что их продолжат вести отдельно от системы.</para>
    ///
    /// <para><b>Что заперто, а что нет.</b> <c>Locked</c> здесь означает «значение кладёт код».
    /// Таких полей два — оба состояния: их двигают действия (разбор, отметка оплаты), а не форма, и
    /// охрана записи не даёт тронуть их руками. Остальные поля модуль ЗАВОДИТ, а заполняет человек за
    /// формой, поэтому <c>Locked: false</c>. Разница обязана быть явной: запертое поле, которое код
    /// не заполняет, не заполнит уже никто.</para>
    ///
    /// <para><b>Обязательность</b> проверяется на переходе «черновик → разобран» и при печати, а не
    /// при сохранении (ТЗ COST-6.2): черновик без строк, без плательщика и без суммы — штатное
    /// состояние счёта, который приехал сканом и ждёт человека.</para>
    /// </summary>
    public static readonly ModuleRecordType Invoice = new(
        InvoiceCode,
        "Счёт на оплату",
        ModuleSchemaLevel.Extendable,
        [
            new("Номер", "Номер счёта", "string", [NumberTag], Required: true, Locked: false),
            new("Дата", "Дата счёта", "date", [DateTag], Required: true, Locked: false),
            new("Поставщик", "Поставщик", "complex", [CounterpartyTag], Required: true, Locked: false,
                Target: OrganizationCode),
            new("Плательщик", "Плательщик", "complex", [PayerTag], Required: true, Locked: false,
                Target: OrganizationCode),
            new("Основание", "Основание", "string", Locked: false),

            // Назначение счёта (ТЗ COST-6.1) — «что куплено и для чего» у документа целиком. Подпись
            // для людей, а не замена строкам: в действующем реестре заказчика это отдельная
            // заполненная колонка («кабель для пожарной сигнализации»).
            new("Назначение", "Назначение", "text", Locked: false),

            new("Итого", "Сумма к оплате", "number", [TotalTag], Locked: false),
            new("ВТомЧислеНДС", "В том числе НДС", "number", [VatTotalTag], Locked: false),

            // Срок оплаты (ТЗ COST-9.1). Здесь только ХРАНЕНИЕ: правило подстановки
            // «дата отгрузки + отсрочка − 1» задаётся настройкой модуля, а настроек модуля ещё нет
            // (M1, issue #1070), и подстановка вместе с условиями поставщика приезжает задачей C4
            // (issue #1080). Колонка, а не расчётное поле: расчётное перекрыть нельзя, а срок человек
            // правит руками — и признак ручной правки хранится рядом, в колонке таблицы.
            new("ДатаОтгрузки", "Дата отгрузки", "date", Locked: false),
            new("Отсрочка", "Отсрочка, дней", "number", Locked: false),
            new("Срок", "Оплатить до", "date", Locked: false),

            // Две оси состояния (ТЗ COST-9). Значения кладёт код: документ двигают действия, оплату —
            // отметка платежа (C5, issue #1082). «Просрочен» здесь НЕТ нарочно: это признак, который
            // считается по дате, а не состояние, которое кто-то ставит.
            new("Состояние", "Состояние документа", "string", Locked: true),
            new("СостояниеОплаты", "Состояние оплаты", "string", Locked: true),

            // ⚠️ Без тэга, и это НЕ пропуск. В ТЗ (TYPE-14) на этом поле стоит `doc.printForm`, но
            // владелец этого тэга — модуль исполнительной документации: он означает «печатная форма, из
            // которой система извлекает метаданные», и читает его генерация. Поставь мы его здесь,
            // установка ТОЛЬКО со счетами не поднялась бы вовсе — тэга в реестре нет, а неизвестный тэг
            // останавливает старт (поймано `CostsOnlyHostTests`). А признак готовности задачи A1 — как
            // раз такая установка.
            //
            // По смыслу тэг здесь и не нужен: скан счёта — бумага ПОСТАВЩИКА, которую мы распознаём, а
            // не наша печатная форма, и печати у счёта в первой версии нет вовсе (решение владельца
            // 29.09.2026, M4). Своё поле модуль находит своей колонкой, мост через тэг ему не нужен.
            new("Скан", "Скан счёта", "file", Locked: false),
        ],
        Group: "Счета и накладные",
        Storage: ModuleStorage.ModuleTable,

        // Тип «Организация» заводит ЧЕЛОВЕК, а не ядро: он есть у заказчика потому, что его когда-то
        // завели. На чистой установке его нет — и отказ старта означал бы, что установка с включённым
        // модулем счетов не поднимается вовсе, а выбраться из отказа нечем: заводить тип надо в
        // приложении, которое не запускается. Поэтому пропуск, а не отказ; причину ядро называет в
        // журнале запуска, а адреса счёта отвечают отказом, который отправляет её читать.
        SkipWhenBlocked: true);

    /// <summary>Всё, что объявляет модуль. Порядок значения не имеет — ядро проецирует каждый.</summary>
    public static readonly IReadOnlyList<ModuleRecordType> All = [Invoice];
}
