using BHS.CRG.Modules.Settings;

namespace BHS.CRG.Modules.Costs;

/// <summary>
/// Настройки модуля «Счета и накладные» (задача M1, issue #1070).
///
/// <para>⚠️ Здесь только то, что уже кто-то читает. Согласование (COST-Q8) объявит работа, которая
/// его введёт.
/// Валюта учёта (COST-7.2) — настройка экземпляра, а не модуля (issue #1248): знак валюты рисует клиент ядра.</para>
/// </summary>
public static class CostsSettings
{
    /// <summary>
    /// Допуск расхождения суммы строк с суммой к оплате (ТЗ COST-13): расхождение в его пределах
    /// уходит в последнюю часть разноски, сверх него счёт не считается разнесённым.
    ///
    /// <para>⚠️ <b>Действует на все счета сразу</b>, а не с момента смены (решение владельца
    /// 07.10.2026): допуск участвует в каждом расчёте баланса, и на счёте не фиксируется. После
    /// понижения счёт с расхождением больше нового допуска остаётся «разобран», но оплатить его
    /// нельзя, а у оплаченного — в том числе в закрытом периоде — расхождение уходит из последней
    /// части в остаток, и суммы по стройкам меняются задним числом. Поэтому у настройки есть
    /// предупреждение перед сохранением, а смена пишется в журнал действий.</para>
    ///
    /// <para>Счетам, которые заперты закрытым периодом или уже исправлялись, смена пишет книгу исправлений
    /// (E2, issue #1100, spec v3.3 п. 1.9; обработчик — <c>ToleranceChange</c>): их закрытые месяцы «на
    /// момент закрытия» остаются как были.</para>
    /// </summary>
    public static readonly NumberSetting AllocationTolerance = new(
        "costs.allocation.tolerance",
        "Допуск расхождения сумм",
        "Насколько сумма строк счёта может отличаться от суммы к оплате. Расхождение в пределах допуска " +
        "относится на последнюю часть разноски; сверх допуска счёт не считается разнесённым — его нельзя " +
        "перевести в «разобран» и оплатить.",
        DefaultValue: 1.00m, Min: 0m, Max: 100m, Scale: 2, Money: true)
    {
        ChangeWarning =
            "Допуск действует на все счета сразу — в том числе оплаченные и счета закрытых периодов. " +
            "Если допуск уменьшить, счета с расхождением больше нового значения перестанут считаться " +
            "разнесёнными: оплатить их будет нельзя, а у уже оплаченных расхождение уйдёт из последней " +
            "части разноски в остаток — суммы по стройкам за прошлые периоды в реестре изменятся. Счетам, " +
            "запертым закрытым периодом или уже исправлявшимся, смена запишет книгу исправлений: закрытые месяцы " +
            "«на момент закрытия» у них останутся как были. " +
            "Если увеличить — расхождения до нового значения будут отнесены на последнюю часть.",
    };

    /// <summary>
    /// Правило срока оплаты (ТЗ COST-9.1; задача C4, issue #1080): считать ли день отгрузки первым днём
    /// отсрочки. Флагом, а не формулой — совет Архитектора: вариантов у правила два, и формула в
    /// настройке была бы языком, на котором можно написать что угодно, кроме этих двух.
    ///
    /// <para>⚠️ <b>Записанные сроки смена не пересчитывает</b> (решение владельца 14.10.2026): правило
    /// подставляет срок, когда у счёта меняются дата отгрузки или отсрочка. Об этом предупреждение
    /// перед сохранением — иначе администратор ждал бы, что сроки старых счетов сдвинутся.</para>
    /// </summary>
    public static readonly FlagSetting ShippingDayCounts = new(
        "costs.due.shipping-day-counts",
        "День отгрузки — первый день отсрочки",
        "Как подставляется срок «оплатить до». Включено: дата отгрузки + отсрочка − 1 — отгрузка 1-го, " +
        "отсрочка 10 дней, оплатить до 10-го. Выключено: дата отгрузки + отсрочка — оплатить до 11-го. " +
        "Срок, исправленный вручную, правило не меняет.",
        DefaultValue: true,
        On: "день отгрузки — первый день отсрочки",
        Off: "отсрочка считается со дня после отгрузки")
    {
        ChangeWarning =
            "Уже записанные сроки не пересчитываются. Новое правило подставит срок у новых счетов и у тех, " +
            "где изменят дату отгрузки или отсрочку; чтобы пересчитать срок счёта сейчас, нажмите в нём " +
            "«По правилу».",
    };

    public static IReadOnlyList<ModuleSetting> All => [AllocationTolerance, ShippingDayCounts];
}
