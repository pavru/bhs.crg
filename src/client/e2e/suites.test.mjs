import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Каждый живой прогон обязан гоняться в CI (issue #975).
 *
 * Зачем сторож. Файл `*-smoke.mjs` в этой папке — работа, которую кто-то сделал и проверил руками;
 * состав же прогона CI перечислен ОТДЕЛЬНО, аргументами `test:e2e:ci`. Забыть дописать имя ничего
 * не ломает: прогон просто не идёт, а папка при этом выглядит полной, и следующий читатель уверен,
 * что проверка стоит на посту. Именно так и теряется вся ценность прогона — молча.
 *
 * Сверяется текст `package.json`, а не поведение: спросить у CI, что он запустил, из юнит-теста
 * нельзя, а список — это и есть то место, где ошибаются.
 *
 * Осознанно исключить прогон из CI можно — впиши его в `NOT_IN_CI` вместе с причиной. Отказ теста
 * тогда превращается в заявление, а не в забывчивость.
 */
const here = path.dirname(fileURLToPath(import.meta.url));

/** Прогоны, которых в CI нет НАРОЧНО: имя → причина. Пусто — значит гоняются все. */
const NOT_IN_CI = {};

describe('состав живых прогонов в CI', () => {
  const pkg = JSON.parse(readFileSync(path.join(here, '..', 'package.json'), 'utf8'));
  const suites = readdirSync(here)
    .filter(f => f.endsWith('-smoke.mjs'))
    .map(f => f.replace('-smoke.mjs', ''));
  const inCi = (pkg.scripts['test:e2e:ci'] ?? '').split(/\s+/).slice(2);

  it('нашлись сами файлы прогонов', () => {
    // Иначе всё ниже проходит на пустом списке и не значит ничего.
    expect(suites.length).toBeGreaterThan(5);
  });

  it.each(suites)('прогон %s гоняется в CI', name => {
    if (name in NOT_IN_CI) {
      expect(inCi, `прогон «${name}» объявлен исключённым (${NOT_IN_CI[name]}), но стоит в списке CI`)
        .not.toContain(name);
      return;
    }
    expect(inCi,
      `прогон «${name}» есть файлом, но не гоняется в CI: допишите его в аргументы test:e2e:ci `
      + '(или в NOT_IN_CI с причиной — молчаливого пропуска быть не должно)')
      .toContain(name);
  });

  it.each(suites)('у прогона %s есть свой скрипт запуска', name => {
    // Отдельный скрипт — то, чем прогон запускают по одному при починке. Без него имя приходится
    // вспоминать, а команду набирать руками, и прогон перестают гонять локально.
    expect(pkg.scripts, `нет скрипта test:e2e:${name}`).toHaveProperty(`test:e2e:${name}`);
  });

  it.each(suites)('прогон %s отдаёт итог кодом возврата, а не своим числом', name => {
    // ⚠️ Сторож на ОДНУ строку, и цена её ошибки несимметрична. `summarize` возвращает готовый код
    // возврата (0 — прошло, 1 — провал), а читается как «получилось ли» — и его тянет обернуть в
    // условие. Обёрнутый `? 0 : 1` переворачивает смысл: зелёный прогон роняет работу (это заметят
    // сразу), а КРАСНЫЙ отчитывается успехом — и вот этого не заметит никто, потому что `run-suites`
    // судит прогон ровно по коду возврата, а не по напечатанному. Наступали в #1078: семь проверок
    // строк счёта не могли уронить CI вовсе.
    //
    // ⚠️ И присваиванием, а не `process.exit()`: тот обрывает недописанный stdout, унося как раз
    // итоговые строки. Ранние отказы («проверять нечего») — другое дело: они и обязаны остановить
    // прогон немедленно, и соврать успехом не могут.
    const text = readFileSync(path.join(here, `${name}-smoke.mjs`), 'utf8');
    const totals = text.split('\n')
      .filter(line => !line.trimStart().startsWith('//') && line.includes('summarize('));

    expect(totals.length, `в «${name}-smoke.mjs» итог подводится не один раз: ${totals.length}`)
      .toBe(1);
    expect(totals[0].trim(), `в «${name}-smoke.mjs» итог собран сам: «${totals[0].trim()}». `
      + 'Отдавайте значение summarize() как есть, присваиванием в process.exitCode')
      .toMatch(/^process\.exitCode = summarize\([^)]*\);$/);
  });

  /**
   * Входы всех прогонов CI обязаны помещаться в предел частоты (issue #1160).
   *
   * Сервер пускает 30 входов за пять минут с одного адреса, а наборы ходят с одного — и с тех пор,
   * как прогоны перестали ждать паузами, все их входы попадают в ОДНО окно. Тридцать первый вход
   * получает 429, и набор, которому он достался, краснеет целиком — не тот, что добавил лишний
   * вход, а тот, что идёт последним. Раньше об этом говорил абзац в README с числом входов словами;
   * число устарело первым же слиянием (ревью PR #1161). Здесь оно считается.
   *
   * Счёт — по тексту наборов: вызовы `login(` и `submitLogin(`. Вход в цикле или в помощнике,
   * вызванном дважды, он занизит — на это и оставлен запас. Упёрлись — не поднимайте запас: либо
   * входите в наборе реже (вторая страница того же человека может взять сессию первой), либо
   * поднимайте предел политики `login` для стенда живых прогонов — это решение о сервере, не о
   * наборе.
   */
  it('входы прогонов CI помещаются в предел частоты с запасом', () => {
    const RESERVE = 4;
    const host = readFileSync(
      path.join(here, '..', '..', 'server', 'BHS.CRG.Api', 'Configuration', 'ServiceRegistration.Host.cs'), 'utf8');
    const policy = host.match(/AddPolicy\("login", PerClient\((\d+), TimeSpan\.FromMinutes\(\d+\)\)\)/);
    // Предел читается у сервера, а не записан здесь вторым экземпляром: сниженный там, он иначе
    // оставил бы эту проверку зелёной ровно до первого красного прогона.
    expect(policy, 'политика «login» в ServiceRegistration.Host.cs не найдена — предел читать не из чего')
      .not.toBeNull();
    const limit = Number(policy[1]);

    // Набор обвязки ходит к собственной подделке сервера, и его входы в предел не идут.
    const perSuite = inCi.filter(name => name !== 'harness' && suites.includes(name)).map(name => {
      const calls = readFileSync(path.join(here, `${name}-smoke.mjs`), 'utf8').split('\n')
        .filter(line => !/^\s*(\/\/|\*|\/\*)/.test(line))
        .reduce((sum, line) => sum + (line.match(/\b(?:login|submitLogin)\(/g) ?? []).length, 0);
      return [name, calls];
    });
    const total = perSuite.reduce((sum, [, calls]) => sum + calls, 0);

    // Иначе счёт сошёлся бы и на нуле — например, переименуй кто-нибудь помощник входа.
    expect(total, 'в наборах не найдено ни одного входа — счёт ничего не считает').toBeGreaterThan(10);
    expect(total, `входов в прогоне CI ${total}, а сервер пускает ${limit} за окно (запас ${RESERVE}): `
      + perSuite.filter(([, calls]) => calls).map(([name, calls]) => `${name} ${calls}`).join(', '))
      .toBeLessThanOrEqual(limit - RESERVE);
  });

  it('в списке CI нет имён без файла', () => {

    // Обратная половина: опечатку в имени `run-suites` ловит сам — «не запустился» и красный итог.
    // Но ловит он её в CI, после подъёма всего приложения: минут десять ради буквы. Здесь то же
    // расхождение называется за секунду и по имени.
    expect(inCi.filter(n => !suites.includes(n))).toEqual([]);
  });
});
