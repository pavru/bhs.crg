// Посев счетов модуля «Счета и накладные» (задача C1 этапа 2, issue #1076).
//
// Отдельным файлом от `seed.mjs` не ради порядка, а по храповику размера: посев и без того один из
// самых длинных файлов репозитория, а читают такие файлы ЦЕЛИКОМ ради одной правки.
//
// Помощники приходят параметрами, а не импортом: они живут в `seed.mjs` и держат его состояние
// (токен, адрес). Импортируй мы их обратно, вышел бы круг — и разбирать его пришлось бы тому, кто
// придёт сюда за одной строкой.

/**
 * Организации и счета для стенда. Возвращает `null`, если модуля `costs` в приложении нет.
 *
 * ⚠️ Отсутствие модуля НЕ проходит молча: посев говорит об этом вслух. Прогон счетов на таком стенде
 * отказывает с названной причиной — молчаливый пропуск стоил бы пяти проверок формы, которые
 * выглядели бы пройденными, не открыв ни одного счёта.
 */
export async function seedInvoices({ api, findType, ensureEntry, ensureUser, field, apiBase, token, png }) {
  const typeId = await ensureOrganizationType({ api, findType, field });
  await seedNomenclature({ api, findType, ensureEntry, field });

  const supplierId = await ensureEntry(typeId, 'ООО «Кабель-Торг» (посев)',
    { Наименование: 'ООО «Кабель-Торг»', ИНН: '7701000010' });
  const payerId = await ensureEntry(typeId, 'ООО «Наша компания» (посев)',
    { Наименование: 'ООО «Наша компания»', ИНН: '7701000011' });

  const existing = await api('GET', '/costs/invoices').catch(e => {
    console.log(`  ! счета не сеются: модуль costs недоступен (${e.message})`);
    return null;
  });
  if (existing === null) return null;

  await seedNarrowUser({ api, ensureUser });

  // ⚠️ Тип счёта может быть ещё НЕ ЗАВЕДЁН, и это нормальный ход событий, а не сбой. Тип объявляет
  // модуль, но ссылается он на тип «Организация», который заводит человек — здесь его только что
  // завёл посев, уже после старта приложения. Проекция типов модуля идёт один раз, при запуске,
  // поэтому счёт появится со следующего. Скажем это вслух и выйдем: уронив посев, мы остановили бы
  // и всё остальное, что он сеет, — а счета прогону не нужны, он заводит свои.
  if (!(await invoiceTypeReady(api))) {
    console.log('  · счета пока не сеются: тип «СчётНаОплату» появится при следующем запуске '
      + 'приложения (он ссылается на тип «Организация», который завёл этот же посев). '
      + 'Перезапустите приложение и повторите посев, если счета нужны на стенде глазами.');
    return null;
  }

  await ensureTableRows(api);

  const ref = id => ({ $ref: 'catalog', entryId: id });
  const requisites = {
    'Номер': 'СЧ-104',
    'Дата': '2026-09-03',
    'Поставщик': ref(supplierId),
    'Плательщик': ref(payerId),
    'Итого': 128400.5,
    'ВТомЧислеНДС': 21400.08,
    'Срок': '2026-10-03',
    'Основание': 'Договор поставки 17/26',
    'Назначение': 'Кабель для пожарной сигнализации',
  };

  // Распознанный черновик: метки приезжают ВМЕСТЕ с полями — так его и создаёт фоновая задача.
  // Именно поэтому они и обязаны переживать повторное открытие: человек открывает счёт потом.
  let recognized = existing.find(i => i.number === 'СЧ-104') ?? null;
  if (!recognized) {
    recognized = await api('POST', '/costs/invoices',
      { requisites, unconfirmed: ['Номер', 'Итого', 'Срок'] });
    console.log('  + счёт СЧ-104 с метками «распознано, не подтверждено»');
  }

  if (!recognized.hasScan && !(recognized.requisites ?? {})['Скан']) {
    await attachScan({ apiBase, token, png, id: recognized.id });
    console.log('  + скан к счёту СЧ-104');
  }

  // Двойник: тот же поставщик, номер и дата — чтобы на стенде было видно оговорку о дубликате.
  const duplicate = existing.find(i => i.number === 'СЧ-104' && i.id !== recognized.id)
    ?? await api('POST', '/costs/invoices',
      { requisites: { ...requisites, 'Назначение': 'Тот же счёт, второй файл' } });

  return { number: 'СЧ-104', recognizedId: recognized.id, duplicateId: duplicate.id };
}

/**
 * Данные живого прогона экрана таблицы (G1e, issue #1092). Прогон берёт их ОТСЮДА ЖЕ: число строк и
 * сумма, записанные во втором месте, разошлись бы с посевом при первой же правке.
 */
export const TABLE_SEED = {
  /** Назначение, по которому прогон отбирает посеянные счета — ровно их, сколько бы счетов ни накопилось. */
  purpose: 'Посев: итог по отбору',
  /** Больше наименьшей страницы экрана (50): иначе «итог по отбору, а не по странице» проверять не на чем. */
  count: 55,
  amount: i => 100 + i,
  /** Учётная запись с модулем счетов, но БЕЗ права на счета: суммы ей закрыты. */
  narrowEmail: 'nakladnye@bhs.local',
  narrowRole: 'Только накладные (посев)',
};

/** Сумма посеянных счетов — по той же формуле, что их сеяла. */
export const tableSeedSum = () =>
  Array.from({ length: TABLE_SEED.count }, (_, i) => TABLE_SEED.amount(i + 1)).reduce((a, b) => a + b, 0);

/**
 * Счета для проверки «итог считается по всему отбору, а не по странице» (G1e, issue #1092).
 *
 * ⚠️ Их нарочно БОЛЬШЕ страницы. На пяти строках та же проверка зелёная и не значит ничего: сумма
 * страницы и сумма отбора совпадают. Сеются один раз — по номерам, которых ещё нет.
 *
 * ⚠️ Зовёт её и посев, и САМ ПРОГОН. В CI посев идёт до перезапуска приложения, когда типа счёта
 * ещё нет (см. `seedInvoices`), и счета он там не сеет вовсе — прогон досеивает их этой же
 * функцией. Вторая, своя, разошлась бы с посевом числом строк или суммой.
 *
 * @param api `(method, path, body) => ответ` — запрос к приложению от имени того, кто вправе заводить счета.
 */
export async function ensureTableRows(api) {
  const existing = await api('GET', '/costs/invoices');
  const have = new Set(existing.filter(i => i.purpose === TABLE_SEED.purpose).map(i => i.number));
  let added = 0;
  for (let i = 1; i <= TABLE_SEED.count; i++) {
    const number = `ИТОГ-${String(i).padStart(2, '0')}`;
    if (have.has(number)) continue;
    await api('POST', '/costs/invoices', {
      requisites: { 'Номер': number, 'Дата': '2026-09-01', 'Итого': TABLE_SEED.amount(i), 'Назначение': TABLE_SEED.purpose },
    });
    added++;
  }
  if (added) console.log(`  + счета для итога по отбору: ${added} (всего ${TABLE_SEED.count})`);
}

/**
 * Роль «модуль есть, счетов нет» и человек с ней (G1e, issue #1092): право на накладные открывает
 * модуль, а суммы счетов — нет. Системной роли такого состава не бывает, поэтому роль своя.
 */
async function seedNarrowUser({ api, ensureUser }) {
  const roles = await api('GET', '/roles');
  let role = roles.find(r => r.title === TABLE_SEED.narrowRole);
  if (!role) {
    role = await api('POST', '/roles', {
      title: TABLE_SEED.narrowRole,
      summary: 'Для живых прогонов: видит модуль счетов, сумм не видит',
      permissions: ['costs.waybill.read'],
    });
    console.log(`  + роль «${TABLE_SEED.narrowRole}»`);
  }
  await ensureUser(TABLE_SEED.narrowEmail, 'Нина Накладная', role.name);
}

/**
 * Позиции номенклатуры для строк счёта (C2, issue #1078) — чтобы на стенде выбор позиции работал
 * глазами, а не только в прогоне.
 *
 * ⚠️ <b>Тип «Номенклатура» посев заводит ТОЛЬКО там, где нет и «Материала».</b> Штатно его поднимает
 * миграция ядра — и только НАД «Материалом» (issue #963): справочник материалов ведёт человек, и
 * синтетический тип с тем же кодом встал бы на его место. Но где «Материала» нет вовсе, миграция по
 * замыслу не делает НИЧЕГО («чистая установка — переносить нечего»), и тогда позицию выбирать не из
 * чего ни в прогоне, ни руками. Ровно такова база в CI и сразу после `install.sh`: на ней прогон
 * строк счёта отказывался работать. В рабочей системе тип завёл бы администратор — на стенде за него
 * это делает посев.
 *
 * ⚠️ «Материал» есть, а «Номенклатуры» нет — посев базу НЕ ТРОГАЕТ и говорит вслух: миграция
 * отказалась строить иерархию осознанно (у «Материала» уже был родитель либо занято имя), и
 * встраиваться в чужую работу посеву тем более незачем.
 */
async function seedNomenclature({ api, findType, ensureEntry, field }) {
  let type = await findType('Номенклатура');
  if (!type) {
    if (await findType('Материал')) {
      console.log('  · позиции номенклатуры не сеются: «Материал» в базе есть, а «Номенклатуры» нет — '
        + 'значит иерархию не построила миграция ядра, и посев в это не вмешивается. Строки счёта '
        + 'будут ждать позиции — это штатно.');
      return;
    }

    // Имя — с приметой посева, а КОД точный: по коду модуль счетов находит справочник (имена
    // уникальны наравне с кодами, и «Номенклатура» именем занимать незачем — его ждёт миграция).
    type = await api('POST', '/document-types', {
      name: 'Номенклатура ядра (посев)', code: 'Номенклатура', kind: 'Composite', parentId: null,
      schema: JSON.stringify({ fields: [field('Наименование', 'Наименование', 'string')] }),
      isAbstract: false, module: 'core',
    });
    console.log('  + тип «Номенклатура ядра (посев)» (код «Номенклатура»)');
  }

  for (const name of ['Кабель ВВГнг-LS 3х2,5 (посев)', 'Труба гофрированная 20 мм (посев)',
    'Лоток лестничный 100х50 (посев)']) {
    await ensureEntry(type.id, name, {});
  }
}

/**
 * Заведён ли тип счёта. Спрашиваем ПРЯМО — списком типов, а не по отказу создания: отказ пришлось бы
 * разбирать по тексту, а текст меняют.
 */
async function invoiceTypeReady(api) {
  const all = await api('GET', '/document-types');
  return all.some(t => t.code === 'СчётНаОплату');
}

/**
 * Тип, который нужен ТОЛЬКО существованием: заводим, если его нет, а найденный НЕ ТРОГАЕМ.
 *
 * ⚠️ Отличие от `ensureType` в `seed.mjs` принципиальное, и цена ошибки высока. Тип с кодом
 * «Организация» заводит человек, и в рабочей базе он есть — со схемой заказчика. Доведи мы его «до
 * нужного состояния», как делает `ensureType`, посев ПЕРЕПИСАЛ БЫ схему живого справочника
 * организаций, а README зовёт натравливать посев на свою базу. Счёту же нужен не состав полей, а сам
 * тип: поля «Поставщик» и «Плательщик» ссылаются на него по коду.
 */
async function ensureOrganizationType({ api, findType, field }) {
  const found = await findType('Организация');
  if (found) return found.id;

  const created = await api('POST', '/document-types', {
    // Имя — не «Организация (посев)»: оно занято типом `ORG_SEED` (имена уникальны наравне с
    // кодами). Важен здесь КОД: по нему поле счёта называет цель.
    name: 'Организация ядра (посев)', code: 'Организация', kind: 'Composite', parentId: null,
    schema: JSON.stringify({
      fields: [field('Наименование', 'Наименование', 'string'), field('ИНН', 'ИНН', 'string')],
    }),
    isAbstract: false, module: 'core',
  });
  console.log('  + тип «Организация ядра (посев)» (код «Организация»)');
  return created.id;
}

/** Скан — многочастным запросом: общий помощник посева шлёт только JSON. */
async function attachScan({ apiBase, token, png, id }) {
  const form = new FormData();
  form.append('file', new Blob([Buffer.from(png, 'base64')], { type: 'image/png' }), 'скан-счёта.png');

  const res = await fetch(`${apiBase}/api/costs/invoices/${id}/scan`,
    { method: 'POST', headers: { Authorization: `Bearer ${token}` }, body: form });
  if (!res.ok) throw new Error(`скан счёта не приложился: ${res.status} ${await res.text()}`);
}
