/**
 * Составной ключ идентичности объекта (issue #582) — ЗЕРКАЛО серверных `IdentityKey` и
 * `MatchKeyNormalizer`.
 *
 * Ключ здесь и ключ на сервере обязаны совпадать до символа: клиент заводит связку «материал →
 * документ качества», а находит её резолвер на генерации. Любое расхождение — нормализации,
 * разделителя, порядка компонентов — означает связку, которая заведена и никогда не срабатывает,
 * причём молча.
 */

/** Разделитель компонентов — тот же, что в IdentityKey.Separator (виден человеку в списке связок). */
export const IDENTITY_SEPARATOR = ' | ';

/**
 * Нормализация одного значения: схлоп пробелов → срез хвостовых точек/пробелов → нижний регистр.
 * «Шт.», «шт», «шт » → «шт».
 *
 * Легаси-маркер ссылки («🔗 …» — так когда-то показывались составные поля) к значению не относится:
 * он приходит только из превью наборов данных, а резолвер на генерации видит значение уже без него.
 */
export function normalizeKey(s: string | null | undefined): string {
  if (!s) return '';
  return s.replace(/🔗/g, ' ').split(/\s+/).filter(Boolean).join(' ').replace(/[.\s]+$/, '').toLowerCase();
}

/**
 * Ключ из значений полей идентичности, взятых В ПОРЯДКЕ `values` (порядок задаёт
 * `materialIdentityKeys`).
 *
 * Пустое поле даёт ПУСТОЙ СЛОТ, а не пропускается: позиция компонента обязана быть постоянной,
 * иначе материал без артикула и материал без наименования дали бы неразличимые ключи из одного
 * значения.
 */
export function identityKey(values: (string | null | undefined)[]): string {
  return values.map(normalizeKey).join(IDENTITY_SEPARATOR);
}

/** Пуст ли ключ по существу: одни разделители и пробелы — сопоставлять нечего. */
export function isIdentityKeyEmpty(key: string | null | undefined): boolean {
  return !key || key.split(IDENTITY_SEPARATOR).join('').trim().length === 0;
}
