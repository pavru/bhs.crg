import { describe, it, expect } from 'vitest';
import { refusalIssues } from './refusals';
import { apiError } from '@/shared/utils/apiError';

/**
 * Разбор отказа сервера (issue #957). Проверяется то, ради чего он написан: текст, написанный для
 * человека, доезжает дословно, а адреса нарушений — раскладываются по путям.
 */
describe('отказ сервера', () => {
  const refusal = {
    response: {
      data: {
        error: 'Запись не сохранена. Поле «Количество»: ожидается число, а хранится строка.',
        details: [
          { code: 'value-type', path: 'Кол', message: 'Поле «Количество»: ожидается число, а хранится строка.' },
          { code: 'locked-field', path: 'Работы[0].Сумма', message: 'Поле «Сумма» заперто.' },
        ],
      },
    },
  };

  it('текст отказа берётся у сервера, а не подменяется общей фразой', () => {
    // Текст — общим помощником, он был раньше адресов; здесь проверяется, что тело отказа
    // охраны ему по зубам (issue #1008).
    expect(apiError(refusal, 'Ошибка')).toContain('Количество');
  });

  it('места нарушений раскладываются по путям — включая путь внутрь строки таблицы', () => {
    expect(refusalIssues(refusal)).toEqual({
      'Кол': 'Поле «Количество»: ожидается число, а хранится строка.',
      'Работы[0].Сумма': 'Поле «Сумма» заперто.',
    });
  });

  it('отказ без адресов даёт пустой список, а не падает', () => {
    // Адреса называет меньшинство отказов; остальные приходят одним текстом, и форма обязана
    // пережить это молча.
    expect(refusalIssues({ response: { data: { error: 'Имя занято.' } } })).toEqual({});
    expect(refusalIssues(new Error('сеть'))).toEqual({});
    expect(apiError(new Error('сеть'), 'Ошибка')).toBe('сеть');
    expect(apiError(undefined, 'Ошибка')).toBe('Ошибка');
  });
});
