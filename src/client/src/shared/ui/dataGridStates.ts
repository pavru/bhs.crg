/** Неизвестный код с сервера — не повод упасть: колонка показывается как обычная. */
export function columnUnavailable(code: string | null | undefined): ColumnUnavailable | null {
  return code === 'no-right' || code === 'removed' ? code : null;
}

/**
 * Что лежит в клетке. «Поля нет в строке» и «значение пустое» — разные ответы: у union строка несёт
 * поля одного варианта, и пустота в колонке другого — не пустое значение, а его отсутствие.
 */
export type CellKind = 'absent' | 'empty' | 'value';

export function cellKind(row: Record<string, unknown>, key: string): CellKind {
  if (!Object.prototype.hasOwnProperty.call(row, key)) return 'absent';
  const v = row[key];
  if (v == null || (typeof v === 'string' && v.trim() === '')) return 'empty';
  return 'value';
}

