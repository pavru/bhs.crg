/**
 * Пять состояний общей сетки (задача G1a этапа 2, issue #1088, ТЗ CORE-33) — ПЕРВОКЛАССНЫМИ
 * значениями, а не отсутствием данных.
 *
 * Зачем отдельным модулем. Каждое из пяти отвечает человеку на свой вопрос — «почему я ничего не
 * вижу», — и ответы ведут в разные стороны: подождать данных, ослабить отбор, попросить право,
 * поправить разметку, включить модуль. Сведи сетка любые два к одной пустоте — человек пошёл бы не
 * туда. Поэтому состояния названы здесь, и тексты у них попарно различны (это сторожит тест).
 *
 * Три состояния — про сетку целиком (почему нет строк), два — про колонку (почему нет значений в
 * ней). Колоночные приходят с сервера КОДОМ причины: текст выбирает клиент, и выбирает один раз.
 */

/** Почему строк нет. */
export type GridState = 'no-data' | 'filtered-out' | 'module-off';

/** Почему колонка не показывает значений. Коды — те же, что шлёт сервер. */
export type ColumnUnavailable = 'no-right' | 'removed';

export type DataGridStateKind = GridState | ColumnUnavailable;

export interface StateText {
  /** Короткая подпись: в клетке колонки, в строке состояния сетки. */
  title: string;
  /** Пояснение — во всплывающей подсказке и под подписью. */
  hint: string;
}

