import { describe, it, expect } from 'vitest';
import { CYRILLIC_ALLOWED } from './editorUnicode';

/**
 * Список разрешённых символов (issue #776). Проверяем не «список непустой», а то, ради чего он
 * заведён: кириллица целиком внутри, латиница снаружи. Обрезанный диапазон дал бы рябь на части
 * букв — и заметить это можно было бы только глазами, на английской локали.
 */
describe('CYRILLIC_ALLOWED', () => {
  it('содержит весь русский алфавит в обоих регистрах', () => {
    for (const ch of 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя') {
      expect(CYRILLIC_ALLOWED[ch], `буква «${ch}» не разрешена`).toBe(true);
    }
  });

  it('не разрешает латиницу — иначе список отменял бы саму проверку', () => {
    for (const ch of 'aeopcxyABCEHKMOPTX') expect(CYRILLIC_ALLOWED[ch]).toBeUndefined();
  });

  /** Греческие «о» и «а» — те самые подмены, ради которых проверка и включена. */
  it('не разрешает похожие буквы других алфавитов', () => {
    for (const ch of 'οαεрτ'.slice(0, 3)) expect(CYRILLIC_ALLOWED[ch]).toBeUndefined();
  });
});
