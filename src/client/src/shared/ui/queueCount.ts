/**
 * Число очереди «что ждёт человека» — одно правило на чип экрана очереди и карточку Главной (shell-08,
 * ТЗ UI-34). Было у чипов экрана счетов (`features/costs/invoiceQueues.ts`); поднято сюда, чтобы Главная не
 * читала модуль и не держала вторую копию.
 *
 * <ul>
 *   <li>ноль не рисуем: чип или карточка с нулём звали бы туда, где пусто;</li>
 *   <li>«проверено не всё» — число с «?», а ноль с этой оговоркой — «?»: он не значит «нет»;</li>
 *   <li>«не пришло» — не ноль: о нём говорят словами {@link NOT_COUNTED}, а не пропажей.</li>
 * </ul>
 */

/** Слова на месте числа, которое не пришло. */
export const NOT_COUNTED = 'не посчитано';

/**
 * Что написать числом — или `null`, когда показывать нечего.
 *
 * @param count сколько.
 * @param doubt проверено не всё.
 * @param keep показать и пустую — нажатый чип: иначе отбор нечем снять. Тогда текст пустой.
 */
export function queueCountText(count: number, doubt: boolean, keep = false): string | null {
  if (count === 0 && !doubt && !keep) return null;
  return count > 0 ? `${count}${doubt ? '?' : ''}` : doubt ? '?' : '';
}
