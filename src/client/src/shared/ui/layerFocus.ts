/**
 * Фокус, который ставит слой сам, а не человек: открывшееся окно или меню — на свой первый элемент,
 * закрывшееся — обратно на открывшую его кнопку. Подсказка (`Tooltip`) на такой фокус не открывается:
 * человек его туда не вёл, и первый Esc достался бы ей, а не странице. Отметка живёт до ближайшей
 * микрозадачи — ровно синхронный шаг, в котором слой ставит фокус.
 */
let fromLayer = false;

export const isLayerFocus = () => fromLayer;

export function markLayerFocus() {
  fromLayer = true;
  queueMicrotask(() => { fromLayer = false; });
}

/**
 * Вернуть фокус открывшему слой. Закрыли слой с клавиатуры — браузер считает такой фокус видимым, и без
 * отметки подсказка кнопки открывалась сама (живой прогон keyboard, ревью PR #1696).
 */
export function focusFromLayer(el: HTMLElement) {
  markLayerFocus();
  el.focus();
}

/**
 * Слой Radix (поповер, окно, меню — `FocusScope`), открываясь, сам ставит фокус на свой первый элемент.
 * Открыли слой с клавиатуры — такой фокус ещё и «виден», и подсказка первой кнопки открывалась сама:
 * первый Esc доставался ей, слой закрывался только со второго (ревью PR #1450).
 *
 * Слой объявляет свой автофокус событием `focusScope.autoFocusOnMount` и сразу, в том же заходе,
 * ставит фокус, синхронно. Событие не всплывает, но перехват на документе его видит — отметка живёт
 * до ближайшей микрозадачи, то есть ровно этот синхронный шаг. Закрываясь, слой Radix шлёт событие уже
 * снятому контейнеру — документ его не видит: фокус, возвращённый открывшему, помечает тот, кто его
 * возвращает (`focusFromLayer`). Подписка — здесь, при первом импорте модуля: её читают и `Tooltip`, и
 * `RichTooltip`, и ни одна из них не должна заводить её второй раз.
 */
if (typeof document !== 'undefined') document.addEventListener('focusScope.autoFocusOnMount', markLayerFocus, true);
