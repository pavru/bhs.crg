/**
 * Фокус, который ставит слой сам, а не человек: открывшееся окно или меню — на свой первый элемент,
 * закрывшееся — обратно на открывшую его кнопку. Подсказка (`Tooltip`) на такой фокус не открывается:
 * человек его туда не вёл, и первый Esc достался бы ей, а не странице. Отметка живёт до ближайшей
 * микрозадачи — ровно синхронный шаг, в котором слой ставит фокус.
 */
let fromLayer = false;

export const isLayerFocus = () => fromLayer;

export function markLayerFocus() {
  fromLayer = true;
  queueMicrotask(() => { fromLayer = false; });
}

/**
 * Вернуть фокус открывшему слой. Закрыли слой с клавиатуры — браузер считает такой фокус видимым, и без
 * отметки подсказка кнопки открывалась сама (живой прогон keyboard, ревью PR #1696).
 */
export function focusFromLayer(el: HTMLElement) {
  markLayerFocus();
  el.focus();
}
