/**
 * Слова архива — одни на всю систему (issue #1185). Отдельным файлом от компонента пометки: модуль,
 * экспортирующий и компонент, и константы, теряет горячую подмену (issue #858).
 *
 * Архив — не неисправность: ни красного, ни зачёркивания, ни счётчиков. Запись убрана из выбора, а
 * там, где она уже стоит, остаётся как была — пометка только говорит, почему её не выбрать заново.
 */
export const ARCHIVED_WORD = 'в архиве';

export const ARCHIVED_HINT = 'Запись в архиве: выбрать её заново нельзя, здесь она остаётся';

/** Название с пометкой — там, где значок поставить некуда (пункт списка, подпись чипа). */
export const withArchiveWord = (name: string, archived: boolean) =>
  archived ? `${name} — ${ARCHIVED_WORD}` : name;
