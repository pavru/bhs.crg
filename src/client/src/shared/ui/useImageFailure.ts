import { useEffect, useState } from 'react';

/** Через сколько картинку, которая не загрузилась, пробуют снова — и сколько раз. */
const RETRY_AFTER = 20_000;
const RETRIES = 2;

/**
 * Помнит, что картинка не загрузилась, — по метке, и недолго.
 *
 * Картинка оформления (логотип, превью значка) может не загрузиться по двум разным причинам, и по
 * одному отказу их не различить: файл не изображение — и тогда отказ постоянен; либо случайный сбой
 * — всплеск хранилища, 429 общей корзины, обрыв сети. Отсюда два правила (ревью PR #1321):
 *
 * - **отказ не переживает метку.** Метка — всё, от чего зависит, загрузится ли картинка: её адрес и
 *   то, что о ней сказал сервер. Сменилась — отказа больше нет;
 * - **отказ не вечен и при той же метке.** Картинку пробуют снова, дважды, с паузой: случайный сбой
 *   проходит сам, а без повтора слова «не читается» стояли бы до перезагрузки страницы рядом с
 *   исправными значками из того же логотипа. Два повтора, а не бесконечный опрос: файл, который
 *   картинкой не является, слал бы запросы с каждой вкладки без конца.
 *
 * Правило жило копиями в шапке и в настройке — с разными метками, и шапка после восстановления
 * хранилища оставалась с общим значком при уже показанном логотипе в настройке.
 *
 * @returns `[не загрузилась ли, сообщить об отказе]`.
 */
export function useImageFailure(mark: string | null): [boolean, () => void] {
  // `shown` — отказ сейчас на экране; снятый ради повтора, он остаётся в счёте попыток.
  const [failure, setFailure] = useState<{ mark: string; tries: number; shown: boolean } | null>(null);
  const own = mark !== null && failure?.mark === mark ? failure : null;
  const failed = own?.shown ?? false;
  const tries = own?.tries ?? 0;

  useEffect(() => {
    if (!failed || tries > RETRIES) return;
    const timer = setTimeout(
      () => setFailure(f => (f && f.mark === mark ? { ...f, shown: false } : f)), RETRY_AFTER);
    return () => clearTimeout(timer);
  }, [failed, tries, mark]);

  return [
    failed,
    () => {
      if (mark !== null) setFailure(f => ({ mark, tries: (f?.mark === mark ? f.tries : 0) + 1, shown: true }));
    },
  ];
}
