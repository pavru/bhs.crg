/**
 * Разрешённые в редакторах кириллические символы (issue #776).
 *
 * <p>Monaco обводит рамкой буквы, начертанием совпадающие с латинскими, — защита от подмены, когда
 * «о» в идентификаторе оказывается не той «о». В латинском коде это к месту; у нас кириллица —
 * обычное содержимое (коды типов, имена полей, тексты документов), и предупреждение срабатывало на
 * норме: строка `as ИсполнительнаяСхемаФорма3` превращалась в рябь из рамок.</p>
 *
 * <p><b>Перечисляем буквы поимённо, а не выключаем проверку.</b> Выключение
 * (`ambiguousCharacters: false`) убрало бы и настоящие подмены: греческая «ο» внутри латинского
 * слова перестала бы подсвечиваться. Со списком проверка остаётся в силе для всех прочих алфавитов
 * — проверено: `wοrd` с греческой буквой по-прежнему помечается.</p>
 *
 * <p>Опция `allowedLocales: {'{ ru: true }'}` выглядела точнее, но на живом Monaco 0.56 не дала
 * ничего: рамок как было 33, так и осталось. Отсюда поимённый список.</p>
 */
export const CYRILLIC_ALLOWED: Record<string, true> = Object.fromEntries(
  [...'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдежзийклмнопрстуфхцчшщъыьэюяЁё']
    .map(ch => [ch, true as const]),
);
