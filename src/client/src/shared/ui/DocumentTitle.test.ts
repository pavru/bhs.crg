import { describe, it, expect } from 'vitest';
import { documentTitle } from './DocumentTitle';

/**
 * Заголовок вкладки = положение в приложении + название экземпляра (ТЗ CORE-25.1, issue #967).
 *
 * Проверяется формат, а не вёрстка: название приходит с сервера, и до #967 оно было зашито
 * строкой — то есть у заказчика в заголовке вкладки стояло чужое имя.
 */
describe('documentTitle', () => {
  it('раздел и название через разделитель', () => {
    expect(documentTitle('Комплекты', 'СУ-155')).toBe('Комплекты · СУ-155');
  });

  it('без раздела — одно название', () => {
    // Маршрут, которого нет в перечне разделов: приписывать ему пустой раздел с разделителем
    // значило бы показать « · СУ-155» — мусор вместо заголовка.
    expect(documentTitle(null, 'СУ-155')).toBe('СУ-155');
  });
});
