/**
 * Текст отказа при регистрации первого администратора (issue #826).
 *
 * Сообщение о САМОМ отказе приходит с сервера уже по-русски и уже точным: Identity подключён с
 * `RuIdentityErrorDescriber` (issue #165), а эндпоинт отдаёт `{ error: "…" }`, который перехватчик
 * axios кладёт в `err.message`. Переводить коды на клиенте не нужно и вредно: «Пароль должен
 * содержать хотя бы одну заглавную букву» полезнее, чем пересказ всей политики.
 *
 * Здесь остаётся то, чего сервер сказать не может, потому что это не про введённые данные:
 *
 * - **403** — регистрация закрылась, пока форма была открыта (вторая вкладка, чужой опередил).
 *   Сервер советует «обратитесь к администратору» — верно для стороннего потребителя API, но
 *   человеку у этой формы нужен другой шаг: обновить страницу и войти.
 * - **429** — предел частоты; тела у ответа нет вовсе, а без объяснения отказ выглядит как
 *   претензия к паролю, и его начинают менять вместо того, чтобы подождать.
 */
export function registerErrorText(e: unknown): string {
  const res = (e as { response?: { status?: number; data?: unknown } })?.response;

  if (res?.status === 403)
    return 'Регистрация уже закрыта — администратор в системе есть. Обновите страницу и войдите.';
  if (res?.status === 429)
    return 'Слишком много попыток. Попробуйте через несколько минут.';

  // Общий `apiError` здесь не годится: не найдя текста в теле, он возвращает `err.message`, а у
  // axios он есть всегда и по-английски — «Request failed with status code 400». На первом
  // экране системы это худший из возможных ответов: непонятно и не по-русски.
  return serverText(res?.data)
    ?? 'Не удалось создать администратора. Проверьте адрес и пароль, попробуйте ещё раз.';
}

/** Текст, присланный сервером: `{ error }` у наших эндпоинтов, `{ detail }` у ProblemDetails. */
function serverText(data: unknown): string | undefined {
  if (typeof data === 'string') return data.trim() || undefined;
  if (data && typeof data === 'object') {
    const d = data as { error?: string; detail?: string };
    return d.error?.trim() || d.detail?.trim() || undefined;
  }
  return undefined;
}

/**
 * Отказ на ВТОРОМ шаге: администратор создан, а автоматический вход не удался (сеть моргнула,
 * сервер ответил 500).
 *
 * Отдельным текстом, потому что общий увёл бы в тупик: «не удалось создать администратора»
 * заставит повторить регистрацию, а она теперь ответит «уже закрыта» — два сообщения, прямо
 * противоречащих друг другу, и ни одно не говорит правду (учётная запись есть, войти можно).
 */
export function autoLoginFailedText(): string {
  return 'Администратор создан, но автоматический вход не удался. Обновите страницу и войдите обычной формой.';
}
