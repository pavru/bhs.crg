/**
 * Тексты списков под фильтром «Избранные стройки» — общие для экранов (ревью PR #1335): копии у счетов
 * и накладных разошлись бы при первой правке. Существительное — у экрана: «счетов», «накладных».
 */

/** Пустой список, когда объекты есть, но все скрыты фильтром: стоит ПЕРЕД «…пока нет». */
export function hiddenEmpty(noun: string, hidden: number): string {
  return `По избранным стройкам ${noun} нет. Скрыто фильтром: ${hidden}.`;
}

export const SHOW_ALL_SITES = 'Показать все стройки';
export const SEARCH_ALL_SITES = 'Искать по всем стройкам';
