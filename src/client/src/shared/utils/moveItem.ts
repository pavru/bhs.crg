/**
 * Перестановка элемента списка, порядок которого ЗНАЧИМ: массив хранится как есть, и его порядок —
 * это порядок на экране пользователя. Используется в редакторах вариантов перечисления, полей типа,
 * полей профиля распознавания и параметров шаблона.
 *
 * Не переведены осознанно: перестановка групп (`GroupedFieldsEditor`) вставляет ПЕРЕД указанным
 * ключом, то есть позицию считает уже после изъятия, а `SetDetail` и `ComplexFields` двигают два
 * массива параллельно — у обоих другая задача, и подгонять их под общий вид значило бы усложнить.
 *
 * Выход за границы и перестановка на место — не ошибка, а обычный исход клика по «выше» у первой
 * строки: возвращаем ТОТ ЖЕ массив. Вызывающий сравнивает по ссылке и не гоняет сохранение впустую.
 */
export function moveItem<T>(items: T[], from: number, to: number): T[] {
  if (from === to || from < 0 || from >= items.length || to < 0 || to >= items.length) return items;
  const next = [...items];
  const [moved] = next.splice(from, 1);
  next.splice(to, 0, moved);
  return next;
}
