/**
 * Идентификатор для локальных нужд интерфейса — ключа строки в React-списке, узла в редакторе,
 * элемента, которого ещё нет на сервере.
 *
 * Существует потому, что `crypto.randomUUID()` есть НЕ ВЕЗДЕ: браузер даёт его только в защищённом
 * контексте — по HTTPS или на localhost. Установка, открытая по `http://192.168.88.224:8080`
 * (руководство по развёртыванию такие допускает внутри доверенной сети), метода не получает, и
 * прямой вызов роняет экран целиком: он стоял в инициализаторе useState, то есть падал на первом
 * же рендере — «Что-то пошло не так» вместо панели параметров шаблона (issue #848).
 *
 * Криптостойкость здесь не нужна и не подразумевается: значения живут в памяти вкладки, наружу не
 * уходят и в данные не попадают. Нужна уникальность в пределах сеанса — её даёт любой из путей ниже.
 */

/** Запасной счётчик: последний рубеж, когда Web Crypto нет вовсе (очень старый браузер, вебвью). */
let counter = 0;

export function newLocalId(): string {
  const c: Crypto | undefined = globalThis.crypto;

  // Есть защищённый контекст — берём готовый UUID.
  if (typeof c?.randomUUID === 'function') return c.randomUUID();

  // getRandomValues доступен и по HTTP: он не ограничен защищённым контекстом, в отличие от
  // randomUUID и crypto.subtle. Собираем тот же вид v4 руками.
  if (typeof c?.getRandomValues === 'function') {
    const bytes = c.getRandomValues(new Uint8Array(16));
    bytes[6] = (bytes[6] & 0x0f) | 0x40;   // версия 4
    bytes[8] = (bytes[8] & 0x3f) | 0x80;   // вариант RFC 4122
    const hex = [...bytes].map(b => b.toString(16).padStart(2, '0')).join('');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
  }

  // Ни того, ни другого. Форму UUID не изображаем — пусть по значению будет видно, откуда оно
  // взялось; на роль ключа списка этого достаточно.
  counter += 1;
  return `local-${Date.now().toString(36)}-${counter}`;
}
