/**
 * Переключить членство значения во множестве, вернув НОВОЕ множество.
 *
 * <p>Идиома «скопировать, переключить, вернуть» встречалась в тринадцати местах — выбор строк
 * таблицы, раскрытые группы, отмеченные подписчики, выбранные материалы. Везде она была записана
 * тернарником вместо ветвления (`n.has(x) ? n.delete(x) : n.add(x)`), то есть выражением, значение
 * которого выбрасывается. Линт на это и ругался: выражение-без-эффекта чаще всего означает забытое
 * присваивание, и чтобы отличить нарочное от забытого, каждое приходилось смотреть глазами.</p>
 *
 * <p>Новое множество, а не правка на месте: состояние React обязано меняться заменой ссылки —
 * мутация прежнего Set не вызовет перерисовку.</p>
 */
export function toggleInSet<T>(set: ReadonlySet<T>, value: T): Set<T> {
  const next = new Set(set);
  if (next.has(value)) next.delete(value);
  else next.add(value);
  return next;
}
