/**
 * Личность строки в редакторе списка (issue #517).
 *
 * Строки списков ключевались индексом, а перестановка меняет массив — React в таком случае
 * оставляет DOM-узел на месте и подменяет в нём данные. Фокус и курсор остаются привязаны к
 * ПОЗИЦИИ, а не к элементу, поэтому повторный клик по «Ниже» двигает уже другой элемент: два
 * нажатия подряд возвращали список в исходный вид, и переставить строку больше чем на одну позицию
 * повторными кликами было нельзя — как и с клавиатуры.
 *
 * Ключ по содержимому не годится: код/имя как раз редактируют. `WeakMap` по объекту-значению тоже
 * не годится: правка создаёт НОВЫЙ объект, и ключ менялся бы на каждое нажатие клавиши, роняя фокус.
 *
 * Поэтому личность живёт на самом объекте строки под символьным ключом:
 * <ul>
 *   <li>`JSON.stringify` символы не сериализует — личность не протечёт ни в сохраняемые данные, ни
 *       в предпросмотр JSON;</li>
 *   <li>расширение объекта (`{...row, ...patch}`) символ сохраняет — личность переживает правку.</li>
 * </ul>
 *
 * Заводить её нужно ТАМ, ГДЕ ЖИВЁТ СОСТОЯНИЕ: редакторы списков управляемые (список приходит
 * пропом), и попытка проставить личность внутри редактора означала бы onChange на ровном месте —
 * форма помечалась бы изменённой сама по себе.
 */
export const ROW_UID: unique symbol = Symbol('rowUid');

let counter = 0;

/** Строка с личностью; уже помеченная возвращается как есть (личность обязана переживать правки). */
export function withRowUid<T extends object>(row: T): T {
  return (row as { [ROW_UID]?: string })[ROW_UID]
    ? row
    : { ...row, [ROW_UID]: `r${++counter}` };
}

/** То же для списка — обычно применяется при загрузке списка в состояние. */
export function withRowUids<T extends object>(rows: readonly T[]): T[] {
  return rows.map(withRowUid);
}

/** Личность строки, если проставлена. */
export function rowUid(row: object): string | undefined {
  return (row as { [ROW_UID]?: string })[ROW_UID];
}

/** Ключ для React: личность строки, иначе позиция (список без личностей ведёт себя как раньше). */
export function rowKey(row: object, index: number): string | number {
  return rowUid(row) ?? index;
}
