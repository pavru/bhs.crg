/**
 * Исходники клиента как текст — общая опора переписей-сторожей (`*.test.ts`, ищущих нарушение по
 * всему коду, а не в одной функции).
 *
 * <p>Заведено потому, что копий этой связки стало четыре и они РАЗОШЛИСЬ: два сторожа глобили
 * `/src/**\/*.tsx`, два — `../../**\/*.{ts,tsx}`, то есть первые два были слепы к `.ts`-файлам, и
 * из их кода это не читалось никак (поймано ревью PR #1067). Охват сторожа — не деталь его
 * реализации: от него зависит, что он вообще способен увидеть, поэтому охват один и здесь.</p>
 *
 * <p>Путь от корня проекта (ведущий «/»), а не относительный: относительный glob возвращает
 * соседей по каталогу как `./Имя.tsx`, и правила вида «внутренности модуля полей — не форма» их не
 * узнают. Через `import.meta.glob`, а не `node:fs`: клиентский проект собирается без типов Node, и
 * `tsc -b` — то есть сборка — на таком импорте встаёт.</p>
 */
export const clientSources = import.meta.glob('/src/**/*.{ts,tsx}', {
  query: '?raw', import: 'default', eager: true,
}) as Record<string, string>;

/**
 * Построчный поиск нарушений: `файл:строка — текст` по каждой строке, которую признал `isOffending`.
 *
 * @param allowed файлы, где нарушение уместно (сам сторож, обёртка-исключение и т. п.).
 * @param sources по умолчанию — весь клиент; в самопроверке сторожа сюда передают выдуманные файлы,
 *   потому что тест, который «зелёный всегда», хуже отсутствующего: он ещё и создаёт уверенность.
 */
export function offendingLines(
  isOffending: (line: string) => boolean,
  allowed: RegExp[] = [],
  sources: Record<string, string> = clientSources,
): string[] {
  const found: string[] = [];
  for (const [file, code] of Object.entries(sources)) {
    if (allowed.some(re => re.test(file))) continue;
    code.split('\n').forEach((line, i) => {
      if (isOffending(line)) found.push(`${file}:${i + 1} — ${line.trim().slice(0, 80)}`);
    });
  }
  return found;
}
