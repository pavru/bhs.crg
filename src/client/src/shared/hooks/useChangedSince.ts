import { useState } from 'react';

/**
 * Изменилось ли значение с первого рендера (issue #1236) — признак «есть несохранённые правки» для
 * диалога, который собирает черновик в состоянии.
 *
 * <p>Нужен там, где `Modal` правку сам не видит: он замечает только события `input` и `change`, а
 * дата из календаря, пункт выпадающего списка, добавленная или удалённая строка, переключатель-кнопка
 * приходят без них. Сравнение — по записи значения: «вернул как было» честно перестаёт быть правкой,
 * чего флажок «трогали» не умеет.</p>
 *
 * <p>⚠️ Передавайте ТО, ЧТО УЙДЁТ НА СЕРВЕР, а не всё состояние диалога (ревью PR #1311): запасы
 * неактивных режимов и черновые строки без значения правкой не являются, а в сравнение попадут.</p>
 *
 * <p>⚠️ Снимок берётся при МОНТИРОВАНИИ. Компоненту, который смонтирован постоянно и лишь
 * показывается по `open`, хук не годится: снимок переживёт закрытие.</p>
 *
 * <p>Не для больших значений: запись строится на каждом рендере. Таблице в сотни строк с
 * картинками нужен свой признак — см. `ArrayTableModal`.</p>
 */
export function useChangedSince(value: unknown): boolean {
  const [initial] = useState(() => recorded(value));
  return recorded(value) !== initial;
}

/**
 * Запись значения для сравнения. Голый `JSON.stringify` здесь лгал бы молча: `Set` и `Map` он
 * пишет как `{}` при любом содержимом (признак правок навсегда «нет», а явный `isDirty={false}`
 * ещё и выключает собственное наблюдение окна), а порядок ключей объекта считает различием.
 */
export function recorded(value: unknown): string {
  return JSON.stringify(value, (_key, v: unknown) => {
    if (v instanceof Set) return { '#set': [...v] };
    if (v instanceof Map) return { '#map': [...v] };
    if (v && typeof v === 'object' && !Array.isArray(v))
      return Object.fromEntries(Object.entries(v).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
    return v;
  }) ?? 'undefined';
}
