import { useMemo, useState } from 'react';

/**
 * Форма поверх серверного значения (issue #858).
 *
 * <p>Так выглядят почти все формы настроек: сервер отдаёт текущее состояние, человек его правит,
 * а пришедший заново ответ обязан правку заместить — расписание могли поменять из другой вкладки.
 * До сих пор это делалось эффектом «пришли данные — перелей их в состояние формы», и у него два
 * общих изъяна. Между приходом ответа и запуском эффекта форма кадр показывала прежнее; а «правил
 * ли человек» и «не устарела ли правка» приходилось хранить отдельными флагами, которые с самой
 * копией разъезжались.</p>
 *
 * <p>Здесь правка хранится ВМЕСТЕ с тем серверным значением, от которого начата. Тогда оба вопроса
 * — один: правка отвечает нынешнему серверному значению или нет. Отвечает — показываем её; нет —
 * показываем свежее серверное, а правка отбрасывается сама.</p>
 *
 * <p>Сравнение по ССЫЛКЕ, и это работает благодаря React Query: он сохраняет прежнюю ссылку, если
 * перечитанные данные совпали по содержимому (structural sharing). Значит перечитывание, ничего не
 * изменившее, правку не сбивает — сбивает только настоящая смена данных.</p>
 */
export function resolveServerForm<S, F>(
  server: S,
  edited: { from: S; value: F } | null,
  fromServer: F,
): F {
  return edited && edited.from === server ? edited.value : fromServer;
}

/**
 * @param server серверное значение (объект из React Query либо любое стабильное по ссылке)
 * @param toForm перевод серверного значения в форму. Обязан быть СТАБИЛЬНЫМ (объявлен на уровне
 *        модуля или обёрнут в useCallback) — по нему считается мемоизация.
 * @returns `[form, setForm, reset]`. `setForm` принимает значение либо функцию от предыдущего;
 *          `reset` снимает правку, возвращая форму к серверному значению (после сохранения).
 */
export function useServerForm<S, F>(server: S, toForm: (s: S) => F) {
  const [edited, setEdited] = useState<{ from: S; value: F } | null>(null);
  const fromServer = useMemo(() => toForm(server), [server, toForm]);
  const form = resolveServerForm(server, edited, fromServer);

  // Функциональный апдейтер: два быстрых действия подряд обязаны сложиться, а не перебить друг
  // друга, поэтому база берётся из предыдущего состояния, а не из отрендеренного значения.
  const setForm = (upd: F | ((prev: F) => F)) =>
    setEdited(prev => {
      const base = prev && prev.from === server ? prev.value : fromServer;
      return { from: server, value: typeof upd === 'function' ? (upd as (p: F) => F)(base) : upd };
    });

  const reset = () => setEdited(null);

  return [form, setForm, reset] as const;
}
