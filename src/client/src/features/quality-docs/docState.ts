/**
 * Состояния документа качества для экрана контроля связок (issue #555).
 *
 * Это ответ на вопрос пользователя про группировки: группировать связки по производителю или типу
 * документа нельзя — значения свободнотекстовые (17 документов дают 11 групп по производителю, среди
 * них «ООО "ЭЛЕКТРОРЕШЕНИЯ"» и «ООО «Электрорешения»» как разные). А «что требует действия»
 * считается честно, и именно за этим такой экран открывают.
 */
export type DocState = 'expired' | 'expiring' | 'unlinked';

/** Порог «скоро истекает» — за сколько дней документ попадает в «требует внимания». */
export const EXPIRING_SOON_DAYS = 90;

/**
 * Состояние документа или null, если он в порядке.
 *
 * `validUntil` — дата окончания действия или null, когда её НЕ УДАЛОСЬ УЗНАТЬ. Это разные вещи, и
 * путать их нельзя: в живой базе срок лежит в реквизите «ПериодДействия», которого нет ни в одном
 * поле схемы (см. #558), поэтому тэг `quality.validUntil` не резолвится и дата недоступна. Молча
 * считать такой документ действующим — то же самое, что утверждать факт, которого не знаешь.
 */
export function docState(validUntil: string | null, linkCount: number, now = new Date()): DocState | null {
  if (linkCount === 0) return 'unlinked';
  if (!validUntil) return null;
  const end = new Date(validUntil);
  if (Number.isNaN(end.getTime())) return null;
  const days = Math.floor((end.getTime() - now.getTime()) / 86_400_000);
  // Просроченный документ с ЖИВЫМИ связками — самое важное: подсказки просроченные прячут, но уже
  // созданные связки продолжают подмешиваться в PDF.
  if (days < 0) return 'expired';
  return days <= EXPIRING_SOON_DAYS ? 'expiring' : null;
}
