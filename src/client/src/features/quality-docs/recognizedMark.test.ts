import { describe, it, expect } from 'vitest';
import { recognizedPaths, recognizedFieldKeys, applyRecognized } from './recognizedMark';

/**
 * Пометка полей, заполненных распознаванием (issue #807). Проверяется главное свойство: помечается
 * ровно то, что подставилось, — правило одно на обе задачи, и разойтись им нельзя.
 */
describe('пометка распознанных полей', () => {
  it('пустые значения не подставляются и не помечаются', () => {
    const flat = { 'Шифр': '25-04-063-ЭМ', 'Стадия': '', 'ГИП': '   ' };
    expect(recognizedPaths(flat)).toEqual(['Шифр']);
    // То же правило внутри подстановки: пустые поля не затирают набранное руками.
    expect(applyRecognized({ Стадия: 'Р' }, flat)).toEqual({ Стадия: 'Р', Шифр: '25-04-063-ЭМ' });
  });

  it('вложенный путь помечает поле верхнего уровня', () => {
    // У составного значения отдельной рамки нет, да и проверять человек будет весь блок.
    expect(recognizedFieldKeys({ 'Организация.ИНН': '7701234567' })).toEqual(new Set(['Организация']));
  });

  it('ничего не распозналось — помечать нечего', () => {
    expect(recognizedFieldKeys({ 'Шифр': '', 'ГИП': '' }).size).toBe(0);
  });

  it('значение приходит в объявленном виде и таким же подставляется', () => {
    // issue #1005: число страниц сервер знает ЧИСЛОМ, и раньше оно подставлялось через String() —
    // отсюда строка в числовом поле. Заодно ноль и «нет»: пустыми они не являются, и отсеять их
    // упрощением фильтра было бы легко и незаметно.
    const flat = { 'КоличествоЛистов': 3, 'Просрочен': false, 'Остаток': 0 };
    expect(applyRecognized({}, flat)).toEqual(flat);
    expect(recognizedPaths(flat)).toEqual(['КоличествоЛистов', 'Просрочен', 'Остаток']);
  });
});
