import { isFieldRef } from '@/shared/api/types';

/**
 * Возврат отредактированных в таблице строк на их места в массиве (issue #755).
 *
 * <p>Модалка «Таблица» правит только НЕссылочные строки — ссылочные из неё исключены, потому что
 * колонок у ссылки нет. Раньше сохранение склеивало массив разделением,
 * <code>[...allItems.filter(isFieldRef), ...rows]</code>, и все ссылочные строки уезжали в НАЧАЛО
 * массива, где бы они ни стояли. Достаточно было открыть таблицу и нажать «Применить», ничего не
 * меняя. Порядок строк здесь — данные: в реестрах и журналах он и есть порядок в готовом PDF
 * (issue #663).</p>
 *
 * <p><b>Правило.</b> Места, которые занимали нессылочные строки, — это «слоты». Отредактированные
 * строки раскладываются по слотам В СВОЁМ порядке: значит перестановка внутри таблицы сохраняется,
 * а ссылочные строки остаются там же, где были. Строк стало меньше — лишние слоты схлопываются
 * (удалённое исчезает, ссылки сдвигаются). Больше — добавленные идут в конец массива, как их и
 * добавляли в таблице.</p>
 *
 * <p>Чистая функция и отдельный файл — ради теста: правило легко описать словами и легко нарушить
 * правкой на месте, а его нарушение не роняет ничего, только тихо меняет порядок документа.</p>
 */
export function mergeTableRows(
  allItems: unknown[], edited: Record<string, unknown>[],
): unknown[] {
  const result: unknown[] = [];
  let next = 0;
  for (const item of allItems) {
    if (isFieldRef(item)) { result.push(item); continue; }
    // Слот нессылочной строки: занимаем следующей отредактированной; кончились — слот схлопывается.
    if (next < edited.length) result.push(edited[next++]);
  }
  // Строк стало больше, чем было слотов, — хвост добавленных идёт в конец.
  for (; next < edited.length; next++) result.push(edited[next]);
  return result;
}
