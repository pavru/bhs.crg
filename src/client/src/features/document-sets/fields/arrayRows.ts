import { isFieldRef } from '@/shared/api/types';

/**
 * Перестановка и удаление строк массива одним общим языком — «порядком» (issue #754).
 *
 * <p>Порядок здесь — массив СТАРЫХ индексов в новом порядке: <code>[2, 0, 1]</code> значит «третья
 * строка стала первой». Операция описывается порядком, а применяется двумя способами — к самим
 * строкам и к номерам выбранных строк. Оба берут ОДИН И ТОТ ЖЕ порядок, поэтому разъехаться не
 * могут: нельзя переставить строки и забыть переставить выбор. Ровно этот класс расхождения —
 * массив пересобрали, а сопутствующее состояние нет — и был дефектом #755.</p>
 *
 * <p>Выбор хранится номерами, а не личностями строк, потому что личностей у элементов массива нет:
 * значение приходит пропом из формы, две одинаковые строки неразличимы, а собственные id пришлось бы
 * синхронизировать с правками извне (таблица, вынос в общие данные) — лишний источник расхождения.
 * Номера же переживают любую нашу операцию, если пропущены через <code>remapSelection</code>.</p>
 */
export function moveOrder(length: number, from: number, to: number): number[] {
  const order = Array.from({ length }, (_, i) => i);
  if (from < 0 || from >= length || to < 0 || to >= length || from === to) return order;
  const [moved] = order.splice(from, 1);
  order.splice(to, 0, moved);
  return order;
}

/** Порядок после удаления строк: те же индексы без выброшенных. */
export function dropOrder(length: number, dropped: Set<number>): number[] {
  const order: number[] = [];
  for (let i = 0; i < length; i++) if (!dropped.has(i)) order.push(i);
  return order;
}

/** Строки в новом порядке. */
export function applyOrder<T>(items: T[], order: number[]): T[] {
  return order.map(i => items[i]);
}

/**
 * Место строки в нумерации, к которой относятся СЕРВЕРНЫЕ пути (issue #759).
 *
 * <p>Диагностика битых ссылок приходит с сервера путями вида <code>Поле[2]</code> и считается по
 * СОХРАНЁННОМУ состоянию. Редактор сверял её с текущим индексом строки — и любое изменение состава
 * или порядка до сохранения уводило метку на чужую строку: удалили строку выше битой, и красная
 * плитка «ссылка на удалённую запись» переезжает на живую запись, а битая выглядит целой.</p>
 *
 * <p>Поэтому у каждой строки помнится её номер в той нумерации, о которой говорил сервер.
 * <code>null</code> — «сервер про эту строку ничего не говорил»: строку добавили после ответа либо
 * состав изменился так, что проследить нельзя. Метка тогда не рисуется вовсе — это честнее, чем
 * рисовать её наугад.</p>
 */
export type PathOrigins = (number | null)[];

/** Исходное соответствие: строка i — это то, что сервер называл `[i]`. */
export function identityOrigins(count: number): PathOrigins {
  return Array.from({ length: count }, (_, i) => i);
}

/** Строки добавлены в конец: сервер про них не знает. */
export function appendOrigins(origins: PathOrigins, count: number): PathOrigins {
  return [...origins, ...Array.from({ length: count }, () => null)];
}

/** Номера выбранных строк в новом порядке; выбывшие строки из выбора исчезают. */
export function remapSelection(selected: Set<number>, order: number[]): Set<number> {
  const next = new Set<number>();
  order.forEach((old, i) => { if (selected.has(old)) next.add(i); });
  return next;
}

/**
 * Возврат отредактированных в таблице строк на их места в массиве (issue #755).
 *
 * <p>Модалка «Таблица» правит только НЕссылочные строки — ссылочные из неё исключены, потому что
 * колонок у ссылки нет. Раньше сохранение склеивало массив разделением,
 * <code>[...allItems.filter(isFieldRef), ...rows]</code>, и все ссылочные строки уезжали в НАЧАЛО
 * массива, где бы они ни стояли. Достаточно было открыть таблицу и нажать «Применить», ничего не
 * меняя. Порядок строк здесь — данные: в реестрах и журналах он и есть порядок в готовом PDF
 * (issue #663).</p>
 *
 * <p><b>Правило.</b> Места, которые занимали нессылочные строки, — это «слоты». Слоты удалённых
 * строк схлопываются ТАМ, ГДЕ БЫЛИ; оставшиеся заполняются отредактированными строками в их
 * порядке, поэтому перестановка внутри таблицы сохраняется, а ссылочные строки не двигаются.
 * Добавленные идут в конец массива, как их и добавляли в таблице.</p>
 *
 * <p><b>Зачем нужно происхождение строк.</b> Без него нельзя отличить удаление от перестановки:
 * строки после правки неотличимы друг от друга, а их количество говорит только «стало меньше». Если
 * при удалении схлопывать ХВОСТОВЫЕ слоты, а не тот, что исчез, данные протащит СКВОЗЬ ссылки:
 * массив <code>[и1, Р1, и2, Р2, и3]</code> после удаления «и1» дал бы
 * <code>[и2, Р1, и3, Р2]</code> вместо <code>[Р1, и2, Р2, и3]</code> — и «и2» оказался бы перед
 * ссылкой, которая раньше стояла над ним. Ровно тот же класс тихой перестановки, который эта
 * функция и чинит. Происхождение берётся из личностей строк таблицы (issue #171), они переживают
 * и перетаскивание, и удаление.</p>
 *
 * <p>Чистая функция и отдельный файл — ради теста: правило легко описать словами и легко нарушить
 * правкой на месте, а его нарушение не роняет ничего, только тихо меняет порядок документа.</p>
 *
 * @param origins для каждой отредактированной строки — её место среди исходных нессылочных
 *   (0-based) либо <code>null</code>, если строку добавили в таблице.
 */
export function mergeTableRows(
  allItems: unknown[], edited: Record<string, unknown>[], origins: (number | null)[],
): unknown[] {
  return mergeTableSources(allItems, edited, origins)
    .map(s => (s.edited != null ? edited[s.edited] : allItems[s.at!]));
}

/**
 * Откуда взялась каждая строка после правки таблицей.
 *
 * <p><code>at</code> — место в исходном массиве (<code>null</code> — строку добавили в таблице),
 * <code>edited</code> — место среди отредактированных (<code>null</code> — ссылочная строка, в
 * таблицу она не попадала). Одного этого списка хватает и на сами строки, и на их серверные номера
 * (issue #759): раньше метки после «Применить» просто гасились ВСЕ, а вернуть их было нечему —
 * следующий ответ сервера приходит тем же объектом, если диагностика не изменилась.</p>
 */
export function mergeTableSources(
  allItems: unknown[], edited: Record<string, unknown>[], origins: (number | null)[],
): { at: number | null; edited: number | null }[] {
  // Слоты, пережившие правку: те, на которые ссылается хоть одна оставшаяся строка.
  const survived = new Set(origins.filter((o): o is number => o != null));
  const keep = new Set<number>();
  let slot = 0;
  allItems.forEach((item, i) => {
    if (isFieldRef(item)) return;
    if (survived.has(slot)) keep.add(i);
    slot++;
  });

  const result: { at: number | null; edited: number | null }[] = [];
  let next = 0;
  allItems.forEach((item, i) => {
    if (isFieldRef(item)) { result.push({ at: i, edited: null }); return; }
    if (!keep.has(i)) return;                      // слот удалённой строки — схлопывается на месте
    if (next < edited.length) result.push({ at: i, edited: next++ });
  });
  // Добавленные в таблице (и всё, чему не хватило слотов) — в конец.
  for (; next < edited.length; next++) result.push({ at: null, edited: next });
  return result;
}

/**
 * Серверные номера строк после правки таблицей — по тем же источникам, что и сами строки.
 *
 * <p>Ссылочная строка сохраняет свой номер (таблица её не трогала), пережившая правку нессылочная —
 * номер своего слота, добавленная — <code>null</code>. Раньше здесь стояло «погасить все метки»:
 * непрослеживаемым состав только КАЖЕТСЯ — слоты известны точно.</p>
 */
export function mergeTableOrigins(
  sources: { at: number | null; edited: number | null }[], prev: PathOrigins,
): PathOrigins {
  return sources.map(s => (s.at == null ? null : prev[s.at] ?? null));
}
