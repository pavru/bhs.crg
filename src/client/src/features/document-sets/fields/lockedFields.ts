import type { SchemaField } from '@/shared/api/schema';

/**
 * Замок поля (ТЗ CORE-20.2, issue #957/#958): значение кладёт КОД МОДУЛЯ, а не человек. Форма такое
 * поле показывает, но не даёт править — и не требует заполнить.
 *
 * <p>Метку ставит ровно одна сторона — проекция объявления модуля в схему типа
 * (`ModuleTypeProjection`); редактор схемы не даёт ни поставить её, ни снять. Поэтому клиенту
 * проверять нечего, кроме самого признака.</p>
 *
 * <p>Отдельной функцией, а не сравнением `f.locked === true` по месту: форм по схеме три
 * (реквизиты документа, документ качества, запись общих данных), и каждая решает про поле четыре
 * вопроса — рисовать ли ввод, требовать ли заполнения, считать ли заполненным и прятать ли под
 * «Заполняются автоматически». Разойдись ответы, дыра была бы ТИХОЙ: поле с замком осталось бы
 * редактируемым, а отказ пришёл бы с сервера уже при сохранении.</p>
 */
export function isLockedField(field: SchemaField): boolean {
  return field.locked === true;
}

/** Подсказка у замка — одна на все формы: иначе три формы объясняют одно и то же тремя словами. */
export const LOCKED_HINT = 'Заполняет модуль — вручную не правится';
