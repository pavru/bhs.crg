import type { SchemaField } from '@/shared/api/schema';

/**
 * Поля, которые ИСТОЧНИК ДАННЫХ вправе заполнять. Из них редактор маппинга собирает свои списки —
 * скалярные, составные, файловые, ссылочные.
 *
 * Отсеиваются два вида полей, и по разным причинам:
 *
 * - **расчётные** (`computed`, issue #368) — значение вычисляется при генерации по формуле, и
 *   привязка была бы просто бесполезной: источник её не переживёт;
 * - **запертые** (`locked`, ТЗ CORE-20.2) — значение кладёт код модуля, а охрана записи требует
 *   оставить его бит-в-бит. Здесь последствие хуже бесполезности: владелец привязки — документ
 *   или запись каталога — перестаёт сохраняться ВОВСЕ, отказом «поле заперто», который указывает
 *   на поле, а не на привязку, снять которую надо в другой панели.
 *
 * Отдельным модулем от редактора (та же причина, что у `objectSummary`, issue #663): правило
 * чистое, и проверять его, вытягивая в тест всё дерево контролов, значило бы проверять React.
 *
 * ⚠️ Правило одно на все входы. Редактор маппинга открывают из пяти мест — вкладка «Источники»
 * документа, добавление и правка привязки записи каталога, материализация источника, редактор
 * дискриминатора union'а, — и фильтр у вызывающего закрывал бы ровно то из них, о котором
 * вспомнили. Именно так дыра и выглядела: «линза» поля была спрятана, а привязка к тому же полю
 * заводилась из соседнего — галкой «этот источник заполнит также».
 */
export function bindableFields(fields: SchemaField[]): SchemaField[] {
  return fields.filter(f => !f.computed && !f.locked);
}
