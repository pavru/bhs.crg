/**
 * Состояние связанного скалярного поля без значения (issue #67): грузится / источник недоступен / источник
 * не дал значения — чтобы пустое поле только для чтения не выглядело «немым». У поля только для чтения это
 * подсказка поля ([UI-86]), у флажка — строка под ним (`BoundStateHint`).
 */
export const boundStateText = (loading: boolean, error: boolean) => loading ? 'Загрузка значения из источника…'
  : error ? 'Источник недоступен — проверьте в «Источниках»'
  : 'Источник не дал значения';
