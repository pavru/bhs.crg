import type { BrandIcons } from '@/shared/api/branding';

/**
 * Слова секции «Название и логотип» о значках из логотипа (issue #1315) — отдельно от экрана, чтобы
 * их можно было проверить. Тексты — Дизайнера (решения от 13.10.2026), кроме отмеченных.
 */

/** С какого отношения длинной стороны к короткой логотип считается вытянутым. */
const ELONGATED_FROM = 2;

/** Сторона значка вкладки на экране и поле в одну точку с каждого края — как строит сервер. */
const TAB_SIDE = 16;
const TAB_ROOM = 14;

/** Под значком приложения на телефоне помещается около стольких знаков. */
export const HOME_SCREEN_NAME = 12;

/**
 * Предупреждение о вытянутом логотипе — или `null`, если он не вытянут либо значки не построены.
 *
 * Порог — «вдвое длиннее»: логотипы двугорбые («знак над надписью» около 1:1, «знак с надписью в
 * строку» — 3:1 и шире), любой порог от 1,6 до 2,5 делит их одинаково, а этот объясним словами.
 * Число точек в тексте проверяется глазами по превью вкладки рядом: оно показано в настоящие 16.
 *
 * Отношение сторон считает сервер — по тому прямоугольнику, который вписан в значок: у SVG без
 * размеров клиент пропорций не узнает, а пустые поля файла в счёт не идут.
 *
 * @param named название продукта задано. Если нет, замена надписи знаком оставит компанию вовсе
 *   без имени на экране — об этом надо сказать.
 */
export function elongatedWarning(icons: BrandIcons, named: boolean): string | null {
  if (icons.state !== 'custom' || icons.aspect === null || icons.aspect <= 0) return null;
  const wide = icons.aspect >= 1;
  const ratio = wide ? icons.aspect : 1 / icons.aspect;
  if (ratio < ELONGATED_FROM) return null;

  const points = Math.max(1, Math.round(TAB_ROOM / ratio));
  return `Логотип вытянутый, а значок квадратный. Вписанный целиком, на вкладке браузера логотип занимает `
    + `${points} из ${TAB_SIDE} точек по ${wide ? 'высоте' : 'ширине'}. Разборчивым значок получится из `
    + 'квадратного знака без надписи — загрузите его логотипом. Цена: знак встанет и в печатные формы, '
    + 'которые ставят логотип; в шапке и на странице входа название и так написано рядом.'
    + (named ? '' : ' Название тогда задайте выше — иначе оно нигде не будет написано.');
}

const FAILED = 'Значки из логотипа не построены. Логотип сохранён и виден в шапке, а на вкладке, в '
  + 'закладках и в приложении остаются стандартные значки.';

/**
 * Что сказать, когда значки из логотипа не построены, — или `null`, если отказа нет.
 *
 * Совет зависит от ПРИЧИНЫ, а не от кнопки «Построить заново», которой нет нарочно: при битом файле
 * она вернула бы тот же отказ, а при случайном сбое то же делает «Заменить» с тем же файлом.
 * Администратор не может знать, какой из случаев его, — сервер знает и говорит.
 */
export function iconsFailure(icons: BrandIcons): string | null {
  if (icons.state !== 'failed') return null;
  switch (icons.problem) {
    case 'file':
      return `${FAILED} Сервер не смог разобрать этот файл как изображение. Сохраните логотип в PNG и загрузите его.`;
    case 'size':
      // Текст не Дизайнера: причина появилась при реализации. Что именно уменьшить, сказано прямо —
      // предел файла в мегабайтах такой логотип проходит, и «слишком большой» прочли бы про них.
      return `${FAILED} Картинка слишком велика в точках. Уменьшите её — значкам хватает тысячи точек по `
        + 'длинной стороне — и загрузите снова.';
    case 'builder':
      return `${FAILED} Причина — сбой на сервере, а не файл. Загрузите логотип ещё раз; если повторится — `
        + 'подробности в журнале сервера.';
    default:
      // Сюда же — «не уложился в срок»: виноват может быть и файл, и занятый сервер.
      return `${FAILED} Загрузите логотип ещё раз; если повторится — сохраните его в PNG и загрузите.`;
  }
}

/**
 * Подсказка под названием, длиннее которого под значком приложения не поместится, — или `null`.
 * Не запрет: в шапке и в заголовке вкладки длинное название стоит целиком.
 */
export function homeScreenNameHint(name: string): string | null {
  return name.trim().length > HOME_SCREEN_NAME
    ? `Под значком приложения поместится около ${HOME_SCREEN_NAME} знаков.`
    : null;
}
