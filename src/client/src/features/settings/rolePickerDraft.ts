/**
 * Черновик выбора ролей: чистая часть `RolePicker` (issue #984, ревью).
 *
 * Вынесено из компонента, потому что вся ошибка была здесь, а не в разметке: галки копились не в
 * одном месте, и второй щелчок собирался из состава, который ещё не обновился, — первый выбор
 * терялся. Накопление и сравнение проверяются тестом; разметка — живым прогоном.
 */

/** Добавить роль к выбранным или убрать её — всегда от НАКОПЛЕННОГО состава, не от исходного. */
export function toggleRole(chosen: string[], name: string): string[] {
  return chosen.includes(name) ? chosen.filter(n => n !== name) : [...chosen, name];
}

/**
 * Один ли это набор ролей. Сравнение БЕЗ учёта порядка: состав ролей — множество, и порядок в нём
 * ничего не значит. Сравнивай мы списки поэлементно, перестановка выглядела бы правкой — и
 * закрытие меню, в котором ничего не меняли, отправляло бы запрос и обнуляло людям токены.
 */
export function sameRoles(a: string[], b: string[]): boolean {
  return a.length === b.length && a.every(n => b.includes(n));
}
