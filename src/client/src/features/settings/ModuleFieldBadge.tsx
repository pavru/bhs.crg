import type { SchemaField } from '@/shared/api/schema';
import { Tooltip } from '@/shared/ui/Tooltip';

/**
 * Откуда поле и заперто ли оно — СЛОВОМ в плашке (issue #958, ТЗ CORE-20.2).
 *
 * ⚠️ Не значком замка, хотя он просится. Глиф `Lock` в этом же списке уже занят: им помечено поле,
 * УНАСЛЕДОВАННОЕ от родителя, и правится оно в другой панели. Один значок с двумя смыслами в одном
 * контейнере перестаёт значить оба. Слово в плашке — идиома, которая здесь уже работает («унаслед.»
 * рядом), и она различима без наведения.
 *
 * Плашка появляется только у поля модуля: у типов заказчика (а сегодня это все типы) экран не
 * меняется ни на пиксель.
 */
export function ModuleFieldBadge({ field }: { field: SchemaField }) {
  if (field.origin !== 'module') return null;
  return (
    <Tooltip content={field.locked
        ? 'Поле модуля: значение кладёт код модуля, вручную оно не заполняется'
        : 'Поле модуля: объявлено модулем, значение заполняется как обычно'}>
      <span
        // ⚠️ Цвет — ТОЛЬКО из объявленных токенов (bg-tonal/text-on-tonal): своего масштаба Tailwind
        // здесь нет, конфига нет тоже, и класс с невыдуманным именем не падает, а просто не рисуется.
        // Плашка осталась бы без фона — то есть ровно тот сигнал, ради которого она заведена, не
        // появился бы, а tsc и линт промолчали бы (найдено ревью PR #1010).
        className="text-label-small px-1.5 py-0.5 rounded-xs bg-secondary-container text-on-secondary-container shrink-0">
        {field.locked ? 'модуль · заперто' : 'модуль'}
      </span>
    </Tooltip>
  );
}
