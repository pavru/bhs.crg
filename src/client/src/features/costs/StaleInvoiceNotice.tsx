import { Refresh } from '@/shared/ui/icons';
import { ModalBanner } from '@/shared/ui/ModalBanner';

/**
 * «Счёт изменили, пока вы правили» — в ОКНАХ разноски строки и матрицы (issue #1176): окно переносит его в
 * начало себя (`ModalBanner`). Сообщения окон остаются в окнах; на самой форме то же сообщение — пункт
 * «Мешает работе» индикатора состояния и banner над частями (costs-invoice-screen-11, D-11.2).
 *
 * <p>Набранное остаётся на экране: сохранение откажет, но ничего не пропадает, пока человек сам не
 * нажмёт «Перечитать счёт». Автоматически черновик не заменяется — он мог набирать его час.</p>
 *
 * <p>⚠️ Текст говорит, что кнопка сделает с набранным, — «заменятся сохранёнными». «Перечитать» без этой
 * оговорки читается как безопасное действие, а стирает правки. Срочное (`urgent`): работающий на прежних
 * данных обязан узнать о них сразу.</p>
 */
export function StaleInvoiceNotice({ what, onReread }: {
  /** Что именно набрано и не сохранится: «части разноски», «клетки матрицы». */
  what: string;
  onReread: () => void;
}) {
  return (
    <ModalBanner tone="warning" urgent actions={[{ label: 'Перечитать счёт', icon: Refresh, onClick: onReread }]}>
      Счёт тем временем изменили — {what} на экране собраны по прежнему виду и поверх чужой правки не
      сохранятся. Набранное остаётся здесь: перенесите нужное себе, затем перечитайте счёт — несохранённые
      правки заменятся сохранёнными.
    </ModalBanner>
  );
}
