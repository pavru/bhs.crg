/**
 * Уход из формы накладной с несохранённым (issue #1653, ревью PR #1817). Чистая: форма берёт отсюда условие
 * охраны, вопрос и то, пишет ли он перед уходом, — их и проверяют тесты.
 *
 * <p><b>В исправлении вопрос не пишет</b>: исправление проведённой записывается только кнопкой «Записать
 * исправление» — с причиной. Прежде кнопка «Сохранить и перейти» стояла погашенной с причиной в подсказке; по
 * решению из #1817 вопрос, который сохранять не может, кнопки записи не показывает вовсе, а причину называет
 * сам текст вопроса.</p>
 */

export interface WaybillLeaveInput {
  /** Правлены реквизиты или строки. */
  dirty: boolean;
  /** Режим исправления проведённой. */
  correcting: boolean;
  /** Набранная причина исправления — тоже правка: уйти молча значило бы её потерять. */
  reason: string;
}

export interface WaybillLeave {
  /** Держит ли охрана уход. */
  guard: boolean;
  /** Текст вопроса; нет — общий. */
  question?: string;
  /** Пишет ли вопрос перед уходом: в исправлении — нет. */
  savable: boolean;
}

export function waybillLeave({ dirty, correcting, reason }: WaybillLeaveInput): WaybillLeave {
  const guard = dirty || (correcting && reason.trim() !== '');
  if (correcting) return {
    guard, savable: false,
    question: 'Исправление не записано: оно записывается только кнопкой «Записать исправление» — с причиной. ' +
      'Уйдя, вы потеряете набранное в нём.',
  };
  return { guard, savable: true };
}
