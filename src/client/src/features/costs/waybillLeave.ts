/**
 * Уход из формы накладной с несохранённым (issue #1653, ревью PR #1817 и #1821). Чистая: форма берёт отсюда
 * условие охраны, вопрос и то, пишет ли он перед уходом, — их и проверяют тесты.
 *
 * <p><b>Охрана держит всё набранное</b>: реквизиты и строки, недописанную дату отпуска (в черновик она не
 * попадает, и сравнение черновика её не видит) и причину исправления. Накладную удалили — охрана молчит:
 * записывать некуда, и вопрос о записи был бы ложным.</p>
 *
 * <p><b>Вопрос, который сохранять не может, кнопки записи не показывает</b> (решение из #1817), а причину
 * называет текстом: в исправлении — оно записывается только кнопкой «Записать исправление», с недописанной
 * датой — накладную с ней не записать.</p>
 *
 * <p><b>Пока идёт запись, начатая кнопкой формы</b>, вопрос её ждёт и говорит об этом, а не о потере: удачная
 * запись уведёт сама, отказ оставит в накладной.</p>
 */

export interface WaybillLeaveInput {
  /** Правлены реквизиты или строки. */
  dirty: boolean;
  /** Дата отпуска дописана не до конца. */
  typing: boolean;
  /** Режим исправления проведённой. */
  correcting: boolean;
  /** Набранная причина исправления — тоже правка: уйти молча значило бы её потерять. */
  reason: string;
  /** Накладную удалили, пока она была открыта. */
  gone: boolean;
  /** Идёт запись, начатая кнопкой формы: сохранение, проведение, исправление, позиция строки. */
  writing: boolean;
}

export interface WaybillLeave {
  /** Держит ли охрана уход. */
  guard: boolean;
  /** Текст вопроса. */
  question: string;
  /** Пишет ли вопрос перед уходом. */
  savable: boolean;
}

const WRITING = 'Переход — после записи; если она откажет, вы останетесь в накладной с набранным.';

export function waybillLeave({ dirty, typing, correcting, reason, gone, writing }: WaybillLeaveInput): WaybillLeave {
  const guard = !gone && (dirty || typing || (correcting && reason.trim() !== ''));
  // Запись своей кнопкой вопрос не гасит: кнопка «Сохранить и перейти» на это время занята, а не пропадает.
  return { guard, savable: !correcting && !typing, question: question(typing, correcting, writing) };
}

function question(typing: boolean, correcting: boolean, writing: boolean): string {
  if (correcting) return writing ? `Исправление записывается. ${WRITING}`
    : 'Исправление не записано: оно записывается только кнопкой «Записать исправление» — с причиной. '
      + 'Уйдя, вы потеряете набранное в нём.';
  if (writing) return `Накладная записывается. ${WRITING}`;
  if (typing) return 'Дата отпуска дописана не до конца — накладную с ней не записать. Уйдя, вы потеряете набранное.';
  return 'Не сохранены изменения накладной. Сохранить их перед переходом?';
}
