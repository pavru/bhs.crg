/**
 * Как реестр счетов называет места разноски в колонках «Объект» и «Раздел» (COST-20.1, D7 change
 * `costs-filter-place-hints`) — копия `RegistryPlaceNames` сервера. Отбор реестра идёт по названию, и
 * подсказка условия собирает названия этими словами: разойдись они с сервером, она предлагала бы то, под
 * что не найдётся ни одного счёта. Копии сверяет общий набор `placeLabelCases.json` — тест здесь и
 * `PlaceLabelCasesTests` на сервере.
 *
 * <p>⚠️ Не `LOST` из `lostReferences.ts`: тот — словарь формы и пометок ссылки («стройка удалена»), с
 * реестром у него совпадает только «раздел удалён», и то случайно.</p>
 */
export const REGISTRY_WORDS = {
  /** Доля на стройку целиком — раздел не назван. */
  noSection: 'без раздела',
  /** Раздел, которого больше нет (и доля без раздела на удалённой стройке). */
  lostSection: 'раздел удалён',
  /** Стройка или статья, которой больше нет. */
  lostObject: 'объект удалён',
} as const;

/** «Комарова 36 / 4 эт.» — так раздел зовут колонка реестра, её отбор и ссылка отчёта. */
export function sectionLabel(site: string, section: string): string {
  return `${site} / ${section}`;
}
