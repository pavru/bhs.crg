import { wordsOf, type FileKind } from '@/shared/api/fileKinds';
import type { InvoiceQueue } from '@/shared/api/invoices';

/**
 * Слова о броске файлов до броска (shell-07-scan-drop-hint, [COST-8] [COST-31], #1435). Целью броска служит всё
 * окно (costs-invoice-screen-14), поэтому отдельного элемента под это нет: о броске говорят пустые состояния — там,
 * куда человек смотрит, пока счёт не открыт. Кто не может заводить счета, приглашения не получает: оно кончилось бы
 * отказом.
 */

/**
 * Описание «Выберите счёт» в правой части. Она сама входит в цель броска — «сюда» здесь правда. Форматы — словами
 * реестра видов файлов, тот же источник, что у выбора файла; реестр не пришёл — без скобок, а не выдуманный перечень.
 * Без права описания нет: заголовка достаточно, а «заведите новый» звало бы в отказ.
 */
export function selectHint(canEdit: boolean, kinds: FileKind[]): string | undefined {
  if (!canEdit) return undefined;
  const named = kinds.length ? ` (${wordsOf(kinds)})` : '';
  return `Или перетащите сюда файлы счетов${named} — из каждого заведём черновик и распознаем его в фоне. `
    + 'Новый счёт можно завести и пустым.';
}

/**
 * Хвост пустого списка без отбора и поиска — после «Счетов пока нет.». Под отбором пустота говорит про отбор; на
 * телефоне перетаскивать нечем (вход там — плавающая кнопка). Форматов нет: рядом, в правой части, их уже назвали.
 */
export function emptyDropTail({ canEdit, wide, queue, query }: {
  canEdit: boolean; wide: boolean; queue: InvoiceQueue | null; query: string;
}): string {
  return canEdit && wide && !queue && !query.trim() ? ' Перетащите файлы счетов в окно или нажмите «Счёт из файла».' : '';
}
