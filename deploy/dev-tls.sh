#!/bin/sh
# Самоподписанный сертификат для ДЕВ-СТЕНДА (issue #940). В поставке TLS терминирует nginx на
# хосте с сертификатом Let's Encrypt (Приложение В в docs/DEPLOYMENT.md) — здесь это невозможно:
# Let's Encrypt требует имя в DNS и доступность по порту 80 снаружи, чего у дев-машины нет.
#
# ── Почему УЦ, а не один самоподписанный сертификат ─────────────────────────────────────────────
# Доверять на телефоне и в системе приходится вручную, и делать это после каждого перевыпуска никто
# не станет — доверие просто отключат целиком. Поэтому здесь два уровня: долгий УЦ (его ставят в
# доверенные ОДИН раз) и короткий сертификат сервера, который перевыпускается при смене имён
# свободно, не требуя ничего заново устанавливать.
#
# Идемпотентен: на готовом каталоге не делает ничего. Перевыпуск — только когда набор имён
# изменился или файлов нет, иначе каждый подъём стенда сбрасывал бы доверие браузера.
set -eu

DIR=${DEV_TLS_DIR:-/tls}
mkdir -p "$DIR"

# Базовый набор имён: петля и имя, по которому до хоста достукивается контейнер nginx.
SAN="DNS:localhost,DNS:host.docker.internal,IP:127.0.0.1,IP:0:0:0:0:0:0:0:1"
PRIMARY=localhost

# Дополнительные имена и адреса — из DEV_TLS_NAMES (через запятую). Именно так в сертификат
# попадает адрес машины в локальной сети: без него телефон получит не предупреждение о доверии,
# а отказ «сертификат выписан не на этот адрес», который установкой УЦ не лечится.
for name in $(echo "${DEV_TLS_NAMES:-}" | tr ',' ' '); do
    [ -n "$name" ] || continue
    case "$name" in
        *:*)       SAN="$SAN,IP:$name" ;;    # адрес IPv6
        *[!0-9.]*) SAN="$SAN,DNS:$name" ;;   # есть что-то кроме цифр и точек — имя
        *)         SAN="$SAN,IP:$name" ;;    # адрес IPv4
    esac
done

# Отпечаток набора имён: по нему и решается, нужен ли перевыпуск.
if [ -f "$DIR/server.crt" ] && [ -f "$DIR/ca.crt" ] && [ "$(cat "$DIR/.names" 2>/dev/null || true)" = "$SAN" ]; then
    echo "Сертификат стенда на месте, имена прежние — перевыпуск не нужен."
    echo "  $SAN"
    exit 0
fi

# ── Удостоверяющий центр стенда ────────────────────────────────────────────────────────────────
# Создаётся один раз и переживает перевыпуски сертификата сервера: в этом весь смысл разделения.
if [ ! -f "$DIR/ca.crt" ] || [ ! -f "$DIR/ca.key" ]; then
    echo "Выпускаю удостоверяющий центр дев-стенда…"
    openssl req -x509 -newkey rsa:2048 -sha256 -days 3650 -nodes \
        -keyout "$DIR/ca.key" -out "$DIR/ca.crt" \
        -subj "/CN=BHS.CRG dev stand CA/O=BHS.CRG dev stand" \
        -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
        -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
fi

# ── Сертификат сервера ─────────────────────────────────────────────────────────────────────────
# 397 дней — предел, который браузеры принимают для сертификатов сервера; больше ставить нельзя
# даже своему УЦ (Safari отвергает такой сертификат независимо от доверия к корню).
echo "Выпускаю сертификат сервера на имена: $SAN"
openssl req -newkey rsa:2048 -nodes -keyout "$DIR/server.key" -out /tmp/server.csr \
    -subj "/CN=$PRIMARY" 2>/dev/null
openssl x509 -req -in /tmp/server.csr -CA "$DIR/ca.crt" -CAkey "$DIR/ca.key" -CAcreateserial \
    -out "$DIR/server.crt" -days 397 -sha256 -extfile - <<EXT 2>/dev/null
subjectAltName=$SAN
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
EXT

# Цепочку nginx отдаёт целиком: браузер, которому УЦ уже известен, обойдётся и одним сертификатом,
# а вот curl с ключом --cacert на цепочке работает без дополнительных объяснений.
cat "$DIR/server.crt" "$DIR/ca.crt" > "$DIR/fullchain.crt"
printf '%s' "$SAN" > "$DIR/.names"

# Читать ключ должен непривилегированный nginx (образ работает не от root). Каталог одноразовый,
# лежит вне репозитория и пересоздаётся одной командой — секрета здесь нет.
chmod 644 "$DIR"/*.crt "$DIR"/*.key

echo "Готово. Поставьте в доверенные: dev-tls/ca.crt"
