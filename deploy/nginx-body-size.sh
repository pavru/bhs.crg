#!/bin/sh
# Предел тела запроса у nginx — из той же переменной, что и предел архива у API (issue #711).
#
# Почему скриптом, а не числом в nginx.conf. Порог существует не сам по себе, а звеном цепи:
#     nginx (client_max_body_size) → Kestrel (MaxRequestBodySize) → разбор формы → проверка в API
# Порог любого звена ниже нашего делает предел приложения недостижимым, а отказ приходит
# HTML-страницей nginx без поля error — ровно тот дефект, ради которого заведён issue #482.
# С issue #711 предел архива стал настройкой развёртывания; оставить здесь константу значило бы
# закрыть одну дверь из двух. Переменная поэтому ОДНА, а запас на обвязку multipart добавляется
# здесь — nginx считать не умеет, а держать в .env два согласованных числа значит однажды их
# рассогласовать.
#
# Диапазон значения не проверяем: это дело API (BackupSizeLimits), и он отказывается стартовать
# на негодном. Две проверки диапазона в двух местах разъедутся, а здесь достаточно убедиться, что
# подставляемое — число, иначе nginx упал бы на разборе конфигурации без объяснения причины.
set -e

mb="${BACKUP_MAX_ARCHIVE_MB:-500}"

case "$mb" in
    ''|*[!0-9]*)
        echo "nginx: BACKUP_MAX_ARCHIVE_MB=\"$mb\" — ожидалось целое число мегабайт." >&2
        exit 1
        ;;
esac

# Запас на служебную обвязку multipart: тело запроса всегда больше самого файла (границы частей,
# заголовки). Без него архив ровно в предел отвергался бы транспортом раньше нашей проверки.
overhead_mb=8

mkdir -p /tmp/nginx
printf 'client_max_body_size %sm;\n' "$((mb + overhead_mb))" > /tmp/nginx/body-size.conf
echo "nginx: client_max_body_size $((mb + overhead_mb))m (BACKUP_MAX_ARCHIVE_MB=$mb)"
