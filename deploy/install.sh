prepare_backups() {
    local dir="backups"
    mkdir -p "$dir"
    # uid 1654 — пользователь app внутри образа. Каталог, созданный от root или от вас, система
    # принять не может и останавливается при старте.
    #
    # ⚠️ БЕЗ ROOT `chown` НА ЧУЖОЙ uid НЕ РАБОТАЕТ ВООБЩЕ — а установку обычно и запускают не от
    # root. Первая редакция на этом останавливалась, то есть ломала каждую вторую установку; но
    # выход есть, и он даже не требует прав: сменить владельца может docker, к которому у
    # запускающего доступ по определению — иначе он не поставил бы систему.
    if chown 1654:1654 "$dir" 2>/dev/null; then
        say "Каталог копий $dir создан и передан пользователю app (uid 1654)."
        return 0
    fi
    if docker run --rm -v "$(pwd)/$dir:/b" alpine:3.22.2 chown -R 1654:1654 /b >/dev/null 2>&1; then
        say "Каталог копий $dir создан и передан пользователю app (uid 1654) — через docker, без root."
        return 0
    fi
    stop "$(cat <<EOF
Каталог $dir создан, но сменить владельца не вышло ни напрямую, ни через docker. Система с чужим
каталогом НЕ ЗАПУСТИТСЯ: сервер работает под пользователем app (uid 1654).

Сделайте любым из способов и запустите установку снова — этот каталог ей не помешает:
  sudo chown -R 1654:1654 $(pwd)/$dir
  docker run --rm -v "$(pwd)/$dir:/b" alpine chown -R 1654:1654 /b
EOF
)"
}


# Печатает ТОЛЬКО ответ системы: функция вызывается через подстановку, и любое сообщение из неё
# попало бы в переменную вместо версии. Проверено живьём — в первом прогоне так и вышло:
# «Система ответила: Ждём готовности системы…». Поэтому ход дела — в stderr.
# ⚠️ ЖДЁМ ЗРЯЧЕ, а не по таймеру (issue #896). Прежняя редакция сто раз опрашивала адрес и молчала
# — даже когда контейнер уже лежал: 100 попыток по 5 секунд это восемь минут тишины, притом что
# человеку обещано «до пяти». Отказ, притворившийся ожиданием, — худший вид отказа: он выглядит
# как «ещё чуть-чуть».
#
# Поэтому на каждом круге спрашиваем и у Compose: контейнер, который перезапускается или вышел, не
# станет отвечать, сколько его ни жди. Падаем сразу и с хвостом ЕГО журнала.
container_broken() { # печатает имя сломанного сервиса, если такой есть
    local name state cid
    while IFS='|' read -r name state; do
        [ -n "$name" ] || continue
        case "$state" in
            restarting|dead) printf '%s' "$name"; return 0 ;;
            exited)
                # ⚠️ Вышедший контейнер — НЕ ОБЯЗАТЕЛЬНО поломка: в стеке есть одноразовые сервисы,
                # которые выходят по устройству (garage-init, а при включённом распознавании ещё и
                # ollama-init, качающий модель). Различаем по КОДУ ВЫХОДА, а не по имени: список
                # имён устареет с первым же новым сервисом, и установка начнёт падать на здоровой
                # системе (найдено ревью).
                cid="$(compose ps -aq "$name" 2>/dev/null | head -1)"
                [ -n "$cid" ] || continue
                [ "$(docker inspect -f '{{.State.ExitCode}}' "$cid" 2>/dev/null || echo 0)" = 0 ] && continue
                printf '%s' "$name"; return 0 ;;
        esac
    done <<EOF
$(compose ps -a --format '{{.Service}}|{{.State}}' 2>/dev/null || true)
EOF
    return 1
}

wait_ready() {
    local url="http://127.0.0.1:$PORT/api/version" i=0 answer broken
    printf 'Ждём готовности системы (первый старт занимает до пяти минут: миграции и проверки)…
' >&2
    while [ "$i" -lt 120 ]; do
        answer="$(curl_local -fsS --max-time 5 "$url" 2>/dev/null || true)"
        case "$answer" in *'"version"'*) printf '%s' "$answer"; return 0 ;; esac
        if broken="$(container_broken)"; then
            printf '
Контейнер «%s» не работает — ждать больше нечего. Последние строки его журнала:
' "$broken" >&2
            compose logs --tail 30 "$broken" >&2 2>/dev/null || true
            return 1
        fi
        sleep 5
        i=$((i + 1))
    done
    printf '
Система не ответила за десять минут, но контейнеры работают. Журнал api:
' >&2
    compose logs --tail 30 api >&2 2>/dev/null || true
    return 1
}


create_admin() {
    local url="http://127.0.0.1:$PORT/api/auth/register" body code
    body="$(printf '{"email":%s,"password":%s,"displayName":%s}' \
        "$(json_string "$ADMIN_EMAIL")" "$(json_string "$ADMIN_PASSWORD")" "$(json_string "$ADMIN_NAME")")"
    # Тело уходит ЧЕРЕЗ STDIN (`@-`), а не аргументом, по двум причинам, и вторая важнее первой.
    #
    # 1. Аргумент командной строки виден в `ps` любому пользователю сервера — а здесь в нём пароль
    #    администратора системы.
    # 2. Аргументы перекодируются: на Windows curl получает их через Win32 в UTF-16 и переводит в
    #    ANSI, отчего кириллица в имени превращается в мусор и сервер отвечает 400 на невалидный
    #    UTF-8. Проверено живьём: тот же JSON через stdin — 200, аргументом — 400.
    # Имя файла — через mktemp, а не «/tmp/…$$»: предсказуемое имя в общем каталоге позволяет
    # местному пользователю подложить символьную ссылку, а `curl -o` пойдёт по ней и перезапишет
    # чужой файл — под установкой, которую обычно запускают от root (найдено ревью).
    local out; out="$(mktemp)"
    code="$(printf '%s' "$body" | curl_local -s -o "$out" -w '%{http_code}' --max-time 30 \
        -X POST -H 'Content-Type: application/json' --data-binary @- "$url" || true)"
    if [ "$code" = 200 ] || [ "$code" = 201 ]; then
        rm -f "$out"
        say "Администратор $ADMIN_EMAIL создан — страница регистрации закрыта."
        return 0
    fi
    warn "$(cat <<EOF
Создать администратора не удалось (ответ $code): $(head -c 300 "$out" 2>/dev/null)

Система при этом РАБОТАЕТ, но страница первого входа открыта: зайдите на неё и заведите
администратора сами, прямо сейчас — до того, как адрес станет доступен кому-то ещё.
EOF
)"
    rm -f "$out"
    return 1
}

# Строку в JSON собираем сами: значения приходят от человека, и кавычка или обратный слэш в пароле
# порвали бы тело запроса. Экранируем ровно то, что обязано быть экранировано.
json_string() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | sed -e 's/^/"/' -e 's/$/"/'
}

