#!/bin/sh
# Приведение свежего Garage в рабочее состояние: раскладка, ключ, бакет, права (issue #885).
#
# Зачем это вообще нужно. Garage без ПРИМЕНЁННОЙ раскладки не обслуживает S3 совсем — не «отдаёт
# пустой список», а отвечает отказом на любой запрос. MinIO поднимался готовым, здесь между
# стартом контейнера и работающим хранилищем есть шаг, и его кто-то должен сделать.
#
# Почему отдельный образ, а не команда в compose. В официальном образе Garage НЕТ shell: там один
# исполняемый файл. Одной командой инициализация не делается (нужен идентификатор узла, который
# заранее неизвестен), а цепочка одноразовых сервисов на каждую команду не была бы идемпотентной.
# Поэтому рядом собирается образ «alpine + тот же бинарь Garage» — см. Dockerfile.garage-init.
#
# Скрипт ИДЕМПОТЕНТЕН: он выполняется при каждом старте стека и на уже настроенном хранилище не
# делает ничего. Это не украшение — compose поднимает его вместе со всеми, и «второй запуск ломает
# установку» здесь означало бы поломку при обычном перезапуске сервера.
set -eu

BUCKET="${GARAGE_BUCKET:?не задан GARAGE_BUCKET}"
KEY_ID="${GARAGE_KEY_ID:?не задан GARAGE_KEY_ID}"
KEY_SECRET="${GARAGE_SECRET:?не задан GARAGE_SECRET}"
KEY_NAME="${GARAGE_KEY_NAME:-bhs-crg}"
ZONE="${GARAGE_ZONE:-dc1}"
CAPACITY="${GARAGE_CAPACITY:-100G}"

say() { printf '  %s\n' "$*"; }

# ── Ждём узел ───────────────────────────────────────────────────────────────────
# Не `depends_on` в одиночку: он говорит «контейнер запущен», а нам нужно «RPC отвечает».
# Ограничение по попыткам, а не `until` до посинения: молчаливое зависание init-сервиса выглядит
# как «стек поднимается» и съедает время, пока человек ждёт систему.
i=0
until garage status >/dev/null 2>&1; do
    i=$((i + 1))
    if [ "$i" -ge 60 ]; then
        echo "Garage не ответил за 60 попыток — инициализация невозможна." >&2
        garage status || true
        exit 1
    fi
    sleep 1
done
say "узел отвечает"

# ── Раскладка ───────────────────────────────────────────────────────────────────
# Роль назначается один раз. Признак ненастроенного узла — «NO ROLE ASSIGNED» в статусе; он
# надёжнее отсутствия файла-отметки, потому что состояние живёт в кластере, а не рядом на диске.
if garage status | grep -q 'NO ROLE ASSIGNED'; then
    NODE="$(garage node id -q | cut -d@ -f1)"
    [ -n "$NODE" ] || { echo "не удалось узнать идентификатор узла" >&2; exit 1; }
    garage layout assign -z "$ZONE" -c "$CAPACITY" "$NODE" >/dev/null
    # Номер версии раскладки берём из показаний самого Garage, а не «1»: на повторной настройке
    # (узел заменили, ёмкость поменяли) версия будет другой, и литерал молча промахнулся бы.
    #
    # `[0-9][0-9]*`, а не `[0-9]*`: звёздочка соглашается на ПУСТОЕ совпадение, и строка со словом
    # «version» без числа дала бы пустую строку — а дальше подстановка по умолчанию тихо вернула бы
    # ту самую единицу, вместо которой всё это и написано. Пусто — останавливаемся и говорим.
    VER="$(garage layout show | sed -n 's/.*version \([0-9][0-9]*\).*/\1/p' | tail -1)"
    if [ -z "$VER" ]; then
        echo "не удалось прочитать номер версии раскладки из вывода 'garage layout show'." >&2
        garage layout show >&2
        exit 1
    fi
    garage layout apply --version "$VER" >/dev/null
    say "раскладка применена (зона $ZONE, ёмкость $CAPACITY)"
else
    say "раскладка уже применена"
fi

# ── Ключ доступа ────────────────────────────────────────────────────────────────
# Ключ ИМПОРТИРУЕМ, а не создаём: сгенерированный Garage секрет пришлось бы вычитывать из вывода и
# куда-то записывать, то есть развёртывание перестало бы быть повторяемым. Так значения задаются в
# `.env` — ровно как раньше задавались MINIO_ROOT_USER/PASSWORD.
if garage key info "$KEY_ID" >/dev/null 2>&1; then
    say "ключ $KEY_ID уже есть"
else
    garage key import --yes -n "$KEY_NAME" "$KEY_ID" "$KEY_SECRET" >/dev/null
    say "ключ $KEY_ID импортирован"
fi

# ── Бакет и права ───────────────────────────────────────────────────────────────
if garage bucket info "$BUCKET" >/dev/null 2>&1; then
    say "бакет $BUCKET уже есть"
else
    garage bucket create "$BUCKET" >/dev/null
    say "бакет $BUCKET создан"
fi

# `bucket allow` идемпотентен — повторная выдача тех же прав ничего не меняет.
garage bucket allow --read --write --owner "$BUCKET" --key "$KEY_ID" >/dev/null
say "права на $BUCKET выданы ключу $KEY_ID"

# Право создавать бакеты ключу НЕ выдаётся намеренно. Приложение зовёт MakeBucket только когда
# бакета нет (EnsureBucketAsync), а бакет здесь уже создан — то есть в норме вызов не случается.
# Выданное право означало бы, что опечатка в имени бакета молча заводит второй, пустой, и система
# «работает», потеряв все файлы из виду.
say "готово"
