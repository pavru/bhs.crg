#!/usr/bin/env bash
#
# Обновление установки BHS.CRG одной командой.
#
#   ./update.sh 0.146.0     — обновить на версию
#   ./update.sh --check     — есть ли выпуск новее (для cron: 0 — есть, 3 — нет)
#   ./update.sh --rollback  — вернуть прежнюю версию, пока миграции не применились
#   ./update.sh --gc        — убрать старые образы, которых текущая версия не касается
#
# Устройство скрипта подчинено одному правилу: МЕХАНИКУ он берёт на себя, а РЕШЕНИЯ оставляет
# человеку — останавливаясь с точным вопросом. «Как-нибудь слить» compose-файл или «подставить
# что-нибудь» в новую переменную опаснее, чем инструкция: инструкция хотя бы не притворяется, что
# справилась. Поэтому там, где §8 DEPLOYMENT.md описывает словами тихий отказ, здесь стоит явная
# остановка (issue #837).
#
# Порядок шагов взят из §8 и держится на том же принципе: всё, что может отказать — недоступный
# реестр, неразобранный compose, недостающая переменная, — происходит ДО первой остановки
# контейнеров. Дойдя до `up -d`, вы уже знаете, что обновление состоится.

set -euo pipefail

REPO="pavru/bhs.crg"
RELEASE_URL="https://github.com/$REPO/releases/download"
SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
NEW_DIR="new"                       # сюда кладутся файлы целевой версии; сюда же человек переносит свои правки
PRISTINE="$NEW_DIR/.docker-compose.release.yml"  # нетронутый файл целевой версии — будущий эталон
# Эталон — copy того compose, который скрипт положил в прошлый раз: файл версии либо ваш, с
# перенесёнными правками. Сравнение с ним отвечает на единственный нужный вопрос — «правили ли
# файл ПОСЛЕ прошлого обновления».
RELEASE_REF="docker-compose.yml.release"
STAMP="$(date +%Y%m%d-%H%M%S)"

FORCE=0            # обойти проверку фоновых задач
NO_BACKUP=0        # не снимать дамп (сняли иначе)
COMPOSE_MERGED=0   # правки в new/docker-compose.yml перенесены человеком
YES=0              # к --gc: удалять, а не только показывать
ROLLBACK=0
CHECK=0
GC=0
ACCEPT_DEFAULTS_SEEN=0
TARGET=""
AUTOFILL=()        # новые переменные, которые скрипт впишет в .env сам (см. check_new_vars)
GENERATE=()        # ключи хранилища, которые скрипт СГЕНЕРИРУЕТ (см. generate_secrets)
# Значения этих ключей человек не выбирает: они случайные и свои для каждой установки. Список
# здесь, а не в проверке, потому что на него смотрят двое — check_new_vars (не спрашивать) и
# generate_secrets (создать).
GENERATED_KEYS=(GARAGE_KEY_ID GARAGE_SECRET GARAGE_RPC_SECRET GARAGE_ADMIN_TOKEN GARAGE_BUCKET)

# ── Разговор с человеком ────────────────────────────────────────────────────────
# Три уровня, и они не взаимозаменяемы: say — ход дела, warn — «прочтите, но идём дальше»,
# stop — «дальше решает человек». Последний всегда называет, ЧТО сделать, чтобы продолжить;
# остановка без следующего шага — это тот же тихий отказ, только громкий.
say()  { printf '%s\n' "$*"; }
warn() { printf '\n! %s\n' "$*" >&2; }
stop() { printf '\n╳ %s\n' "$*" >&2; exit 1; }
head2() { printf '\n── %s ──\n' "$*"; }

# ── Разбор аргументов ───────────────────────────────────────────────────────────
usage() {
    cat <<'USAGE'
Обновление установки BHS.CRG.

  ./update.sh ВЕРСИЯ        обновить на указанную версию (например 0.146.0)
  ./update.sh --check       есть ли выпуск новее вашего; ничего не меняет
                            (коды выхода для cron: 0 — есть, 3 — нет, 1 — спросить не удалось)
  ./update.sh --rollback    вернуть прежнюю версию (пока миграции не применились)
  ./update.sh --gc          показать старые образы BHS.CRG, не нужные текущей версии
                            (удалить их — тот же вызов с --yes)

Ключи (каждый — осознанный обход одной из остановок):
  --force             обновляться, несмотря на незавершённые фоновые задачи
  --no-backup         не снимать дамп базы (вы сняли копию другим способом)
  --compose-merged    ваши правки уже перенесены в new/docker-compose.yml
  --yes               к --gc: удалить показанное
  -h, --help          эта справка

Запускать из каталога, где лежат docker-compose.yml и .env (в клоне репозитория — из deploy/).
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --rollback)        ROLLBACK=1 ;;
        --check)           CHECK=1 ;;
        --gc)              GC=1 ;;
        --force)           FORCE=1 ;;
        --no-backup)       NO_BACKUP=1 ;;
        --compose-merged)  COMPOSE_MERGED=1 ;;
        --yes)             YES=1 ;;
        # Ключ пережил свою остановку: переменные с умолчаниями скрипт теперь дописывает сам
        # (check_new_vars). Не ошибка, а пустой ход — иначе сохранённая где-то команда с этим
        # ключом начала бы падать на ровном месте.
        --accept-defaults) ACCEPT_DEFAULTS_SEEN=1 ;;
        -h|--help)         usage; exit 0 ;;
        -*)                usage >&2; stop "Неизвестный ключ: $1" ;;
        *)
            [ -z "$TARGET" ] || stop "Версия указана дважды: «$TARGET» и «$1»."
            TARGET="${1#v}"   # «v0.146.0» и «0.146.0» — одно и то же
            ;;
    esac
    shift
done

[ "$ACCEPT_DEFAULTS_SEEN" -eq 0 ] || warn \
    "Ключ --accept-defaults больше ничего не делает: переменные с умолчаниями скрипт дописывает сам, а остановка осталась только там, где нужно ваше решение."

# Команды взаимно исключают друг друга. Молча предпочесть одну другой — значит сделать не то, о чём
# просили: `--check --gc` человек пишет, ожидая обе, а получил бы одну и не заметил.
[ $((CHECK + GC + ROLLBACK)) -le 1 ] || stop "--check, --gc и --rollback — разные команды, вместе не выполняются."
if [ "$CHECK" -eq 1 ] || [ "$GC" -eq 1 ]; then
    [ -z "$TARGET" ] || stop "Номер версии здесь не нужен: --check спрашивает про последний выпуск, --gc смотрит на установленную версию."
fi
[ "$YES" -eq 0 ] || [ "$GC" -eq 1 ] || stop "Ключ --yes имеет смысл только с --gc: остальные остановки требуют не согласия, а действия."

# ── Чтение .env ─────────────────────────────────────────────────────────────────
# Читаем ГРЕПОМ, а не `source .env`: в файле лежат пароли и ключи со спецсимволами, и исполнять
# его ради двух значений — лишний способ получить сюрприз (`$` в пароле, перевод строки, `rm` в
# значении). Кавычки по краям снимаем — Compose их тоже не считает частью значения.
env_get() {
    local key="$1" file="${2:-.env}" line
    [ -f "$file" ] || return 0
    line="$(grep -E "^[[:space:]]*$key[[:space:]]*=" "$file" | tail -1 || true)"
    [ -n "$line" ] || return 0
    line="${line#*=}"
    # Комментарий в конце строки Compose отбрасывает (он начинается с # после пробела) — значит и
    # мы обязаны: иначе «APP_VERSION=0.145.1  # поставили руками» превращался бы в номер версии
    # вместе с комментарием, и скрипт уходил бы за несуществующим релизом, ругаясь на его отсутствие.
    line="$(printf '%s' "$line" | sed -E 's/[[:space:]]+#.*$//; s/[[:space:]]+$//')"
    line="${line%\"}"; line="${line#\"}"
    line="${line%\'}"; line="${line#\'}"
    printf '%s' "$line"
}

env_keys() { grep -oE '^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*=' "$1" | tr -d ' \t=' | sort -u; }

compose() { docker compose "$@"; }

# ⚠️ ЗАПРОС К САМОМУ СЕБЕ — НЕ ДЕЛО ПРОКСИ (issue #896). На сервере с `all_proxy=socks5://…` curl
# уважает эту переменную и для петли: опрос `http://localhost:8080/api/version` уходит в прокси,
# который в петлю сервера не попадает, и обновление ждёт готовности до самого таймаута — при
# работающей системе. Загрузки с github.com идут обычным curl: там прокси и есть путь наружу.
curl_local() { curl --noproxy '*' "$@"; }

# ── Общий предполёт ─────────────────────────────────────────────────────────────
preflight_common() {
    command -v docker >/dev/null 2>&1 || stop "Docker не найден. Установка — Приложение А в DEPLOYMENT.md."
    docker compose version >/dev/null 2>&1 || stop \
        "Нет плагина «docker compose» (через пробел). Версия v1 (docker-compose) не годится — Приложение А."
    [ -f docker-compose.yml ] || stop \
        "В текущем каталоге нет docker-compose.yml. Запускайте из каталога установки; в клоне репозитория это deploy/."
    [ -f .env ] || stop \
        "В текущем каталоге нет .env. Запускайте из каталога установки; в клоне репозитория это deploy/."

    CURRENT="$(env_get APP_VERSION)"
    [ -n "$CURRENT" ] || stop \
        "В .env не задан APP_VERSION — непонятно, с какой версии обновляемся. Впишите текущую версию и повторите."
    WEB_PORT="$(env_get WEB_PORT)"; WEB_PORT="${WEB_PORT:-8080}"
    PGUSER="$(env_get POSTGRES_USER)"; PGUSER="${PGUSER:-postgres}"
    PGDB="$(env_get POSTGRES_DB)"; PGDB="${PGDB:-bhs_crg}"
}

# Видит ли compose эту установку. Спрашиваем ПЕРЕД обновлением, потому что отсутствие ответа даёт
# самый сбивающий с толку симптом: правка `name:` (или запуск не из того каталога) уводит все
# команды в ДРУГОЙ проект — система остаётся работать, но перестаёт быть видна, и дальше скрипт
# спотыкался бы об «service postgres is not running» на снятии дампа, ничего не объясняя (поймано
# на стенде). Для ОТКАТА этой проверки нет намеренно: после неудачного обновления контейнеры
# нередко уже остановлены — а откату они и не нужны, он возвращает файлы и поднимает заново.
check_project_visible() {
    [ -z "$(compose ps --format '{{.Name}}' 2>/dev/null | head -1)" ] || return 0
    stop "$(cat <<EOF
docker compose не видит ни одного контейнера этой установки.

Так бывает в двух случаях: запуск не из того каталога — или в docker-compose.yml менялось имя
проекта (\`name:\` в первой строке), а контейнеры подняты под прежним. Система при этом работает,
просто командам не видна. Проверьте: docker compose ps  и  docker ps
EOF
)"
}

# Мажор PostgreSQL из compose-файла: «postgres:18.6-alpine» → «18». Пусто — образа не нашлось.
# Вид хранилища, объявленного в compose-файле: minio | garage | пусто. По ОБРАЗУ, а не по имени
# сервиса: имя можно переименовать не тронув сути, а образ и есть суть.
storage_kind_of() {
    [ -f "$1" ] || return 0
    if grep -qE '^[[:space:]]*image:[[:space:]]*[^[:space:]]*minio:' "$1"; then
        printf 'minio'
    elif grep -qE '^[[:space:]]*image:[[:space:]]*dxflrs/garage:' "$1"; then
        printf 'garage'
    fi
}

# Переход хранилища в этом обновлении: MinIO остаётся позади, Garage приходит на его место.
crosses_storage() {
    [ "$(storage_kind_of docker-compose.yml)" = "minio" ] || return 1
    [ "$(storage_kind_of "$NEW_DIR/docker-compose.yml")" = "garage" ] || return 1
}

pg_major_of() {
    sed -n 's|^ *image: *postgres:\([0-9][0-9]*\).*|\1|p' "$1" 2>/dev/null | head -1
}

# Сравнение версий: возвращает 0, если $1 строго больше $2.
version_gt() {
    [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ]
}

# Пересекает ли ЭТО обновление рубеж $1: CURRENT < $1 <= TARGET.
#
# Одной нижней границы мало, хотя выглядит она достаточной. Она отвечает на вопрос «вы были ДО
# рубежа», а спросить надо «вы через него ПРОХОДИТЕ»: с одной границей переход 0.90.0 → 0.92.0
# получал оговорки про 0.137 и 0.139 — про версии, до которых ещё идти. Оговорка не по адресу
# опаснее молчания: она приучает пропускать оговорки, включая ту единственную, которая касалась
# именно вас (issue #859).
crosses() { version_gt "$1" "$CURRENT" && ! version_gt "$1" "$TARGET"; }

# Список применённых миграций — из САМОЙ базы. Пусто на выходе означает «спросить не удалось», и
# отличить это от «миграций нет» нельзя: таблица есть на любой рабочей базе этой системы.
migrations_snapshot() {
    compose exec -T postgres psql -U "$PGUSER" -d "$PGDB" -t -A \
        -c 'select "MigrationId" from "__EFMigrationsHistory" order by 1;' 2>/dev/null | grep -v '^$' || true
}

# ── Откат ───────────────────────────────────────────────────────────────────────
# Ровно то, что §8 разрешает делать руками, и ровно с той же оговоркой: откат возможен, ПОКА
# миграции не применились. Старый образ с новой схемой работать не обязан, и «вроде обошлось»
# здесь стоит целой базы — поэтому проверка сравнивает СНИМОК СПИСКА МИГРАЦИЙ, снятый перед
# обновлением, с тем, что в базе сейчас.
#
# Не по журналу api: он показывает последние строки ТЕКУЩЕГО контейнера. Откат через день, когда
# строки «Applying migration» вытеснены, или после пересоздания контейнера — и проверка по журналу
# радостно отвечала бы «миграций не было», подставляя старый образ под новую схему. Не знаем —
# отказываем: неизвестность здесь равна опасности (поймано ревью).
do_rollback() {
    preflight_common
    head2 "Откат с версии $CURRENT"

    local dump snap now
    dump="$(ls -1t backups/pre-update-*.dump 2>/dev/null | head -1 || true)"
    snap="$(ls -1t migrations.prev-* 2>/dev/null | head -1 || true)"
    now="$(migrations_snapshot)"

    if [ -z "$now" ]; then
        stop "$(cat <<EOF
Не удалось спросить базу, какие миграции применены (контейнер postgres не отвечает?).

Без этого ответа откат делать нельзя: если миграции успели примениться, прежняя версия не обязана
понимать новую схему. Поднимите базу (docker compose up -d postgres) и повторите.
EOF
)"
    fi
    if [ -z "$snap" ]; then
        stop "$(cat <<EOF
Нет снимка списка миграций (файла migrations.prev-*), снятого перед обновлением, — сравнить не с
чем, а откат вслепую здесь равен потере базы.

Так бывает, если обновление делалось не этим скриптом. Сверьте сами: миграции, которых не было в
прошлой версии, видны в таблице «__EFMigrationsHistory». Если они появились — только
восстановление дампа с пересозданием базы (§9 DEPLOYMENT.md).${dump:+
Свежий дамп этого обновления: $dump}
EOF
)"
    fi

    # `%s\n`, а не `%s`: снимок в файле заканчивается переводом строки, и без него diff считал
    # списки разными ВСЕГДА — откат отказывал даже там, где миграций не появилось. Ошибка в
    # безопасную сторону, но она делала --rollback бесполезным (поймано на стенде).
    if ! printf '%s\n' "$now" | diff -q - "$snap" >/dev/null 2>&1; then
        stop "$(cat <<EOF
Миграции уже применены — список в базе отличается от снятого перед обновлением:

$(printf '%s\n' "$now" | diff "$snap" - | grep '^>' | sed 's/^> /  + /')

Возврат образа тут не поможет: прежняя версия не обязана понимать новую схему. Откат делается
только восстановлением дампа, причём базу перед этим ПЕРЕСОЗДАЮТ (§9 DEPLOYMENT.md) — дамп,
залитый поверх мигрировавшей схемы, оставит смесь новой схемы со старыми данными.${dump:+

Свежий дамп этого обновления: $dump}
EOF
)"
    fi
    say "Миграции не применялись — откат возможен."

    local prev_compose prev_env
    prev_compose="$(ls -1t docker-compose.yml.prev-* 2>/dev/null | head -1 || true)"
    prev_env="$(ls -1t .env.prev-* 2>/dev/null | head -1 || true)"
    [ -n "$prev_compose" ] && [ -n "$prev_env" ] || stop \
        "Нет сохранённых docker-compose.yml.prev-* и .env.prev-* — откатывать не на что. Прежнюю версию впишите в .env вручную."

    local prev_version
    prev_version="$(env_get APP_VERSION "$prev_env")"
    say "Возвращаем: $prev_compose и $prev_env (версия $prev_version)."

    # Мажор PostgreSQL в возвращаемом файле сверяем с нынешним. Откат ЧЕРЕЗ смену мажора невозможен
    # по устройству СУБД: кластер 18 сервер 16 не прочтёт. Проверено — контейнер падает с
    # `initdb: directory "/var/lib/postgresql/data" exists but is not empty`, то есть сообщением,
    # которое показывает на initdb, а не на причину. Здесь причина называется до того, как система
    # ляжет, и предлагается единственный работающий путь: восстановление дампа.
    local pg_prev pg_now
    pg_prev="$(pg_major_of "$prev_compose")"
    pg_now="$(pg_major_of docker-compose.yml)"
    if [ -n "$pg_prev" ] && [ -n "$pg_now" ] && [ "$pg_prev" != "$pg_now" ]; then
        stop "$(cat <<EOF
Откат отсюда сменил бы мажорную версию PostgreSQL: сейчас $pg_now, в возвращаемом файле $pg_prev.
Так не бывает — сервер $pg_prev не читает кластер $pg_now, и база просто не поднимется.

Вернуться на $prev_version можно только через дамп: положите обратно $prev_compose и $prev_env,
удалите том с кластером $pg_now (docker volume rm <проект>_postgres_data) и восстановите в чистую
базу дамп, снятый ДО перехода, — §8.6 и §9 DEPLOYMENT.md.
EOF
)"
    fi

    # ── Откат через смену хранилища: файлы возвращаются ВМЕСТЕ с версией ─────────
    # Возврат одного compose здесь недостаточен, и это не мелочь: после перехода приложение писало
    # в Garage, а прежний том MinIO остался таким, каким был на момент миграции. Простой возврат
    # файлов поднял бы систему на прежней версии со СТАРЫМ хранилищем — и всё, что появилось после
    # обновления, исчезло бы из виду. Не потерялось бы (том Garage цел), но выглядело бы как
    # потеря, а разбираться пришлось бы на работающей системе.
    #
    # Поэтому: сначала переносим обратно, потом откатываем. Не смогли перенести — отказываем, а не
    # откатываемся молча: тихий откат здесь и есть та самая пропажа.
    if [ "$(storage_kind_of docker-compose.yml)" = "garage" ] && [ "$(storage_kind_of "$prev_compose")" = "minio" ]; then
        head2 "Возвращаем файлы в прежнее хранилище"
        local mc_image net src_bucket dst_bucket
        mc_image="$(grep -oE 'image:[[:space:]]*[^[:space:]]*mc:[^[:space:]]+' "$prev_compose" | sed -E 's/^image:[[:space:]]*//' | head -1 || true)"
        [ -n "$mc_image" ] || stop \
            "В $prev_compose нет образа mc — перенести файлы обратно нечем. Откат остановлен: система работает на $CURRENT."

        # Прежнее хранилище должно быть поднято — сейчас его в рабочем compose нет.
        compose -f "$prev_compose" --env-file "$prev_env" up -d minio >/dev/null 2>&1 || stop \
            "Не удалось поднять прежнее хранилище (minio) — откат остановлен, система работает на $CURRENT."

        # При откате рабочий compose — уже с Garage, поэтому обычного `ps` достаточно.
        net="$(network_of "$(compose ps -q garage 2>/dev/null | head -1)")" || net=""
        [ -n "$net" ] || stop "$(cat <<EOF
Хранилище Garage не запущено — файлы, записанные после обновления, брать неоткуда, а откат без них
и есть та пропажа, ради которой этот шаг существует.

Поднимите систему (docker compose up -d), дождитесь готовности и повторите откат.
EOF
)"
        src_bucket="$(env_get MINIO_BUCKET "$prev_env")"
        dst_bucket="$(env_get GARAGE_BUCKET)"
        if ! mirror_blobs "$net" "$mc_image" \
                "$(env_get MINIO_ROOT_USER "$prev_env")" "$(env_get MINIO_ROOT_PASSWORD "$prev_env")" "$src_bucket" \
                "$(env_get GARAGE_KEY_ID)" "$(env_get GARAGE_SECRET)" "$dst_bucket" back; then
            stop "$(cat <<EOF
Не удалось вернуть файлы в прежнее хранилище — сверка не сошлась. Откат ОСТАНОВЛЕН: система как
работала на $CURRENT, так и работает, оба хранилища целы.

Разберитесь с причиной и повторите; вручную это делается тем же зеркалированием, §8.7 DEPLOYMENT.md.
EOF
)"
        fi
        say "Файлы возвращены и сверены."
    fi

    cp "$prev_compose" docker-compose.yml
    cp "$prev_env" .env
    # Эталон убираем: он остался от версии, с которой мы только что ушли, и следующее обновление
    # сравнивало бы вернувшийся файл с чужим — показав «у вас правки» там, где их нет. Без эталона
    # скрипт просто скачает compose текущей версии заново (проверено откатом на стенде).
    rm -f "$RELEASE_REF"
    compose up -d
    wait_for_version "$prev_version" || stop \
        "Прежняя версия не ответила за отведённое время. Журнал: docker compose logs --tail=50 api"
    say ""
    say "Откат завершён: система работает на $prev_version."
}

# ── Ожидание результата ─────────────────────────────────────────────────────────
# Ждём не «контейнер запустился», а «система отвечает ТОЙ версией»: запущенный контейнер ничего не
# обещает — api поднимается до пяти с лишним минут (20 с + 30×10 с healthcheck), и всё это время
# web отдаёт 502. Поэтому единственный честный признак успеха — номер версии в ответе.
wait_for_version() {
    local want="$1" deadline=$((SECONDS + 420)) got=""
    say "Ждём ответа системы на http://localhost:$WEB_PORT/api/version (до 7 минут)…"
    while [ $SECONDS -lt $deadline ]; do
        got="$(curl_local -fsS --max-time 5 "http://localhost:$WEB_PORT/api/version" 2>/dev/null \
               | grep -oE '"version"[[:space:]]*:[[:space:]]*"[^"]+"' | grep -oE '[0-9][^"]*' || true)"
        [ "$got" = "$want" ] && { say "Ответила версия $got."; return 0; }
        sleep 5
    done
    [ -n "$got" ] && warn "Система отвечает версией $got, а ожидалась $want."
    return 1
}

