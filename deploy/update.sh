# ── Остановка 3: мажорная версия PostgreSQL ─────────────────────────────────────
# Единственный рубеж, который скрипт не переводит сам, а ОТКАЗЫВАЕТСЯ переходить (issue #880).
#
# С 0.158.0 поставка едет на PostgreSQL 18. Мажор — не смена тега: кластер 16 новый сервер не
# читает, а официальный образ 18-й версии вдобавок сменил раскладку (данные в подкаталоге с
# номером мажора, том — `/var/lib/postgresql`, а не `/var/lib/postgresql/data`).
#
# Отказ громкий — но только потому, что ИМЯ ТОМА в поставке оставлено прежним. Проверено на живых
# контейнерах: прежний том (кластер 16), смонтированный по новому пути, образ 18 не принимает и
# выходит с кодом 1; а вот НОВЫЙ том по новому пути он поднимает ПУСТЫМ, и система встаёт чистой.
# Первая редакция этой правки том переименовывала — то есть ровно это и получала бы. Здесь и в
# compose стоит одна и та же конструкция, и разъезжаться им нельзя.
#
# Значит цена слепого обновления — не потерянные данные, а система, которая не поднялась. Плохая
# новость: узнать об этом посреди обновления, на боевом сервере, дороже всего.
#
# Почему отказ, а не автоматика. Перенос — это дамп, пересоздание тома и восстановление; каждый
# шаг обратим по отдельности, а вместе они складываются в операцию, где ошибка стоит базы. Скрипт,
# который делает это молча за администратора, отнимает у него единственный момент, когда он ещё
# может остановиться. Поэтому здесь — стоп и адрес процедуры, а не «сейчас всё сделаем».
check_postgres_major() {
    crosses "0.158.0" || return 0
    stop "$(cat <<EOF
Выпуск 0.158.0 переводит систему на PostgreSQL 18, а у вас работает 16. Одним обновлением это не
делается: данные придётся перенести, и скрипт намеренно не берётся за это сам.

Что произойдёт, если всё-таки продолжить (проверено, не предположение): контейнер базы НЕ
ЗАПУСТИТСЯ — образ 18 увидит кластер 16 и откажется, объяснив причину. Данные при этом целы, но
система будет лежать, пока вы не вернёте прежние docker-compose.yml и .env.

Процедура — §8.6 DEPLOYMENT.md «Переход на PostgreSQL 18». Коротко: снять дамп работающей базой и
УБЕДИТЬСЯ, что он не пуст; остановить систему; удалить том прежнего кластера; поднять базу 18 и
восстановить в неё дамп; и только потом поднимать остальное. Занимает минуты, но требует, чтобы вы
были у консоли: страховка здесь — дамп, а не том, и проверить его — ваш шаг, не мой.
EOF
)"
}

# ── Остановка 4: место под перенос файлов в новое хранилище ─────────────────────
# С 0.160.0 поставка едет на Garage (issue #885). В отличие от рубежа PostgreSQL выше, этот скрипт
# переходит САМ: данные не остаются на месте в другом формате, а копируются из одного хранилища в
# другое — операция обратимая, пока прежний том цел, и потому её незачем перекладывать на человека.
#
# Но у неё есть цена, и её называют ДО начала, а не обнаруживают по ходу:
#   — нужно место: какое-то время файлы лежат в ОБОИХ хранилищах;
#   — нужен простой: приложение останавливается на время копирования, иначе файл, записанный после
#     того как зеркало прошло его каталог, потеряется молча (см. migrate_blobs).
# Свободное место спрашиваем ИЗНУТРИ контейнера, на смонтированном томе, а не `df` по
# DockerRootDir. Причина не в удобстве: этого каталога на хосте может не быть вовсе — Docker
# Desktop держит его в своей виртуальной машине, удалённый демон вообще на другой машине. Проверено:
# `df /var/lib/docker` там отвечает «No such file or directory», и проверка места молча
# превращалась бы в «не смогли измерить» на всех таких хостах. Том же виден оттуда, откуда и
# пишется, — из контейнера.
# ⚠️ Ни awk, ни sed, ни grep внутри этого контейнера НЕ ЗОВЁМ: в образе mc их нет. Проверено —
# есть df, du, cut, tr, head, tail, expr, и всё. Первая редакция считала место через awk и молча
# получала пустую строку: проверка места превращалась в «не смогли измерить» ВСЕГДА, то есть
# существовала на словах.
storage_free_kb() {
    local vol="$1" image="$2"
    docker run --rm -v "$vol:/data:ro" --entrypoint /bin/sh "$image" \
        -c "df -Pk /data | tail -1 | tr -s ' ' | cut -d' ' -f4" 2>/dev/null || true
}

# Размер прежнего хранилища в килобайтах. Считаем по ТОМУ, а не спрашиваем MinIO: том виден и
# когда контейнер уже остановлен, а образ для счёта берём тот, что и так есть на хосте.
storage_used_kb() {
    local vol="$1" image="$2"
    docker run --rm -v "$vol:/data:ro" --entrypoint /bin/sh "$image" \
        -c 'du -sk /data 2>/dev/null | cut -f1' 2>/dev/null || true
}

check_storage_migration() {
    crosses_storage || return 0

    local mc_image project vol used_kb free_kb used_mb free_mb
    mc_image="$(grep -oE 'image:[[:space:]]*[^[:space:]]*mc:[^[:space:]]+' docker-compose.yml | sed -E 's/^image:[[:space:]]*//' | head -1 || true)"
    [ -n "$mc_image" ] || stop "$(cat <<EOF
В docker-compose.yml не нашёлся образ клиента mc — а именно им переносятся файлы в новое
хранилище. Похоже, файл правили: верните сервис createbuckets или перенесите файлы вручную по
§8.7 DEPLOYMENT.md, и только потом обновляйтесь.
EOF
)"

    # Том спрашиваем у САМОГО КОНТЕЙНЕРА, а не собираем из имени проекта. Имя можно переопределить
    # (`COMPOSE_PROJECT_NAME` в .env), и собранное «на глазок» `<name>_minio_data` тогда указывает в
    # никуда: `docker run -v` создал бы НОВЫЙ пустой том, `du` вернул бы ноль, и проверка места
    # прошла бы, отчитавшись «файлов 0 МБ» — та же ошибка, от которой уже страхует network_of.
    vol="$(docker inspect -f '{{range .Mounts}}{{if eq .Destination "/data"}}{{.Name}}{{end}}{{end}}' \
        "$(compose ps -q minio 2>/dev/null | head -1)" 2>/dev/null || true)"
    if [ -z "$vol" ]; then
        warn "Контейнер прежнего хранилища не найден — объём файлов и запас места не измерить. Перенос возможен, но оцените запас сами."
        say "Во время переноса приложение будет остановлено — иначе файл, записанный по ходу копирования, потерялся бы молча."
        return 0
    fi

    used_kb="$(storage_used_kb "$vol" "$mc_image")"
    free_kb="$(storage_free_kb "$vol" "$mc_image")"

    # Не смогли измерить — не выдумываем: говорим об этом и идём дальше. Отказ здесь стоил бы
    # обновления там, где места на самом деле вдоволь, а «неизвестно» честнее нуля.
    if [ -z "$used_kb" ] || [ -z "$free_kb" ]; then
        warn "Не удалось измерить объём файлов или свободное место — перенос всё равно возможен, но оцените запас сами."
        return 0
    fi

    used_mb=$((used_kb / 1024))
    free_mb=$((free_kb / 1024))
    say "Файлов в прежнем хранилище: ${used_mb} МБ; свободно на диске Docker: ${free_mb} МБ."

    # Верхняя граница: Garage сжимает блоки zstd (на нашей библиотеке вышло ~70% исходного), но
    # рассчитывать на сжатие чужих данных нельзя — они могут быть уже сжаты.
    if [ "$free_kb" -lt "$used_kb" ]; then
        stop "$(cat <<EOF
Для переноса не хватит места: файлы занимают ${used_mb} МБ, а на диске Docker свободно ${free_mb} МБ.

Во время перехода файлы лежат в ОБОИХ хранилищах — прежнее не удаляется, оно остаётся страховкой
и точкой отката. Освободите место (./update.sh --gc уберёт старые образы системы) и повторите.
Ничего не менялось: система работает на $CURRENT.
EOF
)"
    fi

    say "Во время переноса приложение будет остановлено — иначе файл, записанный по ходу копирования, потерялся бы молча."
}

# ── Фоновые задачи ──────────────────────────────────────────────────────────────
# Спрашиваем базу, а не интерфейс: пилюля задач показывает только СВОИ задачи, а помешает как раз
# чужая — чужая сборка комплекта или распознавание оборвутся и сами не возобновятся.
#
# `group by "Status"`, а не `group by 1`: единица указывает на первое выражение SELECT, а там стоит
# конкатенация со счётчиком, и PostgreSQL отвечает «aggregate functions are not allowed in GROUP
# BY». Именно этот запрос и падал молча, пока ошибку глушило `2>/dev/null`: проверка отвечала
# «задач нет» ВСЕГДА. Нашлось в ту же минуту, как ошибки перестали проглатываться.
check_jobs() {
    local out rc=0
    out="$(compose exec -T postgres psql -U "$PGUSER" -d "$PGDB" -t -A \
            -c "select \"Status\" || ': ' || count(*) from jobs where \"Status\" in ('Queued','Running') group by \"Status\";" \
            2>&1)" || rc=$?

    # Не сумели спросить — не делаем вид, что спросили. Пустой ответ на неудавшемся запросе выглядит
    # ровно как «задач нет», и обновление сносило бы чужую сборку комплекта, отчитавшись, что
    # проверило (поймано ревью).
    if [ "$rc" -ne 0 ]; then
        if [ "$FORCE" -eq 1 ]; then
            warn "Спросить базу о фоновых задачах не удалось — идём дальше, потому что указан --force."
            return 0
        fi
        stop "$(printf 'Не удалось спросить базу о незавершённых фоновых задачах:\n\n%s\n\n%s' \
            "$(printf '%s' "$out" | tail -3)" \
            "Проверьте, что контейнер postgres работает и POSTGRES_USER/POSTGRES_DB в .env те же, что у него. Обойти проверку — --force.")"
    fi

    out="$(printf '%s' "$out" | grep -v '^[[:space:]]*$' || true)"
    [ -n "$out" ] || return 0

    if [ "$FORCE" -eq 1 ]; then
        warn "Незавершённые фоновые задачи ($out) — обновляемся, потому что указан --force. Новая версия пометит их неудавшимися."
        return 0
    fi
    stop "$(cat <<EOF
В системе есть незавершённые фоновые задачи:
$out

Перезапуск их оборвёт: сборка комплекта и распознавание сами не возобновятся, новая версия при
старте пометит их неудавшимися. Дождитесь завершения — или запустите с --force, если решили, что
эти задачи не жалко.
EOF
)"
}

# ── Дамп базы ───────────────────────────────────────────────────────────────────
# Дамп, а не копия приложения: схема мигрирует при старте новой версии, отката миграций нет, и
# вернуть прошлую схему можно ТОЛЬКО из дампа. Снимаем до любой остановки контейнеров — на живой
# базе, пока всё работает.
backup_db() {
    if [ "$NO_BACKUP" -eq 1 ]; then
        warn "Дамп не снимаем — указан --no-backup. Убедитесь, что копия у вас есть: без неё откат после миграций невозможен."
        return 0
    fi
    mkdir -p backups
    DUMP="backups/pre-update-$CURRENT-to-$TARGET-$STAMP.dump"
    say "Снимаем дамп базы в $DUMP …"
    # mktemp, а не фиксированный путь в /tmp: скрипт обычно выполняют от root на общей машине, и
    # предсказуемое имя в общедоступном каталоге — это чужой симлинк, которому наш `>` обрежет файл.
    local err; err="$(mktemp)"
    if ! compose exec -T postgres pg_dump -U "$PGUSER" -d "$PGDB" -Fc > "$DUMP" 2>"$err"; then
        rm -f "$DUMP"
        local reason; reason="$(tail -5 "$err" 2>/dev/null)"; rm -f "$err"
        stop "$(printf 'Не удалось снять дамп базы:\n%s\n\nОбновление не начато — система работает на %s.' \
                "$reason" "$CURRENT")"
    fi
    rm -f "$err"
    [ -s "$DUMP" ] || { rm -f "$DUMP"; stop "Дамп получился пустым. Обновление не начато."; }
    say "Дамп готов: $DUMP ($(du -h "$DUMP" | cut -f1))."
}

# ── Файлы целевой версии ────────────────────────────────────────────────────────
fetch_release_files() {
    mkdir -p "$NEW_DIR"

    # Чистый файл версии качаем ВСЕГДА, даже когда разворачивать будем ваш merged: он станет
    # эталоном для следующего обновления. Эталоном merged-файл быть не может — тогда через версию
    # сравнение сойдётся, и ваши правки заменятся молча. Ровно тот отказ, ради которого остановка и
    # заводилась (поймано ревью).
    curl -fsSL "$RELEASE_URL/v$TARGET/docker-compose.yml" -o "$PRISTINE" \
        || stop "Не удалось скачать docker-compose.yml версии $TARGET."

    if [ "$COMPOSE_MERGED" -eq 1 ]; then
        [ -f "$NEW_DIR/docker-compose.yml" ] || stop \
            "Указан --compose-merged, но $NEW_DIR/docker-compose.yml нет. Запустите без ключа — скрипт скачает файл версии."
        local merged_for; merged_for="$(cat "$NEW_DIR/.version" 2>/dev/null || true)"
        [ "$merged_for" = "$TARGET" ] || stop "$(cat <<EOF
В $NEW_DIR/ лежат файлы версии ${merged_for:-неизвестной}, а обновляемся на $TARGET — развернуть их
значит потерять всё, что версии между ними добавили в compose (сервисы, тома, лимиты), причём молча.

Запустите без --compose-merged: скрипт скачает файлы $TARGET, покажет ваши правки, и перенесёте вы
их уже в свежий файл.
EOF
)"
        say "Берём $NEW_DIR/docker-compose.yml как есть: вы перенесли в него свои правки."
    else
        cp "$PRISTINE" "$NEW_DIR/docker-compose.yml"
        printf '%s\n' "$TARGET" > "$NEW_DIR/.version"
    fi

    curl -fsSL "$RELEASE_URL/v$TARGET/env.example" -o "$NEW_DIR/env.example" \
        || stop "Не удалось скачать env.example версии $TARGET."

    # Конфигурация хранилища — с 0.160.0 (issue #885). Compose монтирует её РЯДОМ С СОБОЙ
    # (`./garage.toml`), поэтому файл обязан лежать и в new/ (пока хранилище поднимают оттуда, при
    # переносе), и в рабочем каталоге. Нет файла — Docker создаёт на его месте КАТАЛОГ, и Garage
    # падает с «IO error: Is a directory»: сообщение, по которому причину не найти (поймано живым
    # прогоном обновления).
    #
    # Выпуски до 0.160.0 такого ассета не прикладывали — их отсутствие здесь не ошибка. Отличаем
    # «версия его не знает» от «не скачалось» по тому, нужен ли он ЦЕЛЕВОМУ compose.
    if grep -qE '^[[:space:]]*-[[:space:]]*\./garage\.toml:' "$NEW_DIR/docker-compose.yml"; then
        curl -fsSL "$RELEASE_URL/v$TARGET/garage.toml" -o "$NEW_DIR/garage.toml" \
            || stop "$(cat <<EOF
Не удалось скачать garage.toml версии $TARGET, а compose этой версии его требует: хранилище
монтирует конфигурацию рядом с собой. Без файла Docker создаст на его месте каталог, и хранилище
не поднимется. Ничего не менялось — система работает на $CURRENT.
EOF
)"
    fi
}

# ── Остановка 1: ваши правки в docker-compose.yml ───────────────────────────────
# Самый тихий отказ из §8, ставший громким. Заменив файл целиком, вы не получите НИКАКОЙ ошибки:
# при изменённом `name:` работающая система просто перестанет быть видна командам, а `up -d`
# поднимет рядом вторую, пустую установку (проверено на стенде). Поэтому сравниваем текущий файл с
# нетронутым файлом его версии — и при расхождении отдаём решение человеку.
check_compose_drift() {
    [ "$COMPOSE_MERGED" -eq 0 ] || return 0

    if [ ! -f "$RELEASE_REF" ]; then
        say "Эталона $RELEASE_REF нет (первый запуск скрипта) — скачиваем compose текущей версии $CURRENT для сравнения…"
        curl -fsSL "$RELEASE_URL/v$CURRENT/docker-compose.yml" -o "$RELEASE_REF" 2>/dev/null || {
            rm -f "$RELEASE_REF"
            stop "$(cat <<EOF
Не удалось скачать compose версии $CURRENT — сравнить ваш файл не с чем, а заменять его вслепую
нельзя: ваши правки (имя проекта, порты, лимиты, свои тома) исчезли бы без единой ошибки.

Сверьте сами и продолжите, когда решите:
  diff docker-compose.yml $NEW_DIR/docker-compose.yml
  # перенесите свои правки в $NEW_DIR/docker-compose.yml
  ./update.sh $TARGET --compose-merged
EOF
)"
        }
    fi

    if diff -q "$RELEASE_REF" docker-compose.yml >/dev/null 2>&1; then
        say "Ваш docker-compose.yml совпадает с файлом версии $CURRENT — замена безопасна."
        return 0
    fi

    # Полный diff кладём в файл, а на экран берём начало. Переносить правки человек будет по
    # нему: экранного обрезка на реально правленом compose не хватает (на 60 строк укладывается
    # версии две правок), а прокрутка терминала — не то место, где хранят единственный экземпляр
    # своих изменений (issue #859).
    local patch="compose-diff-$STAMP.patch"
    diff -u "$RELEASE_REF" docker-compose.yml > "$patch" || true

    stop "$(cat <<EOF
Ваш docker-compose.yml отличается от файла версии $CURRENT — в нём есть правки, и замена унесла бы
их молча. Слева — файл версии, справа — ваш:

$(sed 's/^/  /' "$patch" | head -60)

Полный список различий: $patch (выше — только его начало).

Перенесите свои правки в $NEW_DIR/docker-compose.yml (там уже лежит файл версии $TARGET) и
запустите снова:

  ./update.sh $TARGET --compose-merged
EOF
)"
}

# ── Остановка 2: переменные, которых у вас ещё нет ──────────────────────────────
# Новая версия добавляет переменные, и обновившись «только образами», вы получили бы новую
# настройку в её умолчании, не зная об этом.
#
# Раньше здесь стояла остановка на ЛЮБОЙ новой переменной, а обойти её позволял --accept-defaults.
# Себя она не оправдала: почти всегда вписать требовалось ровно то, что и так подставится, — и
# человек приучался обходить остановку не читая, включая тот единственный раз, когда она была по
# делу. Теперь ключ дописывается сам, но лишь при совпадении двух условий: у него ЕСТЬ умолчание в
# compose-файле И env.example предлагает РОВНО ЕГО. Тогда запись не меняет в поведении системы
# ничего — она делает видимым то, что и так действовало, а .env после обновления совпадает с .env
# свежей установки.
#
# Остановка осталась там, где она означает решение: ключ без умолчания (без него система не
# поднимется) и ключ, у которого образец расходится с умолчанием, — расхождение значит, что версия
# советует не то, что подставится, и выбирать здесь не скрипту (issue #859).

# Умолчание ключа в compose-файле: печатает значение и возвращает 0, если умолчание есть.
compose_default() {
    local raw
    raw="$(grep -oE "\\\$\{$1(:-|-)[^}]*\}" "$NEW_DIR/docker-compose.yml" | head -1 || true)"
    [ -n "$raw" ] || return 1
    raw="${raw#*-}"          # снимаем «${KEY:-» либо «${KEY-»: имя ключа дефиса не содержит
    raw="${raw%\}}"
    # Умолчание, внутри которого прячется другая переменная — ${ALLOWED_ORIGINS:-http://localhost:${WEB_PORT:-8080}} —
    # наш разбор обрезает на первой «}», и получается полстроки. Такой ключ считаем ключом БЕЗ
    # надёжного умолчания: спросить человека дешевле, чем вписать в .env мусор, да ещё и показать
    # его в сообщении как «то, что подставится» (поймано ревью PR #860).
    case "$raw" in *'$'*) return 1 ;; esac
    printf '%s' "$raw"
}

# Начало блока комментария над ключом в env.example — то, чем версия объясняет переменную. Именно
# НАЧАЛО, а не последние строки: у ближайших к ключу строк обрублено начало фразы, и подсказка
# читается как обрывок разговора.
key_comment() {
    awk -v key="$1" '
        /^[[:space:]]*#/ { block = block $0 "\n"; next }
        $0 ~ "^[[:space:]]*" key "[[:space:]]*=" { printf "%s", block; exit }
        { block = "" }' "$NEW_DIR/env.example" | head -4 || true
}

check_new_vars() {
    local new_keys missing=() k example def
    # `|| true` — по той же причине, что в do_gc: env.example без единой строки «КЛЮЧ=» (обрезанная
    # закачка, файл-заглушка) обрывал бы обновление здесь и молча.
    new_keys="$(env_keys "$NEW_DIR/env.example" || true)"
    for k in $new_keys; do
        grep -qE "^[[:space:]]*$k[[:space:]]*=" .env || missing+=("$k")
    done
    [ "${#missing[@]}" -gt 0 ] || return 0

    local ask=()
    for k in "${missing[@]}"; do
        # Ключи доступа к хранилищу человек не придумывает: скрипт генерирует их сам (см.
        # generate_secrets). Спрашивать их значило бы остановить обновление ради значения, у
        # которого нет осмысленного выбора, — и подтолкнуть вписать что попало, а формат у Garage
        # жёсткий: неверная длина секрета роняет хранилище на старте.
        case " ${GENERATED_KEYS[*]} " in *" $k "*) GENERATE+=("$k"); continue ;; esac
        example="$(env_get "$k" "$NEW_DIR/env.example")"
        if def="$(compose_default "$k")" && [ "$def" = "$example" ]; then
            AUTOFILL+=("$k")
        else
            ask+=("$k")
        fi
    done

    if [ "${#GENERATE[@]}" -gt 0 ]; then
        say "Значения хранилища ${GENERATE[*]} скрипт впишет сам: ключи случайные, имя бакета прежнее."
    fi

    if [ "${#AUTOFILL[@]}" -gt 0 ]; then
        say "Новые переменные ${AUTOFILL[*]} впишем в .env сами: образец предлагает ровно то, что подставилось бы и без них."
    fi
    [ "${#ask[@]}" -gt 0 ] || return 0

    local listing="" comment
    for k in "${ask[@]}"; do
        listing+="  $k"
        if def="$(compose_default "$k")"; then
            listing+="   ← образец предлагает «$(env_get "$k" "$NEW_DIR/env.example")», без строки подставится «$def»"
        else
            listing+="   ← без умолчания: без значения система не поднимется"
        fi
        listing+=$'\n'
        comment="$(key_comment "$k")"
        if [ -n "$comment" ]; then
            listing+="$(printf '%s\n' "$comment" | sed 's/^/      /')"$'\n'
        fi
    done

    stop "$(printf 'Версия %s добавила переменные, значение которых выбираете вы:\n\n%s\n%s' "$TARGET" "$listing" \
        "Впишите их в .env (образец с пояснениями — $NEW_DIR/env.example) и запустите снова.")"
}

# Дописываем новые переменные во ВРЕМЕННЫЙ .env — тот, что станет рабочим только после успешной
# загрузки образов. В рабочий файл раньше нельзя: оборвавшаяся загрузка оставила бы .env наполовину
# от новой версии, и понять это по файлам было бы уже нельзя. Та же причина, по которой за pull
# переехал APP_VERSION.
apply_autofill() {
    local env_new="$1" k comment
    [ "${#AUTOFILL[@]}" -gt 0 ] || return 0
    {
        printf '\n# Добавлено обновлением %s → %s. Значения взяты из env.example этой версии; они\n' "$CURRENT" "$TARGET"
        printf '# совпадают с умолчаниями compose-файла — то есть действовали и до этих строк.\n'
        for k in "${AUTOFILL[@]}"; do
            comment="$(key_comment "$k")"
            if [ -n "$comment" ]; then
                printf '%s\n' "$comment"
            fi
            printf '%s=%s\n' "$k" "$(env_get "$k" "$NEW_DIR/env.example")"
        done
    } >> "$env_new"
    say "Дописаны в .env: ${AUTOFILL[*]}"
}

# ── Ключи хранилища: генерируем, а не спрашиваем ────────────────────────────────
# Пишем во ВРЕМЕННЫЙ .env — по той же причине, что и autofill: рабочий файл трогаем только после
# успешной загрузки образов.
#
# Формат у Garage жёсткий и проверяется им на старте: идентификатор ключа — «GK» и 24
# шестнадцатеричных знака, секреты — ровно 64. Значение другой длины роняет хранилище с
# «Invalid RPC secret key: expected 32 bytes of random hex» — то есть система не поднимется.
# Проверено на живом контейнере, поэтому длины здесь литеральные, а не «примерно столько».
rand_hex() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

generate_secrets() {
    local env_new="$1" k value
    [ "${#GENERATE[@]}" -gt 0 ] || return 0
    {
        printf '\n# Ключи хранилища, созданные обновлением %s → %s. Случайные и свои для этой\n' "$CURRENT" "$TARGET"
        printf '# установки; знание их даёт доступ ко ВСЕМ файлам системы.\n'
        for k in "${GENERATE[@]}"; do
            case "$k" in
                GARAGE_KEY_ID)      value="GK$(rand_hex 12)" ;;
                GARAGE_SECRET)      value="$(rand_hex 32)" ;;
                GARAGE_RPC_SECRET)  value="$(rand_hex 32)" ;;
                GARAGE_ADMIN_TOKEN) value="$(rand_hex 24)" ;;
                # Имя бакета НАСЛЕДУЕМ, а не берём из образца: данные переносятся в бакет с тем же
                # именем. Установка, где MINIO_BUCKET был не «bhs-crg», иначе получила бы пустое
                # хранилище рядом с полным — и выглядело бы это как успешное обновление.
                GARAGE_BUCKET)      value="$(env_get MINIO_BUCKET)"
                                    [ -n "$value" ] || value="$(env_get GARAGE_BUCKET "$NEW_DIR/env.example")" ;;
                *)                  value="$(rand_hex 32)" ;;
            esac
            printf '%s=%s\n' "$k" "$value"
        done
    } >> "$env_new"
    say "Значения хранилища вписаны в .env: ${GENERATE[*]} — ключи случайные, имя бакета прежнее"

}

# ── Самообновление скрипта ──────────────────────────────────────────────────────
# Не молча: скрипт версии N обновляет НА N+k, и если целевой релиз принёс другой update.sh —
# сегодняшний может не знать о шаге, который в той версии обязателен.
check_self_update() {
    local tmp; tmp="$(mktemp)"
    if curl -fsSL "$RELEASE_URL/v$TARGET/update.sh" -o "$tmp" 2>/dev/null && [ -s "$tmp" ]; then
        if ! diff -q "$tmp" "$SELF" >/dev/null 2>&1; then
            rm -f "$tmp"
            stop "$(cat <<EOF
В релизе $TARGET другой update.sh — обновите сам скрипт и повторите запуск:

  curl -fsSL $RELEASE_URL/v$TARGET/update.sh -o "$SELF" && chmod +x "$SELF"
  ./update.sh $TARGET
EOF
)"
        fi
    fi
    rm -f "$tmp"
}

# ── --check: есть ли выпуск новее ───────────────────────────────────────────────
# Ничего не меняет и не требует Docker: это команда для cron и мониторинга консольных установок, а
# не для обновления. Ответ несут КОДЫ ВЫХОДА (0 — есть, 3 — нет, 1 — спросить не удалось), потому
# что читать её будет скрипт: «не удалось спросить» и «обновлений нет» для него обязаны различаться,
# иначе оборвавшаяся сеть неделями выглядит как «вы на последней версии».
latest_release() {
    curl -fsSL -o /dev/null -w '%{url_effective}' --max-time 20 \
        "https://github.com/$REPO/releases/latest" 2>/dev/null | sed -nE 's#.*/tag/v?([^/]+)$#\1#p'
}

do_check() {
    [ -f .env ] || stop \
        "В текущем каталоге нет .env. Запускайте из каталога установки; в клоне репозитория это deploy/."
    CURRENT="$(env_get APP_VERSION)"
    [ -n "$CURRENT" ] || stop "В .env не задан APP_VERSION — не с чем сравнивать."

    # `|| true` здесь обязателен. Без него неудача curl (нет сети, DNS молчит) под errexit
    # обрывала бы скрипт ПРЯМО ЗДЕСЬ — с кодом curl и без единого слова, потому что его
    # собственное сообщение заглушено. Обещанный код 1 и объяснение строкой ниже не выполнялись бы
    # НИКОГДА: ровно та остановка-которая-не-срабатывает, от которой скрипт бережёт человека
    # (поймано ревью PR #860, воспроизведено: код 6, пустой вывод).
    local latest; latest="$(latest_release || true)"
    [ -n "$latest" ] || stop "Не удалось узнать последний выпуск: до github.com не достучаться."

    if version_gt "$latest" "$CURRENT"; then
        say "Есть обновление: $CURRENT → $latest."
        say "  ./update.sh $latest"
        exit 0
    fi
    # Молчим, когда никто не смотрит. cron шлёт письмо на ЛЮБОЙ вывод, и еженедельное «новее
    # ничего нет» приучило бы не читать эти письма — включая то единственное, где сказано про
    # выпуск. Человеку в терминале отвечаем словами, скрипту — кодом 3.
    if [ -t 1 ]; then say "Установлена версия $CURRENT, новее ничего нет."; fi
    exit 3
}

# ── --gc: старые образы наших версий ────────────────────────────────────────────
# Каждое обновление оставляет на хосте прежние api и web (вместе под 500 МБ), и сами они не
# исчезают. Убираем ТОЛЬКО свои образы: `docker image prune -a` снёс бы заодно postgres, minio и
# ollama — образы, за которые потом заплатишь простоем на следующем старте. Без --yes команда
# ничего не удаляет: показать, что уйдёт, дешевле, чем объяснять, почему ушло.
do_gc() {
    command -v docker >/dev/null 2>&1 || stop "Docker не найден."
    [ -f docker-compose.yml ] || stop \
        "В текущем каталоге нет docker-compose.yml. Запускайте из каталога установки; в клоне репозитория это deploy/."
    [ -f .env ] || stop \
        "В текущем каталоге нет .env — непонятно, какая версия развёрнута, а значит и какие образы нужны сейчас. Запускайте из каталога установки."

    local repos
    # Берём образы ПРИЛОЖЕНИЯ (`bhs.crg-*`), а не всё, что лежит на ghcr.io. Разница появилась с
    # issue #882: там в наш реестр переехала копия MinIO, у которой upstream архивирован. Прежний
    # отбор «любой ghcr.io» посчитал бы её нашей, а тег `RELEASE.…` никогда не равен APP_VERSION —
    # то есть хранилище стало бы кандидатом на удаление, и спасал бы его только запущенный
    # контейнер. После `docker compose down` образ хранилища ушёл бы молча, а строка ниже про
    # «чужие образы не трогаем» врала бы в лицо.
    #
    # `|| true`: grep без совпадений возвращает 1, и под errexit скрипт молча вышел бы прямо здесь
    # вместо объяснения строкой ниже (поймано ревью PR #860).
    repos="$(grep -oE 'image:[[:space:]]*ghcr\.io/[^:[:space:]]*bhs\.crg-[^:[:space:]]*' docker-compose.yml | sed -E 's/^image:[[:space:]]*//' | sort -u || true)"
    [ -n "$repos" ] || stop \
        "В docker-compose.yml нет образов BHS.CRG (ghcr.io/…/bhs.crg-*) — чистить нечего. Сторонние образы (postgres, minio, ollama) эта команда не трогает, даже нашу копию хранилища в ghcr.io."

    local current in_use
    current="$(env_get APP_VERSION)"
    # Без номера версии удалять нельзя, и это не формальность: пустая строка делает кандидатом
    # КАЖДЫЙ образ, включая развёрнутый прямо сейчас, — «${img##*:}» не равен пустой строке
    # никогда. Единственной защитой остаётся список занятых, а после `docker compose down` он пуст,
    # и `--gc --yes` унёс бы образы работающей версии, отчитавшись, что она их «не касается»
    # (поймано ревью PR #860).
    [ -n "$current" ] || stop \
        "В .env не задан APP_VERSION — непонятно, какие образы нужны сейчас. Впишите текущую версию и повторите."
    # Занятые считаем по ВСЕМ контейнерам, включая остановленные: остановленный контейнер прежней
    # версии — это готовый откат, и снести образ из-под него значит отобрать откат молча. Не сумели
    # спросить — отказываем: пустой список «занятых» от неотвечающего демона выглядит ровно как
    # «ничем не занято», а разницу оплатит человек.
    in_use="$(docker ps -a --format '{{.Image}}' | sort -u)" || stop \
        "Docker не отвечает — не спросить, какие образы заняты контейнерами. Без этого ответа удалять нельзя."

    head2 "Образы BHS.CRG, которых текущая версия не касается"
    local victims=() repo img size
    for repo in $repos; do
        while IFS='|' read -r img size; do
            [ -n "$img" ] || continue
            case "$img" in *:'<none>') continue ;; esac
            [ "${img##*:}" != "$current" ] || continue
            if printf '%s\n' "$in_use" | grep -qxF "$img"; then continue; fi
            victims+=("$img")
            say "  $img   $size"
        done < <(docker images --format '{{.Repository}}:{{.Tag}}|{{.Size}}' "$repo" 2>/dev/null)
    done

    if [ "${#victims[@]}" -eq 0 ]; then
        say "  (пусто: всё, что есть на хосте, — либо версии ${current:-текущей}, либо занято контейнерами)"
        return 0
    fi

    say ""
    if [ "$YES" -eq 0 ]; then
        say "Ничего не удалено — команда только показывает. Удалить эти ${#victims[@]}:"
        say "  ./update.sh --gc --yes"
        say ""
        say "Откату это не помешает: образ прежней версии docker compose скачает заново — были бы .env.prev-* и дамп."
        return 0
    fi
    docker image rm "${victims[@]}" \
        || warn "Часть образов удалить не удалось — обычно на них ссылается контейнер вне этой установки."
    say ""
    say "Готово."
}

# ── Перенос файлов в новое хранилище ────────────────────────────────────────────
# Единственная фаза обновления, которая ДВИГАЕТ ДАННЫЕ. Устроена так, чтобы каждый её шаг можно
# было бросить: прежнее хранилище не изменяется вовсе, том его остаётся на месте, и до самого
# конца система возвращается на прежнюю версию простым `up -d`.
#
# ПОЧЕМУ ПРИЛОЖЕНИЕ ОСТАНАВЛИВАЕТСЯ. `mc mirror` идёт по каталогу один раз. Файл, записанный
# приложением после того, как зеркало прошло его каталог, в копию не попадёт — а обновление
# отчитается об успехе, потому что сверка сойдётся: он появился уже после неё. Потеря была бы
# тихой и обнаружилась бы через недели, когда кто-то откроет документ. Простой на минуты дешевле.
#
# ПОЧЕМУ СВЕРКА ЗДЕСЬ, А НЕ СОВЕТОМ В ИНСТРУКЦИИ. «Перенесите и проверьте» означает, что проверку
# сделает тот, кто помнит про неё в шесть вечера на боевом сервере. Здесь она — часть фазы, и её
# провал останавливает обновление до подмены файлов.
mirror_blobs() {
    local net="$1" mc_image="$2" src_key="$3" src_secret="$4" src_bucket="$5" \
          dst_key="$6" dst_secret="$7" dst_bucket="$8" mode="$9"
    # ⚠️ СВЕРЯЕМ СОСТАВОМ И РАЗМЕРАМИ, А НЕ `mc diff`. Соблазн взять готовую команду велик, но она
    # отвечает не на тот вопрос: `mc diff` считает объекты различными, если различается ВРЕМЯ, — а
    # `mc mirror` время не выравнивает, копия всегда новее оригинала. Проверено на живом стенде:
    # у объекта совпадают размер, ETag и content-type, различается одна дата, и `mc diff` метит его
    # знаком «!». В прямую сторону это молчит случайно (оригинал старше копии), а на возврате
    # сверка находила расхождение в КАЖДОМ объекте — то есть откат был бы невозможен.
    #
    # Сверяем списками «размер + путь» с обеих сторон. Время в них не входит вовсе.
    # Значения передаём ПЕРЕМЕННЫМИ ОКРУЖЕНИЯ, а не подстановкой в текст скрипта: пароль
    # хранилища выбирал администратор, и апостроф в нём разорвал бы кавычки — отказ пришёл бы как
    # «перенос не сошёлся», то есть указывал бы на данные вместо кавычек (найдено ревью).
    docker run --rm --network "$net" --entrypoint /bin/sh \
        -e SRC_KEY="$src_key" -e SRC_SECRET="$src_secret" -e SRC_BUCKET="$src_bucket" \
        -e DST_KEY="$dst_key" -e DST_SECRET="$dst_secret" -e DST_BUCKET="$dst_bucket" \
        -e MODE="$mode" "$mc_image" -c '
        set -e
        mc alias set minio http://minio:9000 "$SRC_KEY" "$SRC_SECRET" >/dev/null
        mc alias set garage http://garage:3900 "$DST_KEY" "$DST_SECRET" >/dev/null
        if [ "$MODE" = mirror ]; then
            from=minio/$SRC_BUCKET; to=garage/$DST_BUCKET
        else
            from=garage/$DST_BUCKET; to=minio/$SRC_BUCKET
        fi
        # `--overwrite`: без него mirror ПРОПУСКАЕТ объект, если в приёмнике он новее (проверено
        # на стенде). Для отката это означало бы, что вернувшаяся установка получает не то
        # состояние, которое ей вернули, а смесь. `--retry` — потому что обрыв одного объекта из
        # тысяч не повод начинать всё заново.
        mc mirror --quiet --overwrite --retry "$from" "$to"

        # Поля `mc ls --recursive`: [дата, время, UTC], размер, класс, путь — отсюда 4 и 6-.
        mc ls --recursive "$from" | tr -s " " | cut -d" " -f4,6- | sort > /tmp/from.lst
        mc ls --recursive "$to"   | tr -s " " | cut -d" " -f4,6- | sort > /tmp/to.lst
        echo "объектов: было $(wc -l < /tmp/from.lst), стало $(wc -l < /tmp/to.lst)"

        # Проверяем ОДНОСТОРОННЕ: каждый объект источника есть в приёмнике с тем же размером.
        # Симметричная разность здесь неверна, и это не придирка: после перехода приложение УДАЛЯЕТ
        # блобы (удалённый комплект, пересозданный шаблон, заменённый набор данных). При возврате
        # такие объекты остаются в MinIO, но их уже нет в Garage — симметричная проверка считала бы
        # это расхождением и блокировала откат НАВСЕГДА, хотя терять нечего (найдено ревью).
        comm -23 /tmp/from.lst /tmp/to.lst > /tmp/lost.lst
        lost_n=$(wc -l < /tmp/lost.lst)
        extra_n=$(comm -13 /tmp/from.lst /tmp/to.lst | wc -l)
        echo "не перенеслось: $lost_n; лишних в приёмнике: $extra_n"
        if [ "$lost_n" != 0 ]; then
            echo "СВЕРКА НАШЛА ПОТЕРИ, первые из них:"
            head -10 /tmp/lost.lst
            exit 1
        fi
    '
}

# Сеть проекта спрашиваем у самого Docker, а не собираем из имени: имя проекта можно задать в .env
# (COMPOSE_PROJECT_NAME), и собранное «на глазок» имя сети завело бы контейнер mc в пустоту, где
# ни minio, ни garage не отзываются.
#
# Принимает УЖЕ НАЙДЕННЫЙ контейнер, а не имя сервиса. Первая редакция искала его через `compose ps`
# по рабочему compose-файлу — а на переносе хранилище поднято из ФАЙЛА ЦЕЛЕВОЙ ВЕРСИИ, и в рабочем
# сервиса garage ещё нет вовсе: сеть не находилась никогда (поймано живым прогоном обновления).
network_of() {
    local cid="$1"
    [ -n "$cid" ] || return 1
    docker inspect -f '{{range $k,$v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$cid" 2>/dev/null \
        | tr -s ' ' | cut -d' ' -f1
}

migrate_blobs() {
    local env_new="$1"
    crosses_storage || return 0

    head2 "Переносим файлы в новое хранилище"

    local mc_image src_bucket dst_bucket src_key src_secret dst_key dst_secret net
    mc_image="$(grep -oE 'image:[[:space:]]*[^[:space:]]*mc:[^[:space:]]+' docker-compose.yml | sed -E 's/^image:[[:space:]]*//' | head -1)"
    src_bucket="$(env_get MINIO_BUCKET)"
    src_key="$(env_get MINIO_ROOT_USER)"
    src_secret="$(env_get MINIO_ROOT_PASSWORD)"
    dst_bucket="$(env_get GARAGE_BUCKET "$env_new")"
    dst_key="$(env_get GARAGE_KEY_ID "$env_new")"
    dst_secret="$(env_get GARAGE_SECRET "$env_new")"
    [ -n "$src_bucket" ] && [ -n "$dst_key" ] && [ -n "$dst_secret" ] || stop \
        "Не удалось собрать данные для переноса (имя бакета или ключи). Система работает на $CURRENT, ничего не менялось."

    # Приложение — вниз. Хранилище и база остаются: из первого читает mc, вторая просто не при чём.
    say "Останавливаем приложение на время переноса…"
    compose stop api web >/dev/null 2>&1 || true

    say "Поднимаем новое хранилище…"
    compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" up -d garage-init >/dev/null 2>&1 || true
    # Код инициализации берём через `docker wait`, а НЕ `docker compose wait`: последняя команда
    # появилась только в Compose 2.22, а инструкция объявляет нижней границей Docker Engine 24 —
    # он приезжает с Compose 2.18–2.21. Там `compose wait` отвечает «unknown docker command», и
    # обновление вставало бы с диагнозом «инициализация завершилась с ошибкой» — при исправной
    # инициализации (найдено ревью). `docker wait` есть везде.
    local init_cid init_code
    init_cid="$(compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" ps -aq garage-init 2>/dev/null | head -1)"
    init_code="$([ -n "$init_cid" ] && docker wait "$init_cid" 2>/dev/null || echo 1)"
    if [ "${init_code:-1}" != 0 ]; then
        compose up -d >/dev/null 2>&1 || true
        stop "$(cat <<EOF
Новое хранилище не удалось подготовить: инициализация (garage-init) завершилась с ошибкой.

Файлы не тронуты, прежнее хранилище цело, система поднята обратно на $CURRENT. Посмотрите причину:
  docker compose -f $NEW_DIR/docker-compose.yml --env-file $env_new logs garage-init
EOF
)"
    fi

    # Контейнер хранилища ищем по ФАЙЛУ ЦЕЛЕВОЙ ВЕРСИИ: только он знает про сервис garage.
    net="$(network_of "$(compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" ps -q garage 2>/dev/null | head -1)")" || net=""
    [ -n "$net" ] || {
        compose up -d >/dev/null 2>&1 || true
        stop "Не удалось определить сеть Compose — переносить файлы некуда. Система поднята обратно на $CURRENT."
    }

    # Вывод придерживаем: `mc mirror` печатает строку на КАЖДЫЙ файл, и на боевой библиотеке это
    # тысячи строк, в которых тонет единственно важное — сошлась ли сверка. При отказе показываем
    # хвост: там причина.
    say "Копируем файлы (прежнее хранилище не изменяется)…"
    local out
    if ! out="$(mirror_blobs "$net" "$mc_image" "$src_key" "$src_secret" "$src_bucket" \
                      "$dst_key" "$dst_secret" "$dst_bucket" mirror 2>&1)"; then
        printf '%s\n' "$out" | tail -20 >&2
        compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" stop garage >/dev/null 2>&1 || true
        compose up -d >/dev/null 2>&1 || true
        stop "$(cat <<EOF
Перенос файлов не сошёлся — число объектов или их содержимое различаются. Обновление остановлено
ДО подмены файлов: система поднята обратно на $CURRENT, прежнее хранилище не изменялось.

Повторите обновление (перенос продолжится с того места, где оборвался) или перенесите файлы
вручную по §8.7 DEPLOYMENT.md.
EOF
)"
    fi
    # Две последние строки — это и есть сверка: сколько объектов было и стало, сколько расхождений.
    printf '%s\n' "$out" | tail -2 | sed 's/^/  /'
    say "Файлы перенесены и сверены."
}

# ── Загрузка образов ────────────────────────────────────────────────────────────
# Три попытки, а не одна: обрыв связи с реестром — самый вероятный сбой всей процедуры, а стоит
# повтор здесь ровно ничего. Отказ безопасен (рабочие файлы ещё не тронуты), но пуст: человек
# повторяет команду с начала, заново снимая дамп. Уже загруженные слои остаются на хосте, поэтому
# повтор продолжает с того места, где оборвалось, а не начинает сначала.
pull_images() {
    local env_new="$1" attempt=1
    while :; do
        compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" pull && return 0
        [ "$attempt" -ge 3 ] && return 1
        warn "Загрузка образов оборвалась (попытка $attempt из 3). Повторяем через 15 с…"
        sleep 15
        attempt=$((attempt + 1))
    done
}

# ── Обновление ──────────────────────────────────────────────────────────────────
do_update() {
    preflight_common
    [ -n "$TARGET" ] || { usage >&2; stop "Не указана версия. Список выпусков: https://github.com/$REPO/releases"; }

    head2 "Обновление $CURRENT → $TARGET"

    [ "$TARGET" != "$CURRENT" ] || stop "В .env уже указана версия $TARGET — обновлять не на что."
    version_gt "$TARGET" "$CURRENT" || stop "$(cat <<EOF
$TARGET ниже текущей $CURRENT — это не обновление, а откат, и так он не делается: старая версия не
обязана понимать мигрировавшую схему. Пока миграции не применились — ./update.sh --rollback;
после — восстановление дампа с пересозданием базы (§9 DEPLOYMENT.md).
EOF
)"

    curl -fsIL --max-time 20 "$RELEASE_URL/v$TARGET/docker-compose.yml" -o /dev/null 2>/dev/null || stop \
        "Выпуска $TARGET нет или до github.com не достучаться. Список: https://github.com/$REPO/releases"

    check_project_visible
    check_postgres_major
    check_self_update
    check_jobs
    fetch_release_files
    # ПОСЛЕ fetch_release_files, и это принципиально: проверка смотрит на файл ЦЕЛЕВОЙ версии —
    # понять, меняется ли хранилище, иначе не из чего. Стояла выше и не срабатывала никогда:
    # new/docker-compose.yml к тому моменту ещё не скачан, `crosses_storage` отвечал «нет», и
    # предполёт (место, предупреждение о простое) молча пропускался — на первом запуске всегда,
    # а на повторном срабатывал, потому что new/ оставался от прошлой попытки. Найдено ревью.
    check_storage_migration
    check_compose_drift
    check_new_vars
    legacy_notes
    backup_db

    # Предполёт на ВРЕМЕННОМ .env: APP_VERSION в рабочий файл пишем только после успешного pull.
    # Иначе оборвавшаяся загрузка оставила бы .env с новой версией при старых образах — состояние,
    # в котором `up -d` уже нельзя выполнить, а понять это по файлам нельзя.
    head2 "Предполётная проверка"
    local env_new=".env.$TARGET.$STAMP"
    if grep -qE '^[[:space:]]*APP_VERSION[[:space:]]*=' .env; then
        # Меняем ЗНАЧЕНИЕ, а не строку целиком: если рядом стоял комментарий («# поставили вручную
        # тогда-то»), он про эту установку, и стирать его при обновлении незачем.
        sed -E "s|^([[:space:]]*APP_VERSION[[:space:]]*=)[^#]*|\1$TARGET  |" .env > "$env_new"
    else
        cp .env "$env_new"; printf '\nAPP_VERSION=%s\n' "$TARGET" >> "$env_new"
    fi

    apply_autofill "$env_new"
    generate_secrets "$env_new"

    compose -f "$NEW_DIR/docker-compose.yml" --env-file "$env_new" config -q || {
        rm -f "$env_new"
        stop "Compose-файл версии $TARGET не разбирается с вашим .env. Система работает на $CURRENT."
    }
    say "Compose-файл разобран."

    say "Загружаем образы $TARGET (система пока работает на $CURRENT)…"
    pull_images "$env_new" || {
        rm -f "$env_new"
        stop "Не удалось загрузить образы (три попытки). Ничего не менялось — система работает на $CURRENT."
    }

    # Точка невозврата пройдена в безопасную сторону: образы на хосте, файлы проверены. Только
    # теперь трогаем рабочие файлы — и прежние сохраняем С ДАТОЙ, чтобы второй запуск не затёр то,
    # на что откатываться.
    head2 "Переключаем версию"
    # Снимок списка миграций — до `up -d`: он единственное, по чему потом отличают «откатиться ещё
    # можно» от «поздно, только дамп». Журнал api для этого не годится: он живёт, пока жив контейнер.
    if migrations_snapshot > "migrations.prev-$STAMP" && [ -s "migrations.prev-$STAMP" ]; then
        say "Снимок списка миграций: migrations.prev-$STAMP"
    else
        rm -f "migrations.prev-$STAMP"
        warn "Список миграций снять не удалось — откат командой --rollback будет отказан: без снимка он вслепую."
    fi

    cp docker-compose.yml "docker-compose.yml.prev-$STAMP"
    cp .env ".env.prev-$STAMP"
    say "Прежние файлы сохранены: docker-compose.yml.prev-$STAMP, .env.prev-$STAMP"

    # Файлы переносим ДО подмены compose и .env: пока рабочие файлы прежние, отказ переноса
    # возвращает систему на текущую версию одной командой `up -d`, а не разбором полусостояния.
    migrate_blobs "$env_new"

    cp "$NEW_DIR/docker-compose.yml" docker-compose.yml
    cp "$PRISTINE" "$RELEASE_REF"   # эталон — ЧИСТЫЙ файл версии, см. fetch_release_files
    # Конфигурация хранилища — рядом с compose, иначе монтировать нечего. Прежнюю сохраняем с
    # датой, как compose и .env: в ней могли поднять ёмкость узла или сменить движок метаданных,
    # и молча затирать такую правку нельзя.
    if [ -f "$NEW_DIR/garage.toml" ]; then
        if [ -f garage.toml ] && ! cmp -s garage.toml "$NEW_DIR/garage.toml"; then
            cp garage.toml "garage.toml.prev-$STAMP"
            # Вслух: файл могли править (ёмкость узла, движок метаданных), и «тихо заменили»
            # здесь равно «ваша настройка исчезла при обновлении».
            say "Конфигурация хранилища заменена файлом версии; прежняя сохранена: garage.toml.prev-$STAMP"
        fi
        cp "$NEW_DIR/garage.toml" garage.toml
    fi
    cp "$NEW_DIR/env.example" .env.example
    mv "$env_new" .env

    # `up -d` под присмотром, а не «как получится»: он отвечает ошибкой в самом частом сценарии
    # неудачи — web ждёт api по healthcheck (20 с + 30×10 с), и неудавшаяся миграция роняет команду
    # минут через пять. Без этой обёртки set -e обрывал бы скрипт молча — ровно там, где обещаны
    # журнал и подсказка про откат (поймано ревью).
    compose up -d || update_failed "Контейнеры новой версии не поднялись."

    head2 "Проверка"
    if wait_for_version "$TARGET"; then
        compose ps
        say ""
        say "Готово: $CURRENT → $TARGET."
        [ "$NO_BACKUP" -eq 1 ] || say "Дамп перед обновлением: $DUMP"
        say "Прежние файлы: docker-compose.yml.prev-$STAMP, .env.prev-$STAMP"
    else
        update_failed "Система не ответила версией $TARGET."
    fi
}

# Единственное место, где система УЖЕ переключена, а результат неизвестен. Отсюда человек должен
# уйти с причиной и следующим шагом, а не с кодом возврата docker.
update_failed() {
    warn "$1 Последние строки журнала api:"
    compose logs --tail=50 api || true
    stop "$(cat <<EOF
Обновление до $TARGET не подтвердилось.

Частые причины видны в журнале выше: не хватило переменной окружения или оборвалась миграция.
Пока миграции не применились, вернуть прежнюю версию можно одной командой (скрипт сам проверит
это по базе и откажет, если поздно):

  ./update.sh --rollback

Если миграции применились — только восстановление дампа с пересозданием базы (§9):
${DUMP:-снятый вами дамп}
EOF
)"
}

if [ "$CHECK" -eq 1 ]; then
    do_check
elif [ "$GC" -eq 1 ]; then
    do_gc
elif [ "$ROLLBACK" -eq 1 ]; then
    [ -z "$TARGET" ] || stop "--rollback не сочетается с номером версии: откат идёт на ту версию, что сохранена в .env.prev-*."
    do_rollback
else
    do_update
fi
